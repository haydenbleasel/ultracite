const readIf = (p) => (existsSync(p) ? readFileSync(p, "utf8") : null);
const relaxDiag = (d) => ({ rule: d.rule, line: d.line, message: d.message });

/**
 * Re-runs verify on the file the agent left (a copy) and checks it reproduces the committed
 * verified file and verify.json. Verify is a fix pass, a formatter and a lint, all deterministic.
 */
function reverify(subject, agentText, tag) {
  if (agentText === null) return { skipped: "the file was deleted" };
  const dir = scratch(tag);
  writeFileSync(join(dir, subject.basename), agentText);
  withRunFiles(dir, subject);
  let remaining;
  try {
    remaining = mirror.verifySafely(
      (f) => verify(subject, dir, f),
      subject.basename,
      dir
    ).remaining;
  } catch (error) {
    return { error: String(error.message).slice(0, 200) };
  }
  return {
    text: readFileSync(join(dir, subject.basename), "utf8"),
    remaining: remaining ?? [],
  };
}

/** Which of the attempt's issues the agent listed on its `Left for review:` line. */
const leftShare = (left, given) => {
  if (!left) return "none";
  return left.issues.length >= given.length ? "all" : "some";
};

/**
 * What Ultracite's verify would hand back if the filter kept the rule alone (nothing new since the
 * handoff): the stricter reading of the handoff, recorded beside the one used.
 */
const topicOnlyRemaining = (remaining) =>
  remaining === null ? null : remaining.filter((d) => isHandoffRule(d.rule));

/**
 * The diagnostics of a committed JSON file with the file each was reported in, as the v3 mirror
 * remembers it during a run (diff.ts recordSourceLines): `text` is that file as the linter read it,
 * from the run's committed copies. A re-measurement then pairs reports as the run did.
 */
const withSnapshot = (diagnostics, text) =>
  text === null || diagnostics === null
    ? diagnostics
    : mirror.recordSourceLinesV3(diagnostics, null, () => text);

async function measure(runId) {
  const runDir = join(lib.RUNS_DIR, runId);
  const meta = JSON.parse(readFileSync(join(runDir, "meta.json"), "utf8"));
  const previousPath = join(runDir, "measure.json");
  const previous = existsSync(previousPath)
    ? JSON.parse(readFileSync(previousPath, "utf8"))
    : null;
  const subject = {
    ...subjectsManifest().find((s) => s.id === meta.subject),
    ...subjectOf(meta.subject),
  };
  const ext = extOf(subject);
  const beforeText = readFileSync(join(runDir, `before${ext}`), "utf8");
  const pristine = readFileSync(join(HERE, subject.path), "utf8");
  const handoff = JSON.parse(
    readFileSync(join(runDir, "handoff.json"), "utf8")
  );
  const handoffIssues = withSnapshot(handoff.diagnostics, beforeText);
  const loop = meta.retryLoop;
  const tagBase = `${runId}`;
  const beforeState = await measureState(
    subject,
    beforeText,
    `${tagBase}-before`
  );
  const attempts = [];
  let inputText = beforeText;
  let given = handoffIssues;
  let leftSoFar = [];
  let lastVerified = null;
  for (const a of meta.attempts) {
    const dir = join(runDir, `attempt${a.attempt}`);
    const givenJson = JSON.parse(
      readFileSync(join(dir, a.diagnosticsFile), "utf8")
    ).diagnostics;
    // The issues this attempt was given: the handoff, or the previous verify's (with its file).
    if (a.attempt === 1) given = handoffIssues;
    else given = withSnapshot(givenJson, inputText);
    const recorded = JSON.parse(readFileSync(join(dir, "verify.json"), "utf8"));
    const agentText = readIf(join(dir, `agent${ext}`));
    const verifiedText = readIf(join(dir, `verified${ext}`));
    const remaining = withSnapshot(recorded.remaining, verifiedText);
    const agentState = await measureState(
      subject,
      agentText,
      `${tagBase}-a${a.attempt}-agent`,
      beforeState
    );
    const verifiedState =
      verifiedText === agentText
        ? agentState
        : await measureState(
            subject,
            verifiedText,
            `${tagBase}-a${a.attempt}-verified`,
            beforeState
          );
    // This attempt's own edit, against the file it was given.
    const ownEdit =
      agentText === null ? null : editOf(subject, agentText, inputText);
    const re = reverify(
      subject,
      agentText,
      `${tagBase}-a${a.attempt}-reverify`
    );
    const recordedRemaining = (recorded.remaining ?? []).map(relaxDiag);
    const vsAttempt =
      remaining === null ? null : mirror.partitionByRemaining(given, remaining);
    const vsHandoff =
      remaining === null
        ? null
        : mirror.partitionByRemaining(handoffIssues, remaining);
    // The agent's `Left for review:` issues, as the diagnostics this attempt was given.
    const leftIssues = a.leftForReview
      ? given.filter((d) =>
          a.leftForReview.issues.includes(`${d.rule} L${d.line}`)
        )
      : [];
    if (a.leftForReview)
      leftSoFar = [
        ...leftSoFar,
        { explanation: a.leftForReview.explanation, issues: leftIssues },
      ];
    // Ultracite's retry decision, recomputed from the committed files.
    const next = mirror.nextRetry({
      issues: given,
      remaining,
      leftForReview: leftSoFar,
      timedOut: a.timedOut,
      attempt: a.attempt,
      maxAttempts: loop.maxAttempts,
    });
    const part = (p) =>
      p && {
        cleared: p.cleared.map((d) => `${d.rule}: ${d.message}`),
        still: p.still.map((d) => `${d.rule}: ${d.message}`),
        introduced: p.introduced.map((d) => `${d.rule}: ${d.message}`),
      };
    const session = attemptSession(runDir, meta, a.attempt, previous, subject);
    attempts.push({
      attempt: a.attempt,
      prompt: a.prompt,
      promptKind:
        a.prompt === "buildPrompt"
          ? "first"
          : !a.retryIssues
            ? "retry"
            : a.retryIssues.introduced.length === 0
              ? "retry: still reported"
              : a.retryIssues.still.length === 0
                ? "retry: new since the edit"
                : "retry: still reported and new",
      given: givenJson.map((d) => `${d.rule} L${d.line}: ${d.message}`),
      retryIssues: a.retryIssues ?? null,
      leftForReview: a.leftForReview ?? null,
      leftForReviewShare: leftShare(a.leftForReview, givenJson),
      wallSeconds: Math.round(a.wallMs / 100) / 10,
      exitCode: a.exitCode,
      timedOut: a.timedOut,
      ok: a.ok,
      unchanged: agentText === inputText,
      ownEdit: ownEdit && {
        edit: ownEdit.edit,
        kinds: ownEdit.kinds,
        guards: ownEdit.guards,
        diff: ownEdit.diff,
      },
      agent: finishState({
        ...agentState,
        text: agentText ?? undefined,
      }),
      verified: finishState({
        ...verifiedState,
        text: verifiedText ?? undefined,
      }),
      verifyChangedTheFile: agentText !== verifiedText,
      ultraciteVerify: {
        error: recorded.error,
        remaining:
          recorded.remaining === null
            ? null
            : recordedRemaining.map(
                (d) => `${d.rule} L${d.line}: ${d.message}`
              ),
        remainingDetail: recordedRemaining,
        remainingTopicRulesOnly:
          recorded.remaining === null
            ? null
            : topicOnlyRemaining(recorded.remaining).map(
                (d) => `${d.rule} L${d.line}: ${d.message}`
              ),
        vsThisAttempt: part(vsAttempt),
        vsHandoff: part(vsHandoff),
        retried: a.retried,
        retryRecomputed: next !== null,
        retryReproduces: (next !== null) === a.retried,
      },
      reverify:
        re.skipped || re.error
          ? re
          : {
              fileMatches: re.text === verifiedText,
              diagnosticsMatch:
                JSON.stringify(re.remaining.map(relaxDiag)) ===
                JSON.stringify(recordedRemaining),
            },
      fileChecks: a.fileChecks,
      session,
    });
    inputText = verifiedText ?? inputText;
    lastVerified = { error: recorded.error, remaining };
  }
  const last = meta.attempts.at(-1);
  // What Ultracite prints after the last attempt: its final message (stdout, gitignored) unless it
  // left issues for review; without stdout, the committed measure's copy.
  const lastStdout = readIf(
    join(runDir, `attempt${last.attempt}`, "stdout.txt")
  );
  const finalMessage =
    lastStdout === null
      ? (previous?.ultracitePrints?.finalMessage ?? "")
      : last.leftForReview
        ? ""
        : lib.redact(mirror.agentOutput(lastStdout, loop.outputCap));
  const outcome = mirror.fileOutcome({
    agentLabel: mirror.AGENT_LABELS[meta.agent],
    issues: handoffIssues,
    attempts: meta.attempts.length,
    agentResult: {
      ok: last.ok,
      stderr: last.stderrTail ?? "",
      timedOut: last.timedOut,
    },
    verified: lastVerified,
    timeoutMs: loop.timeoutMs,
    leftForReview: leftSoFar,
    finalMessage,
  });
  const finalText = readIf(join(runDir, `after${ext}`));
  const finalState = attempts.at(-1).verified;
  const lastLeft = attempts.at(-1).leftForReviewShare;
  const anyLeft = attempts.some((a) => a.leftForReviewShare !== "none")
    ? attempts.some((a) => a.leftForReviewShare === "all")
      ? "all"
      : "some"
    : "none";
  const leftForReview = lastLeft !== "none" ? lastLeft : anyLeft;
  const response = responseOf(
    subject,
    finalState,
    finalState.outcome,
    leftForReview
  );
  const sum = (f) => {
    const xs = attempts
      .map((a) => f(a.session))
      .filter((x) => typeof x === "number");
    return xs.length
      ? Math.round(xs.reduce((p, q) => p + q, 0) * 1e6) / 1e6
      : null;
  };
  // Every file of the run dir the agent changed, created or deleted: the run files the harness put
  // there (init's configs, package.json, tsconfig.json, the stub module), the diagnostics JSON,
  // anything new.
  const otherFileChanges = meta.fileChecks.otherFileChanges;
  const configChanged = otherFileChanges.some((c) =>
    COMMON_RUN_FILES.includes(c.path)
  );
  const stubChanged = otherFileChanges.some(
    (c) => c.path === subject.stubs.name
  );
  const { text: _beforeText, ...beforeOut } = beforeState;
  const out = {
    runId,
    topic: lib.TOPIC,
    subject: meta.subject,
    base: subject.base,
    label: subject.label,
    config: subject.config,
    agent: meta.agent,
    cliVersion: meta.cliVersion,
    mirrorRevision: meta.ultracite?.mirrorRevision ?? null,
    wallSeconds: Math.round(meta.wallMs / 100) / 10,
    attemptCount: meta.attempts.length,
    stoppedBecause: meta.stoppedBecause,
    retryLoop: meta.retryLoop,
    handoff: {
      fixPassChanged: handoff.fixPassChanged,
      reportedBeforeFilter: handoff.diagnosticsReported ?? null,
      leftOutByFilter: handoff.leftOutByFilter ?? null,
      given: handoff.diagnostics.map((d) => ({
        rule: d.rule,
        line: d.line,
        message: d.message,
        help: d.help ?? null,
        url: d.url ?? null,
      })),
      beforeMatchesPristine: beforeText === pristine,
    },
    before: beforeOut,
    attempts,
    final: {
      outcome: finalState.outcome,
      response,
      leftForReview,
      otherFilesTouched: otherFileChanges.length > 0,
      configChanged,
      stubChanged,
    },
    finalMatchesLastVerified:
      finalText ===
      readIf(join(runDir, `attempt${last.attempt}`, `verified${ext}`)),
    ultraciteOutcome: outcome,
    ultracitePrints: {
      finalMessage,
      fromStdout: lastStdout !== null,
    },
    cost: {
      costUSD: sum((s) => s.costUSD),
      tokensUsedReportedOnStderr: sum((s) => s.tokensUsedReportedOnStderr),
      totalTokens: sum((s) =>
        s.tokens
          ? meta.agent === "claude"
            ? s.tokens.input +
              s.tokens.output +
              s.tokens.cacheCreation +
              s.tokens.cacheRead
            : s.tokens.total_tokens
          : null
      ),
    },
    cheating: {
      otherFileChanges,
      configFiles: meta.fileChecks.configFilesNearRun,
      diagnosticsJsonUnchanged: meta.fileChecks.diagnosticsJsonUnchanged,
      pristineSubjectsUnchanged: meta.fileChecks.pristineSubjectsUnchanged,
      newRunsEntries: meta.fileChecks.newRunsEntries,
      newExperimentRootEntries: meta.fileChecks.newExperimentRootEntries,
      exposureInSessionLog: sumExposure(attempts, "exposure"),
      exposureInToolCalls: sumExposure(attempts, "exposureInToolCalls"),
      exposureInToolInputs: sumExposure(attempts, "exposureInToolInputs"),
      toolCallsOutsideRunDir: attempts.flatMap((a) =>
        (a.session.outsideRunDir ?? []).map((c) => ({
          attempt: a.attempt,
          ...c,
        }))
      ),
      lockedDuringRun: meta.isolation?.lockedDuringRun ?? null,
    },
  };
  writeFileSync(
    previousPath,
    `${JSON.stringify(scrubCutHome(lib.redact(out)), null, 2)}\n`
  );
  return out;
}

