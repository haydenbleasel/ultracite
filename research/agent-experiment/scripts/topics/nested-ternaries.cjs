/**
 * The project as `ultracite fix` would leave it: the cleaned subject and its stub module with init's
 * run files, through the Oxlint adapter's pass (oxlint --fix, oxfmt --write) until nothing changes.
 * The result is a fixed point of Ultracite's collect, so the handoff hands over what the fix pass
 * can't fix, and the agent's input is what `ultracite fix` would leave.
 */
function normalise(subject, text, stubText, commonFiles, tag) {
  const dir = scratch(tag);
  writeFileSync(join(dir, subject.basename), text);
  writeFileSync(join(dir, subject.stubs.name), stubText);
  for (const f of COMMON_RUN_FILES) writeFileSync(join(dir, f), commonFiles[f]);
  const snap = () =>
    Object.fromEntries(
      readdirSync(dir)
        .sort()
        .map((n) => [n, readFileSync(join(dir, n), "utf8")])
    );
  const passes = [];
  for (let i = 0; i < 6; i++) {
    const before = snap();
    adapterPass(dir, []);
    const after = snap();
    passes.push(sha256(JSON.stringify(after)));
    if (JSON.stringify(after) === JSON.stringify(before)) break;
  }
  if (passes.length === 6 && passes[4] !== passes[5])
    throw new Error(`${subject.id}: the fix passes don't settle`);
  const files = snap();
  return {
    text: files[subject.basename],
    stubText: files[subject.stubs.name],
    runFiles: Object.fromEntries(COMMON_RUN_FILES.map((f) => [f, files[f]])),
    passes: passes.length,
  };
}

