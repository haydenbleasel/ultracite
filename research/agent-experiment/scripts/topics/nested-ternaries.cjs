/**
 * A mutant's text. Two kinds:
 *   variant  a corpus variant, made by the corpus's own variantsOf from the cleaned corpus subject
 *            (header stripped, the stub imported as ./stubs), then Ultracite's Oxlint pass until
 *            nothing changes (what verify leaves after an agent wrote that edit), unless
 *            `normalise: false` (what the agent wrote)
 *   edits    [from, to] pairs on the prepared subject, each matching exactly once; `normalise:
 *            true` puts the result through the same pass
 */
function mutantText(m) {
  if (mutantCache.has(m.id)) return mutantCache.get(m.id);
  const s = fullSubject(subjectsManifest().find((x) => x.base === m.base));
  let text;
  if (m.variant) {
    variantsCache ??= corpusVariants();
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const cleaned = cleanText(
      original,
      examplesJson().stripFields,
      m.base,
      "subject"
    );
    const v = variantsCache.variantsOf(m.base, cleaned)[m.variant];
    if (!v) throw new Error(`${m.id}: no corpus variant ${m.variant}`);
    text =
      m.normalise === false
        ? v.text
        : normalise(
            s,
            v.text,
            preparedStub(s),
            commonRunFiles(),
            `mutant-${m.id}`
          ).text;
  } else {
    text = preparedTextOf(s);
    for (const [from, to] of m.edits ?? []) {
      const n = text.split(from).length - 1;
      if (n !== 1)
        throw new Error(
          `${m.id}: edit matches ${n} times: ${from.slice(0, 60)}`
        );
      text = text.replace(from, () => to);
    }
    if (m.normalise)
      text = normalise(
        s,
        text,
        preparedStub(s),
        commonRunFiles(),
        `mutant-${m.id}`
      ).text;
  }
  mutantCache.set(m.id, text);
  return text;
}

/**
 * The PRIMING check on the corpus subjects and stubs before they're stripped: it must find the
 * analysis in every one of them (so a clean prepared subject means the check ran).
 */
function primingSanity() {
  const out = {};
  for (const [base, b] of Object.entries(BASES)) {
    const text = readFileSync(join(EXAMPLES, b.example), "utf8");
    const stub = readFileSync(join(EXAMPLES, b.stubs.example), "utf8");
    out[base] = {
      subject: primedLines(text, b.basename).length,
      stubs: primedLines(stub, b.stubs.name).length,
    };
  }
  return out;
}

/** One self-test case: a text measured against its subject's prepared state and checked. */
async function selfTestCase(m, bases, examples) {
  const s = fullSubject(subjectsManifest().find((x) => x.base === m.base));
  const st = await measureState(
    s,
    mutantText(m),
    `self-${m.id}`,
    bases[m.base]
  );
  const outcome = outcomeOf(st);
  const response = responseOf(s, st, outcome, "none");
  const e = m.expect ?? {};
  const why = [];
  if (e.oracle !== undefined && st.oracle.verdict !== e.oracle)
    why.push(`oracle ${st.oracle.verdict}`);
  if (e.nested !== undefined && st.nestedLeft.oxlint !== e.nested)
    why.push(`no-nested-ternary ${st.nestedLeft.oxlint}`);
  if (e.edit !== undefined && outcome !== e.edit) why.push(`edit "${outcome}"`);
  if (e.response !== undefined && response !== e.response)
    why.push(`response "${response}"`);
  for (const k of e.kinds ?? [])
    if (!(st.edit.kinds ?? []).includes(k)) why.push(`kind ${k}`);
  if (e.oneLine !== undefined && st.edit.guards?.oneLine !== e.oneLine)
    why.push(`one-line guards ${st.edit.guards?.oneLine}`);
  // A corpus variant: its verdict, differing count and the nested-ternary rules' Oxlint count must
  // equal examples.json's.
  let corpus = null;
  if (m.variant) {
    const v = examples.subjects[m.base].variants[m.variant];
    corpus = {
      oracle: v.oracle.verdict,
      differing: v.oracle.differing ?? null,
      oxlintNested: v.nestedRules.oxlint,
      ours: {
        oracle: st.oracle.verdict,
        differing: st.oracle.differing,
        oxlintNested: st.views.oxlint.nestedHonor["no-nested-ternary"] ?? 0,
      },
    };
    if (v.oracle.verdict !== st.oracle.verdict)
      why.push("oracle differs from the corpus variant");
    if ((v.oracle.differing ?? null) !== (st.oracle.differing ?? null))
      why.push("differing count differs from the corpus variant");
    if (corpus.oxlintNested !== corpus.ours.oxlintNested)
      why.push(
        "Oxlint's no-nested-ternary count differs from the corpus variant"
      );
  }
  return {
    name: `${m.id}: ${m.description}`,
    mutant: m.id,
    variant: m.variant ?? null,
    normalised: m.variant ? m.normalise !== false : Boolean(m.normalise),
    oracle: st.oracle.verdict,
    differing: st.oracle.differing,
    nested: st.nestedLeft,
    outcome,
    response,
    kinds: st.edit.kinds,
    guards: st.edit.guards ?? null,
    cognitive: st.edit.cognitive ?? null,
    increments: st.edit.increments ?? null,
    typeErrors: st.typeErrors,
    expected: e,
    corpus,
    pass: why.length === 0,
    why,
  };
}

