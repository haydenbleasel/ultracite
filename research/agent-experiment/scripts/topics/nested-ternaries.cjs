/**
 * What `ultracite fix` and `ultracite fix --unsafe` do with Oxlint, Biome and ESLint, no agent, on
 * each subject as upstream wrote it (header stripped) and as handed to the agent. Run with the
 * mirror (the harness's configs) and with Ultracite's real adapter (init's configs and node_modules
 * links), which must agree.
 */
function deterministicPaths() {
  const examples = examplesJson();
  const { root, script } = linkedRoot("deterministic");
  const out = [];
  let n = 0;
  for (const s0 of subjectsManifest()) {
    const s = fullSubject(s0);
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const stubUpstream = cleanText(
      readFileSync(join(EXAMPLES, s.stubs.example), "utf8"),
      [],
      s.base,
      "stubs"
    );
    const inputs = {
      "upstream (header stripped)": [
        cleanText(original, examples.stripFields, s.base, "subject"),
        stubUpstream,
      ],
      "as handed to the agent (Oxlint-normalised)": [
        preparedTextOf(s),
        preparedStub(s),
      ],
    };
    for (const [inputName, [text, stubText]] of Object.entries(inputs))
      for (const [linter, unsafe] of COMMANDS) {
        n++;
        const r = fixPassOn({
          s,
          text,
          stubText,
          linter,
          unsafe,
          root,
          script,
          tag: `d${n}`,
        });
        const { afterText: _after, ...row } = r;
        out.push({ subject: s.id, input: inputName, ...row });
        console.log(
          `${s.id} ${linter}${unsafe ? " --unsafe" : ""} on ${inputName}: code changed ${r.codeChanged}; ${r.edit.edit}; nested ${JSON.stringify(r.nestedReported)}; oracle ${r.oracle.vsInput}; real ${JSON.stringify(r.realAdapter)}`
        );
      }
  }
  return out;
}

/**
 * The same passes on every run's final file (after.<ext>, what the project holds after `ultracite
 * fix --claude/--codex`): does ESLint's prefer-ternary turn early returns back into a ternary, does
 * a fix pass brace a one-line guard, does leaked-render rewrite an `&&`, does a fix nest a ternary
 * again, and does any of it change behaviour? Runs through the mirror and Ultracite's real adapters.
 */
function fixPassesOnFinals(ids) {
  const { root, script } = linkedRoot("finals");
  const out = [];
  let n = 0;
  for (const id of ids) {
    const meta = JSON.parse(
      readFileSync(join(lib.RUNS_DIR, id, "meta.json"), "utf8")
    );
    const s = fullSubject(
      subjectsManifest().find((x) => x.id === meta.subject)
    );
    const text = readIf(join(lib.RUNS_DIR, id, `after${extOf(s)}`));
    if (text === null) continue;
    for (const [linter, unsafe] of COMMANDS) {
      n++;
      const r = fixPassOn({
        s,
        text,
        stubText: preparedStub(s),
        linter,
        unsafe,
        root,
        script,
        tag: `f${n}`,
      });
      const { afterText, ...row } = r;
      out.push({
        runId: id,
        subject: s.id,
        agent: meta.agent,
        ...row,
        // Ternaries the pass wrote: conditionals added, and nested trees.
        // An unchanged file has no counts (nothing was written back).
        ternaryBack:
          (r.edit.conditionals?.after ?? 0) >
          (r.edit.conditionals?.before ?? 0),
        nestedAgain: (r.edit.nested?.after ?? 0) > 0,
        bracedOneLineGuards:
          editFacts(text, s.basename).ifs.filter((i) => i.oneLine && i.returns)
            .length -
          (editFacts(afterText, s.basename).ifs ?? []).filter(
            (i) => i.oneLine && i.returns
          ).length,
      });
      const last = out.at(-1);
      console.log(
        `${id} ${linter}${unsafe ? " --unsafe" : ""}: code changed ${r.codeChanged}; ${r.edit.edit} [${r.edit.kinds.join(", ")}]; ternary back ${last.ternaryBack}; nested ${JSON.stringify(r.nestedReported)}; oracle ${r.oracle.vsPrepared}; real ${JSON.stringify(r.realAdapter)}`
      );
    }
  }
  return out;
}

