/**
 * Checks on a prepared subject: Ultracite's collect leaves every file unchanged (the prepared
 * project is the fix pass's fixed point); the handoff is exactly the rule's reports, as many as the
 * corpus measured on the subject as written; normalising changed no behaviour (the oracle's trace
 * equals the corpus subject's); the normalised stub module behaves as the corpus's on every
 * scenario; and it type-checks.
 */
function subjectChecks(s, text, stubText, corpusText, example) {
  const dir = scratch(`check-${s.id}`);
  writeFileSync(join(dir, s.basename), text);
  withRunFiles(dir, s);
  const laidOut = Object.fromEntries(
    readdirSync(dir).map((n) => [n, readFileSync(join(dir, n), "utf8")])
  );
  baselineCache.delete(s.id);
  const { diagnostics, info } = collect(s, dir);
  const changed = readdirSync(dir).filter(
    (n) => readFileSync(join(dir, n), "utf8") !== laidOut[n]
  );
  if (changed.length > 0)
    throw new Error(`${s.id}: the fix pass changes ${changed.join(", ")}`);
  if (!diagnostics.every((d) => isHandoffRule(d.rule) && d.file === s.basename))
    throw new Error(
      `${s.id}: the handoff is ${diagnostics.map((d) => `${d.file} ${d.rule}: ${d.message}`).join(", ")}`
    );
  const handed = countBy(diagnostics);
  const corpusCounts = Object.fromEntries(
    [...HANDOFF_RULES]
      .map((r) => [r, example.lint.oxlint.byRule[r] ?? 0])
      .filter(([, n]) => n > 0)
  );
  if (JSON.stringify(handed) !== JSON.stringify(corpusCounts))
    throw new Error(
      `${s.id}: the handoff ${JSON.stringify(handed)} differs from the corpus's ${JSON.stringify(corpusCounts)}`
    );
  // Normalising changed no behaviour: the corpus subject (with the corpus stub module, as the oracle
  // always runs it) against the prepared one.
  const corpusTrace = oracle.trace(s.oracleId, corpusText);
  const prepared = oracle.trace(s.oracleId, oracleText(s, text));
  const v = oracle.verdict(corpusTrace, prepared);
  const k = oracle.verdict(canonTrace(corpusTrace), canonTrace(prepared));
  const c = oracle.verdict(classTrace(corpusTrace), classTrace(prepared));
  if (c.verdict !== "same")
    throw new Error(
      `${s.id}: normalising changed behaviour (${JSON.stringify(c).slice(0, 400)})`
    );
  // The stub module the agent sees, in place of the corpus's.
  const withPreparedStub = traceWithStub(s, text, stubText);
  const stubVerdict = oracle.verdict(prepared, withPreparedStub);
  if (stubVerdict.verdict !== "same")
    throw new Error(
      `${s.id}: the normalised stub module behaves differently (${JSON.stringify(stubVerdict).slice(0, 400)})`
    );
  const tsc = typeErrors(s, text, `check-${s.id}-tsc`, stubText);
  if (tsc.length > 0)
    throw new Error(
      `${s.id}: type errors: ${tsc.map(typeErrorKey).join("; ")}`
    );
  const corpusStub = readFileSync(join(EXAMPLES, s.stubs.example), "utf8");
  const inv = corpusLib.inventory(text, s.basename);
  const cog = corpusLib.cognitiveOf(text, s.basename);
  return {
    fixPassUnchanged: true,
    handoff: diagnostics.map((d) => `${d.rule} L${d.line}: ${d.message}`),
    handoffCounts: handed,
    help: [...new Set(diagnostics.map((d) => d.help ?? null))],
    url: [...new Set(diagnostics.map((d) => d.url ?? null))],
    reportedBeforeFilter: info.diagnosticsReported,
    leftOutByFilter: info.leftOutByFilter,
    leftOutByFilterByFile: info.leftOutByFilterByFile,
    fileLines: {
      corpus: corpusText.split("\n").length,
      prepared: text.split("\n").length,
    },
    trees: inv.trees
      .filter((t) => t.members >= 2)
      .map((t) => ({
        line: t.line,
        lines: t.lines,
        shape: t.shape,
        position: t.position,
        members: t.members,
        text: t.text.slice(0, 200),
      })),
    cognitive: Object.fromEntries(
      cog.functions.map((f) => [f.name, f.cognitive])
    ),
    oracle: {
      calls: prepared.calls.length,
      hooks: prepared.hooks.length,
      import: prepared.import,
      verdictAgainstCorpusSubject: v.verdict,
      differingExactly: v.differing ?? 0,
      ignoringKeyOrder: k.verdict,
      ignoringClassOrder: c.verdict,
      withThePreparedStub: stubVerdict.verdict,
      note:
        v.verdict === "same"
          ? "the prepared subject's trace equals the corpus subject's in every scenario, with the corpus's stub module and with the prepared one"
          : "the prepared subject's trace differs from the corpus subject's only in the order of the classes in a className (Oxfmt sorts Tailwind classes); with each className's classes sorted they're the same. The prepared subject is the reference for every run",
    },
    stub: {
      name: s.stubs.name,
      corpusName: s.stubs.example,
      codeChangedByNormalising:
        codeOnly(stubText, s.stubs.name) !== codeOnly(corpusStub, s.stubs.name),
      linesChanged: lineChanges(corpusStub, stubText),
    },
    typeErrors: 0,
  };
}

/** The comment lines of a text that a PRIMING pattern matches (allowed lines skipped). */
function primedLines(text, name, allowed = new Set(), seen = new Set()) {
  const { comments, error } = commentsOf(text, name);
  if (error) throw new Error(`${name}: ${error}`);
  const primed = [];
  for (const c of comments)
    for (const line of commentLines(c)) {
      if (allowed.has(line)) {
        seen.add(line);
        continue;
      }
      for (const re of PRIMING)
        if (re.test(line)) primed.push(`${re} in "${line.slice(0, 90)}"`);
    }
  return primed;
}

/** Oxlint's reports on a text in a scratch project with the run files, counted by rule. */
function oxlintCounts(subject, text, tag) {
  const dir = scratch(tag);
  // The run files first: for a stub module, `text` replaces the prepared copy they include.
  withRunFiles(dir, subject);
  writeFileSync(join(dir, subject.basename), text);
  return countBy(oxlintHits(dir, subject.basename, CONFIG.oxlint));
}

/** What normalising did: the rules whose reports the fix pass removed, and whether code changed. */
function describeNormalisation(s, cleaned, prepared) {
  const before = oxlintCounts(s, cleaned, `norm-${s.id}-before`);
  const after = oxlintCounts(s, prepared, `norm-${s.id}-after`);
  const fixed = Object.fromEntries(
    Object.entries(before)
      .map(([r, n]) => [r, n - (after[r] ?? 0)])
      .filter(([, d]) => d > 0)
  );
  return {
    rulesFixed: fixed,
    oxlintBefore: before,
    oxlintAfter: after,
    codeChanged:
      codeOnly(cleaned, s.basename) !== codeOnly(prepared, s.basename),
  };
}

