      `| ${g} | ${pipe(counts(s.attempts))} | ${s.retried} | ${pipe(counts(s.retryPrompts))} | ${pipe(counts(s.retryTriggers))} | ${s.retriesATopicOnlyFilterWouldMake} | ${s.retryDecisionsReproduce} | ${pipe(counts(s.leftForReviewFinal))} / ${s.leftForReviewAnyAttempt} | ${pipe(counts(s.ultraciteOutro))} | ${pipe(counts(s.ultraciteNotes))} | ${s.ultraciteExitCode1} |`
