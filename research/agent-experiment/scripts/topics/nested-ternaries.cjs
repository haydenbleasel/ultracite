/** Rewrites every lint-suppression directive to a same-length non-directive. */
const neutralizeDirectives = (text) =>
  text
    .replace(/(eslint|oxlint)-(disable|enable)/g, "$1_$2")
    .replace(/biome-ignore/g, "biome_ignore")
    .replace(/@ts-(ignore|expect-error|nocheck)/g, "@ts_$1")
    .replace(/\/\*(\s*)eslint(\s)/g, "/*$1eslinx$2");

function oxlintHits(dir, name, config) {
  const r = spawnSync(
    process.execPath,
    [
      mirror.oxlintBin,
      "-c",
      config,
      "--disable-nested-config",
      "-f",
      "json",
      name,
    ],
    { cwd: dir, encoding: "utf8", maxBuffer: 1 << 28 }
  );
  const start = r.stdout.indexOf("{");
  if (start === -1)
    throw new Error(`oxlint ${basename(config)}: ${r.stderr.slice(0, 300)}`);
  const report = JSON.parse(r.stdout.slice(start));
  return report.diagnostics
    .filter(
      (d) =>
        !d.filename || d.filename === name || d.filename.endsWith(`/${name}`)
    )
    .map((d) => ({
      rule: d.code ? mirror.toOxlintRuleName(d.code) : `parse: ${d.message}`,
      line: d.labels?.[0]?.span?.line ?? null,
      message: d.message,
    }));
}

// One ESLint instance per subject and inline-config mode, linting a file in a fixed scratch dir
// (loading the presets' plugins takes seconds).
const eslintInstances = new Map();
function eslintFor(subject, honor) {
  const key = `${subject.id}|${honor}`;
  if (!eslintInstances.has(key)) {
    const dir = scratch(`eslint-view-${subject.id}-${honor}-${process.pid}`);
    withRunFiles(dir, subject);
    eslintInstances.set(key, {
      dir,
      eslint: new ESLint({
        cwd: dir,
        errorOnUnmatchedPattern: false,
        overrideConfigFile: CONFIG.eslint,
        overrideConfig: [
          {
            linterOptions: {
              noInlineConfig: !honor,
              reportUnusedDisableDirectives: "off",
            },
          },
        ],
      }),
    });
  }
  return eslintInstances.get(key);
}
async function eslintHits(subject, text, honor) {
  const { dir, eslint } = eslintFor(subject, honor);
  writeFileSync(join(dir, subject.basename), text);
  const [result] = await eslint.lintFiles([subject.basename]);
  return (result?.messages ?? [])
    .filter((m) => !isReactDoctor(m.ruleId))
    .map((m) => ({
      rule: m.ruleId ?? (m.fatal ? `parse: ${m.message}` : "eslint"),
      line: m.line ?? null,
      message: m.message,
    }));
}

/** Biome core and react, `biome check`, with init's package.json at the root of a copy. */
function biomeHits(subject, dir) {
  copyFileSync(CONFIG.biome, join(dir, "biome.jsonc"));
  copyFileSync(
    join(INIT_DIR, "biome", "package.json"),
    join(dir, "package.json")
  );
  chmodSync(join(dir, "package.json"), 0o644);
  writeFileSync(join(dir, ".gitignore"), "node_modules\n");
  const r = spawnSync(
    process.execPath,
    [
      mirror.biomeBin,
      "check",
      "--reporter=json",
      "--max-diagnostics=none",
      subject.basename,
    ],
    { cwd: dir, encoding: "utf8", maxBuffer: 1 << 28 }
  );
  const report = JSON.parse(r.stdout.slice(r.stdout.indexOf("{")));
  return (report.diagnostics ?? [])
    .filter((d) => /^(lint|assist|parse|format)/.test(d.category ?? ""))
    .map((d) => ({
      rule: (d.category ?? "").replace(/^lint\//, ""),
      line: d.location?.start?.line ?? null,
      message: typeof d.message === "string" ? d.message : null,
    }));
}

const sortHits = (hits) =>
  [...hits].sort(
    (a, b) =>
      (a.line ?? 0) - (b.line ?? 0) ||
      String(a.rule).localeCompare(String(b.rule)) ||
      String(a.message).localeCompare(String(b.message))
  );

/** Every view of one state: hits honouring and ignoring inline config. */
async function lintViews(text, subject, tag) {
  const out = {};
  for (const [mode, t] of [
    ["honor", text],
    ["ignore", neutralizeDirectives(text)],
  ]) {
    const honor = mode === "honor";
    const oxDir = scratch(`${tag}-${mode}-oxlint`);
    writeFileSync(join(oxDir, subject.basename), t);
    withRunFiles(oxDir, subject);
    const bioDir = scratch(`${tag}-${mode}-biome`);
    writeFileSync(join(bioDir, subject.basename), t);
    withRunFiles(bioDir, subject);
    for (const f of NESTED_CONFIGS) rmSync(join(bioDir, f), { force: true });
    const hits = {
      oxlint: oxlintHits(oxDir, subject.basename, CONFIG.oxlint),
      eslint: await eslintHits(subject, t, honor),
      biome: biomeHits(subject, bioDir),
    };
    for (const view of VIEWS) {
      out[view] ??= {};
      out[view][mode] = sortHits(hits[view]);
    }
  }
  return out;
}

