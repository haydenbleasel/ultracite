/** Cohen's kappa for two raters' labels over the same items. */
function kappa(pairs) {
  const n = pairs.length;
  if (n === 0) return null;
  const cats = [...new Set(pairs.flat())];
  const agree = pairs.filter(([a, b]) => a === b).length / n;
  // Every label the same on both sides: agreement is complete and kappa is undefined.
  if (cats.length === 1)
    return {
      n,
      agreement: Math.round(agree * 1000) / 1000,
      kappa: null,
      note: "both raters gave every item the same label, so kappa is undefined",
    };
  let pe = 0;
  for (const c of cats) {
    const p1 = pairs.filter(([a]) => a === c).length / n;
    const p2 = pairs.filter(([, b]) => b === c).length / n;
    pe += p1 * p2;
  }
  return {
    n,
    agreement: Math.round(agree * 1000) / 1000,
    kappa: pe === 1 ? 1 : Math.round(((agree - pe) / (1 - pe)) * 1000) / 1000,
  };
}

/** Each hand-made mutant and corpus variant through every view, Ultracite's verify and the oracle. */
