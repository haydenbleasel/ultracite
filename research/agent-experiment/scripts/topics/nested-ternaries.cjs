/**
 * Runs Ultracite's own `init` (the CLI source, under Bun) in a scratch project, non-interactively,
 * with React selected and without installing anything, and returns every file it wrote or changed
 * (path -> text).
 */
function runInit(linter) {
  const dir = scratch(`init-${linter}`);
  writeFileSync(join(dir, "package.json"), STARTING_PACKAGE_JSON);
  writeFileSync(join(dir, "tsconfig.json"), TSCONFIG());
  const r = spawnSync("bun", INIT_ARGS(linter), {
    cwd: dir,
    encoding: "utf8",
    input: "",
  });
  if (r.status !== 0)
    throw new Error(`init --linter ${linter} failed: ${r.stderr.slice(-400)}`);
  const files = {};
  const before = {
    "package.json": STARTING_PACKAGE_JSON,
    "tsconfig.json": TSCONFIG(),
  };
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else {
        const rel = relative(dir, p);
        const text = readFileSync(p, "utf8");
        if (before[rel] !== text) files[rel] = text;
      }
    }
  };
  walk(dir);
  return Object.fromEntries(
    Object.entries(files).sort(([a], [b]) => a.localeCompare(b))
  );
}

