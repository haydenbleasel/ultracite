// The nested-ternaries post: Ultracite turns ESLint's `no-nested-ternary` on (Oxlint core, ESLint
// core, Biome's `noNestedTernary`), with `unicorn/prefer-ternary`, `curly`, `no-else-return` and
// the other conditional rules around it. No linter fixes a nested ternary, so in a real project
// `ultracite fix --claude` or `--codex` is what rewrites one. When Ultracite hands the report to an
// agent: does it rewrite without changing behaviour; does the rewrite fit the position (early
// returns where there's a `return`; a variable, helper or child component in JSX); does it fall for
// the rewrites that look equivalent and aren't (a lookup object that evaluates every branch, `&&`
// that renders `0`, an `||` chain); does the result use the maintainer's `if (bool) return x;`
// shape, and does it read better; and what do Ultracite's other rules and fix passes do to the
// agent's edit?
//
// Subjects come from research/corpus/examples/nested-ternaries/ (nested-ternaries-examples.cjs):
//   a  Next.js's denormalize-page-path.ts: a two-test chain that is the function's return value.
//      Right: early returns (or if/else) in the same test order, same behaviour.
//   b  Supabase Studio's ExplorerNavNotebooks.tsx: a loading / empty / list chain, a JSX child
//      inside two wrappers where no statement can go. Right: a variable set above the return, a
//      helper that returns early, or a child component; `&&` with a number renders `0`.
//   c  Astro's vite-plugin-config-alias getConfigAlias: a chain in a `.map` callback's concise
//      body whose first branch runs `++matchId`. Right: a block body with early returns, a switch
//      or a lookup of functions. An object lookup increments the counter for every character.
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks), with
// the mirror of Ultracite's agent-fix code at its v3 revision (the CLI at 9743dfcb; see
// scripts/ultracite-adapters.cjs), which this module selects. The run dir is exactly what
// `ultracite init --linter oxlint --frameworks react` leaves (generated by running init), with the
// subjects' tsconfig.json and the subject's stub module. The rule is on there already; the user
// changes nothing.
//
// The handoff. The subjects are real code, and Ultracite's presets report other rules on them (C's
// `no-plusplus` is on the very line that matters). prepareSubjects runs the Oxlint pass until nothing
// changes (checked not to change behaviour), and the handoff, and every re-lint, keep
// no-nested-ternary and any other diagnostic that is new since the prepared subject (by Ultracite's
// own rule-and-message key, diff.ts). That models a project that lints clean apart from this rule.
// It is a deviation from a real project, recorded in handoff.json and REPORT.md, and every
// diagnostic of every view is measured.
//
// Each attempt is measured as the agent left the file and as verify left it: Oxlint (the user's
// config), ESLint (core + react, as init writes it), Biome (core + react), inline config honoured
// and ignored; tsc; the behaviour oracle (the corpus's nested-ternaries-oracle.cjs, imported
// unchanged); what the edit did (the rewrite, the one-line guard shape, cognitive complexity with
// the corpus's scorer, lines, what else changed); Ultracite's own partition and what it would print;
// and the session logs.
//
// See scripts/topics.cjs for the hooks this module implements.
