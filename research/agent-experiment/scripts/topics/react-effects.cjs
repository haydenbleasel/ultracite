/**
 * A string that was cut to length before it was redacted (session-stats.cjs truncates Codex's tool
 * inputs to 600 characters) can end in part of the home directory, which redaction doesn't see.
 * Any such tail is replaced by "~", everywhere in a value.
 */
const HOME = homedir();
function scrubCutHome(value) {
  if (typeof value === "string") {
    for (let k = HOME.length - 1; k >= 3; k--)
      if (value.endsWith(HOME.slice(0, k))) return `${value.slice(0, -k)}~`;
    return value;
  }
  if (Array.isArray(value)) return value.map(scrubCutHome);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, scrubCutHome(v)])
    );
  return value;
}

