// Every hook and React Compiler rule (rules-of-hooks among them), for the per-view counts.
const isHookRule = (raw) => {
  const rule = bareRule(raw);
  return (
    isDepRule(rule) ||
    /^react-hooks\//.test(rule) ||
    /^react\/(hooks|rules-of-hooks|set-state-in-effect|set-state-in-render|no-deriving-state-in-effects|rule-suppression|refs|purity|immutability|globals|use-memo|void-use-memo|preserve-manual-memoization|incompatible-library|static-components|capitalized-calls|error-boundaries|unsupported-syntax|invariant|todo|syntax)$/.test(
      rule
    ) ||
    rule === "correctness/useHookAtTopLevel"
  );
};
const isSuppressionRule = (rule) => rule === "react/rule-suppression";
