// The React effects post: when Ultracite hands a coding agent Oxlint's dependency-array
// diagnostics (`react-hooks/exhaustive-deps`, "React Hook useEffect has a missing dependency: 'x'",
// help "Either include it or remove the dependency array.", and the React Compiler rule
// `react/exhaustive-effect-dependencies`, "Found missing effect dependencies"), what does the agent
// do with an effect whose warning is a real bug, one whose obvious fix breaks it, and one whose
// omission is deliberate? And what do Ultracite's retry loop and its "Left for review" line do?
//
// Subjects come from research/corpus/examples/react-effects/ (effects-examples.cjs):
//   a  Hono's useSyncExternalStore (hono/jsx, 2026, before honojs/hono#5166): the effect subscribes
//      once, so a component that switches stores keeps the old subscription and shows the old
//      store's value. Listing the dependencies resubscribes but keeps showing the old value until
//      the new store changes; the project's fix also reads the new snapshot.
//   b  Supabase Studio's TimeInput (2026): two effects call `validate`, a function declared during
//      render below them. Adding it to the arrays throws on the first render (TDZ); moving it up and
//      listing everything makes typing revert. useEffectEvent keeps the behaviour.
//   c  Excalidraw's useTTDChatStorage (2026): two effects that omit `loadChats` and
//      `saveCurrentChat` on purpose (suppressed upstream; the suppressions are removed here). Adding
//      the save function saves the chat on every prompt keystroke. Oxlint's compiler rule keeps
//      reporting the auto-save effect's trigger dependencies as extra after any behaviour-preserving
//      edit.
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks):
// Ultracite's Oxlint pass on the project (oxlint --fix, oxfmt --write, then oxlint -f json), then
// up to three agent attempts, each verified with the adapter's pass on the file. Oxlint's
// dependency fix is dangerous, so `ultracite fix` doesn't apply it and the diagnostics reach the
// agent. The run dir is what `ultracite init --linter oxlint --frameworks react` leaves (its
// oxlint.config.ts, oxfmt.config.ts and package.json, generated by running init), with the
// tsconfig.json the subjects need.
//
// The handoff. The subjects are verbatim code, and Ultracite's presets report many other rules on
// them (compiler rules, rules-of-hooks in A, core rules). prepareSubjects runs the Oxlint pass until
// nothing changes (checked not to touch the hooks under test), and the handoff, and every re-lint,
// keep the two dependency rules and any other diagnostic that is new since the prepared subject (by
// Ultracite's own rule-and-message key, diff.ts), such as `react/rule-suppression` after a
// suppression comment. That models a project that lints clean apart from the dependency arrays. It
// is a deviation from a real project, recorded in handoff.json and REPORT.md, and every diagnostic
// of every view is still measured.
//
// Each run is measured after each attempt (the file as the agent left it, and as verify left it)
// and at the end: the dependency rules and every rule of Oxlint react, ESLint react (whose react
// block skips .ts files), ESLint react on every file (a counterfactual) and Biome react (inline
// config honoured and ignored), tsc with React 19's types, the behaviour oracle (the corpus's
// effects-oracle.cjs, imported unchanged) in both of each subject's modes, what the edit did to the
// effects under test (dependencies added or removed, memoised, Effect Events, refs, updater
// functions, code moved, the effect restructured), suppressions and other files, Ultracite's own
// partition and what it would print, and the session logs (cost, tokens, tool calls, commands, the
// final message, what the agent said about behaviour, stale values, loops, the TDZ, mount-only
// intent and useEffectEvent, and every read outside the run dir).
//
// See scripts/topics.cjs for the hooks this module implements.
