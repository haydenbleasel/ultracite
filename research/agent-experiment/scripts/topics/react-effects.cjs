const referenceTraces = new Map();
/**
 * The prepared subject's trace: the reference every state is compared with. It equals the corpus's
 * prepared subject's apart from hook line labels (subjectChecks).
 */
function referenceTrace(subject) {
  if (!referenceTraces.has(subject.base)) {
    const dir = scratch(`reference-${subject.base}-${process.pid}`);
    const file = join(dir, subject.basename);
    copyFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), file);
    chmodSync(file, 0o644);
    const r = oracle.runOracle(subject.oracleId, file);
    if (!r.ok) throw new Error(`${subject.id}: oracle: ${r.error}`);
    referenceTraces.set(subject.base, r.trace);
  }
  return referenceTraces.get(subject.base);
}

const subscriptions = (m) =>
  (m?.events ?? []).filter((e) => e.startsWith("subscribe")).length;

/**
 * The oracle on a source text, in its own process (agent-written code never runs here). Returns the
 * oracle's verdict over both modes and each mode's own: for A, each mode judged against the bug's
 * definition (the oracle reads the `stable` mode, so the other is passed as `stable`) with its
 * subscription count; for B and C, each mode against the reference's same mode.
 */
function judge(subject, text, tag, reference = referenceTrace(subject)) {
  const dir = scratch(tag);
  const file = join(dir, subject.basename);
  writeFileSync(file, text);
  const r = oracle.runOracle(subject.oracleId, file);
  if (!r.ok)
    return {
      error: r.error,
      verdict: "broken",
      differences: [String(r.error).slice(0, 300)],
      modes: {},
    };
  const v = oracle.verdict(subject.oracleId, reference, r.trace);
  const modes = {};
  for (const mode of Object.keys(reference)) {
    const one =
      subject.oracleId === "a"
        ? oracle.verdict(
            "a",
            { stable: reference[mode] },
            { stable: r.trace[mode] }
          )
        : oracle.verdict(
            subject.oracleId,
            { [mode]: reference[mode] },
            { [mode]: r.trace[mode] }
          );
    const m = r.trace[mode];
    // How often effects ran (setups of useEffect, useLayoutEffect and useInsertionEffect, every
    // hook together): an edit can keep what an effect does and still run it more often.
    const effectRuns = (t) =>
      Object.entries(t?.setups ?? {})
        .filter(([k]) => /^use(Layout|Insertion)?Effect@/.test(k))
        .reduce((n, [, v]) => n + v, 0);
    modes[mode] = {
      verdict: one.verdict,
      effectRuns: effectRuns(m),
      effectRunsAsWritten: effectRuns(reference[mode]),
      ...(subject.oracleId === "a"
        ? {
            subscriptions: subscriptions(m),
            subscriptionsAsWritten: subscriptions(reference[mode]),
            texts: (m?.steps ?? []).map((x) => x.text),
          }
        : {}),
      ...(subject.oracleId === "c"
        ? {
            saves: m?.steps?.at(-1)?.saves ?? null,
            savesAsWritten: reference[mode].steps.at(-1).saves,
            loads: m?.steps?.at(-1)?.loads ?? null,
            loadsAsWritten: reference[mode].steps.at(-1).loads,
            savesWhileTyping: m?.steps
              ? m.steps.find((x) => x.label === "typing the next prompt")
                  .saves -
                m.steps.find((x) => x.label === "response finishes").saves
              : null,
          }
        : {}),
      errors: (m?.errors ?? []).slice(0, 3),
    };
  }
  return {
    error: null,
    verdict: v.verdict,
    differences: v.differences,
    modes,
  };
}

// ---------------------------------------------------------------- what the edit did

/** The code without comments or formatting: equal for two texts that differ only in those. */
function codeOnly(text, name) {
  const sf = ts.createSourceFile(
    name,
    text,
    ts.ScriptTarget.Latest,
    false,
    scriptKind(name)
  );
  return ts.createPrinter({ removeComments: true }).printFile(sf);
}
const loose = (s) => String(s ?? "").replaceAll(/[{};\s]/g, "");

// A dependency names a value the rule asked for: the name itself or a member path on it.
const namesValue = (dep, name) =>
  dep === name || dep.startsWith(`${name}.`) || dep.startsWith(`${name}?.`);

/**
 * What the edit did to the effects under test, against the file it was given: for each effect, the
 * dependencies added (and whether they're the ones the rule asked for) and removed (and whether they
 * were triggers), whether its callback changed, or that it's gone; the hooks and constructs added
 * (Effect Events, refs, useCallback, useMemo, updater functions, effects); where the subject's
 * functions went (B's validate, C's loadChats and saveCurrentChat): wrapped, moved into an effect,
 * moved above the effects. `kinds` lists every category that applies; `edit` is the headline.
 */
function editOf(subject, text, beforeText) {
  if (text === beforeText)
    return { edit: "unchanged", kinds: [], targets: [], added: {} };
  const after = hooksOf(text, subject.basename);
  if (after.parseErrors > 0)
    return { edit: "doesn't parse", kinds: [], targets: [], added: {} };
  if (
    codeOnly(text, subject.basename) === codeOnly(beforeText, subject.basename)
  )
    return {
      edit: "comments or formatting only",
      kinds: [],
      targets: [],
      added: {},
    };
  const before = hooksOf(beforeText, subject.basename);
  const tb = targetsOf(subject, before);
  const ta = targetsOf(subject, after);
  const targets = subject.targets.map((t, i) => {
    const b = tb[i];
    const a = ta[i];
    if (!a.found) return { name: t.name, status: "gone" };
    const bdeps = b.found ? b.deps : [];
    const added = a.deps.filter((d) => !bdeps.includes(d));
    const gone = bdeps.filter((d) => !a.deps.includes(d));
    // A named value, or a useCallback/useMemo in this file that wraps one (B's validate).
    const asks = (d) =>
      t.missing.some(
        (m) =>
          namesValue(d, m) ||
          (["useCallback", "useMemo"].includes(after.locals.get(d)?.kind) &&
            new RegExp(`\\b${lib.escapeRegExp(m)}\\b`).test(
              after.locals.get(d).text
            ))
      );
    const addedAsked = added.filter(asks);
    // A dependency that's gone but still there in another form: extracted to a variable
    // (`const minimumKey = JSON.stringify(minimumTime)`), or replaced by the value it reads
    // (`minimumTime` for `JSON.stringify(minimumTime)`).
    const identifiersOf = (d) => new Set(d.match(/[A-Za-z_$][\w$]*/g) ?? []);
    const extracted = gone.filter((d) =>
      added.some((x) => after.consts.get(x) === d)
    );
    const replacedByValue = gone.filter(
      (d) =>
        !extracted.includes(d) &&
        added.some(
          (x) => /^[A-Za-z_$][\w$]*$/.test(x) && identifiersOf(d).has(x)
        )
    );
    const removed = gone.filter(
      (d) => !extracted.includes(d) && !replacedByValue.includes(d)
    );
    return {
      name: t.name,
      status:
        added.length === 0 && removed.length === 0
          ? loose(a.callback) === loose(b.callback)
            ? "unchanged"
            : "callback changed"
          : "dependencies changed",
      hook: a.hook,
      line: a.line,
      deps: a.deps,
      depsBefore: bdeps,
      added,
      addedAsked,
      removed,
      extracted,
      replacedByValue,
      removedTriggers: removed.filter((d) => t.triggers.includes(d)),
      callbackChanged: loose(a.callback) !== loose(b.callback),
      callsEffectEvent: after.effects
        .find((fx) => fx.line === a.line)
        ?.calls.some((n) => after.locals.get(n)?.kind === "useEffectEvent"),
    };
  });
  const added = Object.fromEntries(
    [
      ...COUNTED_HOOKS.map((h) => [h, after.counts[h] - before.counts[h]]),
      ["effects", after.effects.length - before.effects.length],
      ["updaters", after.updaters - before.updaters],
      ["refCurrentReads", after.refCurrentReads - before.refCurrentReads],
    ].filter(([, d]) => d !== 0)
  );
  const firstTarget = Math.min(
    ...after.effects
      .filter((fx) => ta.some((t) => t.found && t.line === fx.line))
      .map((fx) => fx.start)
  );
  const functions = subject.functions.map((f) => {
    const bl = before.locals.get(f.name);
    const al = after.locals.get(f.name);
    const inEffect = after.effects.some((fx) => fx.callback.includes(f.marker));
    return {
      name: f.name,
      before: bl ? bl.kind : "absent",
      after: al
        ? al.insideEffect
          ? `${al.kind} inside an effect`
          : al.kind
        : "absent",
      movedIntoEffect:
        (al ? al.insideEffect : false) ||
        (inEffect &&
          !before.effects.some((fx) => fx.callback.includes(f.marker))),
      movedAboveEffects: Boolean(
        al &&
        bl &&
        !al.insideEffect &&
        al.start < firstTarget &&
        !(bl.start < Math.min(...before.effects.map((fx) => fx.start)))
      ),
      wrapped:
        al && bl && al.kind !== bl.kind && !al.insideEffect ? al.kind : null,
    };
  });
  const suppressionAdded = sumValues(scan(text)) > sumValues(scan(beforeText));
  const kinds = [];
  if (suppressionAdded) kinds.push("suppression");
  if ((added.useEffectEvent ?? 0) > 0) kinds.push("useEffectEvent");
  if ((added.useRef ?? 0) > 0) kinds.push("a ref");
  if (
    (added.useCallback ?? 0) > 0 ||
    (added.useMemo ?? 0) > 0 ||
    functions.some((f) => ["useCallback", "useMemo"].includes(f.wrapped))
  )
    kinds.push("memoised");
  if (functions.some((f) => f.movedIntoEffect))
    kinds.push("moved code into the effect");
  if (functions.some((f) => f.movedAboveEffects))
    kinds.push("moved a declaration above the effects");
  if ((added.updaters ?? 0) > 0) kinds.push("an updater function");
  if (targets.some((t) => (t.addedAsked ?? []).length > 0))
    kinds.push("added the dependencies");
  if (targets.some((t) => (t.extracted ?? []).length > 0))
    kinds.push("extracted a dependency to a variable");
  if (targets.some((t) => (t.replacedByValue ?? []).length > 0))
    kinds.push("replaced a dependency with the value it reads");
  if (targets.some((t) => (t.removed ?? []).length > 0))
    kinds.push(
      targets.some((t) => (t.removedTriggers ?? []).length > 0)
        ? "removed trigger dependencies"
        : "removed dependencies"
    );
  if (targets.some((t) => t.status === "gone") || (added.effects ?? 0) !== 0)
    kinds.push("removed or restructured the effect");
  if (kinds.length === 0) kinds.push("other code edited");
  // The headline, by what most changes how the effect runs.
  const has = (k) => kinds.includes(k);
  let edit;
  if (has("suppression")) edit = "suppression";
  else if (has("useEffectEvent")) edit = "useEffectEvent";
  else if (has("a ref")) edit = "a ref";
  else if (has("moved code into the effect"))
    edit = "moved code into the effect";
  else if (has("memoised") && has("added the dependencies"))
    edit = "added the dependencies and memoised";
  else if (has("memoised")) edit = "memoised";
  else if (has("an updater function")) edit = "an updater function";
  else if (has("removed or restructured the effect"))
    edit = "removed or restructured the effect";
  else if (
    has("added the dependencies") &&
    kinds.some((k) => /^removed (trigger )?dependencies$/.test(k))
  )
    edit = "added and removed dependencies";
  else if (has("added the dependencies"))
    edit = "added the dependencies as the rule asks";
  else if (has("removed trigger dependencies"))
    edit = "removed trigger dependencies";
  else if (has("removed dependencies")) edit = "removed dependencies";
  else edit = "other code edited";
  return { edit, kinds, targets, added, functions };
}

