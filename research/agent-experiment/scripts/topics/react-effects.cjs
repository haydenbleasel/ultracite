/**
 * A scratch root whose node_modules is what `ultracite init` installs, by link: ultracite (this
 * repo's packages/cli), the linters and formatters and their .bin entries, and the packages init
 * adds that packages/cli doesn't resolve (from the Bun store). Projects go in its subfolders. The
 * script runs Ultracite's linters.ts adapter under Bun: `fixAndCollect` on the project or `verify` on
 * one file, with a passthrough (`--unsafe` for `ultracite fix --unsafe`).
 */
function linkedRoot(tag) {
  const root = scratch(tag);
  mkdirSync(join(root, "node_modules/.bin"), { recursive: true });
  const link = (to, from) => {
    mkdirSync(dirname(from), { recursive: true });
    symlinkSync(to, from);
  };
  const pkgDir = (name, base) =>
    dirname(require.resolve(`${name}/package.json`, { paths: [base] }));
  link(CLI, join(root, "node_modules/ultracite"));
  for (const name of ["eslint", "prettier", "stylelint", "@biomejs/biome"])
    link(pkgDir(name, CLI), join(root, "node_modules", name));
  for (const name of ["oxlint", "oxfmt"])
    link(pkgDir(name, REPO), join(root, "node_modules", name));
  for (const name of [
    "prettier-plugin-tailwindcss",
    "stylelint-config-standard",
    "stylelint-config-idiomatic-order",
  ])
    link(storePackage(name), join(root, "node_modules", name));
  link(mirror.eslintBin, join(root, "node_modules/.bin/eslint"));
  link(mirror.prettierBin, join(root, "node_modules/.bin/prettier"));
  link(mirror.stylelintBin, join(root, "node_modules/.bin/stylelint"));
  link(mirror.biomeBin, join(root, "node_modules/.bin/biome"));
  link(mirror.oxlintBin, join(root, "node_modules/.bin/oxlint"));
  link(mirror.oxfmtBin, join(root, "node_modules/.bin/oxfmt"));
  const script = join(root, "real.ts");
  writeFileSync(
    script,
    [
      `import { getLinterAdapter } from ${JSON.stringify(join(CLI, "src/agent-fix/linters.ts"))};`,
      "const [linter, mode, passthroughJson, file] = process.argv.slice(2);",
      "const adapter = getLinterAdapter(linter);",
      "const passthrough = JSON.parse(passthroughJson);",
      'const out = mode === "collect" ? adapter.fixAndCollect([], passthrough) : adapter.verify(file, passthrough);',
      "console.log(JSON.stringify(out));",
    ].join("\n")
  );
  return { root, script };
}

/** Runs Ultracite's own adapter (linters.ts, under Bun) in a project dir. */
function realAdapter(
  script,
  linter,
  mode,
  cwd,
  { file = null, passthrough = [] } = {}
) {
  const r = spawnSync(
    "bun",
    [
      script,
      linter,
      mode,
      JSON.stringify(passthrough),
      ...(file ? [file] : []),
    ],
    { cwd, encoding: "utf8", maxBuffer: 1 << 28 }
  );
  if (r.status !== 0) return { error: String(r.stderr).slice(-400) };
  return { diagnostics: JSON.parse(r.stdout.trim().split("\n").at(-1)) };
}

const relFile = (cwd, file) => {
  for (const d of [cwd, existsSync(cwd) ? realpathSync(cwd) : cwd]) {
    const r = relative(d, file);
    if (!r.startsWith("..")) return r;
  }
  return file;
};
// ESLint's React Compiler rules print the file's absolute path in their messages.
const shape = (cwd, ds) =>
  ds.map((d) => ({
    column: d.column,
    fatal: d.fatal ?? false,
    file: relFile(cwd, d.file),
    help: d.help ?? null,
    line: d.line,
    message: [existsSync(cwd) ? realpathSync(cwd) : cwd, cwd].reduce(
      (m, dir) => m.split(dir).join("<project>"),
      d.message
    ),
    rule: d.rule,
    severity: d.severity,
    url: d.url ?? null,
  }));
const treeTexts = (dir) =>
  Object.fromEntries(
    readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile())
      .map((e) => e.name)
      .sort()
      .map((n) => [n, readFileSync(join(dir, n), "utf8")])
  );

/** Copies what init wrote for a linter into a project dir, under the real names. */
function putInitFiles(dir, linter) {
  for (const stored of readdirSync(join(INIT_DIR, linter))) {
    const name = realName(stored);
    copyFileSync(join(INIT_DIR, linter, stored), join(dir, name));
    chmodSync(join(dir, name), 0o644);
  }
}

/**
 * Runs Ultracite's real Oxlint adapter (packages/cli/src/agent-fix/linters.ts, under Bun) in a
 * project laid out as `ultracite init --linter oxlint --frameworks react` leaves one (init's own
 * oxlint.config.ts and oxfmt.config.ts, which import `ultracite/...`, with node_modules links), next
 * to the harness's mirror (configs passed with -c), on the prepared subjects and the mutants, and
 * compares every diagnostic (every field but `raw`, before the handoff filter) and the files each
 * pass leaves.
 */
function mirrorEquivalence() {
  const { root, script } = linkedRoot("mirror-check");
  const subjects = subjectsManifest();
  const inputs = subjects.map((s) => ({
    subject: s,
    name: `${s.id} as prepared`,
    text: readFileSync(join(HERE, s.path), "utf8"),
  }));
  for (const m of mutantsFile())
    inputs.push({
      subject: subjects.find((x) => x.base === m.base),
      name: m.id,
      text: mutantText(m),
    });
  const cases = [];
  for (const input of inputs) {
    const s = input.subject;
    const realDir = join(root, `real-${cases.length}`);
    const mirrorDir = join(root, `mirror-${cases.length}`);
    for (const d of [realDir, mirrorDir]) {
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, s.basename), input.text);
      withRunFiles(d);
    }
    // The real project gets the config files exactly as init wrote them (not yet formatted).
    putInitFiles(realDir, "oxlint");
    const real = {};
    const ours = {};
    for (const mode of ["collect", "verify"]) {
      if (mode === "verify") {
        writeFileSync(join(realDir, s.basename), input.text);
        writeFileSync(join(mirrorDir, s.basename), input.text);
      }
      const r = realAdapter(script, "oxlint", mode, realDir, {
        file: mode === "verify" ? s.basename : null,
      });
      real[mode] = r.error
        ? r
        : {
            diagnostics: shape(realDir, r.diagnostics),
            files: treeTexts(realDir),
          };
      const m = adapterPass(
        mirrorDir,
        mode === "collect" ? [] : [s.basename]
      ).diagnostics;
      ours[mode] = {
        diagnostics: shape(mirrorDir, m),
        files: treeTexts(mirrorDir),
      };
    }
    // The config files differ by design (init's import `ultracite/...`; the mirror passes its own
    // by path), so the files compared are the subject and the run files both passes format.
    const compared = [s.basename, "package.json", "tsconfig.json"];
    const pick = (files) =>
      Object.fromEntries(compared.map((n) => [n, files?.[n] ?? null]));
    const same = (mode) =>
      !real[mode].error &&
      JSON.stringify(real[mode].diagnostics) ===
        JSON.stringify(ours[mode].diagnostics) &&
      JSON.stringify(pick(real[mode].files)) ===
        JSON.stringify(pick(ours[mode].files));
    const c = {
      name: input.name,
      collectMatches: same("collect"),
      verifyMatches: same("verify"),
      diagnostics: ours.verify.diagnostics.length,
      dependencyRules: ours.verify.diagnostics.filter((d) =>
        isHandoffRule(d.rule)
      ).length,
      realError: real.collect.error ?? real.verify.error ?? null,
    };
    c.pass = c.collectMatches && c.verifyMatches;
    cases.push(c);
    console.log(
      `${c.pass ? "OK  " : "BAD "} mirror ${c.name}: collect ${c.collectMatches}, verify ${c.verifyMatches}, ${c.diagnostics} diagnostics (${c.dependencyRules} from the dependency rules)${c.realError ? ` ${c.realError}` : ""}`
    );
  }
  return {
    note: "Ultracite's own linters.ts Oxlint adapter (fixAndCollect and verify, run under Bun in a project with init's oxlint.config.ts and oxfmt.config.ts, which import `ultracite/...`, and node_modules links to this repo's packages) against the harness's mirror (scripts/ultracite-adapters.cjs, configs passed with -c), on the same files: every diagnostic (every field but `raw`, before the handoff filter) and the subject, package.json and tsconfig.json each pass leaves must match.",
    cases,
  };
}

