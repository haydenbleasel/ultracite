/**
 * What a prepared subject must satisfy: the adapter's collect leaves every file of the project
 * unchanged; the handoff filter keeps exactly the subject's dependency reports, each on an effect
 * under test; normalising changed no effect under test (hook, dependency array and callback, with
 * comments and formatting ignored) and no behaviour (the oracle's trace equals the corpus prepared
 * subject's, in both modes); and it type-checks.
 */
function subjectChecks(s, text, cleaned, corpusPrepared) {
  const dir = scratch(`check-${s.id}`);
  writeFileSync(join(dir, s.basename), text);
  withRunFiles(dir);
  const laidOut = Object.fromEntries(
    readdirSync(dir).map((n) => [n, readFileSync(join(dir, n), "utf8")])
  );
  baselineCache.delete(s.id);
  const { diagnostics, info } = collect(s, dir);
  const changed = readdirSync(dir).filter(
    (n) => readFileSync(join(dir, n), "utf8") !== laidOut[n]
  );
  if (changed.length > 0)
    throw new Error(`${s.id}: the fix pass changes ${changed.join(", ")}`);
  if (
    diagnostics.length === 0 ||
    !diagnostics.every((d) => isHandoffRule(d.rule))
  )
    throw new Error(
      `${s.id}: the handoff is ${diagnostics.map((d) => d.rule).join(", ")}`
    );
  // Each report sits on an effect under test (its call or its array).
  const h = hooksOf(text, s.basename);
  const targets = targetsOf(s, h);
  if (!targets.every((t) => t.found))
    throw new Error(`${s.id}: an effect under test wasn't found`);
  const spans = h.effects.filter((fx) =>
    targets.some((t) => t.line === fx.line)
  );
  for (const d of diagnostics)
    if (!spans.some((fx) => d.line >= fx.line && d.line <= fx.endLine))
      throw new Error(
        `${s.id}: a dependency report on line ${d.line} isn't on an effect under test`
      );
  // Normalising changed no effect under test.
  const shapes = {
    corpus: targetShape(s, corpusPrepared),
    cleaned: targetShape(s, cleaned),
    prepared: targetShape(s, text),
  };
  if (
    JSON.stringify(shapes.corpus) !== JSON.stringify(shapes.prepared) ||
    JSON.stringify(shapes.cleaned) !== JSON.stringify(shapes.prepared)
  )
    throw new Error(
      `${s.id}: normalising changed an effect under test: ${JSON.stringify(shapes)}`
    );
  // Nor any other hook's dependency array.
  const allDeps = (t) =>
    hooksOf(t, s.basename).effects.map(
      (fx) => `${fx.hook}[${fx.deps.join(", ")}]`
    );
  if (JSON.stringify(allDeps(corpusPrepared)) !== JSON.stringify(allDeps(text)))
    throw new Error(`${s.id}: normalising changed an effect's array`);
  const prepared = oracle.runOracle(s.oracleId, join(dir, s.basename));
  const cdir = scratch(`check-${s.id}-corpus`);
  writeFileSync(join(cdir, s.basename), corpusPrepared);
  const corpus = oracle.runOracle(s.oracleId, join(cdir, s.basename));
  if (!prepared.ok || !corpus.ok)
    throw new Error(`${s.id}: oracle error ${prepared.error ?? corpus.error}`);
  const v = oracle.verdict(s.oracleId, corpus.trace, prepared.trace);
  const expectedVerdict = s.base === "a" ? "bug kept" : "same";
  if (v.verdict !== expectedVerdict)
    throw new Error(
      `${s.id}: normalising changed behaviour (${JSON.stringify(v)})`
    );
  const identical =
    JSON.stringify(stripTimings(prepared.trace)) ===
    JSON.stringify(stripTimings(corpus.trace));
  if (!identical)
    throw new Error(
      `${s.id}: the oracle's trace changed beyond hook line labels`
    );
  const tsc = typeErrors(text, s.basename, `check-${s.id}-tsc`);
  if (tsc.length > 0)
    throw new Error(`${s.id}: type errors: ${tsc.join("; ")}`);
  return {
    fixPassUnchanged: true,
    handoff: diagnostics.map((d) => `${d.rule} L${d.line}: ${d.message}`),
    help: [...new Set(diagnostics.map((d) => d.help ?? null))],
    url: [...new Set(diagnostics.map((d) => d.url ?? null))],
    reportedBeforeFilter: info.diagnosticsReported,
    leftOutByFilter: info.leftOutByFilter,
    effectsUnderTest: shapes.prepared.map((t) => ({
      name: t.name,
      hook: t.hook,
      deps: t.deps,
    })),
    effectsUnchangedByNormalising: true,
    oracle: {
      verdictAgainstCorpusSubject: v.verdict,
      traceIdentical: identical,
      modes: Object.keys(prepared.trace),
    },
    typeErrors: 0,
  };
}

/**
 * A trace with each hook's source line (the oracle labels setups and cleanups `useEffect@<line>`)
 * replaced by its rank among the trace's lines, so a trace can be compared across formatting.
 */
const stripTimings = (trace) => {
  const lines = [
    ...new Set(
      Object.values(trace).flatMap((m) =>
        [...Object.keys(m.setups ?? {}), ...Object.keys(m.cleanups ?? {})].map(
          (k) => Number(k.split("@")[1])
        )
      )
    ),
  ].sort((p, q) => p - q);
  const relabel = (o) =>
    Object.fromEntries(
      Object.entries(o ?? {}).map(([k, v]) => {
        const [hook, line] = k.split("@");
        return [`${hook}#${lines.indexOf(Number(line))}`, v];
      })
    );
  return Object.fromEntries(
    Object.entries(trace).map(([mode, m]) => [
      mode,
      { ...m, setups: relabel(m.setups), cleanups: relabel(m.cleanups) },
    ])
  );
};

