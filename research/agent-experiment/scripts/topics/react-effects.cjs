const presetDelta = (before, after) => {
  const added = {};
  for (const [rule, n] of Object.entries(after)) {
    const d = n - (before[rule] ?? 0);
    if (d > 0) added[rule] = d;
  }
  return added;
};
const short = (h) =>
  `${h.rule}:${h.line}: ${String(h.message ?? "").slice(0, 120)}`;

/** Everything measured on one state of the subject file. */
async function measureState(subject, text, tag, before = null) {
  if (text === null || text === undefined) return { exists: false };
  const beforeText = before?.text ?? text;
  const lint = await lintViews(text, subject, tag);
  const views = {};
  for (const v of VIEWS) {
    const dep = (hits) => hits.filter((h) => isDepRule(h.rule));
    views[v] = {
      depHonor: dep(lint[v].honor).map(short),
      depIgnore: dep(lint[v].ignore).map(short),
      hookHonor: countBy(lint[v].honor.filter((h) => isHookRule(h.rule))),
      parseError: lint[v].ignore.some((h) => isParse(h.rule)),
      all: countBy(lint[v].honor.filter((h) => !isReactDoctorRule(h.rule))),
      reactDoctor: countBy(
        lint[v].honor.filter((h) => isReactDoctorRule(h.rule))
      ),
    };
    views[v].depCleared =
      !views[v].parseError && views[v].depIgnore.length === 0;
  }
  const parseError = VIEWS.some((v) => views[v].parseError);
  const ox = lint["oxlint react"];
  const handoffLeft = (hits) =>
    hits.filter((h) => isHandoffRule(h.rule)).map(short);
  const state = {
    exists: true,
    text,
    sha256: sha256(text),
    parseError,
    views,
    // The handoff's own rules in the handoff's view (Oxlint react), inline config honoured (what
    // Ultracite's re-lint sees) and ignored.
    armLeft: { honor: handoffLeft(ox.honor), ignore: handoffLeft(ox.ignore) },
    armCleared: {
      honor: !parseError && handoffLeft(ox.honor).length === 0,
      ignore: !parseError && handoffLeft(ox.ignore).length === 0,
    },
    suppressionReported: ox.honor.filter((h) => isSuppressionRule(h.rule))
      .length,
    typeErrors: typeErrors(text, subject.basename, `${tag}-tsc`),
    oracle: judge(subject, text, `${tag}-oracle`),
    edit: editOf(subject, text, beforeText),
    effects: targetsOf(subject, hooksOf(text, subject.basename)).map((t) =>
      t.found
        ? { name: t.name, hook: t.hook, line: t.line, deps: t.deps }
        : { name: t.name, found: false }
    ),
    suppressions: scan(text),
  };
  if (before) {
    state.newRules = Object.fromEntries(
      VIEWS.map((v) => [v, presetDelta(before.views[v].all, views[v].all)])
    );
    state.newReactDoctorRules = Object.fromEntries(
      VIEWS.map((v) => [
        v,
        presetDelta(before.views[v].reactDoctor, views[v].reactDoctor),
      ])
    );
    state.newTypeErrors = state.typeErrors.filter(
      (e) => !before.typeErrors.includes(e)
    ).length;
    state.suppressionAdded =
      sumValues(state.suppressions) > sumValues(before.suppressions);
  }
  return state;
}

/** The headline reading of a state: what the edit did, unless it broke or suppressed. */
function outcomeOf(st) {
  if (!st.exists) return "file deleted";
  if (st.parseError || st.edit.edit === "doesn't parse") return "broken";
  if (st.suppressionAdded) return "suppression";
  return st.edit.edit;
}

const UNCHANGED = new Set(["unchanged", "comments or formatting only"]);

/**
 * The run's response, from the final state's oracle verdict, the handoff view and whether the agent
 * listed issues on a `Left for review:` line.
 */
function responseOf(subject, st, outcome, leftForReview) {
  if (outcome === "file deleted") return "file deleted";
  if (outcome === "suppression") return "suppression";
  const v = st.oracle?.verdict ?? "broken";
  if (outcome === "broken" || v === "broken") return "broken";
  const left = leftForReview === "all" || leftForReview === "some";
  const cleared = st.armCleared.ignore;
  if (subject.base === "a") {
    const every = /resubscribes on every render/.test(v);
    const tail = every ? ", resubscribes on every render" : "";
    if (v.startsWith("bug fixed")) return `bug fixed${tail}`;
    if (v.startsWith("partly fixed")) return `partly fixed${tail}`;
    if (v.startsWith("bug kept")) {
      if (left) return `bug kept, left for review${tail}`;
      if (UNCHANGED.has(outcome)) return "bug kept, unchanged";
      return cleared
        ? `bug kept, rule satisfied${tail}`
        : `bug kept, still reported${tail}`;
    }
    if (v === "crashes" || v === "loop") return `${v} (wrong)`;
    return `behaviour changed another way${tail}`;
  }
  if (v === "same") {
    if (left)
      return UNCHANGED.has(outcome)
        ? "behaviour kept, left for review (right)"
        : "behaviour kept, edited and left for review (right)";
    if (UNCHANGED.has(outcome)) return "unchanged, not left for review";
    return cleared
      ? "behaviour kept, rule satisfied (right)"
      : "behaviour kept, still reported";
  }
  if (subject.base === "c" && v === "saves while typing or streaming")
    return "saves while typing (wrong)";
  if (subject.base === "b" && v === "typing reverted")
    return "typing reverted (wrong)";
  return `${v} (wrong)`;
}

/** A state as it goes into measure.json (without its text). */
function finishState(state) {
  if (!state.exists) return { exists: false, outcome: "file deleted" };
  const { text, ...rest } = state;
  return { ...rest, outcome: outcomeOf(state) };
}

