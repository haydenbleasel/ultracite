const versionOf = (name, base) => {
  try {
    return JSON.parse(
      readFileSync(
        require.resolve(`${name}/package.json`, { paths: [base] }),
        "utf8"
      )
    ).version;
  } catch {
    // A package that doesn't export its package.json: walk up from its main module.
  }
  let dir = dirname(require.resolve(name, { paths: [base] }));
  while (!existsSync(join(dir, "package.json"))) dir = dirname(dir);
  for (;;) {
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    if (pkg.name === name) return pkg.version;
    dir = dirname(dir);
    if (dir === "/") return null;
  }
};

/** Hits counted by rule, sorted by rule name. */
const countBy = (hits) => {
  const out = {};
  for (const h of hits) out[h.rule] = (out[h.rule] ?? 0) + 1;
  return Object.fromEntries(
    Object.entries(out).sort(([a], [b]) => a.localeCompare(b))
  );
};

