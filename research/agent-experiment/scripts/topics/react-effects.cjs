const printer = ts.createPrinter({ removeComments: true });
const scriptKind = (name) =>
  extname(name) === ".tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
const sourceOf = (text, name) =>
  ts.createSourceFile(
    name,
    text,
    ts.ScriptTarget.Latest,
    true,
    scriptKind(name)
  );
const print = (node, sf) =>
  printer.printNode(ts.EmitHint.Unspecified, node, sf).replaceAll(/\s+/g, " ");
const lineOf = (sf, pos) => sf.getLineAndCharacterOfPosition(pos).line + 1;

const EFFECT_HOOKS = new Set([
  "useEffect",
  "useLayoutEffect",
  "useInsertionEffect",
]);
const COUNTED_HOOKS = [
  "useEffect",
  "useLayoutEffect",
  "useInsertionEffect",
  "useEffectEvent",
  "useRef",
  "useCallback",
  "useMemo",
  "useState",
  "useReducer",
  "useSyncExternalStore",
];
/** A call's hook name: `useX(...)` or `React.useX(...)`. */
const hookName = (call) => {
  const e = call.expression;
  if (ts.isIdentifier(e)) return e.text;
  if (
    ts.isPropertyAccessExpression(e) &&
    ts.isIdentifier(e.expression) &&
    e.expression.text === "React"
  )
    return e.name.text;
  return null;
};
const isFunctionLike = (n) =>
  n && (ts.isArrowFunction(n) || ts.isFunctionExpression(n));

/**
 * Every effect in a text (its hook, lines, callback and dependency array), the hooks and
 * constructs it uses, and the local functions it declares (with where they sit). An effect's
 * `expanded` text is its callback plus the bodies of the local functions it calls, one level deep,
 * so an effect that calls an Effect Event or a ref'd function is still found by what it does.
 */
function hooksOf(text, name) {
  const sf = sourceOf(text, name);
  const effects = [];
  const counts = Object.fromEntries(COUNTED_HOOKS.map((h) => [h, 0]));
  let updaters = 0;
  let refCurrentReads = 0;
  const locals = new Map();
  // Every const's initializer, printed: a dependency extracted to a variable is found by it.
  const consts = new Map();
  const visit = (node) => {
    if (ts.isCallExpression(node)) {
      const h = hookName(node);
      if (h && h in counts) counts[h]++;
      if (h && EFFECT_HOOKS.has(h)) {
        const [cb, deps] = node.arguments;
        effects.push({
          hook: h,
          line: lineOf(sf, node.getStart(sf)),
          endLine: lineOf(sf, node.end),
          start: node.getStart(sf),
          end: node.end,
          callback: cb ? print(cb, sf) : "",
          calls: cb ? calledNames(cb) : [],
          depsForm: !deps
            ? "none"
            : ts.isArrayLiteralExpression(deps)
              ? deps.elements.length === 0
                ? "empty"
                : "literal"
              : "other",
          deps:
            deps && ts.isArrayLiteralExpression(deps)
              ? deps.elements.map((e) => print(e, sf))
              : [],
        });
      }
      // A state setter called with a function: an updater (setX((prev) => ...)).
      const e = node.expression;
      if (
        ts.isIdentifier(e) &&
        /^set[A-Z]/.test(e.text) &&
        isFunctionLike(node.arguments[0])
      )
        updaters++;
    }
    if (
      ts.isPropertyAccessExpression(node) &&
      node.name.text === "current" &&
      !(
        ts.isBinaryExpression(node.parent) &&
        node.parent.left === node &&
        node.parent.operatorToken.kind === ts.SyntaxKind.EqualsToken
      )
    )
      refCurrentReads++;
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.initializer
    )
      consts.set(node.name.text, print(node.initializer, sf));
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.initializer &&
      (isFunctionLike(node.initializer) ||
        (ts.isCallExpression(node.initializer) &&
          ["useCallback", "useEffectEvent", "useMemo", "useRef"].includes(
            hookName(node.initializer)
          )))
    ) {
      const init = node.initializer;
      locals.set(node.name.text, {
        kind: isFunctionLike(init) ? "function" : hookName(init),
        start: node.getStart(sf),
        line: lineOf(sf, node.getStart(sf)),
        text: print(init, sf),
      });
    }
    if (ts.isFunctionDeclaration(node) && node.name)
      locals.set(node.name.text, {
        kind: "function",
        start: node.getStart(sf),
        line: lineOf(sf, node.getStart(sf)),
        text: print(node, sf),
      });
    ts.forEachChild(node, visit);
  };
  visit(sf);
  for (const fx of effects) {
    const inner = fx.calls
      .filter((n) => locals.has(n))
      .map((n) => locals.get(n).text);
    fx.own = fx.callback;
    fx.expanded = [fx.callback, ...inner].join(" ");
  }
  // Where each local sits: inside an effect's callback or not.
  for (const [n, l] of locals)
    l.insideEffect = effects.some(
      (fx) => l.start > fx.start && l.start < fx.end
    );
  return {
    effects,
    counts,
    updaters,
    refCurrentReads,
    locals,
    consts,
    parseErrors: sf.parseDiagnostics?.length ?? 0,
  };
}

/** The identifiers a function calls (`f()` and `f.current()`), and those it reads `.current` on. */
function calledNames(fn) {
  const out = new Set();
  const visit = (n) => {
    if (ts.isCallExpression(n)) {
      if (ts.isIdentifier(n.expression)) out.add(n.expression.text);
      if (
        ts.isPropertyAccessExpression(n.expression) &&
        n.expression.name.text === "current" &&
        ts.isIdentifier(n.expression.expression)
      )
        out.add(n.expression.expression.text);
    }
    ts.forEachChild(n, visit);
  };
  visit(fn);
  return [...out];
}

/**
 * Finds each effect under test in a text: the first effect its matcher accepts that no earlier
 * target took. Returns { name, found, line, depsForm, deps, callback } per target.
 */
function targetsOf(subject, h) {
  const used = new Set();
  return subject.targets.map((t) => {
    const fx = h.effects.find((e) => !used.has(e) && t.match(e));
    if (!fx) return { name: t.name, found: false };
    used.add(fx);
    return {
      name: t.name,
      found: true,
      hook: fx.hook,
      line: fx.line,
      depsForm: fx.depsForm,
      deps: fx.deps,
      callback: fx.callback,
      expanded: fx.expanded,
    };
  });
}

