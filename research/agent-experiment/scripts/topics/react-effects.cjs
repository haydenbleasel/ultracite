/** Rewrites every lint-suppression directive to a same-length non-directive. */
const neutralizeDirectives = (text) =>
  text
    .replace(/(eslint|oxlint)-(disable|enable)/g, "$1_$2")
    .replace(/biome-ignore/g, "biome_ignore")
    .replace(/@ts-(ignore|expect-error|nocheck)/g, "@ts_$1")
    .replace(/\/\*(\s*)eslint(\s)/g, "/*$1eslinx$2");

function oxlintHits(dir, name) {
  const r = spawnSync(
    process.execPath,
    [
      mirror.oxlintBin,
      "-c",
      CONFIG.oxlint,
      "--disable-nested-config",
      "-f",
      "json",
      name,
    ],
    { cwd: dir, encoding: "utf8", maxBuffer: 1 << 28 }
  );
  const report = JSON.parse(r.stdout.slice(r.stdout.indexOf("{")));
  return report.diagnostics.map((d) => ({
    rule: d.code ? mirror.toOxlintRuleName(d.code) : `parse: ${d.message}`,
    line: d.labels?.[0]?.span?.line ?? null,
    message: d.message,
    labels: (d.labels ?? []).map((l) => l.label).filter(Boolean),
  }));
}

// One ESLint instance per config and inline-config mode, linting a file in a fixed scratch dir
// (loading the react preset's plugins takes seconds).
const eslintInstances = new Map();
function eslintFor(configFile, honor) {
  const key = `${configFile}|${honor}`;
  if (!eslintInstances.has(key)) {
    const dir = scratch(`eslint-view-${eslintInstances.size}-${process.pid}`);
    withRunFiles(dir);
    eslintInstances.set(key, {
      dir,
      eslint: new ESLint({
        cwd: dir,
        errorOnUnmatchedPattern: false,
        overrideConfigFile: configFile,
        overrideConfig: [
          {
            linterOptions: {
              noInlineConfig: !honor,
              reportUnusedDisableDirectives: "off",
            },
          },
        ],
      }),
    });
  }
  return eslintInstances.get(key);
}
async function eslintHits(text, name, configFile, honor) {
  const { dir, eslint } = eslintFor(configFile, honor);
  for (const f of readdirSync(dir))
    if (!RUN_FILE_NAMES.includes(f)) rmSync(join(dir, f), { force: true });
  writeFileSync(join(dir, name), text);
  const [result] = await eslint.lintFiles([name]);
  return (result?.messages ?? []).map((m) => ({
    rule: m.ruleId ?? (m.fatal ? `parse: ${m.message}` : "eslint"),
    line: m.line ?? null,
    message: m.message,
  }));
}

/** Biome react, `biome check`, with init's biome.jsonc (by path) and package.json at the root. */
function biomeHits(dir, name) {
  copyFileSync(CONFIG.biome, join(dir, "biome.jsonc"));
  copyFileSync(
    join(INIT_DIR, "biome", "package.json"),
    join(dir, "package.json")
  );
  chmodSync(join(dir, "package.json"), 0o644);
  writeFileSync(join(dir, ".gitignore"), "node_modules\n");
  const r = spawnSync(
    process.execPath,
    [
      mirror.biomeBin,
      "check",
      "--reporter=json",
      "--max-diagnostics=none",
      name,
    ],
    { cwd: dir, encoding: "utf8", maxBuffer: 1 << 28 }
  );
  const report = JSON.parse(r.stdout.slice(r.stdout.indexOf("{")));
  return (report.diagnostics ?? [])
    .filter((d) => /^(lint|assist|parse|format)/.test(d.category ?? ""))
    .map((d) => ({
      rule: (d.category ?? "").replace(/^lint\//, ""),
      line: d.location?.start?.line ?? null,
      message: typeof d.message === "string" ? d.message : null,
    }));
}

const sortHits = (hits) =>
  [...hits].sort(
    (a, b) =>
      (a.line ?? 0) - (b.line ?? 0) ||
      String(a.rule).localeCompare(String(b.rule)) ||
      String(a.message).localeCompare(String(b.message))
  );

/** Every view of one state: hits honouring and ignoring inline config. */
async function lintViews(text, subject, tag) {
  const out = {};
  for (const [mode, t] of [
    ["honor", text],
    ["ignore", neutralizeDirectives(text)],
  ]) {
    const honor = mode === "honor";
    const oxDir = scratch(`${tag}-${mode}-oxlint`);
    writeFileSync(join(oxDir, subject.basename), t);
    withRunFiles(oxDir);
    const bioDir = scratch(`${tag}-${mode}-biome`);
    writeFileSync(join(bioDir, subject.basename), t);
    const eslint = await eslintHits(t, subject.basename, CONFIG.eslint, honor);
    // The counterfactual differs from the preset only for a .ts file.
    const eslintAll = subject.basename.endsWith(".tsx")
      ? eslint
      : await eslintHits(t, subject.basename, CONFIG.eslintAll, honor);
    const hits = {
      "oxlint react": oxlintHits(oxDir, subject.basename),
      "eslint react": eslint,
      "eslint react, every file": eslintAll,
      "biome react": biomeHits(bioDir, subject.basename),
    };
    for (const view of VIEWS) {
      out[view] ??= {};
      out[view][mode] = sortHits(hits[view]);
    }
  }
  return out;
}

