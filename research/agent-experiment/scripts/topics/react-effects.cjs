/** Puts the run files next to a staged copy, writable (the prepared copies are read-only). */
function withRunFiles(dir) {
  for (const f of runFiles()) {
    copyFileSync(f.from, join(dir, f.name));
    chmodSync(join(dir, f.name), 0o644);
  }
}

// ---------------------------------------------------------------- Ultracite's adapter (hooks)

/** The Oxlint adapter pass (oxlint --fix, oxfmt --write, oxlint -f json) on `files` (empty: all). */
function adapterPass(cwd, files, passthrough = []) {
  return mirror.oxlintPass({
    cwd,
    files,
    config: CONFIG.oxlint,
    fmtConfig: CONFIG.oxfmt,
    passthrough,
  });
}

const baselineCache = new Map();
/**
 * The diagnostics other than the two dependency rules that the prepared project itself reports (the
 * subject's; init's config files report none), by file: what the handoff leaves out, and what an
 * edit has to add to before a re-lint hands something else back.
 */
function baselineOther(subject) {
  if (!baselineCache.has(subject.id)) {
    const dir = scratch(`baseline-${subject.id}-${process.pid}`);
    writeFileSync(
      join(dir, subject.basename),
      readFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), "utf8")
    );
    withRunFiles(dir);
    const { diagnostics } = adapterPass(dir, []);
    baselineCache.set(
      subject.id,
      diagnostics.filter((d) => !isHandoffRule(d.rule))
    );
    rmSync(dir, { recursive: true, force: true });
  }
  return baselineCache.get(subject.id);
}

/**
 * The handoff filter: the two dependency rules, and every other diagnostic that isn't one of the
 * prepared project's own (diff.ts partitionByRemaining, by rule and message, file by file). Fatal
 * diagnostics (a file that no longer parses) are never in the baseline, so they always pass.
 */
function handoffFilter(subject, diagnostics) {
  const base = baselineOther(subject);
  const keep = new Set();
  const byFile = new Map();
  for (const d of diagnostics) {
    if (isHandoffRule(d.rule)) continue;
    if (!byFile.has(d.file)) byFile.set(d.file, []);
    byFile.get(d.file).push(d);
  }
  for (const [file, ds] of byFile) {
    const { introduced } = mirror.partitionByRemaining(
      base.filter((b) => b.file === file),
      ds
    );
    for (const d of introduced) keep.add(d);
  }
  return diagnostics.filter((d) => isHandoffRule(d.rule) || keep.has(d));
}

/**
 * run-one.mjs's `collect` hook: Ultracite's fixAndCollect on the run dir (the project root), then
 * the handoff filter. run-one checks the handoff holds exactly the subject's dependency reports.
 */
function collect(subject, runDir) {
  const sources = mirror.checkSources();
  const { diagnostics: all } = adapterPass(runDir, []);
  const diagnostics = handoffFilter(subject, all);
  const dropped = all.filter((d) => !diagnostics.includes(d));
  return {
    diagnostics,
    info: {
      linter: "oxlint",
      adapter:
        "linters.ts runOxlintPass: oxlint --fix ., oxfmt --write ., oxlint -f json .",
      config:
        "what `ultracite init --linter oxlint --frameworks react` writes (oxlint.config.ts: env, extends [core, react], ignorePatterns; oxfmt.config.ts: ...ultracite), passed with -c and importing the presets by absolute URL",
      filter:
        "react-hooks/exhaustive-deps and react/exhaustive-effect-dependencies, plus any other diagnostic not among the prepared project's own (rule and message, file by file, as diff.ts matches them): a project that lints clean apart from the dependency arrays. Every re-lint uses the same filter.",
      diagnosticsReported: all.length,
      diagnosticsHandedOver: diagnostics.length,
      leftOutByFilter: countBy(dropped.map((d) => ({ rule: d.rule }))),
      mirroredSlicesSha256: sources.hashes,
    },
  };
}

/**
 * run-one.mjs's `verify` hook: the adapter's verify (the Oxlint pass on one file), then the
 * handoff filter.
 */
function verify(subject, runDir, file) {
  return handoffFilter(subject, adapterPass(runDir, [file]).diagnostics);
}

