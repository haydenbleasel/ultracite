// ---------------------------------------------------------------- the oracle

const referenceTraces = new Map();
/**
 * The prepared subject's trace: the reference every state is compared with. It equals the corpus
 * subject's, or differs only in object key order (subjectChecks).
 */
function referenceTrace(subject) {
  if (!referenceTraces.has(subject.base)) {
    const r = oracle.run(
      subject.oracleId,
      readFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), "utf8")
    );
    if (r.loadError) throw new Error(`${subject.id}: oracle: ${r.loadError}`);
    referenceTraces.set(subject.base, r);
  }
  return referenceTraces.get(subject.base);
}

/**
 * The oracle on a source text, in its own Node process (the corpus's length-oracle.cjs: transpile,
 * then drive the file's public API through every scenario). The verdict is against the prepared
 * subject, as the corpus compares (same, same except argument arity, changed, crashes, does not
 * load), with the differing scenarios and, for A, those that differ on code with each placeholder
 * once. `ignoringKeyOrder` is the same comparison with every object's keys sorted.
 */
function judge(subject, text, reference = referenceTrace(subject)) {
  const r = oracle.run(subject.oracleId, text);
  const v = oracle.compare(reference, r);
  const k = r.loadError
    ? v
    : oracle.compare(
        { trace: canonTrace(reference.trace) },
        { trace: canonTrace(r.trace) }
      );
  return {
    verdict: v.verdict,
    scenarios: reference.trace.length,
    differing: v.differing ?? null,
    onceDiffering: v.onceDiffering ?? null,
    crashed: v.crashed ?? null,
    arityOnly: v.arityOnly ?? null,
    why: v.why ?? null,
    differences: (v.differences ?? [])
      .slice(0, 3)
      .map((d) => JSON.stringify(d).slice(0, 600)),
    ignoringKeyOrder: k.verdict,
  };
}

