const preparedText = (base) =>
  readFileSync(
    join(HERE, subjectsManifest().find((s) => s.base === base).path),
    "utf8"
  );

/**
 * A mutant's text. Three kinds:
 *   variant + normalised  a corpus variant's edits applied to the cleaned corpus subject, then
 *                         Ultracite's Oxlint pass until nothing changes (what verify leaves after an
 *                         agent wrote that edit)
 *   op on the prepared    the corpus's mechanical `strip` or `join` edit on the prepared subject, as
 *                         written (what an agent's gaming edit looks like before the formatter)
 *   edits on the prepared [from, to] pairs, each matching exactly once
 */
let variantsCache = null;
const mutantCache = new Map();
function mutantText(m) {
  if (mutantCache.has(m.id)) return mutantCache.get(m.id);
  const s = subjectsManifest().find((x) => x.base === m.base);
  let text;
  if (m.variant) {
    variantsCache ??= corpusVariants();
    const v = variantsCache.SUBJECTS[m.base].variants.find(
      (x) => x.id === m.variant
    );
    if (!v) throw new Error(`${m.id}: no corpus variant ${m.variant}`);
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const cleaned = cleanText(original, examplesJson().stripFields, m.base);
    const edited = variantsCache.applyEdits(cleaned, s.basename, v.edits);
    if (m.normalise === false) text = edited;
    else {
      const files = Object.fromEntries(
        RUN_FILE_NAMES.map((f) => [
          f,
          readFileSync(join(RUN_FILES_DIR, storedName(f)), "utf8"),
        ])
      );
      text = normalise(edited, s.basename, files, `mutant-${m.id}`).text;
    }
  } else if (m.op) {
    variantsCache ??= corpusVariants();
    text = variantsCache.applyEdits(preparedText(m.base), s.basename, [
      { [m.op]: m.fn },
    ]);
    // The corpus's join adds a `;` after each statement it joins unless the function's first
    // joinable line ends in one; on the prepared (semicolon) text that gives `;;`, which isn't an
    // edit an agent would write.
    if (m.op === "join") text = text.replaceAll(";; ", "; ");
  } else {
    text = preparedText(m.base);
    for (const [from, to] of m.edits ?? []) {
      const n = text.split(from).length - 1;
      if (n !== 1)
        throw new Error(
          `${m.id}: edit matches ${n} times: ${from.slice(0, 60)}`
        );
      text = text.replace(from, () => to);
    }
  }
  mutantCache.set(m.id, text);
  return text;
}

/**
 * The PRIMING check on the corpus subjects before they're stripped: it must find the analysis in
 * every one of them (so a clean prepared subject means the check ran, not that it can't match).
 */
function primingSanity() {
  const out = {};
  for (const [base, b] of Object.entries(BASES)) {
    const text = readFileSync(join(EXAMPLES, b.example), "utf8");
    out[base] = commentsOf(text, b.basename)
      .comments.flatMap(commentLines)
      .filter((line) => PRIMING.some((re) => re.test(line))).length;
  }
  return out;
}

const fullSubject = (s) => ({ ...s, ...subjectOf(s.id) });

async function selfTest() {
  const examples = examplesJson();
  const subjects = subjectsManifest();
  const cases = [];
  const record = (c) => {
    cases.push(c);
    console.log(
      `${c.pass ? "OK  " : "BAD "} ${c.name}: oracle ${c.oracle}, ${c.outcome}, limit left ${c.handoffLeft}/${c.handoffLeftHonor}${c.why.length ? ` <- ${c.why.join(", ")}` : ""}`
    );
  };
  const bases = {};
  for (const s of subjects) {
    const subject = fullSubject(s);
    const text = readFileSync(join(HERE, s.path), "utf8");
    bases[s.base] = await measureState(subject, text, `self-${s.base}-before`);
    const st = await measureState(
      subject,
      text,
      `self-${s.base}`,
      bases[s.base]
    );
    const why = [];
    if (st.oracle.verdict !== "same") why.push("oracle");
    if (outcomeOf(st) !== "unchanged") why.push("outcome");
    if (st.armLeft.ignore.length !== s.expected.length) why.push("handoff");
    record({
      name: `${s.base} as prepared`,
      oracle: st.oracle.verdict,
      outcome: outcomeOf(st),
      handoffLeft: st.armLeft.ignore.length,
      handoffLeftHonor: st.armLeft.honor.length,
      pass: why.length === 0,
      why,
    });
  }
  for (const m of mutantsFile()) {
    const s = subjects.find((x) => x.base === m.base);
    const subject = fullSubject(s);
    const st = await measureState(
      subject,
      mutantText(m),
      `self-${m.id}`,
      bases[m.base]
    );
    const outcome = outcomeOf(st);
    const why = [];
    const e = m.expect;
    if (st.oracle.ignoringKeyOrder !== e.oracle) why.push("oracle");
    if (outcome !== e.edit) why.push("outcome");
    for (const k of e.kinds ?? [])
      if (!(st.edit.kinds ?? []).includes(k)) why.push(`kind ${k}`);
    const left = st.armLeft.ignore.length;
    const leftHonor = st.armLeft.honor.length;
    if (e.handoffLeft !== undefined && left !== e.handoffLeft)
      why.push("limit left");
    if (e.handoffLeftHonor !== undefined && leftHonor !== e.handoffLeftHonor)
      why.push("limit left (inline config honoured)");
    // A corpus variant: its oracle verdict must equal examples.json's (the prepared subject differs
    // from the corpus subject only in key order), and which functions Oxlint's line limit flags is
    // recorded beside the corpus's count after Oxfmt (verify also runs oxlint --fix).
    let corpus = null;
    if (m.variant) {
      const v = examples.subjects[m.base].variants.find(
        (x) => x.id === m.variant
      );
      corpus = {
        oracle: v.oracle.verdict,
        differing: v.oracle.differing,
        oxlintLinesAfterFormatter: v.afterFormatter.flagged.oxlintLines,
        oxlintParamsAfterFormatter: v.afterFormatter.flagged.oxlintParams,
        ours: {
          oxlintLines: [
            ...new Set(st.armLeft.ignore.map((x) => x.split(":")[0])),
          ],
          oxlintParams: st.views["oxlint strict"].sizeIgnore.params.map(
            (x) => x.split(":")[0]
          ),
          differing: st.oracle.differing,
        },
      };
      if (v.oracle.verdict !== st.oracle.ignoringKeyOrder)
        why.push("oracle differs from the corpus variant");
      if (m.normalise !== false) {
        corpus.linesMatch =
          JSON.stringify([...corpus.ours.oxlintLines].sort()) ===
          JSON.stringify([...v.afterFormatter.flagged.oxlintLines].sort());
        if (e.linesMatchCorpus !== false && !corpus.linesMatch)
          why.push("flagged functions differ from the corpus variant");
      }
    }
    if (e.typeErrors !== undefined && st.typeErrors.length !== e.typeErrors)
      why.push(`tsc: ${st.typeErrors[0]}`);
    record({
      name: `${m.id}: ${m.description}`,
      mutant: m.id,
      oracle: st.oracle.ignoringKeyOrder,
      oracleExact: st.oracle.verdict,
      outcome,
      kinds: st.edit.kinds,
      helpers: (st.edit.helpers ?? []).map(
        (h) =>
          `${h.name} (${h.params} params, ${h.lines} lines, ${h.callSites} call sites)`
      ),
      handoffLeft: left,
      handoffLeftHonor: leftHonor,
      over50: st.over50,
      formattedOver50: st.formatted.handoffLeft ?? null,
      typeErrors: st.typeErrors.length,
      expected: e,
      corpus,
      pass: why.length === 0,
      why,
    });
  }
  const primingCheck = primingSanity();
  const primingPass = Object.values(primingCheck).every((n) => n > 0);
  console.log(
    `${primingPass ? "OK  " : "BAD "} priming patterns match the unstripped corpus subjects: ${JSON.stringify(primingCheck)}`
  );
  const mirrorCheck = mirrorEquivalence();
  const failures =
    cases.filter((c) => !c.pass).length +
    mirrorCheck.cases.filter((c) => !c.pass).length +
    (primingPass ? 0 : 1);
  mkdirSync(lib.RESULTS_DIR, { recursive: true });
  writeFileSync(
    join(lib.RESULTS_DIR, "oracle-self-test.json"),
    `${JSON.stringify(
      lib.redact({
        runtime: `node ${process.version}`,
        oracle:
          "research/corpus/scripts/length-oracle.cjs (shared with the corpus), with its structure measure",
        cases,
        primingCheck: {
          note: "lines of the unstripped corpus subjects' comments that the PRIMING patterns match; each must be above 0",
          hits: primingCheck,
          pass: primingPass,
        },
        mirrorCheck,
        failures,
      }),
      null,
      2
    )}\n`
  );
  return failures;
}

