/**
 * Drops the header fields that carry the analysis (examples.json `stripFields`) and applies
 * TEXT_EDITS. A field continues until a blank comment line or the next field, which starts with a
 * capital letter after " * ".
 */
function cleanText(text, stripFields, base) {
  const drop = new RegExp(
    `^ \\* (${stripFields.map(lib.escapeRegExp).join("|")})\\b`
  );
  const out = [];
  let dropping = false;
  for (const line of text.split("\n")) {
    if (drop.test(line)) {
      dropping = true;
      continue;
    }
    if (dropping) {
      if (line === " *" || line === " */" || /^ \* [A-Z]/.test(line))
        dropping = false;
      else continue;
    }
    out.push(line);
  }
  if (out[0] === "/*" && out[1] === " *") out.splice(1, 1);
  let cleaned = out.join("\n");
  for (const e of TEXT_EDITS[base]) {
    if (!cleaned.includes(e.from))
      throw new Error(`${base}: text edit not found: ${e.from.slice(0, 60)}`);
    cleaned = cleaned.replace(e.from, () => e.to);
  }
  return cleaned;
}

