const scopeManager = require(
  require.resolve("@typescript-eslint/scope-manager", { paths: [PARSER_DIR] })
);
const MUTATORS = new Set([
  "push",
  "pop",
  "shift",
  "unshift",
  "splice",
  "sort",
  "reverse",
  "fill",
  "set",
  "add",
  "delete",
  "clear",
]);

const isFn = (n) =>
  n &&
  (n.type === "FunctionDeclaration" ||
    n.type === "FunctionExpression" ||
    n.type === "ArrowFunctionExpression");

/** Walks an estree node, calling visit(node, parent). */
function walk(node, visit, parent = null) {
  if (!node || typeof node.type !== "string") return;
  visit(node, parent);
  for (const [k, v] of Object.entries(node)) {
    if (k === "parent" || k === "loc" || k === "range") continue;
    if (Array.isArray(v)) {
      for (const c of v)
        if (c && typeof c.type === "string") walk(c, visit, node);
    } else if (v && typeof v.type === "string") walk(v, visit, node);
  }
}

/**
 * The named functions of a text (declarations, `const x = () => …` / `function` expressions, and
 * class and object methods), with where each sits and what it touches: its parameters (count, an
 * object pattern, a rest element, a type literal), whether it reads `arguments`, whether it mutates a
 * parameter (a member assignment or a mutating method call on it), and, from scope analysis, the
 * outer variables it reads and writes (an enclosing function's locals, or module state).
 */
function functionFacts(text, name) {
  let ast;
  try {
    ast = tsEstree.parse(text, {
      comment: true,
      filePath: name,
      jsx: false,
      loc: true,
      range: true,
    });
  } catch (error) {
    return { error: String(error.message).slice(0, 200) };
  }
  const sm = scopeManager.analyze(ast, { sourceType: "module" });
  const named = [];
  walk(ast, (n, parent) => {
    let fname = null;
    let fn = null;
    if (n.type === "FunctionDeclaration" && n.id) {
      fname = n.id.name;
      fn = n;
    } else if (
      n.type === "VariableDeclarator" &&
      n.id.type === "Identifier" &&
      isFn(n.init)
    ) {
      fname = n.id.name;
      fn = n.init;
    } else if (
      (n.type === "MethodDefinition" || n.type === "Property") &&
      isFn(n.value) &&
      n.key?.type === "Identifier"
    ) {
      fname = n.key.name;
      fn = n.value;
    }
    if (fn) named.push({ name: fname, fn, holder: n, parent });
  });
  const lines = text.split("\n");
  const enclosing = (fn) =>
    named
      .filter(
        (o) =>
          o.fn !== fn &&
          o.fn.range[0] <= fn.range[0] &&
          fn.range[1] <= o.fn.range[1]
      )
      .sort((a, b) => b.fn.range[0] - a.fn.range[0])[0]?.name ?? null;
  const facts = named.map(({ name: fname, fn }) => {
    const scope = sm.acquire(fn);
    const params = fn.params.map((p) => {
      const q = p.type === "TSParameterProperty" ? p.parameter : p;
      const inner = q.type === "AssignmentPattern" ? q.left : q;
      return {
        kind: inner.type,
        properties:
          inner.type === "ObjectPattern" ? inner.properties.length : null,
        typeMembers:
          inner.typeAnnotation?.typeAnnotation?.type === "TSTypeLiteral"
            ? inner.typeAnnotation.typeAnnotation.members.length
            : null,
      };
    });
    const paramNames = new Set();
    for (const p of fn.params)
      walk(p, (x) => {
        if (x.type === "Identifier") paramNames.add(x.name);
      });
    let usesArguments = false;
    // Names whose object the function changes: a member assigned or updated, or a mutating method
    // (push, set, splice, ...) called on it.
    const mutatedNames = new Set();
    walk(fn.body, (x, parent) => {
      if (x.type === "Identifier" && x.name === "arguments")
        usesArguments = true;
      if (x.type === "MemberExpression" && x.object.type === "Identifier") {
        const assigned =
          (parent?.type === "AssignmentExpression" && parent.left === x) ||
          (parent?.type === "UpdateExpression" && parent.argument === x);
        const called =
          parent?.type === "CallExpression" &&
          parent.callee === x &&
          x.property.type === "Identifier" &&
          MUTATORS.has(x.property.name);
        if (assigned || called) mutatedNames.add(x.object.name);
      }
    });
    const mutatedParams = new Set(
      [...mutatedNames].filter((n) => paramNames.has(n))
    );
    // Outer variables: references that leave the function's own scopes, resolved to a variable in
    // an enclosing function (a closure) or at module level.
    const reads = new Set();
    const writes = new Set();
    const moduleReads = new Set();
    const moduleWrites = new Set();
    if (scope) {
      const own = new Set();
      const collectScopes = (s) => {
        own.add(s);
        for (const c of s.childScopes) collectScopes(c);
      };
      collectScopes(scope);
      for (const s of own)
        for (const ref of s.references) {
          const v = ref.resolved;
          if (!v || own.has(v.scope)) continue;
          if (ref.isTypeReference && !ref.isValueReference) continue;
          if (v.defs.some((d) => d.type === "ImportBinding")) continue;
          const def = v.defs[0];
          const isFunctionLike =
            def &&
            (def.type === "FunctionName" ||
              def.type === "ClassName" ||
              def.type === "TSEnumName" ||
              (def.type === "Variable" && isFn(def.node.init)));
          if (isFunctionLike) continue;
          const atModule =
            v.scope.type === "module" || v.scope.type === "global";
          if (ref.isWrite()) (atModule ? moduleWrites : writes).add(v.name);
          else (atModule ? moduleReads : reads).add(v.name);
        }
    }
    const startLine = fn.loc.start.line;
    const endLine = fn.loc.end.line;
    const body = lines.slice(startLine - 1, endLine);
    return {
      name: fname,
      startLine,
      endLine,
      topLevel: enclosing(fn) === null,
      enclosing: enclosing(fn),
      params: params.length,
      paramKinds: params.map((p) => p.kind),
      optionsBag: params.some(
        (p) => (p.properties ?? 0) >= 4 || (p.typeMembers ?? 0) >= 4
      ),
      restParam: params.some((p) => p.kind === "RestElement"),
      usesArguments,
      mutatesParams: [...mutatedParams].sort(),
      readsEnclosingLocals: [...reads].sort(),
      writesEnclosingLocals: [...writes].sort(),
      // An enclosing function's object changed through a closure (`promises.push(...)`).
      mutatesEnclosingLocals: [...mutatedNames]
        .filter((n) => reads.has(n))
        .sort(),
      writesModuleState: [
        ...new Set([
          ...moduleWrites,
          ...[...mutatedNames].filter((n) => moduleReads.has(n)),
        ]),
      ].sort(),
      blankLines: body.filter((l) => l.trim() === "").length,
    };
  });
  // Counts over the whole file.
  const counts = {
    loops: 0,
    continues: 0,
    replaceCalls: 0,
    replaceAllCalls: 0,
    reduceCalls: 0,
    topLevelVariables: 0,
    topLevelDataVariables: 0,
  };
  walk(ast, (n, parent) => {
    if (
      /^(For|ForIn|ForOf|While|DoWhile)Statement$/.test(n.type) ||
      (n.type === "CallExpression" &&
        n.callee.type === "MemberExpression" &&
        n.callee.property.name === "forEach")
    )
      counts.loops++;
    if (n.type === "ContinueStatement") counts.continues++;
    if (
      n.type === "CallExpression" &&
      n.callee.type === "MemberExpression" &&
      n.callee.property.type === "Identifier"
    ) {
      if (n.callee.property.name === "replace") counts.replaceCalls++;
      if (n.callee.property.name === "replaceAll") counts.replaceAllCalls++;
      if (n.callee.property.name === "reduce") counts.reduceCalls++;
    }
    if (
      n.type === "VariableDeclaration" &&
      (parent?.type === "Program" ||
        (parent?.type === "ExportNamedDeclaration" &&
          parent.parent?.type === "Program"))
    ) {
      counts.topLevelVariables += n.declarations.length;
      counts.topLevelDataVariables += n.declarations.filter(
        (d) => !isFn(d.init)
      ).length;
    }
  });
  // Exported functions and their parameter names (the API the oracle drives).
  const exportsList = [];
  for (const st of ast.body) {
    if (st.type !== "ExportNamedDeclaration" || !st.declaration) continue;
    const d = st.declaration;
    if (d.type === "FunctionDeclaration")
      exportsList.push(
        `${d.id.name}(${d.params.map((p) => (p.type === "Identifier" ? p.name : p.type)).join(", ")})`
      );
    else if (d.type === "VariableDeclaration")
      for (const v of d.declarations)
        exportsList.push(
          isFn(v.init)
            ? `${v.id.name}(${v.init.params.map((p) => (p.type === "Identifier" ? p.name : p.type)).join(", ")})`
            : v.id.name
        );
    else if (d.id) exportsList.push(`${d.type} ${d.id.name}`);
  }
  const commentLineCount = ast.comments.reduce(
    (n, c) => n + c.loc.end.line - c.loc.start.line + 1,
    0
  );
  // Lines that hold two or more statements (a `;` followed by more code), outside for headers and
  // comments: the gaming move of joining statements.
  let joinedLines = 0;
  const statementEnds = new Map();
  walk(ast, (n) => {
    if (
      /Statement$|Declaration$/.test(n.type) &&
      !/^(BlockStatement|ExportNamedDeclaration|FunctionDeclaration|ClassDeclaration|TSInterfaceDeclaration|TSTypeAliasDeclaration|TSEnumDeclaration|TSModuleDeclaration)$/.test(
        n.type
      ) &&
      n.loc.start.line === n.loc.end.line
    )
      statementEnds.set(
        n.loc.start.line,
        (statementEnds.get(n.loc.start.line) ?? 0) + 1
      );
  });
  for (const k of statementEnds.values()) if (k >= 2) joinedLines++;
  return {
    error: null,
    functions: facts,
    counts,
    exports: exportsList,
    commentLines: commentLineCount,
    blankLines: lines.filter((l) => l.trim() === "").length,
    fileLines: lines.length,
    joinedLines,
  };
}

