/**
 * Runs Ultracite's own `init` (the CLI source, under Bun) in a scratch project, non-interactively and
 * without installing anything, and returns every file it leaves that it wrote or changed (path ->
 * text).
 */
function runInit(linter) {
  const dir = scratch(`init-${linter}`);
  writeFileSync(join(dir, "package.json"), STARTING_PACKAGE_JSON);
  writeFileSync(join(dir, "tsconfig.json"), TSCONFIG());
  const r = spawnSync("bun", INIT_ARGS(linter), {
    cwd: dir,
    encoding: "utf8",
    input: "",
  });
  if (r.status !== 0)
    throw new Error(`init --linter ${linter} failed: ${r.stderr.slice(-400)}`);
  const files = {};
  const before = {
    "package.json": STARTING_PACKAGE_JSON,
    "tsconfig.json": TSCONFIG(),
  };
  for (const name of readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .sort()) {
    const text = readFileSync(join(dir, name), "utf8");
    if (before[name] !== text) files[name] = text;
  }
  return files;
}

