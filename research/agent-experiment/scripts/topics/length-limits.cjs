// The length-limits post: Ultracite turns the size limits off, and one reason given is that a user
// who turns one on can hand the diagnostics to an agent. When a user turns `max-lines-per-function`
// on (its default, 50) and Ultracite hands Oxlint's report ("The function `x` has too many lines
// (72). Maximum allowed is 50.", help "Consider splitting it into smaller functions.") to an agent,
// does the agent's refactor keep behaviour, and does it help a reader or just satisfy the count?
// And what do Ultracite's retry loop and its "Left for review" line do?
//
// Subjects come from research/corpus/examples/length-limits/ (length-examples.cjs):
//   a  Vite's createClientConfigValueReplacer (72 lines): config building that reads top to bottom.
//      Every split that clears the limit adds single-use helpers taking 4-11 values; a table with
//      replaceAll changes the output. Right: leave it for review and say why, or a change that keeps
//      behaviour and doesn't make it harder to follow.
//   b  Next.js's revalidateTags (105 lines): two jobs, one after the other. One clean split keeps
//      behaviour; three tempting ones change it. Right: extract the two jobs, keeping behaviour.
//   c  VS Code's guessIndentation (117 lines; 134 after Oxfmt) and spacesDiff (73): the loop's
//      `continue`s skip state updates, the safe extractions leave it over the limit, and the tempting
//      ones change the guess. Right: keep behaviour and API; leave it for review, or extract only
//      what's safe.
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks):
// Ultracite's Oxlint pass on the project (oxlint --fix, oxfmt --write, then oxlint -f json), then up
// to three agent attempts, each verified with the adapter's pass on the file. No linter has a fix
// for a length limit, so the diagnostics reach the agent. The run dir is what `ultracite init
// --linter oxlint` leaves (its oxlint.config.ts, oxfmt.config.ts and package.json, generated by
// running init), with the one change a user would make, `"max-lines-per-function": "error"` in the
// config's rules, and the tsconfig.json the subjects need. Every other rule is as the presets set
// it, so max-params and max-statements stay off.
//
// The handoff. The subjects are verbatim code, and Ultracite's core preset reports other rules on
// them (func-style, complexity, no-plusplus, ...). prepareSubjects runs the Oxlint pass until nothing
// changes (checked not to change behaviour), and the handoff, and every re-lint, keep
// max-lines-per-function and any other diagnostic that is new since the prepared subject (by
// Ultracite's own rule-and-message key, diff.ts). That models a project that lints clean apart from
// the length limit. It is a deviation from a real project, recorded in handoff.json and REPORT.md,
// and every diagnostic of every view is still measured.
//
// Each run is measured after each attempt (the file as the agent left it, as Oxfmt alone would leave
// it, and as verify left it) and at the end: the length, parameter, statement, file-length and
// complexity rules in Oxlint (the user's config, and with max-params, max-statements and max-lines
// also on), Oxlint with SonarJS's cognitive complexity, ESLint core and Biome core with their length
// rules on (inline config honoured and ignored), tsc, the behaviour oracle (the corpus's
// length-oracle.cjs, imported unchanged) and its structure measure (functions, entry lines,
// helpers' parameters, lines and call sites, call order), what the edit did (helpers, single-use,
// closures, shared mutable state, a table or loop rewrite, the gaming moves and whether the formatter
// undid them, suppressions, config, other files), Ultracite's own partition and what it would print,
// and the session logs (cost, tokens, tool calls, commands, the final message, what the agent said
// about the function and the risks, and every read outside the run dir).
//
// See scripts/topics.cjs for the hooks this module implements.
