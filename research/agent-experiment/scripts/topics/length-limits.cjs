const UNCHANGED = new Set(["unchanged", "comments or formatting only"]);

/**
 * What the edit did, against the file it was given: the helpers it added (each one's parameters,
 * lines, call sites, whether it's nested in an entry function and reads or writes that function's
 * locals, whether it mutates a parameter or module state, an options bag, a rest parameter or
 * `arguments`), a table or loop rewrite (fewer `.replace` calls, a new `.reduce` or loop, `continue`s
 * gone), the gaming moves (blank lines or comments removed, statements joined onto one line, data
 * moved to module scope), suppressions and a changed export. `kinds` lists every category that
 * applies; `edit` is the headline.
 */
function editOf(subject, text, givenText) {
  if (text === null || text === undefined) return { edit: "file deleted" };
  if (text === givenText) return { edit: "unchanged", kinds: [] };
  const now = functionFacts(text, subject.basename);
  const given = functionFacts(givenText, subject.basename);
  if (now.error) return { edit: "doesn't parse", kinds: [], error: now.error };
  const sameCode =
    codeOnly(text, subject.basename) === codeOnly(givenText, subject.basename);
  const givenNames = new Set(given.functions.map((f) => f.name));
  const added = now.functions.filter((f) => !givenNames.has(f.name));
  const nowNames = new Set(now.functions.map((f) => f.name));
  const removed = given.functions
    .filter((f) => !nowNames.has(f.name))
    .map((f) => f.name);
  // The structure measure (the corpus oracle's), against the given file, for each entry.
  const structures = Object.fromEntries(
    subject.entries.map((e) => [
      e,
      oracle.structure(text, subject.basename, e, givenText),
    ])
  );
  const callSites = new Map();
  for (const st of Object.values(structures))
    for (const h of st.helpers ?? [])
      callSites.set(h.name, Math.max(callSites.get(h.name) ?? 0, h.callSites));
  const entriesNow = new Map(
    now.functions
      .filter((f) => subject.entries.includes(f.name))
      .map((f) => [f.name, f])
  );
  const entriesGiven = new Map(
    given.functions
      .filter((f) => subject.entries.includes(f.name))
      .map((f) => [f.name, f])
  );
  const helpers = added.map((f) => ({
    name: f.name,
    lines: f.endLine - f.startLine + 1,
    params: f.params,
    callSites: callSites.get(f.name) ?? null,
    nestedIn: f.enclosing,
    readsEnclosingLocals: f.readsEnclosingLocals,
    writesEnclosingLocals: f.writesEnclosingLocals,
    mutatesEnclosingLocals: f.mutatesEnclosingLocals,
    mutatesParams: f.mutatesParams,
    writesModuleState: f.writesModuleState,
    optionsBag: f.optionsBag,
    restParam: f.restParam,
    usesArguments: f.usesArguments,
  }));
  const kinds = [];
  if (helpers.length) kinds.push("helpers");
  if (helpers.some((h) => h.callSites === 1)) kinds.push("single-use helpers");
  if (helpers.some((h) => h.nestedIn)) kinds.push("nested helpers");
  if (helpers.some((h) => h.readsEnclosingLocals.length))
    kinds.push("closures over an entry's locals");
  if (
    helpers.some(
      (h) =>
        h.writesEnclosingLocals.length ||
        h.mutatesEnclosingLocals.length ||
        h.mutatesParams.length ||
        h.writesModuleState.length
    )
  )
    kinds.push("shared mutable state");
  if (helpers.some((h) => h.optionsBag)) kinds.push("options bag");
  if (helpers.some((h) => h.restParam)) kinds.push("rest parameter");
  if (helpers.some((h) => h.usesArguments)) kinds.push("arguments");
  if (helpers.some((h) => h.params >= 4))
    kinds.push("helper with 4+ parameters");
  const c0 = given.counts;
  const c1 = now.counts;
  const tableRewrite =
    c1.replaceCalls + c1.replaceAllCalls <=
      c0.replaceCalls + c0.replaceAllCalls - 5 ||
    c1.reduceCalls > c0.reduceCalls;
  if (tableRewrite) kinds.push("table or loop rewrite");
  if (c1.replaceAllCalls > c0.replaceAllCalls) kinds.push("more replaceAll");
  if (c1.continues !== c0.continues) kinds.push("continue statements changed");
  if (c1.loops !== c0.loops) kinds.push("loops changed");
  if (c1.topLevelDataVariables > c0.topLevelDataVariables)
    kinds.push("data moved to module scope");
  if (now.functions.some((f) => f.writesModuleState.length))
    kinds.push("module state written");
  // Blank lines and comments are counted over the whole file, so code moved into a helper with its
  // blank lines doesn't count as removing them.
  if (now.blankLines <= given.blankLines - 2) kinds.push("blank lines removed");
  if (now.commentLines < given.commentLines) kinds.push("comments removed");
  if (now.commentLines > given.commentLines) kinds.push("comments added");
  if (now.joinedLines > given.joinedLines) kinds.push("statements joined");
  if (removed.length) kinds.push("functions removed");
  // The exported names and parameter lists, in any order (moving a function isn't an API change).
  if (
    JSON.stringify([...now.exports].sort()) !==
    JSON.stringify([...given.exports].sort())
  )
    kinds.push("exports changed");
  const suppressions = scan(text);
  if (sumValues(suppressions) > sumValues(scan(givenText)))
    kinds.push("suppression");
  const entryCalls = Object.values(structures).reduce(
    (n, st) => n + (st.helperCallsFromEntry ?? 0),
    0
  );
  let edit;
  if (kinds.includes("suppression")) edit = "suppression";
  else if (sameCode) {
    const gaming = [
      "blank lines removed",
      "comments removed",
      "statements joined",
    ];
    edit = kinds.some((k) => gaming.includes(k))
      ? "lines removed or joined"
      : "comments or formatting only";
  } else if (helpers.length && entryCalls > 0)
    edit = tableRewrite
      ? "helpers extracted and rewritten"
      : "helpers extracted";
  else if (helpers.length) edit = "helpers added";
  else if (tableRewrite) edit = "table or loop rewrite";
  else edit = "edited in place";
  return {
    edit,
    kinds,
    helpers,
    removed,
    structures,
    entries: Object.fromEntries(
      subject.entries.map((e) => [
        e,
        {
          linesGiven: entriesGiven.get(e)
            ? entriesGiven.get(e).endLine - entriesGiven.get(e).startLine + 1
            : null,
          linesNow: entriesNow.get(e)
            ? entriesNow.get(e).endLine - entriesNow.get(e).startLine + 1
            : null,
          blankLinesGiven: entriesGiven.get(e)?.blankLines ?? null,
          blankLinesNow: entriesNow.get(e)?.blankLines ?? null,
        },
      ])
    ),
    counts: { given: c0, now: c1 },
    commentLines: { given: given.commentLines, now: now.commentLines },
    joinedLines: { given: given.joinedLines, now: now.joinedLines },
    exports: { given: given.exports, now: now.exports },
    suppressions,
  };
}

