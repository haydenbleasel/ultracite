/**
 * A string that was cut to length before it was redacted (session-stats.cjs truncates Codex's tool
 * inputs to 600 characters) can end in part of the home directory, which redaction doesn't see.
 * Any such tail is replaced by "~", everywhere in a value (react-effects.cjs's scrubCutHome).
 */
const HOME = homedir();
function scrubCutHome(value) {
  if (typeof value === "string") {
    for (let k = HOME.length - 1; k >= 3; k--)
      if (value.endsWith(HOME.slice(0, k))) return `${value.slice(0, -k)}~`;
    return value;
  }
  if (Array.isArray(value)) return value.map(scrubCutHome);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => [k, scrubCutHome(v)])
    );
  return value;
}

const OUTSIDE_RE =
  /(^|[\s"'=(:])(\/(Users|private|tmp|var|opt|etc|usr|Library)\b|~\/|<(repo|experiment|tmp|run-root|os-tmp-root)>|\$HOME|\$TMPDIR)|\.\.\//;

/**
 * Session-derived facts for one attempt, carried over from the previous measure.json when the
 * session log isn't there (a fresh checkout).
 */
function attemptSession(runDir, meta, attempt, previous, subject) {
  const dir = join(runDir, `attempt${attempt}`);
  const transcript = join(dir, "transcript.jsonl");
  const prev =
    previous?.attempts?.find((a) => a.attempt === attempt)?.session ?? null;
  if (!existsSync(transcript))
    return prev ? { ...prev, hasSessionLog: false } : { hasSessionLog: false };
  const stderr = existsSync(join(dir, "stderr.txt"))
    ? readFileSync(join(dir, "stderr.txt"), "utf8")
    : "";
  const stats = lib.redact(
    meta.agent === "claude"
      ? claudeStats(transcript)
      : codexStats(transcript, stderr)
  );
  // Redacted before anything is cut to length, so a truncated path can't keep part of the home
  // directory or the account name.
  const rawTexts =
    meta.agent === "claude" ? claudeTexts(transcript) : codexTexts(transcript);
  const texts = lib.redact(rawTexts);
  const otherRuns = readdirSync(lib.RUNS_DIR).filter((d) => d !== meta.runId);
  const log = readFileSync(transcript, "utf8");
  const count = (text) =>
    Object.fromEntries(
      Object.entries(EXPOSURE_PATTERNS(otherRuns))
        .map(([k, re]) => [k, (text.match(re) ?? []).length])
        .filter(([, v]) => v > 0)
    );
  // The whole log, as every topic counts it (for Codex that includes its memory of the user's
  // projects, which names the Ultracite checkout); the tool calls and their output; and the tool
  // calls' inputs alone (what the agent asked to read, search or run).
  const exposure = count(log);
  // Counted on the unredacted texts, which the patterns are written for.
  const exposureInToolCalls = count(rawTexts.toolTraffic);
  const exposureInToolInputs = count(rawTexts.toolInputs);
  const outsideRunDir = (stats.toolCalls ?? []).filter((c) => {
    if (typeof c.target !== "string") return false;
    const stripped = c.target.split(meta.cwd).join("<RUN>");
    return OUTSIDE_RE.test(stripped);
  });
  const all = [texts.finalMessage ?? "", ...texts.otherText];
  const mentions = (re, n) =>
    [
      ...new Set(
        all
          .flatMap(sentences)
          .filter((s) => re.test(s))
          .map((s) => s.slice(0, 500))
      ),
    ].slice(0, n);
  // Codex runs commands in its sandbox; Claude Code ran only the Bash calls it didn't refuse.
  const commands =
    meta.agent === "claude"
      ? texts.bash.map((b) => ({
          command: b.command.slice(0, 300),
          refused: b.refused,
          refusal: b.refusal,
        }))
      : (stats.toolCalls ?? [])
          .filter(
            (c) =>
              typeof c.target === "string" &&
              !/apply_patch|\*\*\* Begin Patch/.test(c.target) &&
              /exec|shell/.test(String(c.tool))
          )
          .map((c) => ({
            command: c.target.slice(0, 300),
            refused: false,
            refusal: null,
          }));
  const ranTools = commands
    .filter((c) => !c.refused && runsTool(c.command))
    .map((c) => c.command);
  const inputsMatching = (re) =>
    texts.toolInputList.filter((t) => re.test(t)).map((t) => t.slice(0, 300));
  // Whole commands: Claude Code's Bash calls it didn't refuse, Codex's tool inputs.
  const fullCommands =
    meta.agent === "claude"
      ? texts.bash.filter((b) => !b.refused).map((b) => b.command)
      : texts.toolInputList;
  // The agent's own behaviour checks: a script that loads the subject (or a copy) and compares or
  // asserts.
  const ownBehaviourChecks = fullCommands
    .filter(
      (c) =>
        /assert|deepStrictEqual|strictEqual|console\.log\(|JSON\.stringify\(|===/.test(
          c
        ) &&
        (c.includes(subject.basename) ||
          /Transpiler|stripTypeScriptTypes|transpile|--experimental-strip-types|tsx |ts-node|import\(/.test(
            c
          ))
    )
    .map((c) => c.slice(0, 200));
  return scrubCutHome(
    lib.redact({
      hasSessionLog: true,
      models: stats.models ?? [],
      effort: stats.effort ?? stats.reasoningEffort ?? [],
      modelCalls:
        meta.agent === "claude"
          ? (stats.apiResponses ?? null)
          : texts.modelCalls,
      costUSD: stats.costUSD ?? null,
      tokens: stats.tokens ?? null,
      tokensUsedReportedOnStderr: stats.tokensUsedReportedOnStderr ?? null,
      thinkingBlocks: texts.thinkingBlocks,
      toolCalls: (stats.toolCalls ?? []).map((c) => c.tool),
      toolNames: [...new Set(texts.toolNames)],
      toolCallTargets: (stats.toolCalls ?? []).map((c) =>
        typeof c.target === "string" ? c.target.slice(0, 200) : null
      ),
      toolErrors: (stats.toolErrors ?? []).map((e) => e.slice(0, 200)),
      commands,
      ranLinterOrTests: ranTools,
      refusedCommands: commands.filter((c) => c.refused).map((c) => c.command),
      triedToRunLinterOrTests: commands.some((c) => runsTool(c.command)),
      searchedForTests: inputsMatching(TEST_FILE_RE),
      readInstalledCopies: inputsMatching(INSTALLED_RE),
      webAccess: inputsMatching(WEB_RE),
      ownBehaviourChecks,
      projectInstructionsLoaded: texts.instructions,
      edits: texts.edits.map((t) => t.slice(0, 800)),
      finalMessage: texts.finalMessage
        ? texts.finalMessage.slice(0, 4000)
        : null,
      understood: Object.fromEntries(
        Object.entries(UNDERSTOOD).map(([k, re]) => [k, mentions(re, 12)])
      ),
      upstreamMentions: mentions(UPSTREAM_RE, 12),
      exposure,
      exposureInToolCalls,
      exposureInToolInputs,
      outsideRunDir,
    })
  );
}

