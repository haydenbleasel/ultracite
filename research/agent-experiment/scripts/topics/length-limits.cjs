const LIMIT_RULE = {
  oxlint: "max-lines-per-function",
  biome: "lint/complexity/noExcessiveLinesPerFunction",
  eslint: "max-lines-per-function",
};
const LINTERS = {
  oxlint: {
    pass: 'linters.ts runOxlintPass: oxlint --fix (--fix-dangerously with --unsafe) ., oxfmt --write ., oxlint -f json . (init\'s oxlint.config.ts: extends [core], with rules: { "max-lines-per-function": "error" })',
  },
  biome: {
    pass: 'linters.ts runBiomePass: biome check --write --no-errors-on-unmatched [--unsafe] --reporter=json ./ (init\'s biome.jsonc: extends ultracite/biome/core, with linter.rules.complexity.noExcessiveLinesPerFunction: "error")',
  },
  eslint: {
    pass: 'linters.ts runEslintPass: eslint --fix ., stylelint --fix, prettier --write ., eslint -f json-with-metadata . (init\'s eslint.config.mjs: core, with a block setting "max-lines-per-function": "error"). fix.ts drops --unsafe for ESLint with a warning, so `ultracite fix --unsafe` is the same pass',
  },
};

/** The mirror's pass for a linter on a project dir. */
function mirrorPass(linter, dir, passthrough) {
  if (linter === "oxlint")
    return mirror.oxlintPass({
      cwd: dir,
      files: [],
      config: CONFIG.oxlint,
      fmtConfig: CONFIG.oxfmt,
      passthrough,
    }).diagnostics;
  if (linter === "biome") {
    copyFileSync(CONFIG.biome, join(dir, "biome.jsonc"));
    return mirror.biomePass({ cwd: dir, files: [], passthrough }).diagnostics;
  }
  return mirror.eslintPass({
    cwd: dir,
    files: [],
    config: CONFIG.eslint,
    prettierConfig: CONFIG.prettier,
    stylelintConfig: CONFIG.stylelint,
  }).diagnostics;
}

/**
 * What `ultracite fix` and `ultracite fix --unsafe` do with Oxlint, Biome and ESLint, no agent:
 * the adapter's fixAndCollect on a project with the subject and what init writes for that linter,
 * with the limit turned on. Run with the mirror (the harness's configs) and with Ultracite's real
 * adapter (init's configs and node_modules links), which must agree. Each result: whether any
 * function was split or added (names), the entry functions' lines before and after (the formatter
 * moves them), which length diagnostics are still reported (what `--claude`/`--codex` would hand
 * over), and the oracle's verdict against the input's behaviour.
 */
async function deterministicPaths() {
  const examples = examplesJson();
  const { root, script } = linkedRoot("deterministic");
  const out = [];
  let n = 0;
  for (const s of subjectsManifest()) {
    const subject = fullSubject(s);
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const inputs = {
      "upstream (header stripped)": cleanText(
        original,
        examples.stripFields,
        s.base
      ),
      "as handed to the agent (Oxlint-normalised)": readFileSync(
        join(HERE, s.path),
        "utf8"
      ),
    };
    for (const [inputName, text] of Object.entries(inputs)) {
      const inputTrace = oracle.run(subject.oracleId, text);
      const inputFns = functionsOf(text, s.basename).functions;
      for (const linter of Object.keys(LINTERS)) {
        for (const unsafe of [false, true]) {
          n++;
          // ESLint has no unsafe tier: fix.ts drops the flag, so the pass is the safe one.
          const passthrough = unsafe && linter !== "eslint" ? ["--unsafe"] : [];
          const mirrorDir = join(root, `mirror-${n}`);
          const realDir = join(root, `real-${n}`);
          for (const d of [mirrorDir, realDir]) {
            mkdirSync(d, { recursive: true });
            writeFileSync(join(d, s.basename), text);
            writeFileSync(join(d, "tsconfig.json"), TSCONFIG());
            putUserFiles(d, linter);
          }
          if (linter === "oxlint")
            for (const f of NESTED_CONFIGS)
              rmSync(join(mirrorDir, f), { force: true });
          if (linter === "biome")
            writeFileSync(join(realDir, ".gitignore"), "node_modules\n");
          let mine;
          let mirrorError = null;
          try {
            mine = mirrorPass(linter, mirrorDir, passthrough);
          } catch (error) {
            mirrorError = String(error.message).slice(0, 300);
            mine = [];
          }
          const real = realAdapter(script, linter, "collect", realDir, {
            passthrough,
          });
          const after = readFileSync(join(mirrorDir, s.basename), "utf8");
          const realAfter = readFileSync(join(realDir, s.basename), "utf8");
          const afterFns = functionsOf(after, s.basename).functions;
          const names = (fs) =>
            fs
              .filter((f) => f.depth === 0)
              .map((f) => f.name)
              .sort();
          const result = oracle.run(subject.oracleId, after);
          const exact = oracle.compare(inputTrace, result);
          const keyOrder = result.loadError
            ? exact
            : oracle.compare(
                { trace: canonTrace(inputTrace.trace) },
                { trace: canonTrace(result.trace) }
              );
          const mineHere = mine.filter(
            (d) => relFile(mirrorDir, d.file) === s.basename
          );
          const entryLines = (fs) =>
            Object.fromEntries(
              s.entries.map((e) => [
                e,
                fs.find((f) => f.name === e && f.depth === 0)?.lines ?? null,
              ])
            );
          out.push({
            subject: s.id,
            input: inputName,
            linter,
            command: unsafe ? "ultracite fix --unsafe" : "ultracite fix",
            passthrough,
            fixPass: LINTERS[linter].pass,
            changed: after !== text,
            codeChanged:
              codeOnly(after, s.basename) !== codeOnly(text, s.basename),
            functionsBefore: names(inputFns),
            functionsAfter: names(afterFns),
            functionsAddedOrRemoved:
              JSON.stringify(names(inputFns)) !==
              JSON.stringify(names(afterFns)),
            entryLinesBefore: entryLines(inputFns),
            entryLinesAfter: entryLines(afterFns),
            limitStillReported: mineHere
              .filter((d) => d.rule === LIMIT_RULE[linter])
              .map((d) => `${functionAt(afterFns, d.line)}: ${d.message}`),
            limitHelp: [
              ...new Set(
                mineHere
                  .filter((d) => d.rule === LIMIT_RULE[linter])
                  .map((d) => d.help ?? null)
              ),
            ],
            otherStillReported: mineHere.filter(
              (d) => d.rule !== LIMIT_RULE[linter]
            ).length,
            oracle: {
              verdict: exact.verdict,
              ignoringKeyOrder: keyOrder.verdict,
              differing: exact.differing ?? null,
            },
            typeErrors: typeErrors(after, s.basename, `det-${n}-tsc`).length,
            mirrorError,
            realAdapter: real.error
              ? { error: real.error }
              : {
                  fileMatches: realAfter === after,
                  diagnosticsMatch:
                    JSON.stringify(shape(realDir, real.diagnostics)) ===
                    JSON.stringify(shape(mirrorDir, mine)),
                },
          });
          const last = out.at(-1);
          console.log(
            `${s.id} ${linter}${unsafe ? " --unsafe" : ""} on ${inputName}: changed ${last.changed} (code ${last.codeChanged}); functions ${last.functionsAddedOrRemoved ? "CHANGED" : "same"}; entry lines ${JSON.stringify(last.entryLinesBefore)} -> ${JSON.stringify(last.entryLinesAfter)}; limit left ${last.limitStillReported.length}; oracle ${last.oracle.verdict}/${last.oracle.ignoringKeyOrder}; real adapter ${JSON.stringify(last.realAdapter)}`
          );
        }
      }
    }
  }
  return out;
}

