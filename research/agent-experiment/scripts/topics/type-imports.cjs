/**
 * Drops the header fields that carry the analysis (examples.json `stripFields` and
 * EXTRA_STRIP_FIELDS) from the subject, and applies the TEXT_EDITS for `part` (the subject, or
 * another file of its folder by path). A field continues until a blank comment line or the next
 * field, which starts with a capital letter after " * ".
 */
function cleanText(text, stripFields, base, part = "subject") {
  const fields =
    part === "subject" ? [...stripFields, ...EXTRA_STRIP_FIELDS] : [];
  let cleaned = text;
  if (fields.length) {
    const drop = new RegExp(
      `^ \\* (${fields.map(lib.escapeRegExp).join("|")})\\b`
    );
    const out = [];
    let dropping = false;
    for (const line of text.split("\n")) {
      if (drop.test(line)) {
        dropping = true;
        continue;
      }
      if (dropping) {
        if (line === " *" || line === " */" || /^ \* [A-Z]/.test(line))
          dropping = false;
        else continue;
      }
      out.push(line);
    }
    if (out[0] === "/*" && out[1] === " *") out.splice(1, 1);
    cleaned = out.join("\n");
  }
  for (const e of TEXT_EDITS[base][part] ?? []) {
    if (!cleaned.includes(e.from))
      throw new Error(
        `${base} ${part}: text edit not found: ${e.from.slice(0, 60)}`
      );
    cleaned = cleaned.replace(e.from, () => e.to);
  }
  return cleaned;
}

