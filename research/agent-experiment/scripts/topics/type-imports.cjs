// The type-imports post: Ultracite turns on typescript-eslint's `consistent-type-imports` (with
// `consistent-type-exports` and `no-import-type-side-effects`), `import/consistent-type-specifier-style`
// set to "prefer-top-level", and the import rules that interact with them (`import/no-duplicates`,
// `no-duplicate-imports`), all in Oxlint core, with Biome's `useImportType` and `useExportType`. The
// safe fixes convert plain value imports used only as types before an agent sees them, so what
// reaches an agent is what the fixes can't do or leave unsettled: `import()` type annotations (no
// fix), duplicates the single Oxlint pass leaves after splitting, and reports next to rules that push
// the same line toward a static import. When Ultracite hands those to an agent: does it fix them
// without changing which modules load, in which order, under the repo's build, under a compiler that
// keeps imports as written and under one that elides them; does it pick the form the rules ask for
// (`import type` at the top level); does it fall for the moves that compile and change behaviour (a
// value or static import that loads a module eagerly, one merged `import type` that makes a value
// type-only, `import x = require()`); does it leave a report for review when the rule's help would
// change what loads; does its edit survive the next fix pass in Oxlint, ESLint and Biome; and does
// it ever write `import { type X }`?
//
// Subjects come from research/corpus/examples/type-imports/ (type-imports-examples.cjs). Each is a
// folder: the subject file and the modules it imports (copies from the same commit, or STUBs).
//   a  Next.js's telemetry/flush-telemetry.ts: `InstanceType<typeof import('./storage').Telemetry>`.
//      Right: `import type { Telemetry }` (or a type-only namespace import); same in every mode.
//   b  tRPC's TRPCClientError.ts: an `import type` and a mixed import of one module, which the fix
//      pass splits into three declarations that no-duplicates and no-duplicate-imports report.
//      Right: one value import of isObject and one `import type`; one merged `import type` makes
//      isObject type-only.
//   c  Next.js's client/normalize-locale-path.ts: `require(...) as typeof import(...)` inside the
//      `__NEXT_I18N_SUPPORT` branch, with node/global-require and unicorn/prefer-module on the same
//      line. Right: type the require without `import()` and leave the require rules for review; a
//      static import loads the i18n module in every app.
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks), with
// the mirror of Ultracite's agent-fix code at its v4 revision (the CLI at 60a16471; see
// scripts/ultracite-adapters.cjs), which this module selects. The run dir is exactly what
// `ultracite init --linter oxlint` leaves (generated by running init), with the subject's folder
// and a tsconfig.json from the corpus examples. The rules are on there already; the user changes
// nothing.
//
// The handoff. prepareSubjects runs the Oxlint pass until nothing changes (checked not to change
// behaviour in any oracle mode), and the handoff, and every re-lint, keep the topic's six rules
// (plus, for C, the two require rules on the same line) and any other diagnostic that is new since
// the prepared subject (by Ultracite's own rule-and-message key, diff.ts). That models a project
// that lints clean apart from these rules. It is a deviation from a real project, recorded in
// handoff.json and REPORT.md, and every diagnostic of every view is measured.
//
// Each attempt is measured as the agent left the file and as verify left it (the loop's next Oxlint
// fix pass): Oxlint (the user's config, and with --type-aware), ESLint (core as init writes it, and
// with the type-aware preset), Biome (core), inline config honoured and ignored; tsc with the run
// dir's tsconfig, with verbatimModuleSyntax on and with imports elided; the behaviour oracle (the
// corpus's type-imports-oracle.cjs, imported unchanged) in its three modes; what the edit did (the
// import form, top-level or inline, B's declarations, C's require); Ultracite's own partition and
// what it would print; and the session logs.
//
// See scripts/topics.cjs for the hooks this module implements.
