/**
 * A mutant's text. Two kinds:
 *   variant  a corpus variant, made by the corpus's own variantsOf from the cleaned corpus subject
 *            (header stripped), then Ultracite's Oxlint pass until nothing changes (what verify
 *            leaves after an agent wrote that edit), unless `normalise: false` (what the agent
 *            wrote)
 *   edits    [from, to] pairs on the prepared subject, each matching exactly once; `normalise:
 *            true` puts the result through the same pass
 */
function mutantText(m) {
  if (mutantCache.has(m.id)) return mutantCache.get(m.id);
  const s = fullSubject(subjectsManifest().find((x) => x.base === m.base));
  let text;
  const others = preparedTree(s);
  delete others[s.basename];
  const settle = (t) =>
    normalise(
      s,
      { ...others, [s.basename]: t },
      commonRunFiles(),
      `mutant-${m.id}`
    ).files[s.basename];
  if (m.variant) {
    variantsCache ??= corpusVariants();
    const original = readFileSync(join(EXAMPLES, s.dir, s.basename), "utf8");
    const cleaned = cleanText(
      original,
      examplesJson().stripFields,
      m.base,
      "subject"
    );
    const v = variantsCache.variantsOf(m.base, cleaned)[m.variant];
    if (!v) throw new Error(`${m.id}: no corpus variant ${m.variant}`);
    text = m.normalise === false ? v.text : settle(v.text);
  } else {
    text = preparedTextOf(s);
    for (const [from, to] of m.edits ?? []) {
      const n = text.split(from).length - 1;
      if (n !== 1)
        throw new Error(
          `${m.id}: edit matches ${n} times: ${from.slice(0, 60)}`
        );
      text = text.replace(from, () => to);
    }
    if (m.normalise) text = settle(text);
  }
  mutantCache.set(m.id, text);
  return text;
}

/**
 * The PRIMING check on the corpus folders before they're stripped: it must find the analysis in
 * every subject and every other file (so a clean prepared subject means the check ran).
 */
function primingSanity() {
  const out = {};
  for (const s of SUBJECTS) {
    out[s.base] = {};
    for (const rel of [s.basename, ...s.others])
      out[s.base][rel] = primedLines(
        readFileSync(join(EXAMPLES, s.dir, rel), "utf8"),
        rel
      ).length;
  }
  return out;
}

/** One self-test case: a text measured against its subject's prepared state and checked. */
async function selfTestCase(m, bases, examples) {
  const s = fullSubject(subjectsManifest().find((x) => x.base === m.base));
  const st = await measureState(
    s,
    mutantText(m),
    `self-${m.id}`,
    bases[m.base]
  );
  const outcome = outcomeOf(st);
  const response = responseOf(s, st, outcome, "none");
  const e = m.expect ?? {};
  const why = [];
  for (const mode of MODES)
    if (e[mode] !== undefined && st.oracle[mode].verdict !== e[mode])
      why.push(`oracle ${mode} ${st.oracle[mode].verdict}`);
  if (e.oracle !== undefined && st.oracle.verdict !== e.oracle)
    why.push(`oracle ${st.oracle.verdict}`);
  if (e.form !== undefined && outcome !== e.form) why.push(`form "${outcome}"`);
  if (e.response !== undefined && response !== e.response)
    why.push(`response "${response}"`);
  if (e.oxlint !== undefined) {
    const got = st.topicLeft.oxlint;
    if (JSON.stringify(got) !== JSON.stringify(e.oxlint))
      why.push(`oxlint ${JSON.stringify(got)}`);
  }
  for (const k of e.kinds ?? [])
    if (!(st.edit.kinds ?? []).includes(k)) why.push(`kind ${k}`);
  for (const [setting, codes] of Object.entries(e.tsc ?? {})) {
    const got = Object.keys(st.tsc[setting].codes).join(",");
    if (got !== codes) why.push(`tsc ${setting} ${got}`);
  }
  if (
    e.inline !== undefined &&
    st.edit.inlineTypeSpecifiers?.after !== e.inline
  )
    why.push(`inline ${st.edit.inlineTypeSpecifiers?.after}`);
  // A corpus variant: its verdict in every mode must equal examples.json's (as written, or after
  // one fix pass for a normalised variant), and its tsc codes (examples.json's repo setting) too.
  let corpus = null;
  if (m.variant) {
    const v = examples.subjects[m.base].variants[m.variant];
    const theirs = m.normalise === false ? v.oracle : v.afterOneFixPass.oracle;
    corpus = {
      kind: v.kind,
      oracle: Object.fromEntries(MODES.map((x) => [x, theirs[x].verdict])),
      ours: Object.fromEntries(MODES.map((x) => [x, st.oracle[x].verdict])),
      tsc: v.tsc,
    };
    for (const x of MODES)
      if (theirs[x].verdict !== st.oracle[x].verdict)
        why.push(`oracle ${x} differs from the corpus variant`);
  }
  return {
    name: `${m.id}: ${m.description}`,
    mutant: m.id,
    variant: m.variant ?? null,
    normalised: m.variant ? m.normalise !== false : Boolean(m.normalise),
    oracle: Object.fromEntries(MODES.map((x) => [x, st.oracle[x].verdict])),
    outcome,
    response,
    kinds: st.edit.kinds,
    topicLeft: st.topicLeft,
    tsc: Object.fromEntries(TSC_SETTINGS.map((x) => [x, st.tsc[x].codes])),
    inline: st.edit.inlineTypeSpecifiers ?? null,
    expected: e,
    corpus,
    pass: why.length === 0,
    why,
  };
}

