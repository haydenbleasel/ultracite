/**
 * The corpus's hand-made variants (type-imports-examples.cjs `variantsOf`), read from the script
 * without running it: its source is compiled with the final `main()` call left out. The script
 * itself is unchanged, so examples.json regenerates as it is. The script requires the corpus library
 * and oracle, which are already loaded here (the same module instances).
 */
function corpusVariants() {
  const file = join(CORPUS, "scripts/type-imports-examples.cjs");
  const src = readFileSync(file, "utf8");
  if (!src.trimEnd().endsWith(MAIN_CALL))
    throw new Error("type-imports-examples.cjs no longer ends with main()");
  const m = new Module(file, module);
  m.filename = file;
  m.paths = Module._nodeModulePaths(dirname(file));
  const had = Object.hasOwn(process.env, "CORPUS_REPO_LISTS");
  m._compile(
    `${src.trimEnd().slice(0, -MAIN_CALL.length)}\nmodule.exports = { variantsOf };\n`,
    file
  );
  if (!had) delete process.env.CORPUS_REPO_LISTS;
  return m.exports;
}

