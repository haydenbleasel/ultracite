  const compilerOptions = {};
  for (const [k, v] of Object.entries(corpus.compilerOptions)) {
    if (k !== "paths") {
      compilerOptions[k] = v;
      continue;
    }
    const own = Object.fromEntries(
      Object.entries(v)
        .filter(([, targets]) =>
          targets.every((t) => t.startsWith(`./${subject.dir}/`))
        )
        .map(([spec, targets]) => [
          spec,
          targets.map((t) => `./${t.slice(subject.dir.length + 3)}`),
        ])
    );
    if (Object.keys(own).length > 0) compilerOptions.paths = own;
  }
