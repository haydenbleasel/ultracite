/** Writes a tree ({ relative path: text }) under `dir`. */
function writeTree(dir, files) {
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    if (existsSync(join(dir, rel))) chmodSync(join(dir, rel), 0o644);
    writeFileSync(join(dir, rel), text);
  }
}
/** Every file under `dir`, as forward-slash paths relative to it, sorted. */
function listTree(dir) {
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((x, y) =>
      x.name.localeCompare(y.name)
    )) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out.push(relative(dir, p).split("\\").join("/"));
    }
  };
  if (existsSync(dir)) walk(dir);
  return out;
}
const readTree = (dir) =>
  Object.fromEntries(
    listTree(dir).map((rel) => [rel, readFileSync(join(dir, rel), "utf8")])
  );

