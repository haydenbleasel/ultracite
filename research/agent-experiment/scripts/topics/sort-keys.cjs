/**
 * What `ultracite fix` does with Oxlint or Biome, no agent: the adapter's fixAndCollect on a
 * project with the subject and what init writes for that linter. Run with the mirror (the
 * harness's configs) and with Ultracite's real adapter (init's configs and node_modules links),
 * which must agree. Each result: which objects under test the fix pass reordered, what's still
 * reported (sort-keys and other rules), and the oracle's verdict against the subject's behaviour.
 */
async function deterministicPaths() {
  const examples = examplesJson();
  const { root, script } = linkedRoot("deterministic");
  const out = [];
  let n = 0;
  for (const s of subjectsManifest()) {
    const subject = fullSubject(s);
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const inputs = {
      "verbatim (header stripped)": cleanText(
        original,
        examples.stripFields,
        s.base
      ),
      "as handed to the agent (ESLint-normalised)": readFileSync(
        join(HERE, s.path),
        "utf8"
      ),
    };
    for (const [inputName, text] of Object.entries(inputs)) {
      for (const linter of ["oxlint", "biome"]) {
        n++;
        const mirrorDir = join(root, `mirror-${n}`);
        const realDir = join(root, `real-${n}`);
        for (const d of [mirrorDir, realDir]) {
          mkdirSync(d, { recursive: true });
          writeFileSync(join(d, s.basename), text);
          for (const stored of readdirSync(join(INIT_DIR, linter))) {
            const name = realInitName(stored);
            copyFileSync(join(INIT_DIR, linter, stored), join(d, name));
            chmodSync(join(d, name), 0o644);
          }
        }
        let mine;
        if (linter === "oxlint") {
          for (const f of ["oxlint.config.ts", "oxfmt.config.ts"])
            rmSync(join(mirrorDir, f), { force: true });
          mine = mirror.oxlintPass({
            cwd: mirrorDir,
            files: [],
            config: CONFIG.oxlint,
            fmtConfig: CONFIG.oxfmt,
          }).diagnostics;
        } else {
          copyFileSync(CONFIG.biome, join(mirrorDir, "biome.jsonc"));
          mine = mirror.biomePass({ cwd: mirrorDir, files: [] }).diagnostics;
        }
        const real = realAdapter(script, linter, "collect", realDir);
        const after = readFileSync(join(mirrorDir, s.basename), "utf8");
        const realAfter = readFileSync(join(realDir, s.basename), "utf8");
        const edit = editOf(subject, after, text);
        const st = judge(subject, after, `det-${n}-oracle`);
        const sortLeft = mine.filter(
          (d) => d.file === s.basename && isSortRule(d.rule)
        );
        out.push({
          subject: s.id,
          input: inputName,
          linter,
          fixPass:
            linter === "oxlint"
              ? "linters.ts runOxlintPass: oxlint --fix ., oxfmt --write ., oxlint -f json . (init's oxlint.config.ts: extends [core])"
              : "linters.ts runBiomePass: biome check --write --no-errors-on-unmatched --reporter=json ./ (init's biome.jsonc: extends ultracite/biome/core)",
          objectsUnderTest: edit.targets?.length
            ? edit.targets.map((t) => ({
                name: t.name,
                status: t.status,
                keys: t.keys,
              }))
            : subject.targets.map((t) => ({
                name: t.name,
                status: "original",
                keys: t.keys,
              })),
          edit: edit.edit,
          sortKeysStillReported: sortLeft.map((d) => ({
            line: d.line,
            message: d.message,
            help: d.help ?? null,
          })),
          otherStillReported: mine.filter(
            (d) => d.file === s.basename && !isSortRule(d.rule)
          ).length,
          otherFilesReported: [
            ...new Set(
              mine.filter((d) => d.file !== s.basename).map((d) => d.file)
            ),
          ],
          oracle: {
            verdict: st.verdict,
            differences: st.differences,
            encodingChanged: st.encodingChanged,
            example: st.example,
          },
          typeErrors: typeErrors(after, s.basename, `det-${n}-tsc`).length,
          realAdapter: real.error
            ? { error: real.error }
            : {
                fileMatches: realAfter === after,
                diagnosticsMatch:
                  JSON.stringify(shape(realDir, real.diagnostics)) ===
                  JSON.stringify(shape(mirrorDir, mine)),
              },
        });
        const last = out.at(-1);
        console.log(
          `${s.id} ${linter} on ${inputName}: ${last.edit}; ${last.objectsUnderTest.map((t) => `${t.name} ${t.status}`).join(", ")}; sort-keys left ${last.sortKeysStillReported.length}, other ${last.otherStillReported}; oracle ${last.oracle.verdict}; real adapter ${JSON.stringify(last.realAdapter)}`
        );
      }
    }
  }
  return out;
}

