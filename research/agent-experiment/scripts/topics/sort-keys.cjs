/** A mutant's text: its edits applied to the prepared subject, each matching exactly once. */
function mutantText(m) {
  const s = subjectsManifest().find((x) => x.base === m.base);
  let text = readFileSync(join(HERE, s.path), "utf8");
  for (const [from, to] of m.edits) {
    const n = text.split(from).length - 1;
    if (n !== 1)
      throw new Error(`${m.id}: edit matches ${n} times: ${from.slice(0, 60)}`);
    text = text.replace(from, () => to);
  }
  return text;
}

/**
 * The PRIMING check on the corpus subjects before they're stripped: it must find the analysis in
 * every one of them (so a clean prepared subject means the check ran, not that it can't match).
 */
function primingSanity() {
  const out = {};
  for (const [base, b] of Object.entries(BASES)) {
    const text = readFileSync(join(EXAMPLES, b.example), "utf8");
    out[base] = commentsOf(text, b.basename)
      .comments.flatMap((c) => (c.type === "Line" ? [c.value.trim()] : c.lines))
      .filter((line) => PRIMING.some((re) => re.test(line))).length;
  }
  return out;
}

const fullSubject = (s) => ({ ...s, ...subjectOf(s.id) });

async function selfTest() {
  const examples = examplesJson();
  const subjects = subjectsManifest();
  const cases = [];
  const record = (c) => {
    cases.push(c);
    console.log(
      `${c.pass ? "OK  " : "BAD "} ${c.name}: oracle ${c.oracle}, ${c.outcome}, ESLint sort-keys ${c.eslintSortLeft}/${c.eslintSortLeftHonor}${c.why.length ? ` <- ${c.why.join(", ")}` : ""}`
    );
  };
  const bases = {};
  for (const s of subjects) {
    const subject = fullSubject(s);
    const text = readFileSync(join(HERE, s.path), "utf8");
    bases[s.base] = await measureState(subject, text, `self-${s.base}-before`);
    const st = await measureState(
      subject,
      text,
      `self-${s.base}`,
      bases[s.base]
    );
    const why = [];
    if (st.oracle.verdict !== "same") why.push("oracle");
    if (outcomeOf(st) !== "unchanged") why.push("outcome");
    record({
      name: `${s.base} as prepared`,
      oracle: st.oracle.verdict,
      outcome: outcomeOf(st),
      eslintSortLeft: st.views["eslint core"].sortIgnore.length,
      eslintSortLeftHonor: st.views["eslint core"].sortHonor.length,
      pass: why.length === 0,
      why,
    });
  }
  for (const m of mutantsFile()) {
    const s = subjects.find((x) => x.base === m.base);
    const subject = fullSubject(s);
    const st = await measureState(
      subject,
      mutantText(m),
      `self-${m.id}`,
      bases[m.base]
    );
    const outcome = outcomeOf(st);
    const why = [];
    if (st.oracle.verdict !== m.expect.oracle) why.push("oracle");
    if (outcome !== m.expect.outcome) why.push("outcome");
    const left = st.views["eslint core"].sortIgnore.length;
    const leftHonor = st.views["eslint core"].sortHonor.length;
    if (left !== m.expect.eslintSortLeft) why.push("ESLint sort-keys");
    if (leftHonor !== m.expect.eslintSortLeftHonor)
      why.push("ESLint sort-keys (inline config honoured)");
    if (st.typeErrors.length > 0) why.push(`tsc: ${st.typeErrors[0]}`);
    // The corpus variants were linted with ESLint's inline config ignored (and honoured), and
    // with Oxlint and Biome honouring their disable comments, as they always do.
    let corpus = null;
    if (m.mirrors) {
      const v = examples.variants.find((x) => x.id === m.mirrors);
      corpus = {
        oracle: v.oracle.verdict,
        eslint: v.focus.eslint.length,
        "eslint (inline config honoured)":
          v.focus["eslint (inline config honoured)"].length,
        oxlint: v.focus.oxlint.length,
        biome: v.focus.biome.length,
      };
      if (v.oracle.verdict !== st.oracle.verdict)
        why.push("oracle differs from the corpus variant");
      if (corpus.eslint !== left)
        why.push("ESLint differs from the corpus variant");
      if (corpus["eslint (inline config honoured)"] !== leftHonor)
        why.push(
          "ESLint (inline config honoured) differs from the corpus variant"
        );
      if (corpus.oxlint !== st.views["oxlint core"].sortHonor.length)
        why.push("Oxlint differs from the corpus variant");
      if (corpus.biome !== st.views["biome core"].sortHonor.length)
        why.push("Biome differs from the corpus variant");
    }
    record({
      name: `${m.id}: ${m.description}`,
      mutant: m.id,
      oracle: st.oracle.verdict,
      outcome,
      eslintSortLeft: left,
      eslintSortLeftHonor: leftHonor,
      expected: m.expect,
      edit: {
        targets: st.edit.targets?.map((t) => `${t.name}: ${t.status}`) ?? [],
        constructs: st.edit.constructs ?? [],
      },
      sortLeft: Object.fromEntries(
        VIEWS.map((v) => [v, st.views[v].sortIgnore.length])
      ),
      corpus,
      pass: why.length === 0,
      why,
    });
  }
  const primingCheck = primingSanity();
  const primingPass = Object.values(primingCheck).every((n) => n > 0);
  console.log(
    `${primingPass ? "OK  " : "BAD "} priming patterns match the unstripped corpus subjects: ${JSON.stringify(primingCheck)}`
  );
  const mirrorCheck = mirrorEquivalence();
  const failures =
    cases.filter((c) => !c.pass).length +
    mirrorCheck.cases.filter((c) => !c.pass).length +
    (primingPass ? 0 : 1);
  mkdirSync(lib.RESULTS_DIR, { recursive: true });
  writeFileSync(
    join(lib.RESULTS_DIR, "oracle-self-test.json"),
    `${JSON.stringify(
      lib.redact({
        runtime: `node ${process.version}`,
        oracle:
          "research/corpus/scripts/sort-keys-oracle.cjs (shared with the corpus)",
        cases,
        primingCheck: {
          note: "lines of the unstripped corpus subjects' comments that the PRIMING patterns match; each must be above 0",
          hits: primingCheck,
          pass: primingPass,
        },
        mirrorCheck,
        failures,
      }),
      null,
      2
    )}\n`
  );
  return failures;
}

