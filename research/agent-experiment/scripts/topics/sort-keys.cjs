/**
 * Drops the header fields that carry the analysis (examples.json `stripFields`: the subject line,
 * the rules, why the order does or doesn't matter, what the project did, the behaviour to preserve,
 * the expected and tempting responses). A field continues until a blank comment line or the next
 * field, which starts with a capital letter after " * ". Then applies TEXT_EDITS.
 */
function cleanText(text, stripFields, base) {
  const drop = new RegExp(
    `^ \\* (${stripFields.map(lib.escapeRegExp).join("|")})\\b`
  );
  const out = [];
  let dropping = false;
  for (const line of text.split("\n")) {
    if (drop.test(line)) {
      dropping = true;
      continue;
    }
    if (dropping) {
      if (line === " *" || line === " */" || /^ \* [A-Z]/.test(line))
        dropping = false;
      else continue;
    }
    out.push(line);
  }
  if (out[0] === "/*" && out[1] === " *") out.splice(1, 1);
  let cleaned = out.join("\n");
  for (const e of TEXT_EDITS[base]) {
    if (!cleaned.includes(e.from))
      throw new Error(`${base}: text edit not found: ${e.from.slice(0, 60)}`);
    cleaned = cleaned.replace(e.from, () => e.to);
  }
  return cleaned;
}

/** Every comment of a source text, as ESLint sees it (typescript-estree), with its lines. */
function commentsOf(text, name = "x.ts") {
  try {
    const ast = tsEstree.parse(text, {
      comment: true,
      filePath: name,
      jsx: false,
      loc: true,
      range: true,
    });
    return {
      comments: ast.comments.map((c) => ({
        type: c.type,
        line: c.loc.start.line,
        endLine: c.loc.end.line,
        value: c.value,
        lines: c.value
          .split("\n")
          .map((l) => l.replace(/^\s*\*?\s?/, "").trim())
          .filter(Boolean),
      })),
      error: null,
    };
  } catch (error) {
    return { comments: [], error: String(error.message).slice(0, 200) };
  }
}

