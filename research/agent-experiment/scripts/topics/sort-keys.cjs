// The sort-keys post: when Ultracite hands a coding agent ESLint's `sort-keys` ("Expected object
// keys to be in ascending order. 'css' should be before 'js'.", help "Require object keys to be
// sorted"), does the agent sort an object whose order nothing reads, and keep the order of one
// whose order is observable or is the program's meaning? And what do Ultracite's retry loop and
// its "Left for review" line do with each?
//
// Subjects come from research/corpus/examples/sort-keys/ (sort-keys-examples.cjs). Each is one
// subject entry, handed over through Ultracite's ESLint adapter:
//   a  Vite's send() (send.ts, 2026): an `alias` MIME map read only by key, and a generateMap()
//      options bag. Nothing reads their order; the right response sorts both.
//   b  Astro's JSON logger (json.ts, 2026): JSON.stringify({ message, label, level }), compact and
//      pretty. Sorting changes every log line's bytes (the same JSON once parsed), and Astro's own
//      tests compare the strings. The right response keeps the bytes: leave it for a person, or
//      restructure without changing the output.
//   c  Hono's serveStatic() (index.ts, 2026): ENCODINGS = { br, zstd, gzip }, whose Object.keys
//      order is the compression preference. Sorting serves gzip instead of zstd to some clients,
//      and Hono's tests still pass. The right response keeps the order: leave it for review, or
//      make the order explicit without changing behaviour.
//
// Only ESLint hands these to an agent. Oxlint's sort-keys fix (a conditional_fix, applied by
// `oxlint --fix`) and Biome's useSortedKeys (applied by `biome check --write`) sort all three in
// `ultracite fix` before any agent sees them; `aggregate` records those deterministic paths.
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks):
// Ultracite's ESLint pass on the project (eslint --fix, stylelint --fix, prettier --write, then
// eslint -f json-with-metadata), then up to three agent attempts, each verified with the adapter's
// pass on the file. The run dir is what `ultracite init --linter eslint` leaves (its
// eslint.config.mjs, prettier.config.mjs, stylelint.config.mjs and package.json, generated by
// running init), with the subjects' tsconfig.json.
//
// The handoff. The subjects are verbatim code, and ESLint core reports many other rules on them.
// prepareSubjects runs the ESLint pass until nothing changes (which never reorders keys: checked),
// and the handoff, and every re-lint, keep `sort-keys` and any other diagnostic that is new since
// the prepared subject (by Ultracite's own rule-and-message key, diff.ts). That models a project
// that lints clean apart from the keys: an edit that trips another rule is handed back as Ultracite
// would, and the subject's pre-existing diagnostics are never handed over. It is a deviation from a
// real project, recorded in handoff.json and REPORT.md, and every diagnostic of every view is still
// measured.
//
// Each run is measured after each attempt (the file as the agent left it, and as verify left it)
// and at the end: sort-keys and every rule of ESLint core, Oxlint core and Biome core (inline
// config honoured and ignored), tsc, the behaviour oracle (the corpus's sort-keys-oracle.cjs,
// imported unchanged), what the edit did to the objects under test (sorted, sorted in part,
// restructured, order made explicit, unchanged), suppressions and other files, Ultracite's own
// partition and what it would print, and the session logs (cost, tokens, tool calls, commands, the
// final message, what the agent said about order, whether it looked for tests, and every read
// outside the run dir).
//
// See scripts/topics.cjs for the hooks this module implements.
