/**
 * Runs Ultracite's real ESLint adapter (packages/cli/src/agent-fix/linters.ts, under Bun) in a
 * project laid out as `ultracite init --linter eslint` leaves one (init's own config files, which
 * import `ultracite/...`, with node_modules links), next to the harness's mirror (with --config),
 * on the prepared subjects and the mutants, and compares every diagnostic (every field but `raw`,
 * before the handoff filter, files relative to the project) and every file each pass leaves.
 */
function mirrorEquivalence() {
  const { root, script } = linkedRoot("mirror-check");
  const subjects = subjectsManifest();
  const inputs = subjects.map((s) => ({
    subject: s,
    name: `${s.id} as prepared`,
    text: readFileSync(join(HERE, s.path), "utf8"),
  }));
  for (const m of mutantsFile())
    inputs.push({
      subject: subjects.find((x) => x.base === m.base),
      name: m.id,
      text: mutantText(m),
    });
  const initFiles = (dir) => {
    for (const name of readdirSync(join(INIT_DIR, "eslint"))) {
      if (name === "tsconfig.json" || name === "package.json") continue;
      copyFileSync(join(INIT_DIR, "eslint", name), join(dir, name));
      chmodSync(join(dir, name), 0o644);
    }
  };
  const cases = [];
  for (const input of inputs) {
    const s = input.subject;
    const realDir = join(root, `real-${cases.length}`);
    const mirrorDir = join(root, `mirror-${cases.length}`);
    for (const d of [realDir, mirrorDir]) {
      mkdirSync(d, { recursive: true });
      writeFileSync(join(d, s.basename), input.text);
      withRunFiles(d);
    }
    // The real project gets the config files exactly as init wrote them (not yet formatted).
    initFiles(realDir);
    const real = {};
    const ours = {};
    for (const mode of ["collect", "verify"]) {
      if (mode === "verify") {
        writeFileSync(join(realDir, s.basename), input.text);
        writeFileSync(join(mirrorDir, s.basename), input.text);
      }
      const realFile = join(realpathSync(realDir), s.basename);
      const r = realAdapter(
        script,
        "eslint",
        mode,
        realDir,
        mode === "verify" ? realFile : null
      );
      real[mode] = r.error
        ? r
        : {
            diagnostics: shape(realDir, r.diagnostics),
            files: treeTexts(realDir),
          };
      const mirrorFile = join(realpathSync(mirrorDir), s.basename);
      const m = adapterPass(
        mirrorDir,
        mode === "collect" ? [] : [mirrorFile]
      ).diagnostics;
      ours[mode] = {
        diagnostics: shape(mirrorDir, m),
        files: treeTexts(mirrorDir),
      };
    }
    // The config files differ by design (init's import `ultracite/...`, the mirror's by path), so
    // the files compared are the subject and the run files init doesn't write differently.
    const compared = [s.basename, "package.json", "tsconfig.json"];
    const pick = (files) =>
      Object.fromEntries(compared.map((n) => [n, files?.[n] ?? null]));
    const same = (mode) =>
      !real[mode].error &&
      JSON.stringify(real[mode].diagnostics) ===
        JSON.stringify(ours[mode].diagnostics) &&
      JSON.stringify(pick(real[mode].files)) ===
        JSON.stringify(pick(ours[mode].files));
    const c = {
      name: input.name,
      collectMatches: same("collect"),
      verifyMatches: same("verify"),
      diagnostics: ours.verify.diagnostics.length,
      sortKeys: ours.verify.diagnostics.filter((d) => isSortRule(d.rule))
        .length,
      realError: real.collect.error ?? real.verify.error ?? null,
    };
    c.pass = c.collectMatches && c.verifyMatches;
    cases.push(c);
    console.log(
      `${c.pass ? "OK  " : "BAD "} mirror ${c.name}: collect ${c.collectMatches}, verify ${c.verifyMatches}, ${c.diagnostics} diagnostics (${c.sortKeys} sort-keys)${c.realError ? ` ${c.realError}` : ""}`
    );
  }
  return {
    note: "Ultracite's own linters.ts ESLint adapter (fixAndCollect and verify, run under Bun in a project with init's eslint.config.mjs, prettier.config.mjs and stylelint.config.mjs, which import `ultracite/...`, and node_modules links to this repo's packages) against the harness's mirror (scripts/ultracite-adapters.cjs, configs passed with --config), on the same files: every diagnostic (every field but `raw`, before the handoff filter, files relative to the project) and the subject, package.json and tsconfig.json each pass leaves must match.",
    cases,
  };
}

