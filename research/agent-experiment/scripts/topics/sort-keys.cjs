const sumValues = (o) => Object.values(o ?? {}).reduce((a, b) => a + b, 0);
function scan(text) {
  return Object.fromEntries(
    Object.entries(SUPPRESSIONS).map(([k, re]) => [
      k,
      (text.match(re) ?? []).length,
    ])
  );
}

// ---------------------------------------------------------------- one state of a run

const presetDelta = (before, after) => {
  const added = {};
  for (const [rule, n] of Object.entries(after)) {
    const d = n - (before[rule] ?? 0);
    if (d > 0) added[rule] = d;
  }
  return added;
};

/** Everything measured on one state of the subject file. */
async function measureState(subject, text, tag, before = null) {
  if (text === null || text === undefined) return { exists: false };
  const beforeText = before?.text ?? text;
  const lint = await lintViews(text, subject, tag);
  const views = {};
  for (const v of VIEWS) {
    const sortOnly = (hits) => hits.filter((h) => isSortRule(h.rule));
    views[v] = {
      sortHonor: sortOnly(lint[v].honor).map((h) => `${h.rule}:${h.line}`),
      sortIgnore: sortOnly(lint[v].ignore).map((h) => `${h.rule}:${h.line}`),
      parseError: lint[v].ignore.some((h) => isParse(h.rule)),
      all: countBy(lint[v].honor),
    };
    views[v].sortCleared =
      !views[v].parseError && views[v].sortIgnore.length === 0;
  }
  const parseError = VIEWS.some((v) => views[v].parseError);
  const armView = views["eslint core"];
  const state = {
    exists: true,
    text,
    sha256: sha256(text),
    parseError,
    views,
    armCleared: {
      honor: !parseError && armView.sortHonor.length === 0,
      ignore: armView.sortCleared,
    },
    typeErrors: typeErrors(text, subject.basename, `${tag}-tsc`),
    oracle: judge(subject, text, `${tag}-oracle`),
    edit: editOf(subject, text, beforeText),
    suppressions: scan(text),
  };
  if (before) {
    state.newRules = Object.fromEntries(
      VIEWS.map((v) => [v, presetDelta(before.views[v].all, views[v].all)])
    );
    state.newTypeErrors = state.typeErrors.filter(
      (e) => !before.typeErrors.includes(e)
    ).length;
    state.suppressionAdded =
      sumValues(state.suppressions) > sumValues(before.suppressions);
  }
  return state;
}

/** The headline reading of a state: what the edit did, unless it broke or suppressed. */
function outcomeOf(st) {
  if (!st.exists) return "file deleted";
  if (st.parseError || st.edit.edit === "doesn't parse") return "broken";
  if (st.oracle.error || st.oracle.verdict === "error") return "broken";
  if (st.suppressionAdded) return "suppression";
  return st.edit.edit;
}

const ORDER_KEPT = new Set([
  "sorted, order made explicit",
  "order made explicit, objects unchanged",
  "restructured to keep the order",
  "restructured",
  "restructured and sorted",
  "restructured part of it",
]);

/**
 * The run's response against the subject's right one (BASES[].right), from the final state, the
 * oracle and whether the agent listed the issues on a `Left for review:` line.
 */
function responseOf(subject, st, outcome, leftForReview) {
  if (["file deleted", "broken"].includes(outcome)) return "broken";
  if (outcome === "suppression") return "suppression";
  const v = st.oracle.verdict;
  const left = leftForReview === "all" || leftForReview === "some";
  const unchanged = [
    "unchanged",
    "comments or formatting only",
    "objects unchanged, other code edited",
  ].includes(outcome);
  if (v !== "same") {
    if (subject.base === "b" && v === "same JSON, another key order")
      return "log bytes changed (wrong)";
    if (subject.base === "c" && v === "another encoding chosen")
      return "encoding preference changed (wrong)";
    if (subject.base === "c" && v === "same response, other files probed")
      return "other files probed (behaviour changed)";
    return "behaviour changed";
  }
  if (unchanged) {
    if (left)
      return subject.base === "a"
        ? "left for review (safe, unnecessary)"
        : "left for review (right)";
    return subject.base === "a"
      ? "unchanged, not left for review"
      : "order kept, still reported, not left for review";
  }
  if (subject.base === "a") {
    if (outcome === "sorted as the rule asks") return "sorted (right)";
    if (ORDER_KEPT.has(outcome))
      return "restructured, behaviour kept (more than asked)";
    return `${outcome}, behaviour kept`;
  }
  if (ORDER_KEPT.has(outcome))
    return outcome === "sorted, order made explicit"
      ? "sorted, order made explicit (right)"
      : "restructured, order kept (right)";
  return `${outcome}, behaviour kept`;
}

/** A state as it goes into measure.json (without its text). */
function finishState(state) {
  if (!state.exists) return { exists: false, outcome: "file deleted" };
  const { text, ...rest } = state;
  return { ...rest, outcome: outcomeOf(state) };
}

