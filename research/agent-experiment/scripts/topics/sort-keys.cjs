const lineOfPos = (sf, pos) => sf.getLineAndCharacterOfPosition(pos).line + 1;

/**
 * A property's name as ESLint's sort-keys reads it (getStaticPropertyName, or the identifier of a
 * computed `[foo]` key): null for a spread (which ends a group) and for a key with no name.
 */
function eslintKeyName(p) {
  if (ts.isSpreadAssignment(p)) return { spread: true, name: null };
  const n = p.name;
  if (!n) return { spread: false, name: null };
  if (ts.isIdentifier(n) || ts.isPrivateIdentifier(n))
    return { spread: false, name: n.text };
  if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n))
    return { spread: false, name: n.text };
  if (ts.isNumericLiteral(n))
    return { spread: false, name: String(Number(n.text)) };
  if (ts.isComputedPropertyName(n)) {
    const e = n.expression;
    if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e))
      return { spread: false, name: e.text, computed: true };
    if (ts.isNumericLiteral(e))
      return { spread: false, name: String(Number(e.text)), computed: true };
    if (ts.isIdentifier(e))
      return { spread: false, name: e.text, computed: true };
  }
  return { spread: false, name: null };
}

/** Whether ESLint's sort-keys (asc, caseSensitive, not natural, minKeys 2) passes an object. */
function eslintSorted(keys) {
  let prev = null;
  for (const k of keys) {
    if (k.spread) {
      prev = null;
      continue;
    }
    if (k.name === null) continue;
    if (prev !== null && !(prev <= k.name)) return false;
    prev = k.name;
  }
  return true;
}

/** Every object literal in a text, in source order, with its keys and lines. */
function objectLiterals(text, name) {
  const sf = ts.createSourceFile(
    name,
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS
  );
  const objects = [];
  const visit = (node) => {
    if (ts.isObjectLiteralExpression(node)) {
      const keys = node.properties.map(eslintKeyName);
      objects.push({
        line: lineOfPos(sf, node.getStart(sf)),
        endLine: lineOfPos(sf, node.end),
        keys: keys.map((k) => (k.spread ? "..." : (k.name ?? "<computed>"))),
        sorted: eslintSorted(keys),
        named: keys.filter((k) => k.name !== null).length,
      });
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  return { objects, parseErrors: sf.parseDiagnostics?.length ?? 0, sf };
}

/** The key lists of every object with two or more members, in source order. */
const keyOrders = (text, name) =>
  objectLiterals(text, name)
    .objects.filter((o) => o.keys.length >= 2)
    .map((o) => o.keys.join(","));

