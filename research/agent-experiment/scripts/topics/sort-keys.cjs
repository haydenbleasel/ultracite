/**
 * The project as `ultracite fix` would leave it: the cleaned subject with init's run files, through
 * the ESLint adapter's pass (eslint --fix, stylelint, prettier --write) until nothing changes. The
 * result is a fixed point of Ultracite's collect, so the handoff hands over what the fix pass can't
 * fix, and the agent's input is what `ultracite fix` would leave.
 */
function normalise(text, name, initFiles, tag) {
  const dir = scratch(tag);
  writeFileSync(join(dir, name), text);
  for (const f of RUN_FILE_NAMES) writeFileSync(join(dir, f), initFiles[f]);
  const snap = () =>
    Object.fromEntries(
      readdirSync(dir)
        .sort()
        .map((n) => [n, readFileSync(join(dir, n), "utf8")])
    );
  const passes = [];
  for (let i = 0; i < 6; i++) {
    const before = snap();
    adapterPass(dir, []);
    const after = snap();
    passes.push(sha256(JSON.stringify(after)));
    if (JSON.stringify(after) === JSON.stringify(before)) break;
  }
  if (passes.length === 6 && passes[4] !== passes[5])
    throw new Error(`${name}: the fix passes don't settle`);
  const files = snap();
  return {
    text: files[name],
    runFiles: Object.fromEntries(RUN_FILE_NAMES.map((f) => [f, files[f]])),
    passes: passes.length,
  };
}

function writeReadOnly(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  if (existsSync(file)) chmodSync(file, 0o644);
  writeFileSync(file, text);
  chmodSync(file, 0o444);
}

const lineChanges = (a, b) => {
  const x = a.split("\n");
  const y = b.split("\n");
  return {
    removed: x.filter((l) => !y.includes(l)).length,
    added: y.filter((l) => !x.includes(l)).length,
  };
};

