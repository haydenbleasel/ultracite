/** The ESLint adapter pass (eslint --fix, stylelint, prettier, eslint) on `files` (empty: all). */
function adapterPass(cwd, files) {
  return mirror.eslintPass({
    cwd,
    files,
    config: CONFIG.eslint,
    prettierConfig: CONFIG.prettier,
    stylelintConfig: CONFIG.stylelint,
  });
}

/** A diagnostic's file relative to the project root it was linted in. */
const relFile = (cwd, file) => {
  for (const d of [cwd, existsSync(cwd) ? realpathSync(cwd) : cwd]) {
    const r = relative(d, file);
    if (!r.startsWith("..")) return r;
  }
  return file;
};

const baselineCache = new Map();
/**
 * The diagnostics other than sort-keys that the prepared project itself reports (the subject's;
 * init's config files report none), by file relative to the project root: what the handoff leaves
 * out, and what an edit has to add to before a re-lint hands something else back.
 */
function baselineOther(subject) {
  if (!baselineCache.has(subject.id)) {
    const dir = scratch(`baseline-${subject.id}-${process.pid}`);
    writeFileSync(
      join(dir, subject.basename),
      readFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), "utf8")
    );
    withRunFiles(dir);
    const { diagnostics } = adapterPass(dir, []);
    baselineCache.set(
      subject.id,
      diagnostics
        .filter((d) => !isSortRule(d.rule))
        .map((d) => ({ ...d, file: relFile(dir, d.file) }))
    );
    rmSync(dir, { recursive: true, force: true });
  }
  return baselineCache.get(subject.id);
}

/**
 * The handoff filter: sort-keys, and every other diagnostic that isn't one of the prepared
 * project's own (diff.ts partitionByRemaining, by rule and message, file by file). Fatal
 * diagnostics (a file that no longer parses) are never in the baseline, so they always pass.
 */
function handoffFilter(subject, diagnostics, cwd) {
  const base = baselineOther(subject);
  const keep = new Set();
  const byFile = new Map();
  for (const d of diagnostics) {
    if (isSortRule(d.rule)) continue;
    const rel = relFile(cwd, d.file);
    if (!byFile.has(rel)) byFile.set(rel, []);
    byFile.get(rel).push(d);
  }
  for (const [rel, ds] of byFile) {
    const { introduced } = mirror.partitionByRemaining(
      base.filter((b) => b.file === rel),
      ds
    );
    for (const d of introduced) keep.add(d);
  }
  return diagnostics.filter((d) => isSortRule(d.rule) || keep.has(d));
}

/**
 * run-one.mjs's `collect` hook: Ultracite's fixAndCollect on the run dir (the project root), then
 * the handoff filter. run-one checks the handoff holds exactly the subject's sort-keys reports.
 */
function collect(subject, runDir) {
  const sources = mirror.checkSources();
  const { diagnostics: all, steps } = adapterPass(runDir, []);
  const diagnostics = handoffFilter(subject, all, runDir);
  const dropped = all.filter((d) => !diagnostics.includes(d));
  return {
    diagnostics,
    info: {
      linter: "eslint",
      adapter:
        "linters.ts runEslintPass: eslint --fix ., stylelint --fix --allow-empty-input '**/*.{css,scss,less}', prettier --write ., eslint -f json-with-metadata .",
      config:
        "what `ultracite init --linter eslint` writes (eslint.config.mjs spreading ultracite/eslint/core, prettier.config.mjs with prettier-plugin-tailwindcss, stylelint.config.mjs), passed with --config and importing the presets by absolute URL",
      filter:
        "sort-keys, plus any other diagnostic not among the prepared project's own (rule and message, file by file, as diff.ts matches them): a project that lints clean apart from the keys. Every re-lint uses the same filter.",
      stepExitCodes: steps,
      diagnosticsReported: all.length,
      diagnosticsHandedOver: diagnostics.length,
      leftOutByFilter: countBy(dropped.map((d) => ({ rule: d.rule }))),
      mirroredSlicesSha256: sources.hashes,
    },
  };
}

/**
 * run-one.mjs's `verify` hook: the adapter's verify (the ESLint pass on one file), then the
 * handoff filter. `file` is the absolute path ESLint reported.
 */
function verify(subject, runDir, file) {
  return handoffFilter(
    subject,
    adapterPass(runDir, [file]).diagnostics,
    runDir
  );
}

