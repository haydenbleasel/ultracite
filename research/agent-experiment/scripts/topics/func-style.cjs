/** A JSON value with every object's keys sorted, for a comparison that ignores key order. */
const canon = (v) => {
  if (Array.isArray(v)) return v.map(canon);
  if (v && typeof v === "object")
    return Object.fromEntries(
      Object.keys(v)
        .sort()
        .map((k) => [k, canon(v[k])])
    );
  return v;
};
/** An oracle trace with every object's keys sorted (the import record is left as it is). */
const canonTrace = (t) =>
  t.error ? t : { ...t, calls: t.calls.map(canon), hooks: t.hooks.map(canon) };

/**
 * The text the oracle runs: the subject imports its stub module as `./stubs`, and the oracle loads
 * the corpus's stub by its corpus name (func-style-oracle.cjs `transpile`), so the specifier is
 * given that name back. The stub import is the only change; B's is a value import, C's is type-only.
 */
const oracleText = (subject, text) =>
  subject.stubs
    ? text.replace(
        /from\s*["']\.\/stubs(?:\.(?:js|ts|mjs))?["']/g,
        `from "./${subject.stubs.example.replace(/\.ts$/, "")}"`
      )
    : text;

const referenceTraces = new Map();
/** The prepared subject's trace: the reference every state is compared with. */
function referenceTrace(subject) {
  if (!referenceTraces.has(subject.base)) {
    const r = oracle.trace(
      subject.oracleId,
      oracleText(
        subject,
        readFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), "utf8")
      )
    );
    if (r.error || !r.import?.ok)
      throw new Error(`${subject.id}: oracle: ${r.error ?? r.import?.error}`);
    referenceTraces.set(subject.base, r);
  }
  return referenceTraces.get(subject.base);
}

/**
 * The oracle on a source text (the corpus's func-style-oracle.cjs: transpile, import in a fresh Node
 * process, run every scenario through the exports). The verdict is against the prepared subject:
 * same, changed (with the number of differing calls), import-crash (a TDZ at load time),
 * exports-changed or oracle-error. `exportNames` adds each export's `name` and `length`.
 */
function judge(subject, text, reference = referenceTrace(subject)) {
  const t = oracle.trace(subject.oracleId, oracleText(subject, text));
  const v = oracle.verdict(reference, t);
  const k = oracle.verdict(canonTrace(reference), canonTrace(t));
  const shape = exportShape(subject, text);
  const refShape = referenceShape(subject);
  return {
    verdict: v.verdict,
    calls: reference.calls.length,
    differing: v.differing ?? null,
    detail:
      v.verdict === "same" ? null : JSON.stringify(v.detail).slice(0, 600),
    ignoringKeyOrder: k.verdict,
    differingIgnoringKeyOrder: k.differing ?? null,
    importOk: t.import?.ok ?? false,
    importError: t.import?.ok === false ? t.import.error : null,
    exportNames: shape.exports ?? null,
    exportNamesSame:
      JSON.stringify(shape.exports) === JSON.stringify(refShape.exports),
  };
}

const transpileForShape = (text, fileName) =>
  ts.transpileModule(text, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
    fileName,
  }).outputText;

/**
 * Each export's name, type, `name` property and `length`, read in a fresh Node process (the module
 * transpiled as the oracle transpiles it, with the corpus's stub module). The oracle records the
 * names and types; the `name` property is what a stack trace or a log shows.
 */
function exportShape(subject, text) {
  const dir = scratch(`shape-${subject.id}-${process.pid}`);
  const stubBase = subject.stubs?.example.replace(/\.ts$/, "");
  const js = transpileForShape(oracleText(subject, text), "subject.ts").replace(
    /from "\.\/(func-style-[bc]-stubs)"/g,
    'from "./$1.mjs"'
  );
  writeFileSync(join(dir, "subject.mjs"), js);
  if (subject.stubs)
    writeFileSync(
      join(dir, `${stubBase}.mjs`),
      transpileForShape(
        readFileSync(join(EXAMPLES, subject.stubs.example), "utf8"),
        subject.stubs.example
      )
    );
  writeFileSync(
    join(dir, "shape.mjs"),
    [
      "let mod;",
      'try { mod = await import("./subject.mjs"); } catch (e) { process.stdout.write(JSON.stringify({ error: String(e && e.name) + ": " + String(e && e.message) })); process.exit(0); }',
      "process.stdout.write(JSON.stringify({ exports: Object.keys(mod).sort().map((k) => [k, typeof mod[k], typeof mod[k] === 'function' ? mod[k].name : null, typeof mod[k] === 'function' ? mod[k].length : null]) }));",
    ].join("\n")
  );
  const r = spawnSync(process.execPath, [join(dir, "shape.mjs")], {
    cwd: dir,
    encoding: "utf8",
    timeout: 30_000,
  });
  rmSync(dir, { recursive: true, force: true });
  try {
    return JSON.parse(r.stdout);
  } catch {
    return { error: String(r.stderr || "no output").slice(0, 300) };
  }
}
