/**
 * What a prepared subject must satisfy: the adapter's collect leaves every file of the project
 * unchanged; the handoff filter keeps exactly the subject's func-style and no-use-before-define
 * reports, as many as the corpus measured on the subject as written; normalising changed no
 * behaviour (the oracle's trace equals the corpus subject's, and so do the exports' names); and it
 * type-checks.
 */
function subjectChecks(s, text, stubText, corpusText, example) {
  const dir = scratch(`check-${s.id}`);
  writeFileSync(join(dir, s.basename), text);
  withRunFiles(dir, s);
  const laidOut = Object.fromEntries(
    readdirSync(dir).map((n) => [n, readFileSync(join(dir, n), "utf8")])
  );
  baselineCache.delete(s.id);
  const { diagnostics, info } = collect(s, dir);
  const changed = readdirSync(dir).filter(
    (n) => readFileSync(join(dir, n), "utf8") !== laidOut[n]
  );
  if (changed.length > 0)
    throw new Error(`${s.id}: the fix pass changes ${changed.join(", ")}`);
  if (!diagnostics.every((d) => isHandoffRule(d.rule) && d.file === s.basename))
    throw new Error(
      `${s.id}: the handoff is ${diagnostics.map((d) => `${d.file} ${d.rule}: ${d.message}`).join(", ")}`
    );
  const handed = countBy(diagnostics);
  const corpusCounts = Object.fromEntries(
    [...HANDOFF_RULES]
      .map((r) => [r, example.lint.oxlint.byRule[r] ?? 0])
      .filter(([, n]) => n > 0)
      .sort(([a], [b]) => a.localeCompare(b))
  );
  if (JSON.stringify(handed) !== JSON.stringify(corpusCounts))
    throw new Error(
      `${s.id}: the handoff ${JSON.stringify(handed)} differs from the corpus's ${JSON.stringify(corpusCounts)}`
    );
  // Normalising changed no behaviour: the corpus subject (with the corpus stub module, as the
  // oracle always runs it) against the prepared one.
  const corpusTrace = oracle.trace(s.oracleId, corpusText);
  const prepared = oracle.trace(s.oracleId, oracleText(s, text));
  const v = oracle.verdict(corpusTrace, prepared);
  const k = oracle.verdict(canonTrace(corpusTrace), canonTrace(prepared));
  if (k.verdict !== "same")
    throw new Error(
      `${s.id}: normalising changed behaviour (${JSON.stringify(k).slice(0, 400)})`
    );
  // The corpus subject imports the corpus stub by name already.
  const shapeCorpus = exportShape(s, corpusText);
  const shapePrepared = exportShape(s, text);
  if (JSON.stringify(shapeCorpus) !== JSON.stringify(shapePrepared))
    throw new Error(`${s.id}: the exports' names changed`);
  const tsc = typeErrors(s, text, `check-${s.id}-tsc`, stubText);
  if (tsc.length > 0)
    throw new Error(
      `${s.id}: type errors: ${tsc.map(typeErrorKey).join("; ")}`
    );
  const corpusStub = s.stubs
    ? readFileSync(join(EXAMPLES, s.stubs.example), "utf8")
    : null;
  const eq = stubEquivalence(s, stubText);
  if (eq && !eq.same)
    throw new Error(
      `${s.id}: the normalised stub module behaves differently: ${JSON.stringify(eq)}`
    );
  const facts = fileFacts(text, s.basename);
  return {
    fixPassUnchanged: true,
    handoff: diagnostics.map((d) => `${d.rule} L${d.line}: ${d.message}`),
    handoffCounts: handed,
    help: Object.fromEntries(
      [...HANDOFF_RULES].map((r) => [
        r,
        [
          ...new Set(
            diagnostics.filter((d) => d.rule === r).map((d) => d.help ?? null)
          ),
        ],
      ])
    ),
    url: [...new Set(diagnostics.map((d) => d.url ?? null))],
    reportedBeforeFilter: info.diagnosticsReported,
    leftOutByFilter: info.leftOutByFilter,
    leftOutByFilterByFile: info.leftOutByFilterByFile,
    fileLines: {
      corpus: corpusText.split("\n").length,
      prepared: text.split("\n").length,
    },
    order: facts.order,
    direction: facts.direction,
    referencesDown: facts.referencesDown,
    referencesUp: facts.referencesUp,
    forms: facts.functions.map((f) => `${f.name}: ${f.form}, ${f.body}`),
    oracle: {
      calls: prepared.calls.length,
      hooks: prepared.hooks.length,
      import: prepared.import,
      verdictAgainstCorpusSubject: v.verdict,
      differingExactly: v.differing ?? 0,
      ignoringKeyOrder: k.verdict,
      note:
        v.verdict === "same"
          ? "the prepared subject's trace equals the corpus subject's in every scenario"
          : "the prepared subject's trace differs from the corpus subject's only in object key order (Oxlint's sort-keys fix on objects the code returns); the prepared subject is the reference",
    },
    exportNames: shapePrepared.exports,
    stub: s.stubs
      ? {
          name: s.stubs.name,
          corpusName: s.stubs.example,
          codeChangedByNormalising:
            codeOnly(stubText, s.stubs.name) !==
            codeOnly(corpusStub, s.stubs.name),
          linesChanged: lineChanges(corpusStub, stubText),
          equivalence: stubEquivalence(s, stubText),
        }
      : null,
    typeErrors: 0,
  };
}

/** The comment lines of a text that a PRIMING pattern matches (allowed lines skipped). */
function primedLines(text, name, allowed = new Set(), seen = new Set()) {
  const { comments, error } = commentsOf(text, name);
  if (error) throw new Error(`${name}: ${error}`);
  const primed = [];
  for (const c of comments)
    for (const line of commentLines(c)) {
      if (allowed.has(line)) {
        seen.add(line);
        continue;
      }
      for (const re of PRIMING)
        if (re.test(line)) primed.push(`${re} in "${line.slice(0, 90)}"`);
    }
  return primed;
}

