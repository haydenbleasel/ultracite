// The func-style post: Ultracite holds functions to `const` expressions (`func-style`: ["error",
// "expression", { allowArrowFunctions: true }]) and keeps `no-use-before-define` on. No linter has a
// fix that converts a declaration, so in a real project `ultracite fix --claude` or `--codex` is what
// does the conversion. Does the agent convert without changing behaviour, does it reorder a
// top-down file correctly, what does it do when no order can satisfy `no-use-before-define`, and
// does the result use what the maintainer's reasons point to (concise bodies, types on the
// variable, define-before-use order)?
//
// Subjects come from research/corpus/examples/func-style/ (func-style-examples.cjs):
//   a  Next.js's duration-to-string.ts: five declarations, each defined above its first use; three
//      are a single return. Right: rewrite each as a const arrow, keeping types and JSDoc; nothing
//      moves.
//   b  Supabase Studio's ConfigurationDriftPage.utils.ts, written top-down: three exports first,
//      five helpers below them. Right: convert, and move the helpers above their callers (or the
//      exports below), with behaviour unchanged.
//   c  Astro's runtime/server/serialize.ts: serializeArray and serializeObject call
//      convertToSerializedForm, which calls both. As const functions no order clears
//      no-use-before-define, and the remaining report is not a crash. Right: convert what can be
//      converted (or leave the three as declarations) and say no order satisfies the rule for a
//      mutual recursion, under "Left for review".
//
// Every run goes through run-one.mjs's retry loop (this module's `collect` and `verify` hooks):
// Ultracite's Oxlint pass on the project (oxlint --fix, oxfmt --write, then oxlint -f json), then up
// to three agent attempts, each verified with the adapter's pass on the file. The run dir is exactly
// what `ultracite init --linter oxlint` leaves (generated by running init), with the tsconfig.json
// and the stub module the subjects need. Both rules are on there already; the user changes nothing.
//
// The handoff. The subjects are real code, and Ultracite's core preset reports other rules on them.
// prepareSubjects runs the Oxlint pass until nothing changes (checked not to change behaviour), and
// the handoff, and every re-lint, keep func-style and no-use-before-define and any other diagnostic
// that is new since the prepared subject (by Ultracite's own rule-and-message key, diff.ts). That
// models a project that lints clean apart from these two rules. It is a deviation from a real
// project, recorded in handoff.json and REPORT.md, and every diagnostic of every view is measured.
//
// Each attempt is measured as the agent left the file and as verify left it: Oxlint (the user's
// config, and no-use-before-define with { functions: false } and { variables: false }), ESLint core
// (func-style, @typescript-eslint/no-use-before-define, and the base rule and the two option
// variants under local aliases), Biome core (noInvalidUseBeforeDeclaration, useArrowFunction,
// useConsistentArrowReturn), inline config honoured and ignored; tsc (TS2448, TS2454 and any new
// error); the behaviour oracle (the corpus's func-style-oracle.cjs, imported unchanged) and the
// exports' names; what the edit did (each function's form, body and types, JSDoc and comments, the
// order and the reading direction, restructuring, suppressions, other files); Ultracite's own
// partition and what it would print; and the session logs.
//
// See scripts/topics.cjs for the hooks this module implements.
