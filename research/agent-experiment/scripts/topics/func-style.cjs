    'Each linter\'s adapter fixAndCollect on a project with what init writes for that linter, on the upstream code (header stripped) and on the file the Oxlint arm hands over. "Still reported" is what an agent would be handed (the topic\'s rules). The oracle compares the result with the input. "Real adapter" is Ultracite\'s own linters.ts on the same project with node_modules links.'
