/** The code without comments or formatting: equal for two texts that differ only in those. */
function codeOnly(text, name) {
  const sf = ts.createSourceFile(
    name,
    text,
    ts.ScriptTarget.Latest,
    false,
    ts.ScriptKind.TS
  );
  return ts.createPrinter({ removeComments: true }).printFile(sf);
}

/** Lines added and removed, by a longest common subsequence of lines (the diff's size). */
function diffSize(a, b) {
  const x = a.split("\n");
  const y = b.split("\n");
  const dp = Array.from(
    { length: x.length + 1 },
    () => new Uint16Array(y.length + 1)
  );
  for (let i = x.length - 1; i >= 0; i--)
    for (let j = y.length - 1; j >= 0; j--)
      dp[i][j] =
        x[i] === y[j]
          ? dp[i + 1][j + 1] + 1
          : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const same = dp[0][0];
  return { removed: x.length - same, added: y.length - same };
}

/**
 * Which functions moved: the names outside the longest common subsequence of the module-level
 * function order, before and after, and their lines in the new file (func-style-examples.cjs
 * `moved`, the corpus's measure).
 */
function movedFunctions(before, after) {
  const a = before.map((f) => f.name);
  const b = after.map((f) => f.name).filter((n) => a.includes(n));
  const dp = Array.from({ length: a.length + 1 }, () =>
    new Array(b.length + 1).fill(0)
  );
  for (let i = a.length - 1; i >= 0; i--)
    for (let j = b.length - 1; j >= 0; j--)
      dp[i][j] =
        a[i] === b[j]
          ? dp[i + 1][j + 1] + 1
          : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const keep = new Set();
  for (let i = 0, j = 0; i < a.length && j < b.length;) {
    if (a[i] === b[j]) {
      keep.add(a[i]);
      i++;
      j++;
    } else if (dp[i + 1][j] >= dp[i][j + 1]) i++;
    else j++;
  }
  const m = after.filter((f) => a.includes(f.name) && !keep.has(f.name));
  return {
    functions: m.map((f) => f.name),
    lines: m.reduce((s, f) => s + f.lines, 0),
  };
}

const SUPPRESSIONS = {
  "eslint-disable": /eslint-disable/g,
  "eslint inline config": /\/\*\s*eslint\s+[\w@/-]+\s*:/g,
  "oxlint-disable": /oxlint-disable/g,
  "biome-ignore": /biome-ignore/g,
  "@ts-ignore/@ts-expect-error/@ts-nocheck":
    /@ts-(ignore|expect-error|nocheck)/g,
};
const sumValues = (o) => Object.values(o ?? {}).reduce((a, b) => a + b, 0);
function scan(text) {
  return Object.fromEntries(
    Object.entries(SUPPRESSIONS).map(([k, re]) => [
      k,
      (text.match(re) ?? []).length,
    ])
  );
}

/** Where a function of the given file is now, and how it's written. */
function whereNow(name, now) {
  const f = now.functions.find((x) => x.name === name);
  if (f) return { place: "module level", form: f.form, now: f };
  const h = now.holders.find((x) => x.members.includes(name));
  if (h)
    return {
      place: `method of ${h.kind === "class" ? "a class" : "an object"}`,
      form: `${h.kind} member`,
      holder: h.name,
    };
  if (now.forwardDeclarations.includes(name))
    return { place: "module level", form: "forward declaration" };
  const n = now.nested.find((x) => x.name === name);
  if (n) return { place: "nested", form: "nested", enclosing: n.enclosing };
  return { place: "gone", form: "gone" };
}

/** How a function's types were kept: inline annotations, on the variable, or lost. */
function typesOf(g, n) {
  if (!n) return null;
  const inlineParams = n.paramsTyped >= g.paramsTyped;
  const ret = g.returnType
    ? n.returnType
      ? "kept"
      : n.varType
        ? "on the variable"
        : "lost"
    : n.returnType
      ? "added"
      : "none";
  let how;
  if (n.varType) how = "a type on the variable";
  else if (n.wrappers?.includes("TSSatisfiesExpression")) how = "satisfies";
  else if (inlineParams && ret !== "lost") how = "inline annotations";
  else how = "lost";
  return {
    how,
    params: `${n.paramsTyped}/${n.params} (was ${g.paramsTyped}/${g.params})`,
    returnType: ret,
    varType: n.varType,
    typeParamsKept: g.typeParams ? n.typeParams === g.typeParams : null,
  };
}

/**
 * What the edit did, against the file it was given: each of the given file's module-level
 * functions (where it is now, its form, whether a single-return body became concise, how its types
 * were kept, whether its JSDoc is still on it); the order (which functions moved, their lines, the
 * reading direction before and after); restructuring (functions merged or inlined, nested, made
 * methods of an object or a class, given a new parameter, a forward declaration, `var`);
 * suppressions; comments lost; and the diff's size. `kinds` lists every category that applies;
 * `edit` is the headline.
 */
function editOf(subject, text, givenText) {
  if (text === null || text === undefined)
    return { edit: "file deleted", kinds: [] };
  if (text === givenText) return { edit: "unchanged", kinds: [] };
  const now = fileFacts(text, subject.basename);
  const given = fileFacts(givenText, subject.basename);
  if (now.error) return { edit: "doesn't parse", kinds: [], error: now.error };
  const sameCode =
    codeOnly(text, subject.basename) === codeOnly(givenText, subject.basename);
  const perFunction = given.functions.map((g) => {
    const w = whereNow(g.name, now);
    const n = w.now ?? null;
    return {
      name: g.name,
      was: g.form,
      place: w.place,
      form: w.form,
      ...(w.holder ? { holder: w.holder } : {}),
      ...(w.enclosing !== undefined ? { enclosing: w.enclosing } : {}),
      bodyWas: g.body,
      body: n?.body ?? null,
      madeConcise:
        g.body === "block, single return" ? n?.body === "concise" : null,
      types: typesOf(g, n),
      jsdoc: g.jsdoc
        ? n?.jsdoc === g.jsdoc
          ? "kept"
          : n?.jsdoc
            ? "changed"
            : now.comments.includes(g.jsdoc)
              ? "detached"
              : "lost"
        : n?.jsdoc
          ? "added"
          : "none",
      paramsChanged: n ? n.paramText !== g.paramText : null,
      paramsAdded: n ? n.params - g.params : null,
      exportedWas: g.exported,
      exported: n?.exported ?? null,
      linesNow: n?.lines ?? null,
    };
  });
  const added = now.functions
    .filter((f) => !given.order.includes(f.name))
    .map((f) => f.name);
  const moved = movedFunctions(given.functions, now.functions);
  const lostComments = given.comments.filter((c) => !now.comments.includes(c));
  const kinds = [];
  const forms = perFunction.map((p) => p.form);
  const count = (f) => forms.filter(f).length;
  const conversion = {
    arrows: count((f) => /arrow$/.test(f)),
    functionExpressions: count((f) => /function expression$/.test(f)),
    declarations: count((f) => f === "declaration"),
    methods: count((f) => /member$/.test(f)),
    nested: count((f) => f === "nested"),
    gone: count((f) => f === "gone"),
    forward: count((f) => f === "forward declaration"),
    var: count((f) => /^var /.test(f)),
    let: count((f) => /^let /.test(f)),
  };
  const convertedFromDeclaration = perFunction.filter(
    (p) => p.was === "declaration" && /arrow$|function expression$/.test(p.form)
  );
  if (convertedFromDeclaration.length) kinds.push("converted");
  if (perFunction.some((p) => p.was === "declaration" && /arrow$/.test(p.form)))
    kinds.push("const arrows");
  if (
    perFunction.some(
      (p) => p.was === "declaration" && /function expression$/.test(p.form)
    )
  )
    kinds.push("function expressions");
  if (
    perFunction.some((p) => p.was === "declaration" && p.form === "declaration")
  )
    kinds.push("declarations left");
  if (conversion.var) kinds.push("var");
  if (conversion.let) kinds.push("let");
  // A holder (an object or class of functions) the given file didn't have takes the functions
  // that are gone, under the same names or new ones.
  const givenHolders = new Set(given.holders.map((h) => h.name));
  const newHolders = now.holders.filter(
    (h) => !givenHolders.has(h.name) && h.members.length > 0
  );
  const newMembers = newHolders.reduce((n, h) => n + h.members.length, 0);
  const intoHolder =
    conversion.methods > 0 ||
    (conversion.gone > 0 && newMembers >= conversion.gone);
  if (intoHolder)
    kinds.push(
      newHolders.some((h) => h.kind === "class") ||
        now.holders.some(
          (h) =>
            h.kind === "class" && h.members.some((x) => given.order.includes(x))
        )
        ? "methods of a class"
        : "methods of an object"
    );
  if (conversion.nested) kinds.push("nested");
  if (conversion.gone && !intoHolder) kinds.push("merged or inlined");
  if (perFunction.some((p) => (p.paramsAdded ?? 0) > 0))
    kinds.push("parameter added");
  if (now.forwardDeclarations.length > given.forwardDeclarations.length)
    kinds.push("forward declaration");
  if (added.length) kinds.push("functions added");
  if (moved.functions.length) kinds.push("reordered");
  if (perFunction.some((p) => p.madeConcise === true))
    kinds.push("concise bodies");
  if (
    perFunction.some(
      (p) =>
        p.types?.how === "a type on the variable" ||
        p.types?.how === "satisfies"
    )
  )
    kinds.push("types on the variable");
  if (
    perFunction.some(
      (p) => p.types?.how === "lost" || p.types?.returnType === "lost"
    )
  )
    kinds.push("types lost");
  if (
    perFunction.some(
      (p) =>
        p.jsdoc === "lost" || p.jsdoc === "detached" || p.jsdoc === "changed"
    )
  )
    kinds.push("JSDoc changed or lost");
  if (lostComments.length) kinds.push("comments lost");
  if (
    perFunction.some((p) => p.exportedWas !== p.exported && p.exported !== null)
  )
    kinds.push("exports changed");
  const suppressions = scan(text);
  if (sumValues(suppressions) > sumValues(scan(givenText)))
    kinds.push("suppression");
  const restructured = [
    "methods of a class",
    "methods of an object",
    "nested",
    "merged or inlined",
    "parameter added",
    "forward declaration",
  ].filter((k) => kinds.includes(k));
  let edit;
  if (kinds.includes("suppression")) edit = "suppression";
  else if (sameCode) edit = "comments or formatting only";
  else if (restructured.length)
    edit = `restructured (${restructured.join(", ")})`;
  else if (convertedFromDeclaration.length === 0)
    edit = moved.functions.length ? "reordered only" : "edited in place";
  else {
    const all =
      conversion.declarations === 0 ? "converted" : "partly converted";
    const keyword = conversion.var ? "var " : conversion.let ? "let " : "";
    const how = `${keyword}${conversion.functionExpressions && conversion.arrows ? "arrows and function expressions" : conversion.functionExpressions ? "function expressions" : "arrows"}`;
    edit = `${all} (${how}), ${moved.functions.length ? "reordered" : "nothing moved"}`;
  }
  return {
    edit,
    kinds,
    restructured,
    conversion,
    perFunction,
    added,
    moved,
    order: { given: given.order, now: now.order },
    direction: {
      given: given.direction,
      now: now.direction,
      down: now.referencesDown,
      up: now.referencesUp,
    },
    referencesBeforeDefinition: {
      given: given.referencesBeforeDefinition,
      now: now.referencesBeforeDefinition,
    },
    namesUsedBeforeDefinition: now.namesUsedBeforeDefinition,
    loadTimeBeforeDefinition: now.loadTimeBeforeDefinition,
    holders: now.holders,
    newHolders,
    nestedNow: now.nested,
    forwardDeclarations: now.forwardDeclarations,
    lostComments: lostComments.map((c) => c.slice(0, 160)),
    jsdocBlocks: { given: given.jsdocBlocks, now: now.jsdocBlocks },
    diff: diffSize(givenText, text),
    suppressions,
  };
}

