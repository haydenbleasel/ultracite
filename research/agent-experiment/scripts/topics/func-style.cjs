const baselineCache = new Map();
/**
 * The diagnostics other than the two rules that the prepared project itself reports (the subject's
 * and its stub module's; init's config files report none), by file: what the handoff leaves out,
 * and what an edit has to add to before a re-lint hands something else back.
 */
function baselineOther(subject) {
  if (!baselineCache.has(subject.id)) {
    const dir = scratch(`baseline-${subject.id}-${process.pid}`);
    writeFileSync(
      join(dir, subject.basename),
      readFileSync(join(SUBJECTS_DIR, subject.id, subject.basename), "utf8")
    );
    withRunFiles(dir, subject);
    const { diagnostics } = adapterPass(dir, []);
    baselineCache.set(
      subject.id,
      diagnostics.filter((d) => !isHandoffRule(d.rule))
    );
    rmSync(dir, { recursive: true, force: true });
  }
  return baselineCache.get(subject.id);
}

/**
 * The handoff filter: the two rules, and every other diagnostic that isn't one of the prepared
 * project's own (diff.ts partitionByRemaining, by rule and message, file by file). Fatal
 * diagnostics (a file that no longer parses) are never in the baseline, so they always pass.
 */
function handoffFilter(subject, diagnostics) {
  const base = baselineOther(subject);
  const keep = new Set();
  const byFile = new Map();
  for (const d of diagnostics) {
    if (isHandoffRule(d.rule)) continue;
    if (!byFile.has(d.file)) byFile.set(d.file, []);
    byFile.get(d.file).push(d);
  }
  for (const [file, ds] of byFile) {
    const { introduced } = mirror.partitionByRemaining(
      base.filter((b) => b.file === file),
      ds
    );
    for (const d of introduced) keep.add(d);
  }
  return diagnostics.filter((d) => isHandoffRule(d.rule) || keep.has(d));
}

/**
 * run-one.mjs's `collect` hook: Ultracite's fixAndCollect on the run dir (the project root), then
 * the handoff filter. run-one checks the handoff holds exactly the subject's reports of the rules.
 */
function collect(subject, runDir) {
  const sources = mirror.checkSources();
  const { diagnostics: all } = adapterPass(runDir, []);
  const diagnostics = handoffFilter(subject, all);
  const dropped = all.filter((d) => !diagnostics.includes(d));
  return {
    diagnostics,
    info: {
      linter: "oxlint",
      adapter:
        "linters.ts runOxlintPass: oxlint --fix ., oxfmt --write ., oxlint -f json .",
      config:
        "what `ultracite init --linter oxlint` writes (oxlint.config.ts: env, extends [core], ignorePatterns; oxfmt.config.ts: ...ultracite), unchanged, passed with -c and importing the preset by absolute URL",
      filter:
        "func-style and no-use-before-define, plus any other diagnostic not among the prepared project's own (rule and message, file by file, as diff.ts matches them): a project that lints clean apart from these two rules. Every re-lint uses the same filter.",
      diagnosticsReported: all.length,
      diagnosticsHandedOver: diagnostics.length,
      leftOutByFilter: countBy(dropped.map((d) => ({ rule: d.rule }))),
      leftOutByFilterByFile: Object.fromEntries(
        [...new Set(dropped.map((d) => d.file))]
          .sort()
          .map((f) => [f, dropped.filter((d) => d.file === f).length])
      ),
      mirroredSlicesSha256: sources.hashes,
    },
  };
}

/** run-one.mjs's `verify` hook: the adapter's verify (the Oxlint pass on one file), then the filter. */
function verify(subject, runDir, file) {
  return handoffFilter(subject, adapterPass(runDir, [file]).diagnostics);
}

