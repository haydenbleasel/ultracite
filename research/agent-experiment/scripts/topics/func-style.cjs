/**
 * The oracle loads the corpus's stub module; the agent sees the normalised one. For B, whose stub
 * has values, both are imported and compared on the oracle's inputs: CONFIG_SECTIONS,
 * getFieldDefinition on every config path the oracle uses and more, and startCase on every path
 * segment and some edge cases. C's stub has types only.
 */
function stubEquivalence(subject, stubText) {
  if (!subject.stubs) return null;
  const dir = scratch(`stub-eq-${subject.id}`);
  const corpus = readFileSync(join(EXAMPLES, subject.stubs.example), "utf8");
  writeFileSync(
    join(dir, "corpus.mjs"),
    transpileForShape(corpus, "corpus.ts")
  );
  writeFileSync(
    join(dir, "prepared.mjs"),
    transpileForShape(stubText, "prepared.ts")
  );
  const inputs = [
    "api.max_rows",
    "auth.jwt_expiry",
    "db.pooler.default_pool_size",
    "storage.file_size_limit",
    "auth.external.github.enabled",
    "db.major_version",
    "experimental.orioledb_version",
    "compute",
    "api.extraSearchPath",
    "storage.analytics.maxNamespaces",
    "",
    "a",
    "fooBarBaz",
    "x__y--z",
    "ABC",
    "a1B2",
  ];
  writeFileSync(
    join(dir, "eq.mjs"),
    [
      'const a = await import("./corpus.mjs");',
      'const b = await import("./prepared.mjs");',
      `const inputs = ${JSON.stringify(inputs)};`,
      "const run = (m) => JSON.stringify({ keys: Object.keys(m).sort(), sections: m.CONFIG_SECTIONS ?? null, defs: m.getFieldDefinition ? inputs.map((p) => { const d = m.getFieldDefinition(p); return d ? { ...d, settingHref: d.settingHref('ref') } : null; }) : null, start: m.startCase ? inputs.flatMap((p) => [p, ...p.split('.')]).map((x) => m.startCase(x)) : null });",
      "process.stdout.write(JSON.stringify({ same: run(a) === run(b), keys: Object.keys(a).sort() }));",
    ].join("\n")
  );
  const r = spawnSync(process.execPath, [join(dir, "eq.mjs")], {
    cwd: dir,
    encoding: "utf8",
  });
  rmSync(dir, { recursive: true, force: true });
  try {
    return JSON.parse(r.stdout);
  } catch {
    return { error: String(r.stderr).slice(0, 300) };
  }
}

