      `| ${s.id} (${pipe(s.label)}) | \`${s.basename}\` | ${h.reportedBeforeFilter} | ${pipe(h.given.map((g) => `\`${g.rule}\` L${g.line}: ${g.message}`).join("<br>"))} | ${pipe([...new Set(h.given.map((g) => `${g.rule}: ${g.help}`))].join("<br>"))} | ${pipe(counts(h.leftOutByFilter))} |`
