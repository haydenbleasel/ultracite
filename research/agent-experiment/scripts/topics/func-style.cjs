    p(
      `| ${d.subject} | ${pipe(d.input)} | ${d.linter} | \`${d.command}\` | ${d.codeChanged ? "yes" : "no"} | ${d.formsChanged ? "yes" : "no"} | ${d.orderChanged ? "yes" : "no"} | ${pipe((d.renamed ?? []).join(", ") || "none")} | ${pipe(counts(d.topicReported))} | ${d.oracle.verdict} / ${d.oracle.ignoringKeyOrder} | ${d.typeErrors} | ${d.realAdapter.error ? "error" : d.realAdapter.fileMatches && d.realAdapter.diagnosticsMatch ? "yes" : "no"} |`
    );
