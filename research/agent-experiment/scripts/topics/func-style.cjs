/** The mirror's pass for a linter on a project dir. */
function mirrorPass(linter, dir, passthrough) {
  if (linter === "oxlint")
    return mirror.oxlintPass({
      cwd: dir,
      files: [],
      config: CONFIG.oxlint,
      fmtConfig: CONFIG.oxfmt,
      passthrough,
    }).diagnostics;
  if (linter === "biome") {
    copyFileSync(CONFIG.biome, join(dir, "biome.jsonc"));
    return mirror.biomePass({ cwd: dir, files: [], passthrough }).diagnostics;
  }
  return mirror.eslintPass({
    cwd: dir,
    files: [],
    config: CONFIG.eslint,
    prettierConfig: CONFIG.prettier,
    stylelintConfig: CONFIG.stylelint,
  }).diagnostics;
}

/**
 * What `ultracite fix` and `ultracite fix --unsafe` do with Oxlint, Biome and ESLint, no agent: the
 * adapter's fixAndCollect on a project with the subject, its stub module, the tsconfig and what init
 * writes for that linter. Run with the mirror (the harness's configs) and with Ultracite's real
 * adapter (init's configs and node_modules links), which must agree. Each result: whether any
 * function changed form, the topic's rules still reported (what `--claude`/`--codex` would hand
 * over), their help, and the oracle's verdict against the input's behaviour.
 */
async function deterministicPaths() {
  const examples = examplesJson();
  const { root, script } = linkedRoot("deterministic");
  const out = [];
  let n = 0;
  for (const s0 of subjectsManifest()) {
    const s = fullSubject(s0);
    const original = readFileSync(join(EXAMPLES, s.example), "utf8");
    const stubUpstream = s.stubs
      ? cleanText(
          readFileSync(join(EXAMPLES, s.stubs.example), "utf8"),
          [],
          s.base,
          "stubs"
        )
      : null;
    const inputs = {
      "upstream (header stripped)": [
        cleanText(original, examples.stripFields, s.base, "subject"),
        stubUpstream,
      ],
      "as handed to the agent (Oxlint-normalised)": [
        preparedTextOf(s),
        preparedStub(s),
      ],
    };
    for (const [inputName, [text, stubText]] of Object.entries(inputs)) {
      const inputTrace = oracle.trace(s.oracleId, oracleText(s, text));
      const inputFacts = fileFacts(text, s.basename);
      for (const linter of Object.keys(LINTERS)) {
        for (const unsafe of [false, true]) {
          n++;
          const passthrough = unsafe && linter !== "eslint" ? ["--unsafe"] : [];
          const mirrorDir = join(root, `mirror-${n}`);
          const realDir = join(root, `real-${n}`);
          for (const d of [mirrorDir, realDir]) {
            mkdirSync(d, { recursive: true });
            writeFileSync(join(d, s.basename), text);
            if (s.stubs) writeFileSync(join(d, s.stubs.name), stubText);
            writeFileSync(join(d, "tsconfig.json"), TSCONFIG());
            putInitFiles(d, linter);
          }
          if (linter === "oxlint")
            for (const f of NESTED_CONFIGS)
              rmSync(join(mirrorDir, f), { force: true });
          let mine;
          let mirrorError = null;
          try {
            mine = mirrorPass(linter, mirrorDir, passthrough);
          } catch (error) {
            mirrorError = String(error.message).slice(0, 300);
            mine = [];
          }
          const real = realAdapter(script, linter, "collect", realDir, {
            passthrough,
          });
          const after = readFileSync(join(mirrorDir, s.basename), "utf8");
          const realAfter = readFileSync(join(realDir, s.basename), "utf8");
          const afterFacts = fileFacts(after, s.basename);
          const result = oracle.trace(s.oracleId, oracleText(s, after));
          const exact = oracle.verdict(inputTrace, result);
          const keyOrder = oracle.verdict(
            canonTrace(inputTrace),
            canonTrace(result)
          );
          const here = mine.filter(
            (d) => relFile(mirrorDir, d.file) === s.basename
          );
          const topic = here.filter((d) =>
            LINTER_RULES[linter].includes(d.rule)
          );
          out.push({
            subject: s.id,
            input: inputName,
            linter,
            command: unsafe ? "ultracite fix --unsafe" : "ultracite fix",
            passthrough,
            fixPass: LINTERS[linter],
            changed: after !== text,
            codeChanged:
              codeOnly(after, s.basename) !== codeOnly(text, s.basename),
            formsBefore: inputFacts.functions.map(
              (f) => `${f.name}: ${f.form}`
            ),
            formsAfter: afterFacts.error
              ? [afterFacts.error]
              : afterFacts.functions.map((f) => `${f.name}: ${f.form}`),
            formsChanged:
              JSON.stringify(inputFacts.functions.map((f) => f.form)) !==
              JSON.stringify(afterFacts.functions?.map((f) => f.form)),
            // Order among the names both files have (a fix can rename a function: ESLint's
            // unicorn/name-replacements), and the names that changed.
            orderChanged:
              JSON.stringify(
                inputFacts.order.filter((x) => afterFacts.order?.includes(x))
              ) !==
              JSON.stringify(
                (afterFacts.order ?? []).filter((x) =>
                  inputFacts.order.includes(x)
                )
              ),
            renamed: [
              ...inputFacts.order
                .filter((x) => !afterFacts.order?.includes(x))
                .map((x) => `${x} (gone)`),
              ...(afterFacts.order ?? [])
                .filter((x) => !inputFacts.order.includes(x))
                .map((x) => `${x} (new)`),
            ],
            topicReported: countBy(topic),
            topicMessages: [
              ...new Set(topic.map((d) => `${d.rule}: ${d.message}`)),
            ],
            topicHelp: Object.fromEntries(
              [...new Set(topic.map((d) => d.rule))].map((r) => [
                r,
                [
                  ...new Set(
                    topic.filter((d) => d.rule === r).map((d) => d.help ?? null)
                  ),
                ],
              ])
            ),
            otherReported: here.length - topic.length,
            oracle: {
              verdict: exact.verdict,
              ignoringKeyOrder: keyOrder.verdict,
              differing: exact.differing ?? null,
            },
            typeErrors: typeErrors(s, after, `det-${n}-tsc`, stubText).length,
            mirrorError,
            realAdapter: real.error
              ? { error: real.error }
              : {
                  fileMatches: realAfter === after,
                  diagnosticsMatch:
                    JSON.stringify(shape(realDir, real.diagnostics)) ===
                    JSON.stringify(shape(mirrorDir, mine)),
                },
          });
          const last = out.at(-1);
          console.log(
            `${s.id} ${linter}${unsafe ? " --unsafe" : ""} on ${inputName}: code changed ${last.codeChanged}; forms ${last.formsChanged ? "CHANGED" : "same"}; topic ${JSON.stringify(last.topicReported)}; oracle ${last.oracle.verdict}/${last.oracle.ignoringKeyOrder}; real ${JSON.stringify(last.realAdapter)}`
          );
        }
      }
    }
  }
  return out;
}

