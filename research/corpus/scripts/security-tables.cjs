// Generates results/<topic>/tables.md for the security-rules post from the JSON the other
// security-*.cjs scripts write. Pure formatting: no linting, no network.
//
// Usage (from the repo root):
//   node research/corpus/scripts/security-tables.cjs [--topic security-rules]
"use strict";

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const lib = require("./security-lib.cjs");

const load = (name) => {
  const path = join(lib.RESULTS_DIR, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : null;
};
const fmt = (n) =>
  typeof n === "number" ? n.toLocaleString("en-US") : String(n ?? "–");
const pct = (n, d) => (d ? `${Math.round((n / d) * 1000) / 10}%` : "–");
const table = (head, rows, align) => [
  `| ${head.join(" | ")} |`,
  `| ${head.map((_, i) => (align?.[i] === "r" ? "---:" : "---")).join(" | ")} |`,
  ...rows.map((r) => `| ${r.join(" | ")} |`),
  "",
];

const main = () => {
  const inventory = load("inventory.json");
  const census = load("rule-census.json");
  const linters = load("linters.json");
  const sinks = load("sink-census.json");
  const sample = load("sample.json");
  const classes = load("classifications.json");
  const advisories = load("advisories.json");
  const fixes = load("advisory-fixes.json");
  const out = [
    "# Security rules: generated tables",
    "",
    `Generated by \`scripts/security-tables.cjs\` from the JSON in this folder. Corpus: ${census.pooled.repos.length} repos, ${fmt(census.pooled.lines)} lines (Ultracite's own CLI listed separately where shown). Tools: ${Object.entries(
      inventory.tools
    )
      .map(([k, v]) => `${k} ${v}`)
      .join(", ")}.`,
    "",
  ];

  // ── 1. inventory ────────────────────────────────────────────────────
  const rules = inventory.rules.filter((r) => !r.deprecated);
  const on = (r) => r.oxlint.presets.length > 0 || r.eslint.presets.length > 0;
  out.push("## 1. Security rules in Ultracite's presets", "");
  const count = (pred) => rules.filter(pred).length;
  out.push(
    ...table(
      ["Linter", "Preset", "Security rules on", "Of which type-aware"],
      [
        [
          "Oxlint",
          "core (default)",
          count((r) => r.oxlint.presets.includes("core")),
          count((r) => r.oxlint.presets.includes("core") && r.oxlint.typeAware),
        ],
        [
          "Oxlint",
          "react (default for React)",
          count((r) => r.oxlint.presets.includes("react")),
          0,
        ],
        [
          "Oxlint",
          "js-plugins (opt-in)",
          count((r) => r.oxlint.presets.includes("js-plugins")),
          0,
        ],
        [
          "ESLint",
          "core",
          count((r) => r.eslint.presets.includes("core")),
          count((r) => r.eslint.presets.includes("core") && r.eslint.typeAware),
        ],
        [
          "ESLint",
          "type-aware (opt-in)",
          count((r) => r.eslint.presets.includes("type-aware")),
          count((r) => r.eslint.presets.includes("type-aware")),
        ],
        [
          "ESLint",
          "react",
          count((r) => r.eslint.presets.includes("react")),
          0,
        ],
        [
          "Biome",
          "core + react (incl. recommended)",
          inventory.biome.filter((b) => b.biome.enabled).length,
          0,
        ],
      ],
      ["l", "l", "r", "r"]
    ),
    '"Type-aware" for ESLint core means the plugin marks the rule `requiresTypeChecking` but Ultracite keeps it in core because it also works from the syntax tree.',
    ""
  );
  const cell = (list) => (list.length ? list.join(", ") : "–");
  out.push(
    ...table(
      ["Rule", "Class", "Detects", "Oxlint", "ESLint", "Type-aware"],
      rules
        .filter(on)
        .filter((r) => r.plugin !== "sonarjs" || !r.rule.startsWith("aws-"))
        .map((r) => [
          `\`${r.oxlint.name}\``,
          r.class,
          r.detects,
          r.oxlint.available === "missing"
            ? "not in Oxlint"
            : cell(r.oxlint.presets),
          `${cell(r.eslint.presets)}${r.eslint.offIn.length ? ` (off in ${r.eslint.offIn.join(", ")})` : ""}`,
          r.oxlint.typeAware || r.eslint.typeAware ? "yes" : "",
        ]),
      null
    ),
    `Plus the 18 \`sonarjs/aws-*\` CDK rules, on in Oxlint js-plugins and ESLint core. react-doctor files ${rules.filter((r) => r.plugin === "react-doctor").length - 1} rules under its Security category (no-document-write, filed under Performance, is counted here too); ${rules.filter((r) => r.plugin === "react-doctor" && on(r)).length} of those ${rules.filter((r) => r.plugin === "react-doctor").length} are on in some preset (${rules.filter((r) => r.plugin === "react-doctor" && r.oxlint.presets.length > 0).length} in Oxlint js-plugins, ${rules.filter((r) => r.plugin === "react-doctor" && r.eslint.presets.length > 0).length} in ESLint react), the rest in none.`,
    ""
  );
  out.push(
    ...table(
      ["Biome rule", "Class", "Ultracite", "Recommended", "Default severity"],
      inventory.biome.map((b) => [
        `\`${b.rule}\``,
        b.class,
        b.biome.enabled
          ? "on"
          : `off${b.biome.explicit === "off" ? " (explicitly)" : ""}`,
        b.biome.recommended ? "yes" : "",
        b.biome.defaultSeverity,
      ]),
      null
    )
  );
  const gaps = rules.filter(
    (r) => r.eslint.presets.length > 0 && r.oxlint.presets.length === 0
  );
  const oxOnly = rules.filter(
    (r) => r.oxlint.presets.length > 0 && r.eslint.presets.length === 0
  );
  out.push(
    `On in ESLint but in no Oxlint preset (${gaps.length}): ${gaps.map((r) => `\`${r.eslint.name}\``).join(", ")}.`,
    "",
    `On in Oxlint but in no ESLint preset (${oxOnly.length}): ${oxOnly.map((r) => `\`${r.oxlint.name}\``).join(", ") || "none"}.`,
    ""
  );

  // ── 2. census ──────────────────────────────────────────────────────
  out.push("## 2. Rule census (Oxlint core + react + js-plugins)", "");
  const names = census.pooled.repos;
  const hit = census.focus.filter(
    (r) => census.rules[r].raw.pooled > 0 || census.rules[r].reported.pooled > 0
  );
  out.push(
    ...table(
      [
        "Rule",
        "Preset",
        "Reported",
        "Raw",
        "Per 10k",
        "Repos",
        ...names,
        "ultracite",
      ],
      hit.map((r) => {
        const x = census.rules[r];
        const preset = inventory.rules
          .find((i) => i.oxlint.name === r)
          ?.oxlint.presets.join("+");
        return [
          `\`${r}\``,
          preset,
          fmt(x.reported.pooled),
          fmt(x.raw.pooled),
          x.reported.per10k,
          `${x.reported.reposWithHits} of ${names.length}`,
          ...names.map((n) => fmt(x.raw.byRepo[n])),
          fmt(x.raw.byRepo.ultracite),
        ];
      }),
      ["l", "l", "r", "r", "r", "r", ...names.map(() => "r"), "r"]
    )
  );
  const silent = census.focus.filter((r) => census.rules[r].raw.pooled === 0);
  const totals = (mode, filter) =>
    census.focus
      .filter(filter)
      .reduce((s, r) => s + census.rules[r][mode].pooled, 0);
  const preset = (r) =>
    inventory.rules.find((i) => i.oxlint.name === r)?.oxlint.presets ?? [];
  const allDiagnostics = Object.values(census.rules).reduce(
    (s, r) => s + r.reported.pooled,
    0
  );
  out.push(
    `Default presets (core + react): ${fmt(totals("reported", (r) => !preset(r).includes("js-plugins")))} security diagnostics reported (${fmt(totals("raw", (r) => !preset(r).includes("js-plugins")))} raw). With js-plugins: ${fmt(totals("reported", () => true))} reported, ${fmt(totals("raw", () => true))} raw. All rules, reported: ${fmt(allDiagnostics)}; security rules are ${pct(
      totals("reported", () => true),
      allDiagnostics
    )} of them.`,
    "",
    `Focus rules with no hits in either mode (${silent.length}): ${silent.map((r) => `\`${r}\``).join(", ")}.`,
    ""
  );
  // parity
  if (linters?.corpus) {
    out.push(
      "### Same rules, three linters (raw mirror, external repos pooled)",
      ""
    );
    const sum = (tool, rule) =>
      names.reduce((s, n) => s + (linters.corpus[n]?.[tool]?.[rule] ?? 0), 0);
    const ruleNames = new Set();
    for (const n of names) {
      for (const tool of ["eslint", "biome", "biome (off in Ultracite)"]) {
        for (const r of Object.keys(linters.corpus[n]?.[tool] ?? {})) {
          if (!/^(parse|syntax|suppressions)/.test(r))
            ruleNames.add(`${tool}|${r}`);
        }
      }
    }
    const eslintRules = [...ruleNames]
      .filter((k) => k.startsWith("eslint|"))
      .map((k) => k.split("|")[1]);
    const oxName = (r) => r.replace("@typescript-eslint/", "typescript/");
    const allRules = [...new Set([...hit, ...eslintRules.map(oxName)])].sort();
    out.push(
      ...table(
        ["Rule", "Oxlint (raw)", "ESLint", "Note"],
        allRules.map((r) => {
          const ox = census.rules[r]?.raw.pooled ?? null;
          const es = sum("eslint", r);
          const inOx = inventory.rules.find((i) => i.oxlint.name === r);
          return [
            `\`${r}\``,
            inOx?.oxlint.presets.length ? fmt(ox) : "not in Oxlint",
            fmt(es),
            ox !== null && ox !== es && inOx?.oxlint.presets.length
              ? "differs"
              : "",
          ];
        }),
        ["l", "r", "r", "l"]
      )
    );
    const biomeRules = [...ruleNames]
      .filter((k) => k.startsWith("biome"))
      .map((k) => k.split("|"));
    out.push(
      ...table(
        ["Biome rule", "Hits", "In Ultracite"],
        biomeRules.map(([tool, r]) => [
          `\`${r}\``,
          fmt(sum(tool, r)),
          tool === "biome" ? "on" : "off",
        ]),
        ["l", "r", "l"]
      )
    );
  }

  // ── 3. sinks ───────────────────────────────────────────────────────
  out.push("## 3. Syntactic sink census", "");
  const kinds = Object.entries(sinks.coverage);
  const defaultRule = (r) =>
    preset(r).length > 0 && !preset(r).includes("js-plugins");
  const seenDefault = (k) =>
    sinks.sites.filter(
      (s) =>
        s.kind === k &&
        !lib.DOGFOOD.has(s.repo) &&
        s.expectedHit.oxlint.some(defaultRule)
    ).length;
  out.push(
    ...table(
      [
        "Kind",
        "Sites",
        "Per 10k",
        ...names,
        "Oxlint default sees",
        "Oxlint + js-plugins sees",
        "… (reported)",
        "ESLint sees",
        "Biome sees",
        "Biome, rules off in Ultracite",
      ],
      kinds.map(([k, c]) => [
        `${k}${c.sink ? "" : " (context)"}`,
        fmt(c.total),
        c.per10k,
        ...names.map((n) => fmt(c.byRepo[n])),
        `${seenDefault(k)}`,
        `${c.seenBy.oxlint}`,
        `${c.seenBy["oxlint (reported)"]}`,
        `${c.seenBy.eslint}`,
        `${c.seenBy.biome}`,
        `${c.seenBy["biome (off in Ultracite)"]}`,
      ]),
      ["l", "r", "r", ...names.map(() => "r"), "r", "r", "r", "r", "r", "r"]
    ),
    '"Sees" = a rule expected for that kind (security-sink-census.cjs EXPECTED) reports on a line the site spans. Oxlint default = core + react; "(reported)" honours in-file suppressions; ESLint is Ultracite\'s core + react presets, where the sonarjs, github and unicorn rules are on by default.',
    ""
  );
  out.push("### By sub-kind", "");
  out.push(
    ...table(
      ["Kind", "Sub-kind", "Sites", "Oxlint", "ESLint", "Biome"],
      kinds.flatMap(([k, c]) =>
        Object.entries(c.bySub).map(([s, v]) => [
          k,
          s,
          fmt(v.n),
          fmt(v.oxlint),
          fmt(v.eslint),
          fmt(v.biome),
        ])
      ),
      ["l", "l", "r", "r", "r", "r"]
    )
  );
  out.push("### Which rule saw which sinks", "");
  out.push(
    ...table(
      ["Kind", "Rule hits on sites (tool:rule = sites)"],
      kinds
        .filter(([, c]) => Object.keys(c.byRule).length)
        .map(([k, c]) => [
          k,
          Object.entries(c.byRule)
            .map(([r, n]) => `${r} = ${n}`)
            .join("; "),
        ]),
      null
    )
  );
  out.push("### Security-rule hits on no sink", "");
  out.push(
    ...table(
      ["tool:rule", "Hits"],
      Object.entries(sinks.unmatchedSummary)
        .sort((a, b) => b[1] - a[1])
        .map(([k, n]) => [`\`${k}\``, fmt(n)]),
      ["l", "r"]
    )
  );

  // ── 4. classification ──────────────────────────────────────────────
  out.push("## 4. Hand classification", "");
  const groups = Object.keys(sample.codebook);
  for (const g of groups) {
    const ids = sample.sites.filter((s) => s.group === g);
    const cats = Object.keys(sample.codebook[g].categories);
    const counts = Object.fromEntries(cats.map((c) => [c, 0]));
    for (const s of ids) {
      counts[classes.labels[s.id].category] =
        (counts[classes.labels[s.id].category] ?? 0) + 1;
    }
    out.push(
      `### ${g} (${ids.length} sites): ${sample.codebook[g].question}`,
      ""
    );
    out.push(
      ...table(
        ["Category", "Sites", "Share"],
        cats.map((c) => [
          `\`${c}\``,
          fmt(counts[c]),
          pct(counts[c], ids.length),
        ]),
        ["l", "r", "r"]
      )
    );
    if (g === "injection") {
      const kindsIn = [...new Set(ids.map((s) => s.kind))];
      out.push(
        ...table(
          [
            "Sink kind",
            ...cats,
            "Seen by Oxlint (any preset)",
            "Seen by Oxlint default",
            "Seen by ESLint",
            "Seen by Biome",
          ],
          kindsIn.map((k) => {
            const list = ids.filter((s) => s.kind === k);
            const site = (id) => sinks.sites.find((x) => x.id === id);
            const seen = (tool, filter = () => true) =>
              list.filter(
                (s) => site(s.id).expectedHit[tool].filter(filter).length > 0
              ).length;
            const defaultRule = (r) =>
              !preset(r).includes("js-plugins") && preset(r).length > 0;
            return [
              k,
              ...cats.map((c) =>
                fmt(
                  list.filter((s) => classes.labels[s.id].category === c).length
                )
              ),
              fmt(seen("oxlint")),
              fmt(seen("oxlint", defaultRule)),
              fmt(seen("eslint")),
              fmt(seen("biome")),
            ];
          }),
          ["l", ...cats.map(() => "r"), "r", "r", "r", "r"]
        )
      );
      // The same sinks by category: how many each configuration reports.
      const site = (id) => sinks.sites.find((x) => x.id === id);
      const defaultRuleHit = (r) =>
        !preset(r).includes("js-plugins") && preset(r).length > 0;
      out.push(
        ...table(
          [
            "Category",
            "Sinks",
            "Oxlint default reports",
            "Oxlint + js-plugins",
            "ESLint",
            "Biome",
          ],
          [...cats, "all"].map((c) => {
            const list =
              c === "all"
                ? ids
                : ids.filter((s) => classes.labels[s.id].category === c);
            const n = (tool, f = () => true) =>
              list.filter(
                (s) => site(s.id).expectedHit[tool].filter(f).length > 0
              ).length;
            return [
              c === "all" ? "all" : `\`${c}\``,
              fmt(list.length),
              fmt(n("oxlint", defaultRuleHit)),
              fmt(n("oxlint")),
              fmt(n("eslint")),
              fmt(n("biome")),
            ];
          }),
          ["l", "r", "r", "r", "r", "r"]
        )
      );
      const risky = ids.filter(
        (s) => classes.labels[s.id].category === "user-controlled"
      );
      out.push(
        ...table(
          ["Site", "Kind", "Source", "Rules that fire", "Permalink"],
          risky.map((s) => {
            const site = sinks.sites.find((x) => x.id === s.id);
            const fired = [
              ...new Set([
                ...site.rules.oxlint,
                ...site.rules.eslint,
                ...site.rules.biome,
              ]),
            ];
            return [
              s.id,
              s.kind,
              classes.labels[s.id].source ?? "",
              fired.join(", ") || "none",
              s.permalink,
            ];
          }),
          null
        )
      );
    }
  }
  if (classes.agreement) {
    out.push("### Second-rater agreement", "");
    out.push(
      ...table(
        ["Group", "Pairs", "Same category", "Cohen's kappa"],
        [
          ...Object.entries(classes.agreement.byGroup),
          ["overall", classes.agreement.overall],
        ].map(([g, a]) => [
          g,
          fmt(a.n),
          `${a.same} (${pct(a.same, a.n)})`,
          a.kappa === null ? "undefined (one category)" : a.kappa,
        ]),
        ["l", "r", "r", "r"]
      ),
      `Disagreements: ${classes.agreement.disagreements.map((d) => `${d.id} (${d.first} vs ${d.second})`).join("; ") || "none"}.`,
      ""
    );
  }
  out.push(
    `Biome noSecrets: ${fmt(sample.noSecretsTotal)} hits on the external repos (rule off in Ultracite); ${sample.sites.filter((s) => s.group === "nosecrets").length} sampled, ${sample.sites.filter((s) => s.group === "nosecrets" && classes.labels[s.id].category === "real-secret").length} real secrets.`,
    ""
  );

  // ── 5. calibration ─────────────────────────────────────────────────
  if (linters?.calibration) {
    out.push("## 5. Calibration: which linter catches which case", "");
    const short = (r) =>
      r
        .replace("@typescript-eslint/", "ts-eslint/")
        .replace("typescript/", "ts/");
    const cfgs = [
      "oxlint",
      "oxlint (env on root)",
      "oxlint +js-plugins",
      "oxlint +js-plugins +type-aware",
      "eslint",
      "eslint +type-aware",
      "biome",
      "biome (off in Ultracite)",
    ];
    const added = (row, t, base) =>
      (row.hits[t] ?? []).filter((r) => !(row.hits[base] ?? []).includes(r));
    out.push(
      ...table(
        [
          "Case",
          "Description",
          "Oxlint default",
          "+ core env on root",
          "+ js-plugins",
          "+ type-aware",
          "ESLint",
          "+ type-aware",
          "Biome",
          "Biome, off in Ultracite",
        ],
        linters.calibration.cases.map((row) => [
          row.id,
          row.description,
          cell((row.hits.oxlint ?? []).map(short)),
          cell(added(row, cfgs[1], cfgs[0]).map(short)),
          cell(added(row, cfgs[2], cfgs[0]).map(short)),
          cell(added(row, cfgs[3], cfgs[2]).map(short)),
          cell((row.hits.eslint ?? []).map(short)),
          cell(added(row, cfgs[5], cfgs[4]).map(short)),
          cell(row.hits.biome ?? []),
          cell(row.hits["biome (off in Ultracite)"] ?? []),
        ]),
        null
      ),
      "Columns after a configuration list only the rules the opt-in adds. \"Core env on root\" re-declares core's `env: { browser: true }` on the root config, which Oxlint doesn't inherit through `extends` and `ultracite init` doesn't generate. ESLint's react rules apply to .jsx/.tsx only; Oxlint's react plugin and js-plugins apply to every file.",
      ""
    );
  }

  // ── 6. advisories ──────────────────────────────────────────────────
  if (advisories) {
    out.push("## 6. Published advisories", "");
    const list = advisories.advisories;
    const projects = [...new Set(list.map((a) => a.project))];
    const verdicts = ["flagged", "sink-only", "not-flagged", "unknown"];
    out.push(
      ...table(
        ["Project", "Advisories", ...verdicts, "Earliest", "Latest"],
        [...projects, "all"].map((p) => {
          const l = p === "all" ? list : list.filter((a) => a.project === p);
          const dates = l.map((a) => a.published).sort();
          return [
            p,
            fmt(l.length),
            ...verdicts.map((v) =>
              fmt(l.filter((a) => a.label.lint === v).length)
            ),
            dates[0],
            dates.at(-1),
          ];
        }),
        ["l", "r", "r", "r", "r", "r", "l", "l"]
      )
    );
    const cls = [...new Set(list.map((a) => a.label.class))].sort(
      (a, b) =>
        list.filter((x) => x.label.class === b).length -
        list.filter((x) => x.label.class === a).length
    );
    out.push(
      ...table(
        ["Class", "Advisories", ...verdicts],
        cls.map((c) => [
          c,
          fmt(list.filter((a) => a.label.class === c).length),
          ...verdicts.map((v) =>
            fmt(
              list.filter((a) => a.label.class === c && a.label.lint === v)
                .length
            )
          ),
        ]),
        ["l", "r", "r", "r", "r", "r"]
      )
    );
    const sev = ["critical", "high", "medium", "low"];
    out.push(
      ...table(
        ["Severity", "Advisories"],
        sev.map((s) => [s, fmt(list.filter((a) => a.severity === s).length)]),
        ["l", "r"]
      )
    );
    out.push(
      ...table(
        ["Advisory", "Project", "Class", "Verdict", "Rule", "Note"],
        list
          .filter((a) => ["flagged", "sink-only"].includes(a.label.lint))
          .map((a) => [
            `[${a.ghsa}](${a.url})`,
            a.project,
            a.label.class,
            a.label.lint,
            a.label.rule ?? "",
            a.label.note,
          ]),
        null
      )
    );
  }
  if (fixes) {
    out.push("### Fix commits linted before and after", "");
    out.push(
      ...table(
        [
          "Advisory",
          "Why sampled",
          "Files",
          "Lines removed",
          "Security hits on removed lines",
          "Security hits in the changed files, before → after (Oxlint, ESLint and Biome summed)",
        ],
        fixes.sample.map((s) => {
          const before = Object.entries(s.hitsBefore)
            .filter(([k]) => !k.startsWith("biome (off"))
            .reduce((t, [, n]) => t + n, 0);
          const after = Object.entries(s.hitsAfter)
            .filter(([k]) => !k.startsWith("biome (off"))
            .reduce((t, [, n]) => t + n, 0);
          return [
            `[${s.ghsa}](${s.commit})`,
            s.why,
            fmt(s.files.length),
            fmt(s.linesRemoved),
            cell([
              ...new Set(
                s.hitsOnRemovedLines.map((d) => `${d.tool}: ${d.rule}`)
              ),
            ]),
            `${before} → ${after}`,
          ];
        }),
        null
      )
    );
  }
  writeFileSync(join(lib.RESULTS_DIR, "tables.md"), out.join("\n"));
  console.log(`wrote ${join(lib.RESULTS_DIR, "tables.md")}`);
};

main();
