// Generates results/func-style/tables.md from the topic's JSON results.
//
// Usage: node research/corpus/scripts/func-style-tables.cjs
"use strict";

const { join } = require("node:path");

const lib = require("./func-style-lib.cjs");

const R = (name) => lib.readJson(join(lib.RESULTS_DIR, name), null);
const fmt = (n) =>
  n === null || n === undefined
    ? "–"
    : typeof n === "number"
      ? n.toLocaleString("en-US")
      : String(n);
const pct = (a, b) =>
  b ? `${(Math.round((a / b) * 1000) / 10).toFixed(1)}%` : "–";
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map((h, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(fmt).join(" | ")} |`),
  ].join("\n");

const main = () => {
  const census = R("census.json");
  const linters = R("linters.json");
  const convert = R("convert.json");
  const cycles = R("cycles.json");
  const history = R("history.json");
  const labels = R("history-labels.json") ?? [];
  const markers = R("markers.json");
  const cls = R("classifications.json");
  const cal = R("calibration.json");
  const agents = R("agent-runs.json");
  const rules = R("rules.json");
  const ex = lib.readJson(join(lib.EXAMPLES_DIR, "examples.json"), null);
  const rc = R("rule-census.json");
  const out = [];
  const names = [...lib.CORE, ...lib.REACT, "ultracite"];
  const P = (set, part = "source") => census.pooled[set][part];
  const S = (name, part = "source") => census.repos[name][part];

  out.push(
    "# func-style and no-use-before-define: tables",
    "",
    `Generated by \`scripts/func-style-tables.cjs\` on ${new Date().toISOString().slice(0, 10)} from \`results/func-style/*.json\`. Corpus: the eight repos of every topic; React set: the four React codebases from the accessibility post; external: both. Ultracite's CLI is listed apart and never pooled. Source only unless a table says tests.`,
    ""
  );

  // 1 corpus
  out.push("## 1. Corpus", "");
  out.push(
    table(
      [
        "Repo",
        "SHA",
        "Source files",
        "Lines",
        "Functions",
        "Test files",
        "Test lines",
        "Test functions",
      ],
      names.map((n) => [
        n,
        `\`${census.repos[n].sha.slice(0, 10)}\``,
        S(n).files,
        S(n).lines,
        S(n).functions.total,
        S(n, "tests").files,
        S(n, "tests").lines,
        S(n, "tests").functions.total,
      ])
    ),
    "",
    `External source: ${fmt(P("external").files)} files, ${fmt(P("external").lines)} lines, ${fmt(P("external").functions.total)} functions. Tests: ${fmt(P("external", "tests").functions.total)} functions in ${fmt(P("external", "tests").files)} files.`,
    ""
  );

  // 2 forms
  out.push("## 2. How functions are written", "");
  const groups = [
    "declaration",
    "const-arrow",
    "const-function",
    "let/var-function",
    "method",
    "class-field",
    "object-property",
    "callback",
    "iife",
    "other",
  ];
  const formRow = (label, s) => [
    label,
    ...groups.map((g) => s.functions.byGroup[g] ?? 0),
    s.functions.total,
  ];
  out.push(
    table(
      ["Repo", ...groups, "all"],
      [
        ...names.map((n) => formRow(n, S(n))),
        formRow("**corpus**", P("corpus")),
        formRow("**React set**", P("react")),
        formRow("**external**", P("external")),
        formRow("external tests", P("external", "tests")),
      ]
    ),
    "",
    "Named functions only (declarations against functions bound to a variable):",
    "",
    table(
      [
        "Repo",
        "Declarations",
        "Variable-bound",
        "Declaration share",
        "Declarations per 10k",
        "Variable-bound per 10k",
        "func-style reports (predicted)",
      ],
      [
        ...names.map((n) => [
          n,
          S(n).named.declarations,
          S(n).named.varBound,
          `${S(n).named.declarationShare ?? "–"}%`,
          S(n).named.declarationsPer10k,
          S(n).named.varBoundPer10k,
          S(n).declarations.reportedByFuncStyle,
        ]),
        ...["corpus", "react", "external"].map((k) => [
          `**${k}**`,
          P(k).named.declarations,
          P(k).named.varBound,
          `${P(k).named.declarationShare}%`,
          P(k).named.declarationsPer10k,
          P(k).named.varBoundPer10k,
          P(k).declarations.reportedByFuncStyle,
        ]),
        [
          "external tests",
          P("external", "tests").named.declarations,
          P("external", "tests").named.varBound,
          `${P("external", "tests").named.declarationShare}%`,
          P("external", "tests").named.declarationsPer10k,
          P("external", "tests").named.varBoundPer10k,
          P("external", "tests").declarations.reportedByFuncStyle,
        ],
      ]
    ),
    ""
  );
  const d = P("external").declarations;
  out.push(
    "Declarations (external source):",
    "",
    table(
      ["Fact", "Declarations", "Share"],
      [
        ["all", d.total, "100%"],
        ...Object.entries(d.byForm).map(([k, v]) => [
          `form: ${k}`,
          v,
          pct(v, d.total),
        ]),
        ...Object.entries(d.byScope).map(([k, v]) => [
          `scope: ${k}`,
          v,
          pct(v, d.total),
        ]),
        ["React components", d.components, pct(d.components, d.total)],
        ["async", d.async, pct(d.async, d.total)],
        ["generator", d.generator, pct(d.generator, d.total)],
        ["uses this", d.usesThis, pct(d.usesThis, d.total)],
        ["this parameter", d.thisParam, pct(d.thisParam, d.total)],
        ["uses arguments", d.usesArguments, pct(d.usesArguments, d.total)],
        ["uses new.target", d.usesNewTarget, pct(d.usesNewTarget, d.total)],
        [
          "called with new in its file",
          d.calledWithNewInFile,
          pct(d.calledWithNewInFile, d.total),
        ],
        [
          "called with new by an importer",
          d.calledWithNewCrossFile,
          pct(d.calledWithNewCrossFile, d.total),
        ],
        [".prototype used", d.prototypeUse, pct(d.prototypeUse, d.total)],
        ["instanceof", d.instanceofUse, pct(d.instanceofUse, d.total)],
        [".call/.apply/.bind", d.callApplyBind, pct(d.callApplyBind, d.total)],
        ["TypeScript overloads", d.overloaded, pct(d.overloaded, d.total)],
        [
          "assertion function (asserts)",
          d.assertion,
          pct(d.assertion, d.total),
        ],
        ["type predicate (is)", d.typePredicate, pct(d.typePredicate, d.total)],
        [
          "merged with a namespace",
          d.mergedNamespace,
          pct(d.mergedNamespace, d.total),
        ],
        ["reassigned", d.reassigned, pct(d.reassigned, d.total)],
        ["generic", d.generic, pct(d.generic, d.total)],
        [
          "generic in .tsx, needs <T,> as an arrow",
          d.genericNeedsCommaInTsx,
          pct(d.genericNeedsCommaInTsx, d.total),
        ],
        [
          "referenced above its line",
          d.usedAboveDefinition,
          pct(d.usedAboveDefinition, d.total),
        ],
        [
          "module-level, referenced above its line",
          d.moduleUsedAboveDefinition,
          pct(d.moduleUsedAboveDefinition, d.total),
        ],
        [
          "body is a single return",
          d.singleReturn,
          pct(d.singleReturn, d.total),
        ],
        [
          "every parameter and the return typed",
          d.fullyTyped,
          pct(d.fullyTyped, d.total),
        ],
        ["return type written", d.returnTyped, pct(d.returnTyped, d.total)],
      ]
    ),
    "",
    "What conversion would need (census rule; func-style-census.cjs `conversionOf`):",
    "",
    table(
      ["Conversion", "Declarations", "Share"],
      Object.entries(d.conversion).map(([k, v]) => [k, v, pct(v, d.total)])
    ),
    ""
  );

  // 3 bodies and types
  out.push("## 3. Bodies and types", "");
  const arrowRow = (label, s) => [
    label,
    s.arrows.total,
    pct(s.arrows.concise, s.arrows.total),
    s.arrows.varBound,
    pct(s.arrows.varBoundConcise, s.arrows.varBound),
    s.arrows.varBoundBlock,
    s.arrows.varBoundBlockSingleReturn,
    pct(s.declarations.singleReturn, s.declarations.total),
  ];
  out.push(
    table(
      [
        "Repo",
        "Arrows",
        "Concise",
        "Variable-bound arrows",
        "Concise",
        "Block bodies",
        "Block with a single return",
        "Declarations with a single return",
      ],
      [
        ...names.map((n) => arrowRow(n, S(n))),
        ...["corpus", "react", "external"].map((k) =>
          arrowRow(`**${k}**`, P(k))
        ),
      ]
    ),
    ""
  );
  const typeRow = (label, s) => {
    const c = s.constFunctions;
    return [
      label,
      c.total,
      c.varAnnotated,
      c.varAnnotatedNamed,
      c.varAnnotatedFunctionType,
      c.satisfies,
      c.asserted,
      pct(c.typedThroughVariable, c.total),
      pct(c.inlineFullyTyped, c.total),
      pct(s.declarations.fullyTyped, s.declarations.total),
    ];
  };
  out.push(
    table(
      [
        "Repo",
        "const functions",
        "Variable annotated",
        "…with a named type",
        "…with a function type",
        "satisfies",
        "as",
        "Typed through the variable",
        "const: every parameter and return typed",
        "Declarations: every parameter and return typed",
      ],
      [
        ...names.map((n) => typeRow(n, S(n))),
        ...["corpus", "react", "external"].map((k) =>
          typeRow(`**${k}**`, P(k))
        ),
      ]
    ),
    "",
    `Most common named types on a const function's variable (external source): ${Object.entries(
      P("external").constFunctions.topAnnotationNames
    )
      .map(([k, v]) => `\`${k}\` ${v}`)
      .join(", ")}.`,
    "",
    "React components by form (external source):",
    "",
    table(
      ["Form", "Components"],
      Object.entries(P("external").components).map(([k, v]) => [k, v])
    ),
    ""
  );

  // 4 order
  out.push(
    "## 4. File order",
    "",
    "A reference from one module-level function to another is *down* when the callee is defined below the caller (top-down, the stepdown order) and *up* when above (helpers first). Files with at least two such references: top-down when 75% or more are down, bottom-up when 75% or more are up, otherwise mixed.",
    ""
  );
  const ordRow = (label, s) => {
    const o = s.order;
    return [
      label,
      o.filesWithEdges,
      o.byOrder["top-down"] ?? 0,
      o.byOrder["bottom-up"] ?? 0,
      o.byOrder.mixed ?? 0,
      o.byOrder["one-edge"] ?? 0,
      o.edges,
      `${o.downShare ?? "–"}%`,
      o.sccs,
      o.selfRecursive,
      o.topLevelRefsDown,
    ];
  };
  out.push(
    table(
      [
        "Repo",
        "Files with references",
        "Top-down",
        "Bottom-up",
        "Mixed",
        "One reference",
        "References",
        "Down share",
        "Mutual recursion (SCCs)",
        "Self-recursive",
        "Top-level reads of a function below",
      ],
      [
        ...names.map((n) => ordRow(n, S(n))),
        ...["corpus", "react", "external"].map((k) => ordRow(`**${k}**`, P(k))),
        ordRow("external tests", P("external", "tests")),
      ]
    ),
    "",
    "By the form of a file's module-level functions (external source):",
    "",
    table(
      [
        "File form",
        "Files with references",
        "Top-down",
        "Bottom-up",
        "Mixed",
        "Down share",
      ],
      Object.entries(P("external").order.byFileForm).map(([k, v]) => [
        k,
        v.files,
        v.byOrder["top-down"] ?? 0,
        v.byOrder["bottom-up"] ?? 0,
        v.byOrder.mixed ?? 0,
        `${v.downShare ?? "–"}%`,
      ])
    ),
    "",
    `Mutual recursion among module-level functions (external source): ${P("external").order.sccs} components in ${P("external").order.sccFiles} files, by size ${JSON.stringify(P("external").order.sccsBySize)}, by form ${JSON.stringify(P("external").order.sccsByKinds)}.`,
    ""
  );

  // 5 what the rules report
  out.push(
    "## 5. What the rules report",
    "",
    "Each rule alone (raw: disable directives neutralised; no corpus file has a directive naming these rules, so reported equals raw). Per 10,000 lines in brackets.",
    ""
  );
  const views = [
    "oxlint/func-style",
    "eslint/func-style",
    "biome/useConsistentFunctionStyle",
    "oxlint/func-style:declaration",
    "eslint/func-style:declaration",
    "biome/useConsistentFunctionStyle:declaration",
    "oxlint/func-style:declaration+arrows",
    "eslint/func-style:declaration+arrows",
    "biome/useConsistentFunctionStyle:declaration+arrows",
    "oxlint/no-use-before-define",
    "eslint/ultracite:no-use-before-define",
    "eslint/no-use-before-define",
    "eslint/ts/no-use-before-define",
    "oxlint/no-use-before-define:nofunc",
    "eslint/ts/no-use-before-define:nofunc",
    "oxlint/no-use-before-define:same-context",
    "eslint/ts/no-use-before-define:same-context",
    "biome/noInvalidUseBeforeDeclaration",
    "oxlint/func-names",
    "eslint/func-names",
    "biome/useNamedFunction",
    "oxlint/prefer-arrow-callback",
    "eslint/prefer-arrow-callback",
    "biome/useArrowFunction",
    "oxlint/arrow-body-style",
    "eslint/arrow-body-style",
    "biome/useConsistentArrowReturn",
    "oxlint/unicorn/consistent-function-scoping",
  ];
  const pool = (set, part = "source") => {
    const members =
      set === "corpus"
        ? lib.CORE
        : set === "react"
          ? lib.REACT
          : [...lib.CORE, ...lib.REACT];
    const o = {};
    for (const v of views) {
      o[v] = members.reduce(
        (s, n) => s + (linters.repos[n]?.[part]?.[v]?.raw ?? 0),
        0
      );
    }
    return o;
  };
  const ext = pool("external");
  const extTests = pool("external", "tests");
  out.push(
    table(
      ["View", ...lib.CORE, ...lib.REACT, "external", "per 10k", "tests"],
      views.map((v) => [
        `\`${v}\``,
        ...[...lib.CORE, ...lib.REACT].map(
          (n) => linters.repos[n]?.source?.[v]?.raw ?? 0
        ),
        ext[v],
        Math.round((ext[v] / P("external").lines) * 1e5) / 10,
        extTests[v],
      ])
    ),
    ""
  );
  if (rc) {
    const focus = [
      "func-style",
      "no-use-before-define",
      "func-names",
      "func-name-matching",
      "prefer-arrow-callback",
      "arrow-body-style",
      "unicorn/consistent-function-scoping",
      "no-inner-declarations",
      "react/function-component-definition",
    ];
    out.push(
      "Ultracite's Oxlint presets unchanged (rule-census.cjs, core + react + js-plugins, reported), and each rule's rank among every rule the presets enable:",
      "",
      table(
        ["Rule", "Pooled", "Per 10k", "Rank"],
        focus.map((r) => {
          const all = Object.entries(rc.rules ?? {})
            .map(([k, x]) => [k, x.reported?.pooled ?? 0])
            .sort((a, b) => b[1] - a[1]);
          const rank = all.findIndex(([k]) => k === r) + 1;
          const x = rc.rules?.[r];
          return [
            `\`${r}\``,
            x?.reported?.pooled ?? "–",
            x?.reported?.per10k ?? "–",
            rank ? `${rank} of ${all.length}` : "–",
          ];
        })
      ),
      ""
    );
  }

  // 6 agreement
  out.push("## 6. Where the implementations disagree", "");
  for (const [k, v] of Object.entries(linters.agreement.source)) {
    out.push(
      `**${k}** (${v.views.map((x) => `\`${x}\``).join(", ")}):`,
      "",
      table(
        ["Who flags it | why", "Items"],
        Object.entries(v.combos)
          .slice(0, 14)
          .map(([c, n]) => [c, n])
      ),
      ""
    );
  }

  // 7 use-before-define classes
  out.push(
    "## 7. Every use-before-define candidate by what happens at runtime",
    "",
    "Candidates are references above their binding's first definition, or read during its own initialisation (func-style-lib.cjs). Classes: hoisted-function (a declaration: works), deferred (inside a function that runs later), deferred-maybe-module-evaluation (inside a callback passed to a call at load time, or a function passed somewhere at load time), tdz-* (read before initialisation: throws), type-only, export-specifier.",
    ""
  );
  const classes = [
    ...new Set(names.flatMap((n) => Object.keys(S(n).useBeforeDefine.byClass))),
  ].sort();
  out.push(
    table(
      ["Repo", ...classes, "all"],
      [
        ...names.map((n) => [
          n,
          ...classes.map((c) => S(n).useBeforeDefine.byClass[c] ?? 0),
          S(n).useBeforeDefine.candidates,
        ]),
        [
          "**external**",
          ...classes.map((c) => P("external").useBeforeDefine.byClass[c] ?? 0),
          P("external").useBeforeDefine.candidates,
        ],
        [
          "external tests",
          ...classes.map(
            (c) => P("external", "tests").useBeforeDefine.byClass[c] ?? 0
          ),
          P("external", "tests").useBeforeDefine.candidates,
        ],
      ]
    ),
    ""
  );

  // 8 messages and fixes
  out.push("## 8. Messages, help and fixes", "");
  const msgs = new Map();
  for (const n of names) {
    for (const m of linters.repos[n]?.messages ?? []) {
      if (!/func-style|use-before|UseBefore|FunctionStyle/.test(m.view)) {
        continue;
      }
      const k = `${m.view}\u0000${m.message}\u0000${m.help ?? ""}`;
      msgs.set(k, (msgs.get(k) ?? 0) + m.n);
    }
  }
  out.push(
    table(
      ["View", "Message", "Help", "Count"],
      [...msgs.entries()]
        .sort((a, b) => b[1] - a[1])
        .slice(0, 20)
        .map(([k, n]) => {
          const [v, m, h] = k.split("\u0000");
          return [
            `\`${v}\``,
            m.replaceAll("|", "\\|"),
            (h || "–").replaceAll("|", "\\|"),
            n,
          ];
        })
    ),
    ""
  );
  out.push(
    table(
      ["Rule", "Oxlint fix", "ESLint fixable", "Biome fix"],
      [
        [
          "func-style",
          rules.oxlintRules.find((r) => r.rule === "eslint/func-style")?.fix,
          rules.eslintMeta["func-style"].fixable ?? "none",
          `useConsistentFunctionStyle: ${rules.biomeExplain.useConsistentFunctionStyle.fix}`,
        ],
        [
          "no-use-before-define",
          rules.oxlintRules.find(
            (r) => r.rule === "eslint/no-use-before-define"
          )?.fix,
          rules.eslintMeta["no-use-before-define"].fixable ?? "none",
          `noInvalidUseBeforeDeclaration: ${rules.biomeExplain.noInvalidUseBeforeDeclaration.fix}`,
        ],
        [
          "arrow-body-style",
          rules.oxlintRules.find((r) => r.rule === "eslint/arrow-body-style")
            ?.fix,
          rules.eslintMeta["arrow-body-style"].fixable,
          `useConsistentArrowReturn: ${rules.biomeExplain.useConsistentArrowReturn.fix}`,
        ],
        [
          "prefer-arrow-callback",
          rules.oxlintRules.find(
            (r) => r.rule === "eslint/prefer-arrow-callback"
          )?.fix,
          rules.eslintMeta["prefer-arrow-callback"].fixable,
          `useArrowFunction: ${rules.biomeExplain.useArrowFunction.fix}`,
        ],
        [
          "react/function-component-definition",
          rules.oxlintRules.find(
            (r) => r.rule === "react/function-component-definition"
          )?.fix,
          rules.eslintMeta["react/function-component-definition"].fixable,
          `useReactFunctionComponentDefinition: ${rules.biomeExplain.useReactFunctionComponentDefinition.fix}`,
        ],
      ]
    ),
    ""
  );

  // 9 conversion
  out.push(
    "## 9. Converting every reported declaration",
    "",
    "On copies (func-style-convert.cjs). Crash at import: a converted binding read while its module loads, before its line (directly, from a function called at load time, or from a synchronous callback). Crash when called: a nested declaration used above its line in the same function body. Oxlint counts are the converted files' only.",
    ""
  );
  const cv = (n) => convert.repos[n];
  const cnames = [...lib.CORE, ...lib.REACT].filter((n) => cv(n));
  const total = (f) => cnames.reduce((s, n) => s + (f(cv(n)) ?? 0), 0);
  out.push(
    table(
      [
        "Repo",
        "Converted files",
        "Arrows",
        "Function expressions",
        "Not reported",
        "References to converted bindings above their line",
        "…already reported (functions: true)",
        "Crash at import",
        "Crash when called",
        "Files needing reorder",
        "No valid order",
        "Moved statements",
        "Moved lines",
        "Oxlint ubd before → converted → reordered",
        "Parse failures",
      ],
      [
        ...cnames.map((n) => {
          const r = cv(n);
          const dd = r.decisions;
          return [
            n,
            r.convertedFiles,
            dd.arrow ?? 0,
            (dd["function-expression:this-arguments-new"] ?? 0) +
              (dd["function-expression:generator"] ?? 0),
            (dd["not-reported:overloads"] ?? 0) +
              (dd["not-reported:export-default"] ?? 0),
            r.newReferences.total,
            r.newReferences.alreadyCandidates,
            r.newReferences.crashAtImport,
            r.newReferences.crashWhenCalled,
            r.reorder.filesWithReports,
            r.reorder.filesUnsolvable,
            r.reorder.movedStatements,
            r.reorder.movedLines,
            `${r.oxlint.original.ubd} → ${r.oxlint.converted.ubd} → ${r.oxlint.reordered.ubd}`,
            r.parseFailures.length,
          ];
        }),
        [
          "**external**",
          total((r) => r.convertedFiles),
          total((r) => r.decisions.arrow),
          total(
            (r) =>
              (r.decisions["function-expression:this-arguments-new"] ?? 0) +
              (r.decisions["function-expression:generator"] ?? 0)
          ),
          total(
            (r) =>
              (r.decisions["not-reported:overloads"] ?? 0) +
              (r.decisions["not-reported:export-default"] ?? 0)
          ),
          total((r) => r.newReferences.total),
          total((r) => r.newReferences.alreadyCandidates),
          total((r) => r.newReferences.crashAtImport),
          total((r) => r.newReferences.crashWhenCalled),
          total((r) => r.reorder.filesWithReports),
          total((r) => r.reorder.filesUnsolvable),
          total((r) => r.reorder.movedStatements),
          total((r) => r.reorder.movedLines),
          `${total((r) => r.oxlint.original.ubd)} → ${total((r) => r.oxlint.converted.ubd)} → ${total((r) => r.oxlint.reordered.ubd)}`,
          total((r) => r.parseFailures.length),
        ],
      ]
    ),
    "",
    "Why no valid order (statement lists):",
    "",
    table(
      ["Repo", ...["mutual-recursion", "evaluation-order"]],
      cnames.map((n) => [
        n,
        cv(n).reorder.unsolvableByReason["mutual-recursion"] ?? 0,
        cv(n).reorder.unsolvableByReason["evaluation-order"] ?? 0,
      ])
    ),
    "",
    "Type checks (each repo's tsconfig; diagnostics added by file and code):",
    "",
    table(
      [
        "Repo",
        "Before",
        "Unresolved imports",
        "Added (converted)",
        "Added (reordered)",
        "Codes added (converted)",
      ],
      lib.CORE.filter((n) => cv(n)?.typecheck).map((n) => {
        const t = cv(n).typecheck;
        return [
          n,
          t.before,
          t.beforeUnresolved,
          t.converted?.added,
          t.reordered?.added,
          Object.entries(t.converted?.byCode ?? {})
            .map(([c, k]) => `TS${c}×${k}`)
            .join(", ") || "–",
        ];
      })
    ),
    ""
  );

  // 10 cycles
  out.push(
    "## 10. Module cycles",
    "",
    `Runtime import cycles (import-cycles-graph.cjs, with every read on each edge) in the eight corpus repos: ${cycles.pooled.cycles} (${cycles.pooled.topLevelUse} already TDZ-prone, ${cycles.pooled.lateUse} late-use). ${cycles.pooled.flips} late-use cycles are safe only because a function declaration is read at load time (${cycles.pooled.hoistedReads} such reads); converting those declarations makes them TDZ-prone.`,
    ""
  );
  for (const [n, r] of Object.entries(cycles.repos)) {
    for (const row of r.rows.filter((x) => x.flips)) {
      out.push(
        `- ${n} ${row.id} (${row.files} files): ${row.hoisted.map((h) => `\`${h.name}\` read at [${h.from}:${h.line}](${h.permalink})`).join("; ")}`
      );
    }
  }
  out.push("");

  // 11 history
  out.push("## 11. History", "");
  const lab = labels.reduce(
    (o, l) => ({ ...o, [l.label]: (o[l.label] ?? 0) + 1 }),
    {}
  );
  out.push(
    `Keyword commits (whole mainline history of each clone): ${labels.length}, hand-read: ${Object.entries(
      lab
    )
      .map(([k, v]) => `${k} ${v}`)
      .join(", ")}.`,
    ""
  );
  out.push(
    table(
      ["Repo", "SHA", "Date", "Label", "Subject"],
      labels
        .filter((l) => l.label !== "unrelated")
        .map((l) => [
          l.repo,
          `\`${l.sha.slice(0, 10)}\``,
          l.date,
          l.label,
          l.subject.replaceAll("|", "\\|").slice(0, 90),
        ])
    ),
    ""
  );
  out.push(
    "Style churn in the three years before each pinned commit (definition lines removed and added in the same commit and file):",
    "",
    table(
      [
        "Repo",
        "Commits",
        "To expression (commits / functions)",
        "To declaration (commits / functions)",
        "Moves (commits / functions)",
        "Move commits called fixes",
        "Move commits naming order",
      ],
      Object.entries(history.repos).map(([n, r]) => [
        n,
        r.churn?.commits,
        `${r.churn?.conversions.toExpression.commits} / ${r.churn?.conversions.toExpression.functions}`,
        `${r.churn?.conversions.toDeclaration.commits} / ${r.churn?.conversions.toDeclaration.functions}`,
        `${r.churn?.moves.commits} / ${r.churn?.moves.functions}`,
        r.churn?.moves.fixCommits,
        r.churn?.moves.orderWords,
      ])
    ),
    ""
  );
  const a = history.analysis;
  out.push(
    `Bug fixes by form (named functions at the pinned commits with 30+ days of exposure: ${fmt(a.units.n)}, ${fmt(a.units.declarations)} declarations; the heuristic is ${history.heuristic?.precision}% precise and misses ${history.heuristic?.missRate}% of other commits, from ${history.heuristic?.from}):`,
    "",
    table(
      [
        "Form",
        "Functions",
        "Median own lines",
        "Changed",
        "Changed by a fix",
        "Fixes per 100 line-years",
      ],
      Object.entries(a.byForm).map(([k, v]) => [
        k,
        v.n,
        v.medianOwnLines,
        `${v.changedShare}%`,
        `${v.fixedShare}%`,
        v.fixesPer100LineYears,
      ])
    ),
    "",
    table(
      ["Model", "n", "Term", "Odds ratio", "95% CI"],
      Object.entries(a.models)
        .filter(([, m]) => m)
        .flatMap(([k, m]) =>
          Object.entries(m.coef)
            .filter(([t]) =>
              ["declaration", "usedAbove", "moduleLevel"].includes(t)
            )
            .map(([t, c]) => [k, m.n, t, c.oddsRatio, `[${c.ci95.join(", ")}]`])
        )
    ),
    ""
  );

  // 12 policy
  out.push("## 12. Policy", "");
  const pol = [];
  for (const [n, r] of Object.entries(markers.repos)) {
    for (const c of r.configs) {
      for (const l of c.lines.filter((x) => x.kind === "rule")) {
        pol.push([
          n,
          `[${c.file}:${l.line}](${l.permalink})`,
          `\`${l.text.replaceAll("|", "\\|").slice(0, 120)}\``,
          l.added ? `${l.added.date} (${l.added.sha.slice(0, 10)})` : "–",
        ]);
      }
    }
  }
  out.push(
    table(["Repo", "Where", "Setting", "Added"], pol),
    "",
    `Disable comments naming these rules in the measured files: ${Object.values(markers.repos).reduce((s, r) => s + r.directives.length, 0)}.`,
    ""
  );

  // 13 hand classification
  out.push("## 13. Hand classification", "");
  if (cls) {
    out.push(
      `Declarations: ${Object.keys(cls.rater1).filter((k) => k.startsWith("F")).length} (the random part weighted by each repo's population); use-before-define reports: ${Object.keys(cls.rater1).filter((k) => k.startsWith("U")).length} (weighted by stratum).`,
      "",
      table(
        ["Field", "Shares (rater 1)", "κ (blind subset)", "Same"],
        [
          [
            "conversion",
            JSON.stringify(cls.shares.F.conversion),
            cls.agreement?.F.conversion.kappa,
            `${cls.agreement?.F.conversion.same}/${cls.agreement?.F.conversion.n}`,
          ],
          [
            "reads (converted vs written)",
            JSON.stringify(cls.shares.F.reads),
            cls.agreement?.F.reads.kappa,
            `${cls.agreement?.F.reads.same}/${cls.agreement?.F.reads.n}`,
          ],
          [
            "concise body possible",
            JSON.stringify(cls.shares.F.concise),
            cls.agreement?.F.concise.kappa,
            `${cls.agreement?.F.concise.same}/${cls.agreement?.F.concise.n}`,
          ],
          [
            "runtime (use-before-define)",
            JSON.stringify(cls.shares.U.runtime),
            cls.agreement?.U.runtime.kappa,
            `${cls.agreement?.U.runtime.same}/${cls.agreement?.U.runtime.n}`,
          ],
          [
            "order",
            JSON.stringify(cls.shares.U.order),
            cls.agreement?.U.order.kappa,
            `${cls.agreement?.U.order.same}/${cls.agreement?.U.order.n}`,
          ],
        ]
      ),
      "",
      table(
        ["Stratum (declarations)", "n", "Conversion", "Reads"],
        Object.entries(cls.shares.F.byStratum).map(([k, v]) => [
          k,
          v.n,
          JSON.stringify(v.conversion),
          JSON.stringify(v.reads),
        ])
      ),
      "",
      `Rater 1 against the automatic labels: declarations ${cls.automatic.F.same}/${cls.automatic.F.n} (κ ${cls.automatic.F.kappa}), use-before-define ${cls.automatic.U.same}/${cls.automatic.U.n} (κ ${cls.automatic.U.kappa}).`,
      ""
    );
  }

  // 14 calibration
  out.push(
    "## 14. Calibration",
    "",
    "Each case through Ultracite's Oxlint config (core; core + react for .tsx), ESLint (the census pass), Biome (each rule alone), tsc and Node, as written and converted (func-style-convert.cjs). Cells list the lines each view reports.",
    ""
  );
  const calViews = [
    "oxlint-init/func-style",
    "eslint/func-style",
    "biome/useConsistentFunctionStyle",
    "oxlint-init/no-use-before-define",
    "eslint/ts/no-use-before-define",
    "biome/noInvalidUseBeforeDeclaration",
  ];
  const lines = (c, stage, v) =>
    (c[stage].lint[v] ?? []).map((x) => x.line).join(",") || "–";
  const nodeOf = (n) =>
    n?.importError
      ? `throws at import: ${n.importError.slice(0, 60)}`
      : n?.exports
        ? Object.entries(n.exports)
            .filter(([, v]) => typeof v === "string" && /Error/.test(v))
            .map(([k, v]) => `${k}: ${v.slice(0, 50)}`)
            .join("; ") || "ok"
        : "?";
  out.push(
    table(
      [
        "Case",
        ...calViews.map((v) => `\`${v}\``),
        "tsc",
        "Node",
        "converted: ubd (Oxlint)",
        "converted: Biome",
        "converted: tsc",
        "converted: Node",
      ],
      Object.entries(cal.cases).map(([f, c]) => [
        f.replace(/\.(tsx?|js)$/, ""),
        ...calViews.map((v) => lines(c, "original", v)),
        c.original.tsc.map((x) => `${x.code}@${x.line}`).join(" ") || "–",
        nodeOf(c.original.node),
        lines(c, "converted", "oxlint-init/no-use-before-define"),
        lines(c, "converted", "biome/noInvalidUseBeforeDeclaration"),
        c.converted.tsc.map((x) => `${x.code}@${x.line}`).join(" ") || "–",
        nodeOf(c.converted.node),
      ])
    ),
    "",
    "What `ultracite fix` and `ultracite fix --unsafe` do with Ultracite's presets (the cases whose functions change):",
    "",
    table(
      ["Case", "Pass", "Functions rewritten", "Node afterwards"],
      Object.entries(cal.presetFixes).flatMap(([f, x]) =>
        Object.entries(x)
          .filter(([, v]) => v.changed && v.functionsConverted > 0)
          .map(([k, v]) => [f, k, v.functionsConverted, nodeOf(v.node)])
      )
    ),
    ""
  );

  // 15 agents
  out.push("## 15. Agents in our own data", "");
  const ag = agents.committed;
  const agRow = (label, x) => [
    label,
    x.runs,
    x.added.total,
    x.added.byKind.declaration ?? 0,
    x.added.byKind.expression ?? 0,
    `${x.added.matchesStyle}/${x.added.matchesStyle + x.added.notMatchesStyle}`,
    x.added.placement["above-callers"] ?? 0,
    x.added.placement["below-callers"] ?? 0,
    `${x.reports.funcStyleBefore} → ${x.reports.funcStyleAfter}`,
    `${x.reports.ubdBefore} → ${x.reports.ubdAfter}`,
    x.retries.total,
    x.retries.withFuncStyle,
    x.retries.funcStyleIssues,
    x.retries.onlyTopicRules,
  ];
  out.push(
    table(
      [
        "Runs",
        "n",
        "Functions added",
        "Declarations",
        "Variable-bound",
        "Match the file's style",
        "Helpers above callers",
        "Below",
        "func-style before → after",
        "no-use-before-define before → after",
        "Retries",
        "…with func-style",
        "func-style issues in retries",
        "Retries only for these rules",
      ],
      [
        agRow("all", ag.all),
        agRow("Claude Code", ag.byAgent.claude),
        agRow("Codex", ag.byAgent.codex),
        ...Object.entries(ag.byTopic).map(([t, x]) => agRow(t, x)),
      ]
    ),
    ""
  );

  // 16 subjects
  if (ex) {
    out.push("## 16. Agent-experiment subjects", "");
    for (const [id, s] of Object.entries(ex.subjects)) {
      out.push(
        `**${id.toUpperCase()}** \`${s.file}\` ([source](${s.origin.permalink})): verbatim ${s.verbatim.ok} (${s.verbatim.lines} lines); tsc ${s.tsc.length}; Oxlint (init's config) ${Object.entries(
          s.lint.oxlint.byRule
        )
          .map(([r, n]) => `\`${r}\` ${n}`)
          .join(", ")}; oracle ${s.oracle.calls} calls.`,
        ""
      );
      out.push(
        table(
          [
            "Variant",
            "Kind",
            "Oxlint func-style",
            "Oxlint ubd",
            "ESLint func-style",
            "ESLint ubd",
            "Biome ubd",
            "Rules added (Oxlint)",
            "tsc",
            "Oracle",
            "Moved",
          ],
          Object.entries(s.variants).map(([n, v]) => [
            n,
            v.kind,
            v.topic.oxlint["func-style"],
            v.topic.oxlint["no-use-before-define"],
            v.topic.eslint["func-style"],
            v.topic.eslint["no-use-before-define"],
            v.topic.biome.noInvalidUseBeforeDeclaration,
            Object.entries(v.added.oxlint)
              .map(([r, k]) => `${r} ${k}`)
              .join(", ") || "–",
            v.tsc,
            `${v.oracle.verdict}${v.oracle.differing ? ` (${v.oracle.differing})` : ""}`,
            `${v.structure.functions.length} / ${v.structure.lines} lines`,
          ])
        ),
        ""
      );
    }
    out.push(
      "ESLint here ignores inline config (so suppression comments don't count for it); Oxlint honours them.",
      ""
    );
  }

  lib.writeText(join(lib.RESULTS_DIR, "tables.md"), `${out.join("\n")}\n`);
  console.log(`wrote tables.md (${out.length} lines)`);
};

main();
