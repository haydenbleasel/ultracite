// Generates results/import-cycles/tables.md from the topic's JSON results.
//
// Usage (from the repo root):
//   node research/corpus/scripts/import-cycles-tables.cjs
"use strict";

const { existsSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const ic = require("./import-cycles-lib.cjs");

const R = (name) => ic.readJson(join(ic.RESULTS_DIR, name), null);
const fmt = (n) =>
  n === null || n === undefined
    ? "–"
    : typeof n === "number"
      ? n.toLocaleString("en-US")
      : String(n);
const pct = (a, b) => (b ? `${Math.round((a / b) * 1000) / 10}%` : "–");
const sum = (xs) => xs.reduce((a, b) => a + (b ?? 0), 0);
const REPOS = ic.EXTERNAL;

const table = (head, rows) => [
  `| ${head.join(" | ")} |`,
  `| ${head.map((h, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
  ...rows.map((r) => `| ${r.map(fmt).join(" | ")} |`),
  "",
];

const main = () => {
  const census = R("rule-census.json");
  const graph = R("graph.json");
  const linters = R("linters.json");
  const inventory = R("inventory.json");
  const historyLint = R("history-lint.json");
  const history = R("history.json");
  const classes = R("classifications.json");
  const examples = ic.readJson(join(ic.EXAMPLES_DIR, "examples.json"), null);
  const out = [
    "# Import cycles and barrel files: tables",
    "",
    `Generated by \`scripts/import-cycles-tables.cjs\` on ${new Date().toISOString().slice(0, 10)} from the JSON files in this folder. Pooled numbers cover the eight external repos.`,
    "",
  ];

  // 1. inventory
  out.push("## 1. What Ultracite turns on", "", "### Oxlint", "");
  const onIn = (r) =>
    Object.entries(r.presets)
      .filter(([, v]) => v?.on)
      .map(([p]) => p)
      .join(", ") || "off";
  out.push(
    ...table(
      [
        "Rule",
        "On in",
        "Options set",
        "Defaults",
        "Reads other modules",
        "Type-aware",
      ],
      inventory.oxlint
        .filter((r) => Object.values(r.presets).some(Boolean))
        .map((r) => [
          `\`${r.rule}\``,
          onIn(r),
          JSON.stringify(
            Object.values(r.presets).find((v) => v?.options?.length)?.options ??
              []
          ),
          r.defaults ? `\`${JSON.stringify(r.defaults)}\`` : "",
          r.crossFile ? "yes" : "",
          r.typeAware ? "yes" : "",
        ])
    )
  );
  out.push(
    "### ESLint (calculateConfigForFile on a .ts file; react column on .tsx)",
    ""
  );
  out.push(
    ...table(
      ["Rule", "core", "core + react (.tsx)"],
      inventory.eslint.rows.map((r) => [
        `\`${r.rule}\``,
        `\`${JSON.stringify(r.core)}\``,
        `\`${JSON.stringify(r["core+react (.tsx)"])}\``,
      ])
    ),
    `Resolver settings: \`${JSON.stringify(inventory.eslint.settings)}\``,
    ""
  );
  out.push("### Biome", "");
  out.push(
    ...table(
      ["Rule", "core", "type-aware", "Domain", "Fix"],
      inventory.biome.map((r) => [
        `\`${r.rule}\``,
        JSON.stringify(r.presets.core),
        JSON.stringify(r.presets["type-aware"]),
        r.domain ?? "",
        r.fix ?? "",
      ])
    )
  );

  // 2. census
  out.push("## 2. Rule census (Oxlint core + react + js-plugins)", "");
  const focus = census.focus;
  out.push(
    ...table(
      ["Rule", "Reported", "Raw", "Per 10k (reported)", ...REPOS],
      focus.map((rule) => {
        const r = census.rules[rule];
        return [
          `\`${rule}\``,
          r.reported.pooled,
          r.raw.pooled,
          r.reported.per10k,
          ...REPOS.map(
            (n) =>
              `${r.reported.byRepo[n]}${r.raw.byRepo[n] === r.reported.byRepo[n] ? "" : ` (raw ${r.raw.byRepo[n]})`}`
          ),
        ];
      })
    ),
    "Raw mode lints a mirror of the corpus files only (no tsconfig, package.json or other files), so for the module-graph rules the raw/reported difference is resolution, not suppressions: the corpus has no disable comment naming these rules.",
    ""
  );

  // 3. graph
  const G = graph.repos;
  out.push("## 3. The import graph", "");
  out.push(
    ...table(
      [
        "Repo",
        "Files",
        "Statements",
        "Internal",
        "Type-only (decl/inline)",
        "Elided at compile",
        "Resolved",
        "verbatimModuleSyntax",
      ],
      [
        ...REPOS.map((n) => {
          const r = G[n];
          return [
            n,
            r.files.measured,
            r.statements.total,
            r.statements.internal,
            `${r.statements.byTypeOnly.decl ?? 0}/${r.statements.byTypeOnly.inline ?? 0}`,
            r.statements.internalElided,
            `${r.resolution.resolvedShare}%`,
            r.verbatimModuleSyntax ? "on" : "off",
          ];
        }),
        [
          "**all**",
          sum(REPOS.map((n) => G[n].files.measured)),
          sum(REPOS.map((n) => G[n].statements.total)),
          sum(REPOS.map((n) => G[n].statements.internal)),
          `${sum(REPOS.map((n) => G[n].statements.byTypeOnly.decl))}/${sum(REPOS.map((n) => G[n].statements.byTypeOnly.inline))}`,
          sum(REPOS.map((n) => G[n].statements.internalElided)),
          "",
          "",
        ],
      ]
    )
  );
  out.push(
    "### Cycles (strongly connected components with 2+ files) by edge model",
    ""
  );
  const models = ["all", "oxlint", "eslint", "biome", "runtime", "lazy"];
  out.push(
    ...table(
      ["Repo", ...models.map((m) => `${m}: comps / files (share)`)],
      [
        ...REPOS.map((n) => [
          n,
          ...models.map(
            (m) =>
              `${G[n].models[m].components} / ${G[n].models[m].filesInCycles} (${G[n].models[m].shareOfFiles}%)`
          ),
        ]),
        [
          "**all**",
          ...models.map((m) => {
            const files = sum(REPOS.map((n) => G[n].models[m].filesInCycles));
            return `${sum(REPOS.map((n) => G[n].models[m].components))} / ${files} (${pct(files, sum(REPOS.map((n) => G[n].files.measured)))})`;
          }),
        ],
      ]
    ),
    "Models: all = every static import and re-export, type-only included; oxlint/eslint/biome = the edges each linter follows (calibration); runtime = what survives compilation with the repo's settings, plus top-level require(); lazy = runtime plus import() and require() inside functions.",
    ""
  );
  out.push("### Runtime cycles, classified automatically", "");
  out.push(
    ...table(
      [
        "Repo",
        "Runtime cycles",
        "Sizes",
        "late-use",
        "top-level-use",
        "barrel-induced",
        "Type-only static components",
        "Their sizes",
      ],
      [
        ...REPOS.map((n) => {
          const c = G[n].cycles;
          return [
            n,
            c.runtime,
            c.sizes.join(", "),
            c.byLabel["late-use"] ?? 0,
            c.byLabel["top-level-use"] ?? 0,
            c.byLabel["barrel-induced"] ?? 0,
            c.typeOnlyComponents,
            c.typeOnlySizes.join(", "),
          ];
        }),
        [
          "**all**",
          sum(REPOS.map((n) => G[n].cycles.runtime)),
          "",
          sum(REPOS.map((n) => G[n].cycles.byLabel["late-use"])),
          sum(REPOS.map((n) => G[n].cycles.byLabel["top-level-use"])),
          sum(REPOS.map((n) => G[n].cycles.byLabel["barrel-induced"])),
          sum(REPOS.map((n) => G[n].cycles.typeOnlyComponents)),
          "",
        ],
      ]
    )
  );
  out.push(
    "### Oxlint's import/no-cycle reports (Ultracite's default config), each report's cycle path classified",
    ""
  );
  out.push(
    ...table(
      [
        "Repo",
        "Reports",
        "Predicted by the graph",
        "Matched",
        "Files reported",
        "type-only",
        "late-use",
        "top-level-use",
        "barrel-induced",
        "Median path length",
      ],
      [
        ...REPOS.map((n) => {
          const o = G[n].oxlint;
          const lengths = Object.entries(o.pathLengths).flatMap(([k, v]) =>
            Array(v).fill(Number(k))
          );
          return [
            n,
            o.noCycle,
            o.predicted,
            o.matched,
            o.filesReported,
            o.byLabel["type-only"] ?? 0,
            o.byLabel["late-use"] ?? 0,
            o.byLabel["top-level-use"] ?? 0,
            o.byLabel["barrel-induced"] ?? 0,
            ic.median(lengths),
          ];
        }),
        (() => {
          const all = REPOS.map((n) => G[n].oxlint);
          const lengths = all.flatMap((o) =>
            Object.entries(o.pathLengths).flatMap(([k, v]) =>
              Array(v).fill(Number(k))
            )
          );
          return [
            "**all**",
            sum(all.map((o) => o.noCycle)),
            sum(all.map((o) => o.predicted)),
            sum(all.map((o) => o.matched)),
            sum(all.map((o) => o.filesReported)),
            sum(all.map((o) => o.byLabel["type-only"])),
            sum(all.map((o) => o.byLabel["late-use"])),
            sum(all.map((o) => o.byLabel["top-level-use"])),
            sum(all.map((o) => o.byLabel["barrel-induced"])),
            ic.median(lengths),
          ];
        })(),
      ]
    )
  );

  // 4. linters on the corpus
  if (linters?.corpus) {
    const L = linters.corpus;
    out.push("## 4. The three cycle rules on the corpus", "");
    out.push(
      ...table(
        [
          "Repo",
          "Oxlint import/no-cycle",
          "ESLint import-x/no-cycle",
          "ESLint predicted (import-x simulation)",
          "ESLint matched",
          "Biome noImportCycles",
          "Biome predicted",
          "Biome matched",
          "Biome missed (needs alias/`..` edge)",
        ],
        [
          ...REPOS.map((n) => [
            n,
            G[n].oxlint.noCycle,
            L[n].eslintCycle.actual,
            L[n].eslintCycle.predicted,
            L[n].eslintCycle.matched,
            L[n].biomeCycle.actual,
            L[n].biomeCycle.predicted,
            L[n].biomeCycle.matched,
            `${L[n].biomeCycle.missed.length} (${L[n].biomeCycle.missed.filter((m) => m.needsAliasOrDirectoryEdge).length})`,
          ]),
          [
            "**all**",
            sum(REPOS.map((n) => G[n].oxlint.noCycle)),
            sum(REPOS.map((n) => L[n].eslintCycle.actual)),
            sum(REPOS.map((n) => L[n].eslintCycle.predicted)),
            sum(REPOS.map((n) => L[n].eslintCycle.matched)),
            sum(REPOS.map((n) => L[n].biomeCycle.actual)),
            sum(REPOS.map((n) => L[n].biomeCycle.predicted)),
            sum(REPOS.map((n) => L[n].biomeCycle.matched)),
            sum(REPOS.map((n) => L[n].biomeCycle.missed.length)),
          ],
        ]
      ),
      "ESLint ran in a fresh process per repo, started in the clone root; Biome on a copy of every file the graph loaded plus every tsconfig and package.json, with only the rules in BIOME_RULES on.",
      ""
    );
    if (linters.eslintState) {
      out.push(
        "### ESLint's import-x/no-cycle depends on what the process linted before",
        ""
      );
      out.push(
        ...table(
          ["Run (one process)", "no-cycle reports per step"],
          Object.entries(linters.eslintState).map(([k, v]) => [
            k,
            v.map((s) => `${s.step}: ${s.noCycle}`).join("; "),
          ])
        )
      );
    }
    out.push(
      "### Ultracite's Oxlint fix pass (`oxlint --fix`, what `ultracite fix` runs first) and the cycle reports",
      ""
    );
    out.push(
      ...table(
        [
          "Repo",
          "no-cycle before",
          "after",
          "Files changed",
          "`import type` lines added",
        ],
        [
          ...REPOS.map((n) => [
            n,
            linters.fixPass[n].before,
            linters.fixPass[n].after,
            linters.fixPass[n].filesChanged,
            linters.fixPass[n].typeImportLinesAdded,
          ]),
          [
            "**all**",
            sum(REPOS.map((n) => linters.fixPass[n].before)),
            sum(REPOS.map((n) => linters.fixPass[n].after)),
            sum(REPOS.map((n) => linters.fixPass[n].filesChanged)),
            sum(REPOS.map((n) => linters.fixPass[n].typeImportLinesAdded)),
          ],
        ]
      )
    );
  }

  // 5. barrels
  out.push("## 5. Barrel files", "");
  out.push(
    ...table(
      [
        "Repo",
        "Files with a value re-export",
        "pure barrels",
        "mostly re-exports",
        "of which package entries",
        "internal",
        "index.*",
        "`export *` statements",
        "`export * as`",
        "named re-export statements",
        "Biome noBarrelFile",
        "ESLint unicorn/no-barrel-files",
        "oxc/no-barrel-file",
        "react-doctor/no-barrel-import (importers)",
      ],
      REPOS.map((n) => {
        const b = G[n].barrels;
        const L = linters?.corpus?.[n];
        return [
          n,
          b.filesWithValueReexport,
          b.byTier.pure ?? 0,
          b.byTier.mostly ?? 0,
          b.entryBarrels,
          b.internalBarrels,
          b.indexBarrels,
          b.exportStarStatements,
          b.exportStarAsStatements,
          b.exportNamedStatements,
          L?.biomeBarrel.actual,
          L?.unicornBarrel.actual,
          G[n].oxlint.barrelFile,
          census.rules["react-doctor/no-barrel-import"]?.reported.byRepo[n],
        ];
      })
    ),
    "pure = only re-exports (at least one value re-export); mostly = at least 2 value re-exports and at least half the top-level statements. Entry = mapped from a package.json exports/main/module/types/bin.",
    ""
  );
  out.push(
    "### What a consumer loads through an internal barrel (runtime closure, modules in the repo)",
    ""
  );
  out.push(
    ...table(
      [
        "Repo",
        "Consumer imports",
        "Barrels",
        "Median via barrel",
        "Median direct",
        "Median extra",
        "Max extra",
        "Median ratio",
        "Max ratio",
        "Namespace consumers",
        "Unresolvable",
      ],
      REPOS.map((n) => {
        const f = G[n].fanout;
        return [
          n,
          f.all.consumerImports,
          f.all.barrels,
          f.all.viaMedian,
          f.all.directMedian,
          f.all.extraMedian,
          f.all.extraMax,
          f.all.ratioMedian,
          f.all.ratioMax ? Math.round(f.all.ratioMax * 10) / 10 : 0,
          f.namespaceConsumers,
          f.unknown,
        ];
      })
    )
  );
  out.push("### oxc/no-barrel-file's module count", "");
  out.push(
    ...table(
      [
        "Repo",
        "Files with `export *`",
        "Fires (> 100)",
        "Predicted > 100",
        "Median count",
        "Max count",
      ],
      REPOS.map((n) => {
        const o = G[n].oxlint;
        return [
          n,
          o.exportStarFiles,
          o.barrelFile,
          o.barrelFilePredictedOver100,
          o.exportStarTotalMedian,
          o.exportStarTotalMax,
        ];
      })
    )
  );
  out.push("### Namespace imports (`import * as`)", "");
  const usages = [
    "member-access",
    "type-only-use",
    "whole-object",
    "dynamic-access",
    "unused",
  ];
  const targets = [
    "internal",
    "internal-unresolved",
    "workspace-package",
    "third-party",
    "node-builtin",
  ];
  out.push(
    ...table(
      [
        "Repo",
        "Total",
        "`import type * as`",
        ...usages,
        ...targets,
        "Biome noNamespaceImport",
        "ESLint sonarjs/no-wildcard-import (incl. `export *`)",
      ],
      REPOS.map((n) => {
        const s = G[n].namespaces;
        const L = linters?.corpus?.[n];
        return [
          n,
          s.total,
          s.importType,
          ...usages.map((u) => s.byUsage[u] ?? 0),
          ...targets.map((t) => s.byTarget[t] ?? 0),
          L?.namespace.biomeNoNamespaceImport,
          L?.namespace.sonarWildcard,
        ];
      })
    )
  );
  out.push(
    "### How codebases already keep cycles out of runtime: edges that would close a runtime cycle",
    ""
  );
  out.push(
    ...table(
      [
        "Repo",
        "`import type`",
        "inline `type`",
        "elided by compiler",
        "dynamic import()",
        "lazy require()",
      ],
      REPOS.map((n) => {
        const c = G[n].closers;
        return [
          n,
          c.typeDecl,
          c.typeInline,
          c.elided,
          c.dynamic,
          c.requireLazy,
        ];
      })
    )
  );

  // 6. calibration
  if (linters?.calibration) {
    out.push("## 6. Calibration", "");
    const cfgs = linters.calibration.configs;
    out.push(
      ...table(
        ["Case", ...cfgs],
        linters.calibration.matrix.map((m) => [
          m.case,
          ...cfgs.map(
            (c) =>
              (m[c] ?? [])
                .map((r) =>
                  r.replace(
                    /^(?:import-x|import|suspicious|performance|style|oxc|react-doctor|unicorn|sonarjs|@typescript-eslint|typescript)\//,
                    ""
                  )
                )
                .join(", ") || "–"
          ),
        ])
      )
    );
    out.push("### Messages and help text", "");
    for (const [k, v] of Object.entries(linters.calibration.messages).filter(
      ([k]) =>
        /no-cycle|ImportCycles|self-import|barrel|Barrel|wildcard|NamespaceImport|prefer-export-from|ExportedImports/.test(
          k
        )
    )) {
      out.push(
        `- **${k}**: ${v
          .slice(0, 2)
          .map(
            (x) =>
              `"${x.message}"${x.help ? ` (help: "${x.help.split("\n")[0]}")` : ""}${x.notes?.length ? ` (notes: ${x.notes.map((n) => `"${n}"`).join(" ")})` : ""}`
          )
          .join(" / ")}`
      );
    }
    out.push("");
  }
  if (linters?.autofix) {
    out.push("### What each fix pass does to the calibration cases", "");
    out.push(
      ...table(
        [
          "Fix pass",
          "Files changed",
          "Cycle reports before",
          "after",
          "Cleared",
        ],
        Object.entries(linters.autofix).map(([k, v]) => [
          k,
          v.changed.length,
          v.cyclesBefore,
          v.cyclesAfter,
          v.cyclesCleared
            .map((c) => c.split("/")[1])
            .filter((x, i, a) => a.indexOf(x) === i)
            .join(", "),
        ])
      )
    );
  }
  if (linters?.preferExportFromDanger) {
    out.push(
      "### `oxlint --fix-dangerously` with unicorn/prefer-export-from (one pass, the rule alone, on a copy of each repo)",
      ""
    );
    out.push(
      ...table(
        [
          "Repo",
          "Files changed",
          "Files that lost exports",
          "Exported names lost",
        ],
        REPOS.map((n) => {
          const p = linters.preferExportFromDanger[n];
          return [n, p.filesChanged, p.filesLosingExports, p.namesLost];
        })
      )
    );
  }

  // 7. history
  if (history && historyLint) {
    out.push(
      "## 7. Fixed bugs from history (files at each fix's parent commit, linted)",
      ""
    );
    const lintById = new Map(historyLint.bugs.map((b) => [b.id, b]));
    out.push(
      ...table(
        [
          "Fix",
          "Kind",
          "Top-level use",
          "Through a re-export file",
          "Oxlint",
          "ESLint",
          "Biome (type-aware)",
          "Fix shape",
        ],
        history.bugs.map((b) => {
          const l = lintById.get(b.id);
          const yes = (k) =>
            l?.virtual
              ? "– (virtual modules)"
              : l?.flagged?.[k]
                ? "flags"
                : "misses";
          return [
            `[${b.id}](${b.fix})`,
            b.kind,
            b.topLevelUse ? "yes" : "no",
            b.throughBarrel ? "yes" : "no",
            yes("oxlint"),
            yes("eslint"),
            yes("biome"),
            (b.fixShape ?? "").split(":")[0],
          ];
        })
      )
    );
  }

  // 8. classification
  if (classes) {
    out.push("## 8. Hand classification of Oxlint's reports", "");
    out.push(
      `Population ${fmt(sum(Object.values(classes.population)))} reports; sample ${classes.items.length} (${classes.method})`,
      ""
    );
    const labels = [
      "type-only",
      "late-use",
      "top-level-use",
      "barrel-induced",
      "unclear",
    ];
    out.push(
      ...table(
        ["Label", "Rater 1", "Automatic", "Rater 2 (blind subset)"],
        labels.map((l) => [
          l,
          classes.counts.rater1[l] ?? 0,
          classes.counts.auto[l] ?? 0,
          classes.counts.rater2[l] ?? 0,
        ])
      )
    );
    out.push(
      ...table(
        ["Agreement", "Pairs", "Same", "κ"],
        Object.entries(classes.agreement).map(([k, v]) => [
          k,
          v.n,
          v.same,
          v.kappa,
        ])
      )
    );
    out.push(
      ...table(
        ["Right fix (rater 1)", "Items"],
        Object.entries(classes.counts.rater1RightFix).sort(
          (a, b) => b[1] - a[1]
        )
      )
    );
  }

  // 9. examples
  if (examples) {
    out.push("## 9. Agent-experiment subjects", "");
    for (const s of examples.subjects) {
      out.push(
        `- **${s.id}** (${s.dir}): ${s.role}. ${Object.entries(s.lint.summary)
          .map(
            ([c, v]) =>
              `${c}: ${v.focus.map((f) => `\`${f.rule}\` ${f.file}:${f.line}`).join(", ") || "none"}`
          )
          .join("; ")}.`
      );
    }
    out.push("");
  }
  writeFileSync(join(ic.RESULTS_DIR, "tables.md"), `${out.join("\n")}\n`);
  console.log(`wrote tables.md (${out.length} lines)`);
  void existsSync;
};

main();
