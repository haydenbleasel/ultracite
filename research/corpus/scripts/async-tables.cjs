// Generates results/<topic>/tables.md for the floating-promises post from the JSON the other
// async-*.cjs scripts write. Nothing here measures anything; it only formats.
//
// Usage (from the repo root):
//   node research/corpus/scripts/async-tables.cjs [--topic floating-promises]
"use strict";

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join, resolve } = require("node:path");

const HERE = resolve(__dirname, "..");
const args = process.argv.slice(2);
const TOPIC = args.includes("--topic")
  ? args[args.indexOf("--topic") + 1]
  : (process.env.RESEARCH_TOPIC ?? "floating-promises");
const DIR = join(HERE, "results", TOPIC);
const read = (name) => {
  const path = join(DIR, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : null;
};

const REPOS = [
  "zod",
  "hono",
  "trpc",
  "vite",
  "astro",
  "excalidraw",
  "next.js",
  "vscode",
];
const fmt = (n) =>
  typeof n === "number" ? n.toLocaleString("en-US") : (n ?? "–");
const pct = (a, b) => (b ? `${((a / b) * 100).toFixed(1)}%` : "–");
const per10k = (n, lines) => (lines ? ((n / lines) * 1e4).toFixed(1) : "–");
const row = (cells) => `| ${cells.join(" | ")} |`;
const table = (head, align, rows) =>
  [row(head), row(align), ...rows.map(row)].join("\n");

const main = () => {
  const inventory = read("rule-inventory.json");
  const census = read("rule-census.json");
  const asyncCensus = read("async-census.json");
  const typed = read("typed-census.json");
  const check = read("detector-check.json");
  const linters = read("linters.json");
  const sample = read("sample.json");
  const classes = read("classifications.json");
  const history = read("history.json");
  const configs = read("repo-configs.json");
  const examples = existsSync(
    join(HERE, "examples", "floating-promises", "examples.json")
  )
    ? JSON.parse(
        readFileSync(
          join(HERE, "examples", "floating-promises", "examples.json"),
          "utf8"
        )
      )
    : null;
  const lines = Object.fromEntries(
    REPOS.map((r) => [r, census.repos[r].lines])
  );
  const pooledLines = census.pooled.lines;
  const out = [
    "# Floating promises and async mistakes: generated tables",
    "",
    `Generated by \`scripts/async-tables.cjs\` from the JSON in this folder. Pooled numbers cover the 8 external repos (${fmt(pooledLines)} lines); Ultracite's own CLI is excluded. See REPORT.md for method and caveats.`,
    "",
  ];

  // 1. What Ultracite enables
  out.push("## 1. Async and promise rules Ultracite enables", "");
  const ox = inventory.oxlint.presets;
  out.push(
    `Oxlint ${inventory.oxlint.version}, core preset (react adds none). T = needs type information (\`--type-aware\`).`,
    "",
    ox.core.rules
      .map(
        (r) => `\`${r.rule}\`${r.typeAware ? " T" : ""}${r.on ? "" : " (off)"}`
      )
      .join(", "),
    "",
    `Oxlint js-plugins preset (opt-in): ${ox["js-plugins"].rules.map((r) => `\`${r.rule}\``).join(", ")}.`,
    "",
    `ESLint ${inventory.eslint.version} (typescript-eslint ${inventory.eslint["@typescript-eslint/eslint-plugin"]}, eslint-plugin-promise ${inventory.eslint["eslint-plugin-promise"]}), core + type-aware presets, resolved for a .ts file: ${inventory.eslint.rules
      .map(
        (r) =>
          `\`${r.rule}\`${r.typeAware ? " T" : ""}${r.on ? "" : " (off)"}${r.on && !r.inCore ? " (type-aware preset)" : ""}${!r.on && r.inCore ? " (core only)" : ""}`
      )
      .join(", ")}.`,
    "",
    `Biome ${inventory.biome.version}, core preset: ${inventory.biome.presets.core.map((r) => `\`${r.group}/${r.rule}\``).join(", ")}. Not enabled: ${inventory.biome.available
      .filter((r) => !r.enabledByUltracite)
      .map((r) => `\`${r.group}/${r.rule}\``)
      .join(", ")}.`,
    ""
  );

  // 2. Rule census
  out.push("## 2. Rule census (Oxlint core + react, syntactic rules)", "");
  const focus = census.focus;
  out.push(
    table(
      [
        "Rule",
        "Reported",
        "Raw",
        "Suppressed",
        "Per 10k (raw)",
        "Repos",
        ...REPOS,
      ],
      [
        "---",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        ...REPOS.map(() => "---:"),
      ],
      focus.map((rule) => {
        const r = census.rules[rule];
        return [
          `\`${rule}\``,
          fmt(r.reported.pooled),
          fmt(r.raw.pooled),
          fmt(r.raw.pooled - r.reported.pooled),
          r.raw.per10k,
          `${r.raw.reposWithHits} of 8`,
          ...REPOS.map((n) => fmt(r.raw.byRepo[n])),
        ];
      })
    ),
    ""
  );

  // 3. Syntactic census
  out.push(
    "## 3. Syntactic census (async-census.cjs, every file, no types)",
    ""
  );
  const t = (n) => asyncCensus.repos[n].tally;
  const pooledT = asyncCensus.pooled.tally;
  const cols = [
    ["async functions", (x) => x.asyncFunctions],
    ["await", (x) => x.awaitExpressions],
    ["floating call", (x) => x.floatingCall.total],
    ["floating chain", (x) => x.floatingChain.total],
    ["async callback", (x) => x.asyncCallback.total],
    ["`.map(async)`", (x) => x.mapAsync.total],
    ["await in loop", (x) => x.awaitInLoop.total],
    ["async, no await", (x) => x.asyncNoAwait.total],
    ["`void x;`", (x) => x.voidStatements.total],
    ["`.catch(`", (x) => x.catchCalls.total],
    ["`.then(`", (x) => x.thenCalls],
  ];
  out.push(
    table(
      ["Repo", ...cols.map(([h]) => h)],
      ["---", ...cols.map(() => "---:")],
      [
        ...REPOS.map((n) => [n, ...cols.map(([, f]) => fmt(f(t(n))))]),
        ["**pooled**", ...cols.map(([, f]) => `**${fmt(f(pooledT))}**`)],
        [
          "per 10k (pooled)",
          ...cols.map(([, f]) => per10k(f(pooledT), pooledLines)),
        ],
      ]
    ),
    ""
  );
  const breakdown = (title, obj) => {
    const total = Object.values(obj).reduce((a, b) => a + b, 0);
    out.push(
      `**${title}** (n = ${fmt(total)}): ${Object.entries(obj)
        .sort((a, b) => b[1] - a[1])
        .map(([k, v]) => `${k} ${fmt(v)} (${pct(v, total)})`)
        .join("; ")}.`,
      ""
    );
  };
  breakdown(
    "`.catch(h)` handlers by what h does",
    pooledT.catchCalls.byHandler
  );
  breakdown(
    "`.then(a, b)` rejection handlers",
    pooledT.thenRejectionHandlers.byHandler
  );
  breakdown(
    "`void x;` statements by operand",
    pooledT.voidStatements.byOperand
  );
  breakdown(
    "`.map(async …)` by what happens to the array",
    pooledT.mapAsync.byFate
  );
  breakdown("Floating calls by target", pooledT.floatingCall.byTarget);
  breakdown("Floating chains by last call", pooledT.floatingChain.byEnd);
  breakdown(
    "Async functions without await, by what they return",
    pooledT.asyncNoAwait.byReturn
  );
  breakdown(
    "Async functions without await, by where they sit",
    pooledT.asyncNoAwait.byContext
  );
  breakdown("`await` in loops by loop", pooledT.awaitInLoop.byLoop);
  const callees = Object.entries(pooledT.asyncCallback.byCallee).sort(
    (a, b) => b[1] - a[1]
  );
  out.push(
    `**Async functions passed straight to a call, by callee** (n = ${fmt(pooledT.asyncCallback.total)}; top 20): ${callees
      .slice(0, 20)
      .map(([k, v]) => `\`${k}\` ${v}`)
      .join(", ")}.`,
    "",
    `**Suppression comments naming an async rule:** ${fmt(pooledT.disables.total)} (${
      Object.entries(pooledT.disables.byRule)
        .map(([k, v]) => `${k} ${v}`)
        .join(", ") || "none"
    }).`,
    "",
    `Cross-checks: the detector's await-in-loop count equals Oxlint's raw \`no-await-in-loop\` (${fmt(pooledT.awaitInLoop.total)} vs ${fmt(census.rules["no-await-in-loop"].raw.pooled)}), and its async-without-await count equals Oxlint's raw \`require-await\` (${fmt(pooledT.asyncNoAwait.total)} vs ${fmt(census.rules["require-await"].raw.pooled)}), in every repo.`,
    ""
  );

  // 4. Typed census
  out.push("## 4. Type-aware rules (async-typed-census.cjs)", "");
  out.push(
    `typescript-eslint ${typed.tools["@typescript-eslint/eslint-plugin"]} (TypeScript ${typed.tools.typescript}) with each repo's own tsconfig via the project service; Oxlint ${typed.tools.oxlint} --type-aware with oxlint-tsgolint ${typed.tools["oxlint-tsgolint"]}. Every occurrence counted (inline suppressions ignored; none of these hits had one).`,
    ""
  );
  const tr = (n) => typed.repos[n];
  const lowerBound = (n) =>
    tr(n).probe.importResolution < 99 ? "lower bound" : "full";
  out.push(
    table(
      [
        "Repo",
        "TS files",
        "Imports resolved",
        "Bare calls typed any/error",
        "`no-floating-promises`",
        "per 10k",
        "`no-misused-promises`",
        "per 10k",
        "`require-await` (ts)",
        "`return-await`",
        "`promise-function-async`",
        "`await-thenable`",
        "`strict-void-return`",
        "Oxlint type-aware",
        "Status",
      ],
      [
        "---",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---:",
        "---",
        "---",
      ],
      REPOS.map((n) => {
        const c = tr(n).eslint.counts;
        const oxc = tr(n).oxlint;
        const oxHits = Object.values(oxc.counts).reduce((a, b) => a + b, 0);
        const refused = oxc.tsconfigErrors?.length ?? 0;
        let oxCell = `${fmt(oxc.counts["no-floating-promises"] ?? 0)} / ${fmt(oxc.counts["no-misused-promises"] ?? 0)}`;
        if (refused && oxHits === 0) {
          oxCell = "refused the tsconfig, linted nothing";
        } else if (refused) {
          oxCell += " (one tsconfig refused)";
        }
        return [
          n,
          fmt(tr(n).files),
          `${tr(n).probe.importResolution}%`,
          `${tr(n).probe.bareCallsUntyped}%`,
          fmt(c["no-floating-promises"] ?? 0),
          per10k(c["no-floating-promises"] ?? 0, lines[n]),
          fmt(c["no-misused-promises"] ?? 0),
          per10k(c["no-misused-promises"] ?? 0, lines[n]),
          fmt(c["require-await"] ?? 0),
          fmt(c["return-await"] ?? 0),
          fmt(c["promise-function-async"] ?? 0),
          fmt(c["await-thenable"] ?? 0),
          fmt(c["strict-void-return"] ?? 0),
          oxCell,
          lowerBound(n),
        ];
      })
    ),
    ""
  );
  const sum = (rule) =>
    REPOS.reduce((s, n) => s + (tr(n).eslint.counts[rule] ?? 0), 0);
  out.push(
    `Pooled: \`no-floating-promises\` ${fmt(sum("no-floating-promises"))} (${per10k(sum("no-floating-promises"), pooledLines)} per 10k lines), \`no-misused-promises\` ${fmt(sum("no-misused-promises"))} (${per10k(sum("no-misused-promises"), pooledLines)}), \`require-await\` ${fmt(sum("require-await"))}, \`return-await\` ${fmt(sum("return-await"))}, \`promise-function-async\` ${fmt(sum("promise-function-async"))}, \`await-thenable\` ${fmt(sum("await-thenable"))}, \`strict-void-return\` ${fmt(sum("strict-void-return"))}.`,
    ""
  );
  const byMsg = {};
  for (const n of REPOS) {
    for (const [k, v] of Object.entries(tr(n).eslint.byMessageId)) {
      if (/floating|misused/.test(k)) {
        byMsg[k] = (byMsg[k] ?? 0) + v;
      }
    }
  }
  breakdown("By message", byMsg);
  out.push(
    "Where unresolved imports point (top packages per repo):",
    "",
    ...REPOS.map(
      (n) =>
        `- ${n}: ${
          Object.entries(tr(n).probe.topUnresolved)
            .slice(0, 6)
            .map(([k, v]) => `${k} ${v}`)
            .join(", ") || "none"
        }${
          Object.keys(tr(n).probe.topOutside).length
            ? `; resolved through this repo's node_modules: ${Object.entries(
                tr(n).probe.topOutside
              )
                .slice(0, 4)
                .map(([k, v]) => `${k} ${v}`)
                .join(", ")}`
            : ""
        }`
    ),
    "",
    "Oxlint's tsgolint refused these tsconfigs (and type-checked none of their files):",
    "",
    ...REPOS.filter((n) => tr(n).oxlint.tsconfigErrors?.length).map(
      (n) =>
        `- ${n}: ${[...new Set(tr(n).oxlint.tsconfigErrors.map((e) => e.split(": ").slice(1).join(": ").split("\n")[0]))].join("; ")}`
    ),
    ""
  );

  // 5. Repo configs
  out.push("## 5. What each repo's own config does with these rules", "");
  for (const n of REPOS) {
    const c = configs.repos[n];
    out.push(
      `- **${n}** (${c.configFiles.join(", ") || "no root lint config"}): ${c.lines.map((l) => `[${l.file}:${l.line}](${l.permalink}) \`${l.text.replace(/`/g, "'")}\``).join("; ") || "no async rule named"}`
    );
  }
  out.push("");

  // 6. Detector check
  out.push(
    "## 6. Syntactic detector vs the type-aware rules (async-detector-check.cjs)",
    ""
  );
  out.push(
    table(
      [
        "Repo",
        "Imports resolved",
        "Detector floating",
        "typescript-eslint floating",
        "Both",
        "Detector only (real)",
        "Typed only",
        "Recall",
      ],
      ["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:"],
      REPOS.map((n) => {
        const f = check.repos[n].floating;
        return [
          n,
          `${check.repos[n].importResolution}%`,
          fmt(f.detector),
          fmt(f.typed),
          fmt(f.both),
          `${f.detectorOnly.length} (${f.reviewedTrue})`,
          fmt(f.typedOnly),
          f.recall === null ? "–" : `${f.recall}%`,
        ];
      })
    ),
    ""
  );
  const pf = check.pooled.floating;
  out.push(
    `Pooled: ${fmt(pf.both)} sites found by both, ${fmt(pf.detectorOnly)} by the detector only (all ${fmt(pf.reviewedTrue)} reviewed by hand as real floating promises the typed rule missed), ${fmt(pf.typedOnly)} by the typed rule only. Precision against the typed rule ${pf.precisionAgainstTyped}%, after review ${pf.precisionWithReview}%; recall ${pf.recall}%.`,
    ""
  );
  breakdown("Why the detector missed a typed hit", check.pooled.missReasons);
  const callers = Object.entries(check.pooled.byCallee).filter(
    ([, v]) => v.total >= 4
  );
  out.push(
    "**Async functions passed to a call, and how often no-misused-promises flags them** (callees with 4 or more):",
    "",
    table(
      ["Callee", "Async callbacks", "Flagged", "Share"],
      ["---", "---:", "---:", "---:"],
      callers.map(([k, v]) => [
        `\`${k}\``,
        fmt(v.total),
        fmt(v.flagged),
        pct(v.flagged, v.total),
      ])
    ),
    ""
  );

  // 7. Linters
  out.push("## 7. The same rules in three linters", "");
  const cal = linters.calibration.cases;
  const s = (a) => (a.length ? a.map((x) => `\`${x}\``).join(", ") : "–");
  const asyncOnly = (a) =>
    a.filter((x) =>
      /^ts\/(no-floating|no-misused|await-thenable|return-await|require-await|promise-function-async|strict-void-return)|^no-await-in-loop|^require-await|^no-async-promise-executor|^no-promise-executor-return|^unicorn\/no-unnecessary-await|^sonarjs\/no-try-promise|^no(Void|Float|Misused|AwaitIn|AsyncPromise)|^useAwait/.test(
        x
      )
    );
  out.push(
    `Calibration: ${cal.length} cases in \`calibration/floating-promises/cases.ts\`, run through the TypeScript compiler, Ultracite's Oxlint presets (type-aware), Ultracite's ESLint presets (core + type-aware) and Ultracite's Biome preset, plus Biome's nursery rules that Ultracite doesn't enable. Only the floating/misused/await rules are shown here; \`linters.json\` has every async and promise rule.`,
    "",
    table(
      [
        "Case",
        "tsc",
        "Oxlint",
        "ESLint",
        "Biome (Ultracite)",
        "Biome nursery (off)",
      ],
      ["---", "---", "---", "---", "---", "---"],
      cal.map((c) => [
        `${c.id} ${c.description.replace(/\|/g, "\\|")}`,
        s(c.tsc),
        s(asyncOnly(c.oxlint)),
        s(asyncOnly(c.eslint)),
        s(asyncOnly(c.biome)),
        s(c["biome nursery (not enabled)"]),
      ])
    ),
    ""
  );
  const lc = linters.corpus;
  out.push(
    "Corpus (raw mirror), syntactic rules shared by all three, and Biome's inference-based rules:",
    "",
    table(
      [
        "Repo",
        "no-await-in-loop (Oxlint / ESLint / Biome)",
        "require-await (Oxlint / ESLint / Biome useAwait)",
        "no-async-promise-executor (O / E / B)",
        "Biome noFloatingPromises (vs typescript-eslint)",
        "Biome noMisusedPromises (vs typescript-eslint)",
        "Biome parse errors",
      ],
      ["---", "---", "---", "---", "---", "---", "---:"],
      REPOS.map((n) => {
        const o = (rule) => census.rules[rule].raw.byRepo[n];
        const e = lc[n].eslint;
        const b = lc[n].biome;
        const bc = check.repos[n].biome;
        return [
          n,
          `${o("no-await-in-loop")} / ${e["no-await-in-loop"] ?? 0} / ${b.noAwaitInLoops ?? 0}`,
          `${o("require-await")} / ${e["require-await"] ?? 0} / ${b.useAwait ?? 0}`,
          `${o("no-async-promise-executor")} / ${e["no-async-promise-executor"] ?? 0} / ${b.noAsyncPromiseExecutor ?? 0}`,
          `${bc.noFloatingPromises.biome} (${bc.noFloatingPromises.both} shared of ${bc.noFloatingPromises.typescriptEslint})`,
          `${bc.noMisusedPromises.biome} (${bc.noMisusedPromises.both} shared of ${bc.noMisusedPromises.typescriptEslint})`,
          lc[n].biomeParseErrorFiles.length,
        ];
      })
    ),
    ""
  );

  // 8. Classification
  if (classes) {
    out.push("## 8. Hand classification", "");
    const labelOf = new Map(classes.labels.map((l) => [l.id, l]));
    for (const kind of ["floating", "await-loop"]) {
      const sites = sample.sites.filter((x) => x.kind === kind);
      const counts = {};
      const weighted = {};
      const perRepoSampled = {};
      for (const x of sites) {
        perRepoSampled[x.repo] = (perRepoSampled[x.repo] ?? 0) + 1;
      }
      for (const x of sites) {
        const c = labelOf.get(x.id).category;
        counts[c] = (counts[c] ?? 0) + 1;
        weighted[c] =
          (weighted[c] ?? 0) +
          sample.totals[kind][x.repo] / perRepoSampled[x.repo];
      }
      const wTotal = Object.values(weighted).reduce((a, b) => a + b, 0);
      out.push(
        `**${kind === "floating" ? "Floating promises" : "`await` in loops"}** (n = ${sites.length}, up to ${sample.perRepo} per repo, seed ${sample.seed}; population ${Object.entries(
          sample.totals[kind]
        )
          .map(([r, v]) => `${r} ${v}`)
          .join(", ")}):`,
        "",
        table(
          ["Category", "Sampled", "Unweighted", "Weighted by repo totals"],
          ["---", "---:", "---:", "---:"],
          Object.keys(counts)
            .sort((a, b) => counts[b] - counts[a])
            .map((c) => [
              c,
              counts[c],
              pct(counts[c], sites.length),
              pct(weighted[c], wTotal),
            ])
        ),
        ""
      );
      const field = (name) => {
        const o = {};
        for (const x of sites) {
          const v = String(labelOf.get(x.id)[name]);
          o[v] = (o[v] ?? 0) + 1;
        }
        return o;
      };
      if (kind === "floating") {
        breakdown("canReject", field("canReject"));
        breakdown("fix", field("fix"));
        breakdown(
          "bugKind (latent bugs)",
          Object.fromEntries(
            Object.entries(field("bugKind")).filter(([k]) => k !== "null")
          )
        );
        const byRepo = {};
        for (const x of sites) {
          const c = labelOf.get(x.id).category;
          byRepo[x.repo] ??= {};
          byRepo[x.repo][c] = (byRepo[x.repo][c] ?? 0) + 1;
        }
        out.push(
          `By repo: ${Object.entries(byRepo)
            .map(
              ([r, o]) =>
                `${r} ${Object.entries(o)
                  .map(([c, v]) => `${c} ${v}`)
                  .join(", ")}`
            )
            .join("; ")}.`,
          ""
        );
        for (const [name, a] of Object.entries(classes.annotations ?? {})) {
          out.push(
            `**${name}** (${a.ids.length} of ${sites.length}: ${a.ids.join(", ")}): ${a.note}`,
            ""
          );
        }
        const bySource = {};
        for (const x of sites) {
          const src = x.sources.some((z) =>
            z.startsWith("no-floating-promises")
          )
            ? "no-floating-promises"
            : x.sources.some((z) => z.startsWith("no-misused-promises"))
              ? "no-misused-promises"
              : "detector only";
          bySource[src] ??= {};
          const c = labelOf.get(x.id).category;
          bySource[src][c] = (bySource[src][c] ?? 0) + 1;
        }
        out.push(
          `By what flagged it: ${Object.entries(bySource)
            .map(
              ([src, o]) =>
                `${src}: ${Object.entries(o)
                  .map(([c, v]) => `${c} ${v}`)
                  .join(", ")}`
            )
            .join("; ")}.`,
          ""
        );
      } else {
        breakdown("documented", field("documented"));
        breakdown("earlyExit", field("earlyExit"));
      }
    }
    if (classes.agreement) {
      out.push(
        "**Blind second pass:**",
        "",
        table(
          [
            "Kind",
            "Same category",
            "Cohen's κ",
            "Same coarse label",
            "Coarse κ",
          ],
          ["---", "---:", "---:", "---:", "---:"],
          Object.entries(classes.agreement).map(([k, a]) => [
            k,
            `${a.same} of ${a.n}`,
            a.kappa,
            `${a.coarse.same} of ${a.n}`,
            a.coarse.kappa,
          ])
        ),
        "",
        ...Object.entries(classes.agreement).map(
          ([k, a]) =>
            `- ${k} disagreements: ${a.disagreements.map((d) => `${d.id} (${d.first} / ${d.second})`).join(", ") || "none"}`
        ),
        ""
      );
    }
  }

  // 9. History
  if (history) {
    out.push("## 9. Fixed bugs in the repos' history", "");
    out.push(
      table(
        [
          "Repo",
          "Fix",
          "Date",
          "What broke",
          "no-floating-promises",
          "no-misused-promises",
          "Other",
        ],
        ["---", "---", "---", "---", "---", "---", "---"],
        history.confirmed.map((c) => [
          c.repo,
          `[${c.id.split("#")[1]}](${c.fixUrl})`,
          c.date,
          c.description.replace(/\|/g, "\\|"),
          c.flaggedBy["no-floating-promises"],
          c.flaggedBy["no-misused-promises"],
          c.flaggedBy.other ?? "–",
        ])
      ),
      ""
    );
    const yes = history.confirmed.filter(
      (c) =>
        c.flaggedBy["no-floating-promises"] === "yes" ||
        c.flaggedBy["no-misused-promises"] === "yes"
    );
    out.push(
      `${yes.length} of ${history.confirmed.length} would have been flagged by one of the two rules (no-floating-promises ${history.confirmed.filter((c) => c.flaggedBy["no-floating-promises"] === "yes").length}, no-misused-promises ${history.confirmed.filter((c) => c.flaggedBy["no-misused-promises"] === "yes").length}).`,
      ""
    );
  }

  // 10. Examples
  if (examples) {
    out.push("## 10. Agent-experiment subjects", "");
    out.push(
      table(
        [
          "Subject",
          "Source",
          "In place",
          "Standalone (typescript-eslint / Oxlint / tsc)",
        ],
        ["---", "---", "---", "---"],
        examples.subjects.map((x) => [
          `\`${x.id}\` (${x.function})`,
          `[${x.github} ${x.file}#L${x.lines[0]}-L${x.lines[1]}](${x.permalink})`,
          x.inPlace.map((d) => `L${d.line} ${d.rule}`).join(", "),
          `${x.standalone.eslint.map((d) => `L${d.sourceLine} ${d.rule}`).join(", ")} / ${x.standalone.oxlint.map((d) => `L${d.sourceLine} ${d.rule}`).join(", ")} / ${x.standalone.tsc.length} diagnostics`,
        ])
      ),
      ""
    );
  }

  writeFileSync(join(DIR, "tables.md"), `${out.join("\n")}\n`);
  console.log(`wrote ${join(DIR, "tables.md")}`);
};

main();
