// Generates results/length-limits/tables.md from the topic's JSON results.
//
// Usage: node research/corpus/scripts/length-tables.cjs
"use strict";

const { join } = require("node:path");

const lib = require("./length-lib.cjs");

const R = (f) => lib.readJson(join(lib.RESULTS_DIR, f));
const fmt = (n) =>
  n === null || n === undefined
    ? "–"
    : typeof n === "number"
      ? n.toLocaleString("en-US")
      : String(n);
const pc = (x) => (x === null || x === undefined ? "–" : `${x}%`);
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map((h, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");

const main = () => {
  const census = R("census.json");
  const lint = R("corpus-lint.json");
  const format = R("format.json");
  const history = R("history.json");
  const complexity = R("complexity.json");
  const cls = R("classifications.json");
  const calibration = R("calibration.json");
  const markers = R("markers.json");
  const agents = R("agent-runs.json");
  const rules = R("rules.json");
  const check = R("history-check.json");
  const examples = lib.readJson(join(lib.EXAMPLES_DIR, "examples.json"));
  const out = [
    "# Length limits: generated tables",
    "",
    `Generated by \`scripts/length-tables.cjs\` on ${new Date().toISOString().slice(0, 10)} from the JSON files in this folder. Source and tests are kept apart throughout; the corpus is the eight repos, the React set the four React codebases, and Ultracite's CLI is listed apart and left out of every pooled number.`,
    "",
  ];

  // §1 corpus
  out.push("## 1. Corpus", "");
  out.push(
    table(
      [
        "Repo",
        "Set",
        "SHA",
        "Source files",
        "Source lines",
        "Functions",
        "Test files",
        "Test lines",
        "Test functions",
      ],
      Object.entries(census.repos).map(([name, r]) => [
        name,
        r.set,
        `\`${r.sha.slice(0, 10)}\``,
        fmt(r.source.files),
        fmt(r.source.lines),
        fmt(r.source.functions),
        fmt(r.tests?.files ?? 0),
        fmt(r.tests?.lines ?? 0),
        fmt(r.tests?.functions ?? 0),
      ])
    ),
    ""
  );
  const P = census.pooled;
  out.push(
    table(
      [
        "Pool",
        "Files",
        "Lines",
        "Functions",
        "IIFEs",
        "Inline callbacks",
        "Components",
        "Test callbacks",
        "Type-level signatures",
      ],
      Object.entries(P).map(([k, v]) => [
        k,
        fmt(v.files),
        fmt(v.lines),
        fmt(v.functions),
        fmt(v.iifes),
        fmt(v.callbacks),
        fmt(v.components),
        fmt(v.testCallbacks),
        fmt(v.signatures),
      ])
    ),
    ""
  );

  // §2 distributions
  out.push("## 2. Distributions (source)", "");
  const dist = (d) =>
    `${fmt(d.median)} / ${fmt(d.p90)} / ${fmt(d.p99)} / ${fmt(d.max)}`;
  out.push(
    "Median / p90 / p99 / max. Lines are max-lines-per-function's count (IIFEs skipped); code lines skip blank and comment-only lines; Biome lines are noExcessiveLinesPerFunction's body count; callback depth is over callbacks only.",
    "",
    table(
      [
        "Repo",
        "Lines",
        "Code lines",
        "Biome lines",
        "Statements",
        "Parameters",
        "Block depth",
        "Callback depth",
        "Cognitive",
        "File lines",
      ],
      [
        ...Object.entries(census.repos).map(([name, r]) => [
          name,
          r.source.distributions,
        ]),
        ...[
          "core:source",
          "react:source",
          "external:source",
          "core:tests",
          "react:tests",
          "external:tests",
          "dogfood:tests",
        ].map((k) => [`**${k}**`, P[k].distributions]),
      ].map(([name, d]) => [
        name,
        dist(d.lines),
        dist(d.linesCode),
        dist(d.biomeLines),
        dist(d.statements),
        dist(d.params),
        dist(d.maxDepth),
        dist(d.callbackDepth),
        dist(d.cognitive),
        dist(d.fileLines),
      ])
    ),
    ""
  );
  out.push(
    table(
      ["Pool", ...census.lengthBuckets],
      Object.entries(P).map(([k, v]) => [
        k,
        ...census.lengthBuckets.map((b) => fmt(v.lengthBuckets[b] ?? 0)),
      ])
    ),
    ""
  );

  // §3 what each limit reports
  out.push("## 3. What each limit would report", "");
  const keys = Object.keys(lint.pooled["external:source"].reports).filter(
    (k) => !["lines", "functions", "files", "typeLevelParams"].includes(k)
  );
  for (const pool of [
    "core:source",
    "react:source",
    "external:source",
    "external:tests",
    "dogfood:source",
  ]) {
    const rep = lint.pooled[pool].reports;
    out.push(
      `### ${pool} (${fmt(rep.functions)} functions, ${fmt(rep.files)} files, ${fmt(rep.lines)} lines)`,
      ""
    );
    out.push(
      table(
        [
          "Linter, rule, threshold",
          "Functions or files",
          "Share",
          "Per 10k lines",
        ],
        keys.map((k) => {
          const v = rep[k];
          return [
            `\`${k}\``,
            fmt(v.functions ?? v.files ?? v.diagnostics),
            v.diagnostics !== undefined ? "(diagnostics)" : pc(v.pct),
            fmt(v.per10k),
          ];
        })
      ),
      "",
      `Type-level max-params reports (function types and declared functions, not functions): ESLint ${fmt(rep.typeLevelParams.eslint)} at 3, Oxlint ${fmt(rep.typeLevelParams.oxlint)} at 3, Biome ${fmt(rep.typeLevelParams.biome)} at 4.`,
      ""
    );
  }
  out.push("Per repo, source, at each linter's default:", "");
  const perRepoKeys = [
    "eslint max-lines-per-function 50",
    "biome noExcessiveLinesPerFunction 50",
    "sonarjs sonarjs/max-lines-per-function 200",
    "eslint max-statements 10",
    "eslint max-params 3",
    "biome useMaxParams 4",
    "eslint max-depth 4",
    "eslint max-lines 300",
    "sonarjs sonarjs/max-lines 1000",
    "eslint max-classes-per-file 1",
  ];
  out.push(
    table(
      ["Repo", ...perRepoKeys.map((k) => `\`${k}\``)],
      Object.entries(lint.repos).map(([name, r]) => [
        name,
        ...perRepoKeys.map((k) => {
          const v = r.source[k];
          return `${fmt(v.functions ?? v.files)} (${pc(v.pct)}; ${fmt(v.per10k)})`;
        }),
      ])
    ),
    "",
    "Each cell: count (share of functions or files; per 10,000 lines).",
    ""
  );

  // §4 agreement
  out.push("## 4. Where the implementations disagree", "");
  for (const pool of ["external:source", "external:tests"]) {
    const a = lint.pooled[pool].agreement;
    out.push(`### ${pool} (${fmt(a.compared)} functions)`, "");
    out.push(
      table(
        ["Reason", "Functions", "Example"],
        Object.entries(a.reasons)
          .sort((x, y) => y[1].n - x[1].n)
          .map(([k, v]) => [
            k,
            fmt(v.n),
            v.examples[0]
              ? `[${v.examples[0].repo} \`${v.examples[0].name}\`](${v.examples[0].permalink})`
              : "",
          ])
      ),
      ""
    );
    const g = a.biomeUncountedLineBreaks;
    const total = Object.values(g).reduce((s, x) => s + x, 0);
    out.push(
      "Every line break from a function's head to its end, by whether Biome's noExcessiveLinesPerFunction counts it:",
      "",
      table(
        ["Where the line break is", "Line breaks", "Share"],
        [
          ["counted by Biome", g.counted],
          ["in the head (signature, the line of `{`)", g.head],
          ["in front of `{` or `}` (closing braces, `} else {`)", g.brace],
          ["inside JSX text", g.jsxText],
          ["inside a template or string", g.string],
          ["inside a comment", g.comment],
        ].map(([k, v]) => [k, fmt(v), pc(lib.pct(v, total))])
      ),
      "",
      `Functions over 50 for ESLint but not Biome: ${fmt(a.eslintOnlyOver50.n)} (getters and setters, which Biome doesn't check: ${fmt(a.eslintOnlyOver50.accessor)}). The largest uncounted category in each: ${Object.entries(
        a.eslintOnlyOver50.dominantReason
      )
        .map(([k, v]) => `${k} ${fmt(v)}`)
        .join(", ")}.`,
      ""
    );
    const fa = lint.pooled[pool].fileAgreement;
    if (Object.keys(fa).length) {
      out.push(
        table(
          ["File-level reason", "Files"],
          Object.entries(fa).map(([k, v]) => [k, fmt(v.n)])
        ),
        ""
      );
    }
  }

  // §5 shapes
  out.push("## 5. What the functions over 50 lines are", "");
  out.push(
    table(
      [
        "Pool",
        "Over 50",
        "Kinds (a function can have several)",
        "Top level / nested",
        "Share of their lines inside nested functions",
      ],
      Object.entries(P).map(([k, v]) => [
        k,
        fmt(v.long50.n),
        Object.entries(v.long50.kinds)
          .map(([kk, n]) => `${kk} ${fmt(n)}`)
          .join(", "),
        `${fmt(v.long50.nested["top-level"] ?? 0)} / ${fmt(v.long50.nested.nested ?? 0)}`,
        pc(v.long50.shareOfLinesInNested),
      ])
    ),
    ""
  );

  // §6 formatter
  out.push("## 6. How much is the formatter", "");
  const fRows = [];
  for (const [name, cfgs] of Object.entries(format.repos)) {
    for (const scope of ["source", "tests"]) {
      const u = cfgs.ultracite[scope];
      if (!u) {
        continue;
      }
      const x100 = cfgs.pw100[scope];
      const x120 = cfgs.pw120[scope];
      const d = (s) =>
        `${fmt(s.fileLinesAfter)} (${s.fileLinesAfter >= s.fileLinesBefore ? "+" : ""}${lib.pct(s.fileLinesAfter - s.fileLinesBefore, s.fileLinesBefore)}%)`;
      const cross = (s) =>
        `${fmt(s.limits["lines>50"].after)} (+${fmt(s.limits["lines>50"].crossUp)} −${fmt(s.limits["lines>50"].crossDown)})`;
      fRows.push([
        `${name} ${scope}`,
        fmt(u.fileLinesBefore),
        d(u),
        d(x100),
        d(x120),
        fmt(u.limits["lines>50"].before),
        cross(u),
        cross(x100),
        cross(x120),
        `${fmt(u.statementsChanged)} (${fmt(u.statementsChangedByEmpty)})`,
        fmt(u.paramsChanged),
      ]);
    }
  }
  out.push(
    "File lines as the project formats them, after Oxfmt with Ultracite's preset (printWidth 80), and at printWidth 100 and 120; functions over 50 lines before, and after each (functions that crossed up and down). Statement changes in brackets are those fully explained by removed empty statements.",
    "",
    table(
      [
        "Repo",
        "Lines as written",
        "Ultracite (80)",
        "100",
        "120",
        "Over 50 as written",
        "Over 50, Ultracite",
        "Over 50, 100",
        "Over 50, 120",
        "Statements changed (empty)",
        "Parameters changed",
      ],
      fRows
    ),
    ""
  );
  const fProblems = Object.entries(format.repos).flatMap(([n, cfgs]) =>
    Object.entries(cfgs).flatMap(([c, s]) =>
      s.problems.parseErrors.length ||
      s.problems.unmatchedFiles ||
      s.problems.formatErrors.length
        ? [
            `${n} ${c}: ${s.problems.parseErrors.length} parse errors, ${s.problems.unmatchedFiles} unmatched files, ${s.problems.formatErrors.length} format errors`,
          ]
        : []
    )
  );
  out.push(
    fProblems.length
      ? fProblems.map((x) => `- ${x}`).join("\n")
      : "Every formatted file parsed, and every function matched its unformatted self, at all three widths.",
    ""
  );

  // §7 history
  out.push("## 7. Size and outcomes (history)", "");
  out.push(
    table(
      [
        "Repo",
        "Window from",
        "Mainline commits",
        "Bug-fix commits",
        "Mass commits",
        "Functions",
        "Born in window",
        "Changed",
        "Changed by a fix",
        "Renames followed",
      ],
      Object.entries(history.repos).map(([n, r]) => [
        n,
        new Date(r.since * 1000).toISOString().slice(0, 10),
        fmt(r.commits),
        `${fmt(r.bugFixCommits)} (${pc(lib.pct(r.bugFixCommits, r.commits))})`,
        fmt(r.massCommits),
        fmt(r.functions),
        fmt(r.bornInWindow),
        fmt(r.functionsChanged),
        fmt(r.functionsFixed),
        fmt(r.renamesFollowed),
      ])
    ),
    ""
  );
  if (check?.result) {
    out.push(
      `Hand check of the fix heuristic (one rater, 100 commits): ${check.result.heuristicFixes.labelled} it calls fixes, ${JSON.stringify(check.result.heuristicFixes.raw)}, weighted precision ${pc(check.result.heuristicFixes.weightedYesShare)}; ${check.result.heuristicOthers.labelled} it doesn't, ${JSON.stringify(check.result.heuristicOthers.raw)}, weighted share of real fixes ${pc(check.result.heuristicOthers.weightedYesShare)}.`,
      ""
    );
  }
  const A = history.analysis;
  out.push(
    `Pooled: ${fmt(A.units.n)} functions with at least ${history.method.minExposureDays} days of exposure (${fmt(A.units.changed)} changed, ${fmt(A.units.fixed)} changed by a fix).`,
    ""
  );
  for (const field of ["lines", "ownLines"]) {
    out.push(
      `By ${field === "lines" ? "length (max-lines-per-function's count)" : "own lines (nested functions' interiors left out, as changes are attributed)"}:`,
      "",
      table(
        [
          "Bucket",
          "Functions",
          "Changed",
          "Changed by a fix",
          "Fixes per function-year",
          "Fixes per 100 line-years",
          "Fixes among changes",
        ],
        Object.entries(A.buckets[field]).map(([b, v]) => [
          b,
          fmt(v.n),
          pc(v.changedShare),
          pc(v.fixedShare),
          fmt(v.fixesPerFunctionYear),
          fmt(v.fixesPer100LineYears),
          pc(v.fixShareOfChanges),
        ])
      ),
      ""
    );
  }
  out.push(
    'Logistic regressions of "changed by a fix" (repo fixed effects, log exposure; odds ratio per unit of each term, 95% interval from file-clustered standard errors). Terms: log own lines, log lines, log(1 + statements), parameters, block depth, log(1 + cognitive), log cyclomatic, log(1 + changes).',
    "",
    table(
      ["Model", "n", "Terms (odds ratio [95% CI])", "Log-likelihood"],
      Object.entries(A.models).map(([k, m]) => [
        k,
        fmt(m.n),
        Object.entries(m.coef)
          .filter(([t]) => t !== "exposure")
          .map(([t, c]) => `${t} ${c.oddsRatio} [${c.ci95.join(", ")}]`)
          .join("; "),
        fmt(m.ll),
      ])
    ),
    "",
    `Likelihood-ratio χ² (1 df) for adding each metric to size: ${Object.entries(
      A.lrTests
    )
      .map(([k, v]) => `${k} ${v.chi2}`)
      .join(", ")}.`,
    "",
    `Spearman with fixes per year (and partial on own lines): ${Object.entries(
      A.correlations
    )
      .map(
        ([k, v]) =>
          `${k} ${v.spearman}${v.partialOnOwnLines !== null ? ` (${v.partialOnOwnLines})` : ""}`
      )
      .join(", ")}.`,
    ""
  );

  // §8 complexity
  out.push("## 8. Length and cognitive complexity", "");
  out.push(
    `Ultracite's threshold: ${complexity.threshold.eslint} (ESLint), ${complexity.threshold.oxlintJsPlugins} (Oxlint js-plugins), ${complexity.threshold.biome} (Biome).`,
    "",
    table(
      [
        "Pool",
        "Functions",
        "ρ lines–cognitive",
        "ρ (cognitive > 0)",
        "ρ lines–statements",
        "ρ statements–cognitive",
        "Over 50 lines",
        "…cognitive 0",
        "…≤ 5",
        "…≤ limit",
        "…≤ limit with nested",
        "…hidden in nested",
        "Over the limit",
        "…≤ 50 lines",
        "…≤ 25 lines",
      ],
      Object.entries(complexity.pooled).map(([k, v]) => [
        k,
        fmt(v.n),
        v.spearman.linesCognitive,
        v.spearman.linesCognitivePositive,
        v.spearman.linesStatements,
        v.spearman.statementsCognitive,
        fmt(v.long.n),
        fmt(v.long.cognitive0),
        fmt(v.long.cognitiveAtMost5),
        fmt(v.long.cognitiveAtMostLimit),
        fmt(v.long.subtreeAtMostLimit),
        fmt(v.long.hiddenInNested),
        fmt(v.complex.n),
        fmt(v.complex.atMost50Lines),
        fmt(v.complex.atMost25Lines),
      ])
    ),
    "",
    "Long and flat (over 50 lines, no cognitive score in it or any function nested in it), by shape:",
    ""
  );
  for (const [shape, xs] of Object.entries(
    complexity.examples.longFlatByShape
  )) {
    out.push(
      `- **${shape}:** ${xs.map((e) => `[${e.repo} \`${e.name}\`](${e.permalink}) (${e.lines} lines)`).join(", ")}`
    );
  }
  out.push(
    "",
    "Short and complex (over the limit, fewest lines):",
    "",
    ...complexity.examples.shortComplex.map(
      (e) =>
        `- [${e.repo} \`${e.name}\`](${e.permalink}): ${e.lines} lines, cognitive ${e.cognitive}`
    ),
    ""
  );

  // §9 policy
  out.push("## 9. Policy: the projects' own settings and disable comments", "");
  const pRows = [];
  for (const [n, r] of Object.entries(markers.repos)) {
    for (const c of r.configs) {
      for (const l of c.lines) {
        pRows.push([
          n,
          `[\`${c.file}\` L${l.line}](${l.permalink})`,
          `\`${l.text}\``,
          l.added ? `${l.added.date} (${l.added.sha.slice(0, 10)})` : "–",
        ]);
      }
    }
  }
  out.push(table(["Repo", "Config", "Setting", "Added"], pRows), "");
  const dRows = [];
  for (const [n, r] of Object.entries(markers.repos)) {
    for (const d of r.directives) {
      dRows.push([
        n,
        `[\`${d.file}\` L${d.line}](${d.permalink})`,
        d.kind,
        d.rules.join(", "),
        d.reason ?? "–",
        d.covers === "block"
          ? "the file"
          : d.covers
            ? `\`${d.covers.name}\` (${d.covers.lines} lines, ${d.covers.params} params)`
            : "a statement",
        d.test ? "test" : "source",
      ]);
    }
  }
  out.push(
    table(
      ["Repo", "Where", "Kind", "Rules", "Reason", "Covers", "File"],
      dRows
    ),
    ""
  );

  // §10 hand classification
  out.push("## 10. Hand classification", "");
  out.push(
    `Rater 1 labelled all ${fmt(cls.items.length)} items; rater 2 (blind) the seeded subsets. Shares weighted to the population.`,
    "",
    table(
      ["Field", "Weighted shares (rater 1)", "κ", "Same / n"],
      [
        ...Object.entries(cls.weighted.long).map(([f, v]) => [
          `long: ${f}`,
          v,
          cls.agreement.long[f],
        ]),
        ["long: splitCost (any cost)", {}, cls.agreement.long.splitCostAny],
        ...Object.entries(cls.weighted.params).map(([f, v]) => [
          `params: ${f}`,
          v,
          cls.agreement.params[f],
        ]),
      ].map(([f, v, a]) => [
        f,
        Object.entries(v)
          .map(([k, x]) => `${k} ${x}%`)
          .join(", "),
        fmt(a?.kappa),
        a ? `${a.same} / ${a.n}` : "–",
      ])
    ),
    "",
    table(
      ["whyLong / splitHelps", "n"],
      Object.entries(cls.crossTabs.whyLongBySplitHelps).map(([k, v]) => [
        k,
        fmt(v),
      ])
    ),
    "",
    table(
      ["readsEndToEnd / splitHelps", "n"],
      Object.entries(cls.crossTabs.readsEndToEndBySplitHelps).map(([k, v]) => [
        k,
        fmt(v),
      ])
    ),
    ""
  );

  // §11 calibration
  out.push("## 11. Calibration", "");
  const cRows = [];
  for (const [id, c] of Object.entries(calibration.cases).sort()) {
    for (const f of c.functions) {
      const e = f.views["eslint@0"] ?? {};
      const o = f.views["oxlint@0"] ?? {};
      const b = f.views["biome@min"] ?? {};
      const cb = [0, 1, 2, 3, 4, 5, 6]
        .map((m) =>
          f.views[`biome:callbacks@${m}`]?.[
            "complexity/noExcessiveNestedCallbacks"
          ]
            ? m
            : null
        )
        .filter((x) => x !== null);
      cRows.push([
        `${id} \`${f.name}\``,
        `${fmt(e["max-lines-per-function"] ?? (f.census.iife ? "skip" : 0))} / ${fmt(o["max-lines-per-function"] ?? (f.census.iifeLoose ? "skip" : 0))} / ${fmt(b["complexity/noExcessiveLinesPerFunction"] ?? "≤1")} / ${fmt(e["sonarjs/max-lines-per-function"] ?? "skip")}`,
        `${fmt(e["max-statements"] ?? 0)} / ${fmt(o["max-statements"] ?? 0)} / ${fmt(b["nursery/noExcessiveStatementsPerFunction"] ?? 0)}`,
        `${fmt(e["max-params"] ?? 0)} / ${fmt(o["max-params"] ?? 0)} / ${fmt(b["complexity/useMaxParams"] ?? "–")}`,
        `${fmt(e["max-depth"] ?? 0)} / ${fmt(o["max-depth"] ?? 0)} / ${fmt(f.census.sonarNestMax)}`,
        `${fmt(e["max-nested-callbacks"] ?? 0)} / ${fmt(o["max-nested-callbacks"] ?? 0)} / ${cb.length ? cb.at(-1) + 1 : 0}`,
      ]);
    }
  }
  out.push(
    "At each rule's lowest threshold. Lines: ESLint / Oxlint / Biome / SonarJS. Statements and parameters: ESLint / Oxlint / Biome. Depth: ESLint / Oxlint / SonarJS S134's nesting. Callbacks: ESLint / Oxlint / Biome (the depth at which Biome first stops reporting). `skip` is a function the rule skips; `≤1` Biome doesn't report under its minimum of 1.",
    "",
    table(
      [
        "Case and function",
        "Lines",
        "Statements",
        "Parameters",
        "Depth",
        "Callback depth",
      ],
      cRows
    ),
    "",
    `The printWidth case P01: ${Object.entries(calibration.printWidth)
      .map(([w, v]) => `${w}: ${v.lines} lines, ${v.statements} statements`)
      .join("; ")}.`,
    ""
  );
  const typeLevel = Object.entries(calibration.cases)
    .filter(([, c]) => c.typeLevel.length)
    .map(
      ([id, c]) =>
        `- ${id}: ${[...new Set(c.typeLevel.filter((t) => /@0|@min/.test(t.view)).map((t) => `${t.view.split("@")[0].split(":")[0]} ${t.count}`))].join(", ")}`
    );
  out.push(
    "Type-level max-params reports (no function body) at the lowest threshold:",
    "",
    ...typeLevel,
    ""
  );

  // §12 agent runs
  out.push("## 12. Length in the agent experiment's runs", "");
  out.push(
    table(
      [
        "Topic",
        "Runs",
        "Runs adding functions",
        "Functions added",
        "Their median lines / params",
        "Functions before → after",
        "File lines before → after",
        "Crossed over 50 lines (up/down)",
        "Over 10 statements before → after",
        "Over 3 params before → after",
      ],
      Object.entries(agents.byTopic).map(([t, v]) => {
        const a = v.all;
        return [
          t,
          fmt(a.runs),
          fmt(a.runsAddingHelpers),
          fmt(a.helpersAdded),
          `${fmt(a.helpersAddedMedianLines)} / ${fmt(a.helpersAddedMedianParams)}`,
          `${fmt(a.functions[0])} → ${fmt(a.functions[1])}`,
          `${fmt(a.fileLines[0])} → ${fmt(a.fileLines[1])}`,
          `${a.crossed.lines.over} / ${a.crossed.lines.under}`,
          `${a.over.statements[0]} → ${a.over.statements[1]}`,
          `${a.over.params[0]} → ${a.over.params[1]}`,
        ];
      })
    ),
    "",
    "The cognitive-complexity runs, subject function before → after, and what the agents added:",
    "",
    table(
      [
        "Run",
        "Subject lines",
        "Statements",
        "Depth",
        "Cognitive",
        "Added (lines / params)",
      ],
      agents.cognitiveComplexityRuns.map((r) => [
        r.id,
        r.subject
          ? `${r.subject.before.lines} → ${r.subject.after.lines}`
          : "–",
        r.subject
          ? `${r.subject.before.statements} → ${r.subject.after.statements}`
          : "–",
        r.subject
          ? `${r.subject.before.depth} → ${r.subject.after.depth}`
          : "–",
        r.subject
          ? `${r.subject.before.cognitive} → ${r.subject.after.cognitive}`
          : "–",
        r.added
          .map((h) => `\`${h.name}\` (${h.lines} / ${h.params})`)
          .join(", ") || "–",
      ])
    ),
    ""
  );

  // §13 subjects
  out.push("## 13. Agent-experiment subjects and variants", "");
  for (const [id, s] of Object.entries(examples.subjects)) {
    out.push(
      `### ${id}: \`${s.entry}\` (${s.file})`,
      "",
      `As committed: ${s.structure.entry.lines} lines, ${s.structure.entry.statements} statements, ${s.structure.entry.params} parameters, cognitive ${s.structure.entry.cognitive}; the file has ${s.structure.functions} functions. Verbatim: ${s.verbatim.every((v) => v.matches) ? "matches" : "DIFFERS"}; tsc: ${s.tsc.length} errors; the oracle runs ${fmt(s.oracle.scenarios)} scenarios.`,
      "",
      table(
        [
          "Variant",
          "Intent",
          "Behaviour",
          "Entry lines (after Oxfmt)",
          "Functions",
          "Helpers (params / lines / call sites)",
          "In call order",
          "ESLint lines flags",
          "ESLint params flags",
          "Biome lines flags",
          "After Oxfmt, ESLint lines flags",
        ],
        s.variants.map((v) => [
          v.id,
          v.intent,
          v.oracle.verdict,
          `${fmt(v.structure.entry?.lines)} (${fmt(v.afterFormatter.structure.entry?.lines)})`,
          `${v.structure.functionsBefore} → ${v.structure.functions}`,
          v.structure.helpers
            .map(
              (h) => `\`${h.name}\` ${h.params} / ${h.lines} / ${h.callSites}`
            )
            .join(", ") || "–",
          v.structure.helpers.length
            ? v.structure.helpersInCallOrder
              ? "yes"
              : "no"
            : "–",
          v.flagged.eslintLines.join(", ") || "–",
          v.flagged.eslintParams.join(", ") || "–",
          v.flagged.biomeLines.join(", ") || "–",
          v.afterFormatter.flagged.eslintLines.join(", ") || "–",
        ])
      ),
      "",
      s.variants.map((v) => `- **${v.id}:** ${v.what}`).join("\n"),
      ""
    );
  }

  // §14 messages
  out.push("## 14. What each linter says", "");
  out.push(
    table(
      ["Linter and rule", "Message (example)", "Help or notes"],
      Object.entries(lint.messages)
        .sort()
        .map(([k, v]) => [
          `\`${k}\``,
          v.example?.replaceAll("|", "\\|") ?? "–",
          v.help ?? "–",
        ])
    ),
    "",
    "Biome's notes, from its terminal output:",
    "",
    ...Object.entries(calibration.messages)
      .filter(([k, v]) => k.startsWith("biome") && v.notes?.length)
      .map(([k, v]) => `- \`${k}\`: ${v.notes.join(" / ")}`),
    ""
  );
  // §15 presets
  out.push("## 15. What Ultracite's presets set", "");
  out.push(
    "```json",
    JSON.stringify(
      {
        biome: rules.biome,
        eslint: rules.eslint["src/example.ts"],
        oxlint: rules.oxlint,
      },
      null,
      1
    ),
    "```",
    "",
    ...rules.notes.map((n) => `- ${n}`),
    ""
  );
  lib.writeFileSync(join(lib.RESULTS_DIR, "tables.md"), `${out.join("\n")}\n`);
  console.log(`tables.md: ${out.length} lines`);
};

