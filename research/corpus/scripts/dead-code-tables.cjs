// Generates results/dead-code/tables.md from the topic's JSON results.
//
// Usage (from the repo root):
//   node research/corpus/scripts/dead-code-tables.cjs
"use strict";

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const lib = require("./dead-code-lib.cjs");

const read = (name) => {
  const p = join(lib.RESULTS_DIR, name);
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
};
const fmt = (n) =>
  n === null || n === undefined
    ? "–"
    : typeof n === "number"
      ? n.toLocaleString("en-US")
      : String(n);
const code = (s) => `\`${s}\``;
const esc = (s) =>
  String(s ?? "")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
const table = (head, rows, align) => [
  `| ${head.join(" | ")} |`,
  `| ${head.map((_, i) => (align?.[i] === "r" ? "---:" : "---")).join(" | ")} |`,
  ...rows.map((r) => `| ${r.map(esc).join(" | ")} |`),
  "",
];

const out = [];
const h = (level, text) => out.push(`${"#".repeat(level)} ${text}`, "");

const main = () => {
  const inventory = read("inventory.json");
  const linters = read("linters.json");
  const census = read("rule-census.json");
  const typed = read("typed-census.json");
  const exportsR = read("exports.json");
  const clones = read("clones.json");
  const markers = read("markers.json");
  const disagreements = read("disagreements.json");
  const classifications = read("classifications.json");
  const sample = read("sample.json");
  const historyLint = read("history-lint.json");
  const history = read("history.json");
  const repos = lib.EXTERNAL;

  out.push(
    "# Dead code and duplication: generated tables",
    "",
    `Generated by \`scripts/dead-code-tables.cjs\` on ${new Date().toISOString().slice(0, 10)} from the JSON files in this folder. Pooled numbers cover the 8 external repos; Ultracite's own CLI is listed separately where it appears.`,
    ""
  );

  // ── 1. inventory ──
  if (inventory) {
    h(2, "1. What Ultracite turns on");
    h(3, "1.1 Oxlint (core, react, js-plugins)");
    out.push(
      ...table(
        [
          "Rule",
          "Category",
          "Preset",
          "Options",
          "Test-file override",
          "Type-aware",
          "Fix",
          "Oxlint category",
        ],
        inventory.oxlint
          .filter(
            (r) =>
              Object.values(r.presets).some((p) => p.on) ||
              r.oxlintCategory === "nursery"
          )
          .map((r) => [
            code(r.rule),
            r.category,
            Object.entries(r.presets)
              .filter(([, p]) => p.on)
              .map(([p]) => p)
              .join(", ") || "off (not in any preset)",
            Object.values(r.presets).find((p) => p.on)?.options?.length
              ? JSON.stringify(
                  Object.values(r.presets).find((p) => p.on).options
                )
              : "defaults",
            r.testOverride
              ? `${r.testOverride.value} (${r.testOverride.preset})`
              : "–",
            r.typeAware ? "yes" : "no",
            r.fix ?? "–",
            r.oxlintCategory ?? "JS plugin",
          ])
      )
    );
    h(3, "1.2 ESLint (core; type-aware and react where they add a rule)");
    out.push(
      ...table(
        [
          "Rule",
          "Category",
          "On for .ts",
          "On for .js",
          "Only with type-aware",
          "Only in react (.tsx)",
          "Options (.ts)",
          "Test files",
          "Fixable",
          "Suggestions",
        ],
        inventory.eslint
          .filter(
            (r) =>
              r.core.ts.on ||
              r.core.js.on ||
              r.typeAware.ts.on ||
              r.react?.tsx?.on
          )
          .map((r) => [
            code(r.name),
            r.category,
            r.core.ts.on ? "yes" : "no",
            r.core.js.on ? "yes" : "no",
            r.onlyWithTypes ? "yes" : "",
            r.onlyWithReact ? "yes" : "",
            r.core.ts.options.length
              ? JSON.stringify(r.core.ts.options)
              : r.typeAware.ts.options.length
                ? JSON.stringify(r.typeAware.ts.options)
                : "defaults",
            r.testDiffers
              ? r.testDiffers.on
                ? "different options"
                : "off"
              : "same",
            r.fixable ?? "",
            r.hasSuggestions ? "yes" : "",
          ])
      )
    );
    h(
      3,
      "1.3 Biome (core + react, Biome's recommended set unless the preset says otherwise)"
    );
    out.push(
      ...table(
        [
          "Rule",
          "Category",
          "On",
          "Set by",
          "Fix (Biome default)",
          "Preset fix setting",
          "Overrides",
        ],
        inventory.biome.map((r) => [
          code(r.rule),
          r.category,
          r.on ? "yes" : "no",
          r.viaRecommended
            ? "Biome recommended"
            : r.core || r.react
              ? "preset"
              : "–",
          r.fix,
          typeof r.core === "object" && r.core?.fix ? r.core.fix : "",
          r.overrides
            .map((o) => `${o.level} for ${o.includes.join(", ")}`)
            .join("; "),
        ])
      )
    );
    h(3, "1.4 The same concept in each linter");
    out.push(
      ...table(
        [
          "Concept",
          "Oxlint core",
          "Oxlint js-plugins",
          "ESLint",
          "Biome",
          "TypeScript",
        ],
        inventory.concepts.map((c) => [
          c.concept,
          c.oxlintCoreOn.map(code).join(", ") || "–",
          c.oxlintJsPluginsOn.map(code).join(", ") || "–",
          c.eslintOn.map(code).join(", ") ||
            (c.eslint.length ? `off: ${c.eslint.map(code).join(", ")}` : "–"),
          c.biomeOn.map(code).join(", ") || "–",
          c.tsc ?? "–",
        ])
      )
    );
    out.push(
      `On in ESLint but in no Oxlint preset (${inventory.gaps.eslintOnly.length}): ${inventory.gaps.eslintOnly.map(code).join(", ")}.`,
      ""
    );
    out.push(
      `On in Oxlint but not ESLint: ${inventory.gaps.oxlintOnly.map(code).join(", ") || "none"}.`,
      ""
    );
  }

  // ── 2. messages ──
  if (linters?.calibration) {
    h(2, "2. What each linter says (calibration, exact text)");
    out.push(
      "`{name}` stands for the identifier, `{n}` for a number. Oxlint's `help` and ESLint's suggestions reach an agent through the diagnostics file `ultracite fix --claude/--codex` writes; Biome's notes appear only in its terminal output (its JSON reporter's `advices` is empty, and the JSON is what the agent handoff reads).",
      ""
    );
    const main =
      /no-unused-vars|noUnused|unused-imports|unused-import|no-unused-function-argument|no-dead-store|no-useless-assignment|no-unassigned|noUnassigned|no-unreachable|noUnreachable|no-unused-expressions|noUnusedExpressions|identical-functions|duplicated-branches|no-duplicate-string|no-unused-collection|no-useless-increment|no-ignored-return|no-unused-builtin|TS6|TS7|private-class|noUselessCatchBinding/;
    out.push(
      ...table(
        ["Linter", "Rule", "Message(s)", "Help / suggestions / notes"],
        linters.calibration.messageMap
          .filter(
            (m) =>
              main.test(m.rule) &&
              m.tool !== "eslint +type-aware" &&
              m.tool !== "oxlint +js-plugins"
          )
          .map((m) => [
            m.tool,
            code(m.rule),
            m.messages.join(" / "),
            [
              ...m.help.map((x) => `help: ${x}`),
              ...m.suggestions.map((x) => `suggestion: ${x}`),
              ...m.notes.map((x) => `note: ${x}`),
            ].join(" / ") || "–",
          ])
      )
    );
  }

  if (linters?.autofix) {
    h(3, "2.1 What the fix pass changes before an agent sees anything");
    out.push(
      "`ultracite fix` runs each linter's own fixer first (`oxlint --fix`, `eslint --fix`, `biome check --write`; with `--unsafe`, `oxlint --fix-dangerously` and `biome check --write --unsafe`). Removed and added lines per calibration case; cases no fixer touches are omitted.",
      ""
    );
    const tools = [
      "oxlint --fix",
      "oxlint --fix-dangerously",
      "eslint --fix",
      "biome check --write",
      "biome check --write --unsafe",
    ];
    const show = (d) =>
      d
        ? `−${d.removed.map((x) => `\`${x}\``).join(" ")}${d.added.length ? ` +${d.added.map((x) => `\`${x}\``).join(" ")}` : ""}`
        : "–";
    out.push(
      ...table(
        ["Case", ...tools],
        Object.entries(linters.autofix)
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([id, r]) => [id, ...tools.map((t) => show(r[t]))])
      )
    );
  }

  // ── 3. calibration ──
  if (linters?.calibration) {
    h(2, "3. Calibration matrix");
    out.push(
      "Dead-code and duplication rules only (`other` rules are in `linters.json`). Oxlint = core + react as `ultracite init` writes it.",
      ""
    );
    const tools = [
      "oxlint",
      "oxlint +js-plugins",
      "eslint",
      "eslint +type-aware",
      "biome",
      "tsc",
    ];
    const cell = (row, t) =>
      [...new Set((row.hits[t] ?? []).map((x) => x.rule))].join(", ") || "–";
    const added = (row, t, base) => {
      const b = new Set((row.hits[base] ?? []).map((x) => x.rule));
      return (
        [...new Set((row.hits[t] ?? []).map((x) => x.rule))]
          .filter((r) => !b.has(r))
          .join(", ") || "–"
      );
    };
    out.push(
      ...table(
        [
          "Case",
          "Oxlint",
          "+ js-plugins adds",
          "ESLint",
          "+ type-aware adds",
          "Biome",
          "tsc",
        ],
        linters.calibration.cases.map((row) => [
          `${row.id} ${row.description}`,
          cell(row, tools[0]),
          added(row, tools[1], tools[0]),
          cell(row, tools[2]),
          added(row, tools[3], tools[2]),
          cell(row, tools[4]),
          cell(row, tools[5]),
        ])
      )
    );
  }

  // ── 4. census ──
  if (census) {
    h(2, "4. How often the rules fire (Oxlint core + react + js-plugins)");
    const focus = census.focus.filter((r) => census.rules[r].raw.pooled > 0);
    out.push(
      ...table(
        [
          "Rule",
          "Reported",
          "Raw",
          "Suppressed",
          "Per 10k (raw)",
          "Repos",
          ...repos,
        ],
        focus
          .sort(
            (a, b) => census.rules[b].raw.pooled - census.rules[a].raw.pooled
          )
          .map((r) => {
            const x = census.rules[r];
            return [
              code(r),
              fmt(x.reported.pooled),
              fmt(x.raw.pooled),
              fmt(x.raw.pooled - x.reported.pooled),
              x.raw.per10k,
              `${x.raw.reposWithHits} of 8`,
              ...repos.map((n) => fmt(x.raw.byRepo[n])),
            ];
          }),
        [null, "r", "r", "r", "r", "r", ...repos.map(() => "r")]
      )
    );
    const silent = census.focus.filter((r) => census.rules[r].raw.pooled === 0);
    out.push(
      `Silent focus rules (${silent.length}): ${silent.map(code).join(", ")}.`,
      ""
    );
  }

  // ── 5. three linters on the corpus ──
  if (linters?.corpus) {
    h(2, "5. The same rules in three linters (raw mirror)");
    const c = linters.corpus.comparisons;
    out.push(
      ...table(
        [
          "Concept",
          "Oxlint lines",
          "ESLint lines",
          "Biome lines",
          "Lines by which linters report them",
        ],
        Object.entries(c).map(([k, v]) => [
          k,
          fmt(v.perTool.oxlint),
          fmt(v.perTool.eslint),
          fmt(v.perTool.biome),
          Object.entries(v.lines)
            .sort((a, b) => b[1] - a[1])
            .map(([s, n]) => `${s}: ${n}`)
            .join(", "),
        ])
      )
    );
    if (disagreements) {
      h(3, "5.1 Why they disagree");
      for (const k of [
        "unused names",
        "unused expressions",
        "useless assignment vs dead store",
        "duplicate imports",
      ]) {
        const rows = [];
        for (const [sig, reasons] of Object.entries(
          disagreements[k]?.byToolsAndReason ?? {}
        )) {
          for (const [reason, n] of Object.entries(reasons).sort(
            (a, b) => b[1] - a[1]
          )) {
            rows.push([sig, reason, n]);
          }
        }
        out.push(
          `**${k}** (names counted individually for unused names)`,
          "",
          ...table(["Reported only by", "Reason", "Count"], rows, [
            null,
            null,
            "r",
          ])
        );
      }
    }
  }

  // ── 6. TypeScript ──
  if (typed) {
    h(2, "6. TypeScript's own checks (noUnusedLocals, noUnusedParameters)");
    out.push(
      ...table(
        [
          "Repo",
          "TS files",
          "Repo's own noUnusedLocals / noUnusedParameters",
          "TS6133",
          "TS6196",
          "TS6192/6198/6199",
          "TS7027 unreachable",
          "`_` names among unused",
          "Imports resolved",
          "Oxlint: both / lint only / TS only",
          "ESLint: both / lint only / TS only",
          "Biome: both / lint only / TS only",
        ],
        Object.entries(typed.repos)
          .filter(([n]) => n !== "ultracite")
          .map(([n, r]) => {
            const flags = Object.values(r.tsconfigs).map(
              (t) =>
                `${t.flags?.noUnusedLocals ?? "–"}/${t.flags?.noUnusedParameters ?? "–"}`
            );
            const tri = (t) =>
              r.compare[t]
                ? `${r.compare[t].both} / ${r.compare[t].lintOnly} / ${r.compare[t].tsOnly}`
                : "–";
            return [
              n,
              r.files,
              [...new Set(flags)].join(", "),
              fmt(r.byCode["6133"] ?? 0),
              fmt(r.byCode["6196"] ?? 0),
              fmt(
                (r.byCode["6192"] ?? 0) +
                  (r.byCode["6198"] ?? 0) +
                  (r.byCode["6199"] ?? 0)
              ),
              fmt(r.byCode["7027"] ?? 0),
              fmt(r.underscore),
              `${r.importResolution}%`,
              tri("oxlint"),
              tri("eslint"),
              tri("biome"),
            ];
          })
      )
    );
  }

  // ── 7. exports ──
  if (exportsR) {
    h(2, "7. Unused exports and unused files (TypeScript program per repo)");
    const cats = [
      "used-in-source",
      "public-api",
      "used-elsewhere",
      "dynamic",
      "own-file-only",
      "unreferenced",
    ];
    out.push(
      ...table(
        [
          "Repo",
          "Exports",
          ...cats,
          "of which wildcard-subpath only",
          "Files",
          "File categories",
          "Specifiers resolved",
        ],
        Object.entries(exportsR.repos).map(([n, r]) => [
          n,
          r.exports.total,
          ...cats.map((c) => fmt(r.exports.byCategory[c] ?? 0)),
          Object.values(r.exports.wildcardOnly ?? {}).reduce(
            (a, b) => a + b,
            0
          ),
          r.files.total,
          Object.entries(r.files.byCategory)
            .map(([k, v]) => `${k} ${v}`)
            .join(", "),
          `${r.resolution.resolvedShare}%`,
        ])
      )
    );
    out.push(
      `Not measurable: ${Object.entries(exportsR.notMeasurable)
        .map(([n, why]) => `${n} (${why})`)
        .join("; ")}.`,
      ""
    );
  }

  // ── 8. duplication ──
  if (clones) {
    h(2, "8. Duplication (token-based clone detector)");
    out.push(
      `Thresholds: ${clones.method.minTokens} tokens and ${clones.method.minLines} lines (jscpd's defaults), and ${clones.method.sensitivityTokens} tokens (maven-pmd-plugin's CPD default). Duplicated lines are code lines (lines with a token) inside any clone fragment, both copies counted. Imports excluded.`,
      ""
    );
    const rows = [];
    const pool = {};
    for (const n of [...repos, "ultracite"]) {
      const r = clones.repos[n];
      if (!r) {
        continue;
      }
      const w = r.window;
      rows.push([
        n,
        fmt(r.totals.source.codeLines),
        `${w["type1@50"].duplicatedShare.source}%`,
        `${w["type2@50"].duplicatedShare.source}%`,
        `${w["type1@100"].duplicatedShare.source}%`,
        `${w["type2@100"].duplicatedShare.source}%`,
        fmt(r.totals.test.codeLines),
        r.totals.test.codeLines
          ? `${w["type2@50"].duplicatedShare.test}%`
          : "–",
        fmt(r.totals.vendored.codeLines),
        r.totals.vendored.codeLines
          ? `${w["type2@50"].duplicatedShare.vendored}%`
          : "–",
        r.skipped.length,
      ]);
      if (n !== "ultracite") {
        for (const [mode, ww] of Object.entries(w)) {
          for (const cat of ["source", "test", "vendored"]) {
            pool[mode] ??= {};
            pool[mode][cat] ??= [0, 0];
            pool[mode][cat][0] += ww.duplicatedCodeLines[cat];
            pool[mode][cat][1] += r.totals[cat].codeLines;
          }
        }
      }
    }
    const p = (mode, cat) =>
      `${Math.round((pool[mode][cat][0] / pool[mode][cat][1]) * 1000) / 10}%`;
    rows.push([
      "**pooled**",
      fmt(pool["type1@50"].source[1]),
      p("type1@50", "source"),
      p("type2@50", "source"),
      p("type1@100", "source"),
      p("type2@100", "source"),
      fmt(pool["type1@50"].test[1]),
      p("type2@50", "test"),
      fmt(pool["type1@50"].vendored[1]),
      p("type2@50", "vendored"),
      "",
    ]);
    out.push(
      ...table(
        [
          "Repo",
          "Source code lines",
          "T1 @50",
          "T2 @50",
          "T1 @100",
          "T2 @100",
          "Test code lines",
          "Test T2 @50",
          "Vendored code lines",
          "Vendored T2 @50",
          "Skipped (minified/huge)",
        ],
        rows
      )
    );
    h(3, "8.1 Clone classes in source (window detector, 50 tokens)");
    out.push(
      ...table(
        [
          "Repo",
          "T1 classes",
          "T1 cross-file",
          "T1 tokens median / p90 / max",
          "T2 classes",
          "T2 cross-file",
          "T2 class sizes (all file categories)",
        ],
        repos.map((n) => {
          const w = clones.repos[n].window;
          const t1 = w["type1@50"];
          const t2 = w["type2@50"];
          return [
            n,
            t1.sourceClasses,
            t1.sourceClassesCrossFile,
            `${t1.sourceClassTokens.median ?? "–"} / ${t1.sourceClassTokens.p90 ?? "–"} / ${t1.sourceClassTokens.max ?? "–"}`,
            t2.sourceClasses,
            t2.sourceClassesCrossFile,
            Object.entries(t2.classSize)
              .map(([k, v]) => `${k}: ${v}`)
              .join(", "),
          ];
        })
      )
    );
    h(
      3,
      "8.2 What sonarjs/no-identical-functions can see (source function clones)"
    );
    const sum = (key, mode) => {
      const acc = {};
      for (const n of repos) {
        for (const [k, v] of Object.entries(clones.repos[n][key][mode])) {
          acc[k] = (acc[k] ?? 0) + v;
        }
      }
      return acc;
    };
    const reasons = [
      ...new Set([
        ...Object.keys(sum("reachOfSourceFunctionClonesAtRuleThreshold", "t1")),
        ...Object.keys(sum("reachOfSourceFunctionClonesAtRuleThreshold", "t2")),
        ...Object.keys(sum("reachOfSourceFunctionClones", "t2")),
      ]),
    ];
    out.push(
      ...table(
        [
          "Where the clone class sits",
          "Type-1, body >= 3 lines",
          "Type-2, body >= 3 lines",
          "Type-1, >= 50 tokens",
          "Type-2, >= 50 tokens",
        ],
        reasons.map((r) => [
          r,
          fmt(sum("reachOfSourceFunctionClonesAtRuleThreshold", "t1")[r] ?? 0),
          fmt(sum("reachOfSourceFunctionClonesAtRuleThreshold", "t2")[r] ?? 0),
          fmt(sum("reachOfSourceFunctionClones", "t1")[r] ?? 0),
          fmt(sum("reachOfSourceFunctionClones", "t2")[r] ?? 0),
        ])
      )
    );
    out.push(
      ...table(
        [
          "Repo",
          "Rule hits",
          "Detector's prediction",
          "Matched",
          "Branch statements with an identical pair (source)",
          "Pairs multi-line / single-line",
          "no-duplicated-branches + no-all-duplicated-branches hits",
        ],
        repos.map((n) => {
          const r = clones.repos[n];
          const s = r.sonarIdenticalFunctions;
          const b = r.branches;
          return [
            n,
            s.actual,
            s.expectedByDetector,
            s.matched,
            b.statementsWithDuplicate,
            `${b.identicalPairsMultiLine} / ${b.identicalPairsSingleLine}`,
            Object.values(b.sonarHits).reduce((a, x) => a + x, 0),
          ];
        })
      )
    );
  }

  // ── 9. markers ──
  if (markers) {
    h(2, "9. Markers: suppressions, `_` names, silencing idioms, repo configs");
    out.push(
      ...table(
        [
          "Repo",
          "Suppressions naming these rules",
          "@ts-ignore/@ts-expect-error (any)",
          "`_` bindings",
          "of which ESLint reports unused",
          "`_` by kind",
          "`void x;`",
          "bare `x;`",
        ],
        Object.entries(markers.repos).map(([n, r]) => [
          n,
          `${r.suppressions.comments}${
            Object.keys(r.suppressions.byRule).length
              ? ` (${Object.entries(r.suppressions.byRule)
                  .map(([k, v]) => `${k} ${v}`)
                  .join(", ")})`
              : ""
          }`,
          r.suppressions.tsIgnore,
          r.underscore.total,
          r.underscore.unusedByEslint,
          Object.entries(r.underscore.byKind)
            .map(([k, v]) => `${k} ${v}`)
            .join(", "),
          r.voidIdentifier,
          r.bareIdentifierStatements,
        ])
      )
    );
  }

  // ── 10. classification ──
  if (classifications?.shares) {
    h(2, "10. Hand classification");
    for (const [kind, s] of Object.entries(classifications.shares)) {
      out.push(`**${kind}** (n = ${s.n})`, "");
      out.push(
        ...table(
          ["Category", "Sampled", "Unweighted", "Weighted by repo population"],
          Object.keys(s.unweighted)
            .filter((c) => s.unweighted[c] > 0)
            .map((c) => [
              c,
              s.unweighted[c],
              `${s.unweightedPct[c]}%`,
              `${s.weightedPct[c]}%`,
            ]),
          [null, "r", "r", "r"]
        )
      );
    }
    if (classifications.agreement) {
      out.push(
        ...table(
          ["Kind", "Pairs", "Same category", "Cohen's κ", "Disagreements"],
          Object.entries(classifications.agreement).map(([k, a]) => [
            k,
            a.n,
            a.same,
            a.kappa,
            a.disagreements
              .map((d) => `${d.id} ${d.first}→${d.second}`)
              .join("; ") || "–",
          ])
        )
      );
    }
    if (sample) {
      out.push(
        ...table(
          ["Repo", ...sample.kinds.map((k) => `${k} population`)],
          Object.entries(sample.populations).map(([n, p]) => [
            n,
            ...sample.kinds.map((k) => p[k]),
          ])
        )
      );
    }
  }

  // ── 11. history ──
  if (history?.confirmed) {
    h(2, "11. Fixed bugs in the repos' history");
    const lintBy = new Map((historyLint?.rows ?? []).map((r) => [r.id, r]));
    out.push(
      ...table(
        [
          "Bug",
          "Kind",
          "What broke",
          "Oxlint (core+react)",
          "+ js-plugins",
          "ESLint",
          "Biome",
          "tsc",
        ],
        history.confirmed.map((b) => {
          const l = lintBy.get(b.id);
          const f = (t) =>
            l ? (l.flaggedBy[t] ?? []).join(", ") || "–" : "not linted";
          return [
            `[${b.id}](${b.fixUrl})`,
            b.kind,
            b.description,
            f("oxlint"),
            f("oxlint +js-plugins"),
            f("eslint"),
            f("biome"),
            f("tsc"),
          ];
        })
      )
    );
  }

  writeFileSync(join(lib.RESULTS_DIR, "tables.md"), `${out.join("\n")}\n`);
  console.log(
    `wrote ${join(lib.RESULTS_DIR, "tables.md")} (${out.length} lines)`
  );
};

main();
