// Generates results/nested-ternaries/tables.md from the topic's JSON results.
//
// Usage: node research/corpus/scripts/nested-ternaries-tables.cjs
"use strict";

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const lib = require("./nested-ternaries-lib.cjs");

const R = lib.RESULTS_DIR;
const load = (f) =>
  existsSync(join(R, f)) ? JSON.parse(readFileSync(join(R, f), "utf8")) : null;
const fmt = (n) =>
  typeof n === "number" ? n.toLocaleString("en-US") : (n ?? "–");
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map((h, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(fmt).join(" | ")} |`),
    "",
  ].join("\n");
const kv = (o) =>
  Object.entries(o ?? {})
    .map(([k, v]) => `${k} ${fmt(v)}`)
    .join(", ");

const out = [
  "# Nested ternaries: generated tables",
  "",
  "Generated by `nested-ternaries-tables.cjs` from the JSON files in this folder. External source unless a table says otherwise.",
  "",
];

// ── corpus and inventory ───────────────────────────────────────────────
const census = load("census.json");
if (census) {
  out.push("## Corpus and inventory (`census.json`)", "");
  out.push(
    table(
      [
        "Repo",
        "SHA",
        "Files",
        "Lines",
        "Conditionals",
        "per 10k",
        "Nested",
        "per 10k",
        "Early-return",
        "Statement",
        "Extraction",
        "Test files",
        "Nested in tests",
      ],
      lib.ALL.filter((n) => census.repos[n]).map((n) => {
        const r = census.repos[n];
        const s = r.source;
        return [
          n,
          `\`${String(r.sha).slice(0, 10)}\``,
          s.files,
          s.lines,
          s.conditionals,
          s.conditionalsPer10k,
          s.nested.total,
          s.nestedPer10k,
          s.nested.earlyReturnPossible,
          s.nested.statementInPlace,
          s.nested.extractionOnly,
          r.tests.files,
          r.tests.nested.total,
        ];
      })
    )
  );
  for (const set of ["corpus", "react", "external"]) {
    const s = census.pooled[set].source;
    out.push(`### ${set} (pooled)`, "");
    out.push(
      `- Lines ${fmt(s.lines)}, conditionals ${fmt(s.conditionals)} (${s.conditionalsPer10k} per 10k), nested ternaries ${fmt(s.nested.total)} (${s.nestedPer10k} per 10k; ${s.nestedPer10kJsx} per 10k JSX lines), ${s.nested.conditionalsInNestedShare}% of conditionals sit in one.`,
      `- Depth: ${kv(s.nested.byDepth)}. Shape: ${kv(s.nested.byShape)}.`,
      `- Position: ${kv(s.nested.byPosition)}.`,
      `- Rewrite class: ${kv(s.nested.byRewrite)}. In JSX: ${fmt(s.nested.inJsx)}; with a JSX branch: ${fmt(s.nested.jsxLeaves)}.`,
      `- Tests: ${kv(s.nested.testShapes)}. Dispatch shapes: lookup ${s.nested.dispatch.lookup}, switch ${s.nested.dispatch.switch}; discriminants ${kv(s.nested.dispatch.discriminantKinds)}; all branches pure ${s.nested.dispatch.allPure}, member reads only ${s.nested.dispatch.readsOnly}, effects ${s.nested.dispatch.withEffects}; loose equality ${s.nested.dispatch.looseEquality}.`,
      `- Branches: ${kv(s.nested.leafKinds)}. Risk if evaluated eagerly: ${kv(s.nested.leafRisks)}. Trees with a call, await or throw in a branch: ${fmt(s.nested.treesWithEffects)}.`,
      `- Parenthesised nested conditionals: all ${s.nested.parenthesized.all}, some ${s.nested.parenthesized.some}, none ${s.nested.parenthesized.none}. Multi-line: ${fmt(s.nested.multiline)}; lines ${kv(s.nested.lines)}.`,
      `- Conditionals nested through other expressions (not trees): ${fmt(s.indirect.total)}, ${fmt(s.indirect.sonarNested)} of them reported by sonarjs.`,
      `- TypeScript conditional types: ${fmt(s.conditionalTypes)}, ${fmt(s.conditionalTypesNested)} nested (${kv(s.conditionalTypesNestedIn)}).`,
      `- If statements: ${fmt(s.ifChains.total)} heads; else-if chains ${fmt(s.ifChains.elseIf)} (lengths ${kv(s.ifChains.lengths)}), ${fmt(s.ifChains.elseIfTernaryShaped)} ternary-shaped (${kv(s.ifChains.elseIfTernaryShapedByKind)}). Guard chains (if-return runs ending in a return): ${fmt(s.guardChains)}, ${fmt(s.guardChainsTwoPlus)} with two or more guards.`,
      `- Functions with a nested ternary: ${fmt(s.functions.withNested)}; cognitive ${kv(s.functions.withNestedCognitive)}; ${fmt(s.functions.withNestedOver20)} over 20. Other functions with a conditional: ${kv(s.functions.withoutNestedCognitive)}.`,
      ""
    );
  }
  const t = census.pooled.external.tests;
  out.push(
    `Tests (external): ${fmt(t.lines)} lines, ${fmt(t.conditionals)} conditionals, ${fmt(t.nested.total)} nested ternaries.`,
    ""
  );
  out.push(
    "Prediction checks (raw): " +
      lib.ALL.filter((n) => census.repos[n])
        .map(
          (n) =>
            `${n} ${Object.entries(census.repos[n].check)
              .map(([k, [a, p]]) => `${k} ${a}/${p}`)
              .join(" ")} (mismatches ${census.repos[n].mismatchCount})`
        )
        .join("; "),
    ""
  );
}

// ── the rules ──────────────────────────────────────────────────────────
const linters = load("linters.json");
if (linters) {
  const p = linters.pooled.external.source;
  out.push("## What the rules report (`linters.json`)", "");
  const rules = Object.keys(p.byLinterRule.raw).filter(
    (k) => !/parse|syntax/.test(k)
  );
  out.push(
    table(
      ["Linter/rule", "Raw", "Reported"],
      rules.map((k) => [
        k,
        p.byLinterRule.raw[k],
        p.byLinterRule.reported[k] ?? 0,
      ])
    )
  );
  out.push(
    `Units flagged (outermost conditional groups): ${kv(p.unitCounts)}.`,
    ""
  );
  out.push(
    `Reports per flagged unit: ${Object.entries(p.perTree)
      .map(([k, v]) => `${k} {${kv(v)}}`)
      .join("; ")}.`,
    ""
  );
  out.push(`Conditional level: ${kv(p.conditionalLevel)}.`, "");
  out.push(
    table(
      [
        "Pair",
        "Both",
        "Only first",
        "Only second",
        "Only-first signatures",
        "Only-second signatures",
      ],
      Object.entries(p.disagreements).map(([k, d]) => [
        k,
        d.both,
        d.onlyA,
        d.onlyB,
        kv(d.onlyASignatures),
        kv(d.onlyBSignatures),
      ])
    )
  );
  out.push("Messages and help (raw):", "");
  for (const [k, v] of Object.entries(linters.messages)) {
    if (
      /ternar|Ternary|nested-conditional|else-return|UselessElse|negated|NegationElse|logical-operator/.test(
        k
      )
    ) {
      out.push(
        `- \`${k}\`: ${Object.entries(v)
          .map(([m, n]) => `"${m}" (${fmt(n)})`)
          .join("; ")}`
      );
    }
  }
  out.push("");
  if (linters.preferTernary) {
    const pt = linters.preferTernary;
    out.push(
      "### unicorn/prefer-ternary, ESLint (unicorn 79, Ultracite's options) against Oxlint",
      ""
    );
    out.push(
      `Total: ${kv(pt.total)}. Branch already holds a ternary: ${kv(pt.branchHasTernary)}. Multi-line: ${kv(pt.multiline)}.`,
      ""
    );
    out.push(
      `- Both: ${kv(pt.both)}`,
      `- ESLint only: ${kv(pt.eslintOnly)}`,
      `- Oxlint only: ${kv(pt.oxlintOnly)}`,
      ""
    );
  }
}

// ── formatters ─────────────────────────────────────────────────────────
const format = load("format.json");
if (format) {
  out.push("## Formatters (`format.json`)", "");
  out.push(
    table(
      [
        "Version",
        "Lines (sum)",
        "Median",
        "p90",
        "Max",
        "Multi-line",
        "Nested test on its own line (all)",
        "3+ chains stepped",
        "3+ chains flat",
        "3+ chains on one line",
        "Parenthesised",
      ],
      Object.entries(format.versions).map(([k, v]) => {
        const s = v.source;
        return [
          k,
          s.lines.sum,
          s.lines.median,
          s.lines.p90,
          s.lines.max,
          s.multiline,
          s.nestedOnOwnLine.all,
          s.chains.steppedIndent,
          s.chains.flatIndent,
          s.chains.singleLine,
          s.parenthesizedTrees,
        ];
      })
    )
  );
  out.push(
    `Change against the files as written: ${Object.entries(format.change)
      .map(
        ([k, v]) =>
          `${k}: grew ${v.grew}, same ${v.same}, shrank ${v.shrank}, sum ${v.lineChange.sum}`
      )
      .join("; ")}.`,
    ""
  );
  out.push(
    `Ping-pong (${format.pingPongFiles} files where unicorn/no-nested-ternary's fix adds parentheses): ${Object.entries(
      format.pingPong
    )
      .map(
        ([k, v]) => `${k}: ${v.cycles} of ${v.changedByFix} changed files cycle`
      )
      .join("; ")}.`,
    ""
  );
}

// ── rewrites ───────────────────────────────────────────────────────────
const rewrite = load("rewrite.json");
if (rewrite) {
  out.push("## Rewrites (`rewrite.json`)", "");
  const s = rewrite.summary.source;
  const kinds = Object.keys(s).filter((k) => k !== "trees");
  out.push(
    table(
      [
        "Rewrite",
        "Built",
        "Lines added (median, sum)",
        "Enclosing fn cognitive (median before → after)",
        "Change (median, sum)",
        "Change with helper (sum)",
        "Helper (median)",
        "ESLint fix gives a ternary back",
        "… a nested one",
        "Oxlint fix",
        "Biome fix",
      ],
      kinds.map((k) => {
        const x = s[k];
        return [
          k,
          `${x.built}/${x.attempted}`,
          `${x.linesAdded?.median}, ${x.linesAdded?.sum}`,
          `${x.cognitiveBefore?.median} → ${x.cognitiveAfter?.median}`,
          `${x.cognitiveChange?.median}, ${x.cognitiveChange?.sum}`,
          x.cognitiveChangeWithHelper?.sum,
          x.cognitiveHelper?.median ?? "–",
          x.fix.eslint.conditionalsBack,
          x.fix.eslint.nestedBack,
          `${x.fix.oxlint.conditionalsBack}/${x.fix.oxlint.nestedBack}`,
          `${x.fix.biome.conditionalsBack}/${x.fix.biome.nestedBack}`,
        ];
      })
    )
  );
  for (const k of kinds) {
    const x = s[k];
    out.push(
      `- **${k}**: Oxlint adds ${kv(x.presets.oxlint.itemsWithMore)}; ESLint adds ${kv(x.presets.eslint.itemsWithMore)}; Biome adds ${kv(x.presets.biome.itemsWithMore)}. Behaviour signs: ${kv(x.signs) || "none"} (${x.signsAny} rewrites). Skipped: ${kv(x.skipped) || "none"}.`
    );
  }
  out.push(
    "",
    `Trees by the rewrites that apply: ${kv(s.trees.withKinds)}. No statement rewrite without an extraction: ${s.trees.noStatementRewrite} of ${s.trees.total}.`,
    ""
  );
}

const fixes = load("fixes.json");
if (fixes) {
  out.push("## Two fixes that write conditionals (`fixes.json`)", "");
  out.push(
    `- react/jsx-no-leaked-render's fix (ESLint react preset), on every .tsx/.jsx source file: ${kv(fixes.leakedRender.total)}.`
  );
  out.push(
    `- unicorn/prefer-logical-operator-over-ternary with Oxlint's --fix-dangerously, on every \`x ? x : …\` conditional (${fixes.logical.sites}): by alternate ${kv(fixes.logical.byAlternate)}; precedence changed ${fixes.logical.precedenceChanged.length}; fixed files that don't parse ${fixes.logical.unparsable}.`
  );
  for (const r of fixes.logical.precedenceChanged) {
    out.push(
      `  - ${r.repo} [\`${r.file}\` L${r.line}](${r.permalink}): \`${r.text.replace(/`/g, "'")}\``
    );
  }
  out.push("");
}

// ── calibration ────────────────────────────────────────────────────────
const cal = load("calibration.json");
if (cal) {
  out.push("## Calibration (`calibration.json`)", "");
  const views = [
    "oxlint/presets",
    "oxlint/presets+js-plugins",
    "eslint/presets",
    "biome/presets",
  ];
  out.push(
    table(
      ["Case", ...views, "sonarjs cognitive"],
      Object.entries(cal.cases).map(([f, c]) => [
        f.replace(/\.tsx?$/, ""),
        ...views.map(
          (v) => [...new Set(c.views[v].map((d) => d.rule))].join(", ") || "–"
        ),
        c.cognitive.map((x) => `${x.name} ${x.score}`).join(", "),
      ])
    )
  );
  out.push("Behaviour cases:", "");
  for (const [f, b] of Object.entries(cal.behaviour)) {
    out.push(
      `- \`${f}\` (${b.header}): ${Object.entries(b.verdicts ?? {})
        .map(
          ([k, v]) =>
            `${k} ${v.verdict}${v.resultsDiffer ? ` (${v.resultsDiffer} of ${b.inputs} inputs)` : ""}`
        )
        .join("; ")}`
    );
  }
  out.push(
    "",
    `Ping-pong: ${Object.entries(cal.pingPong)
      .map(
        ([f, p]) =>
          `${f}: ${Object.entries(p)
            .map(([k, v]) => `${k} ${v.cycles ? "cycles" : "converges"}`)
            .join(", ")}`
      )
      .join("; ")}.`,
    ""
  );
}

// ── history, policy, agents, classification, subjects ─────────────────
const history = load("history.json");
if (history) {
  out.push("## History (`history.json`)", "");
  out.push(
    `Window: ${history.window.days} days before each pinned commit. Bug-fix heuristic: precision ${history.heuristic.precision}%, misses ${history.heuristic.missRate}%.`,
    ""
  );
  out.push(`- Nested-ternary events: ${kv(history.events.pooled.ternary.all)}`);
  if (history.events.pooled.elseIf) {
    out.push(`- Else-if events: ${kv(history.events.pooled.elseIf.all)}`);
  }
  out.push("");
  const models = history.analysis.models ?? {};
  out.push(
    table(
      ["Model", "n", "Odds ratio [95% CI]"],
      Object.entries(models).map(([k, m]) => {
        const key = Object.keys(m.coef).find(
          (c) => !/ownLines|exposure|changes/.test(c)
        );
        const c = m.coef[key];
        return [
          `${k} (${key})`,
          m.n,
          c ? `${c.oddsRatio} [${c.ci95[0]}, ${c.ci95[1]}]` : "–",
        ];
      })
    )
  );
  out.push(
    `Groups: ${Object.entries(history.analysis.byGroup)
      .map(
        ([k, g]) =>
          `${k} n ${g.n}, fixed ${g.fixedShare}%, median own lines ${g.medianOwnLines}`
      )
      .join("; ")}.`,
    ""
  );
  out.push(
    `Keyword commits: ${history.keywords.commits}; labels ${kv(history.keywords.labels.byCategory)}.`,
    ""
  );
}
const markers = load("markers.json");
if (markers) {
  out.push("## Policy (`markers.json`)", "");
  for (const [n, r] of Object.entries(markers.repos)) {
    const lines = (r.configs ?? []).flatMap((c) =>
      c.lines
        .filter((l) => l.kind === "rule")
        .map((l) => `\`${c.file}\` L${l.line} \`${l.text}\``)
    );
    const shared = (r.configs ?? []).flatMap((c) =>
      c.lines.filter((l) => l.kind === "shared").map((l) => `\`${l.text}\``)
    );
    out.push(
      `- ${n}: ${lines.length ? lines.join("; ") : "no line naming these rules"}${shared.length ? `; shared: ${shared.slice(0, 4).join(", ")}` : ""}; ${(r.directives ?? []).length} disable comments.`
    );
  }
  out.push("");
}
const agents = load("agent-runs.json");
if (agents) {
  out.push("## Agents in our own data (`agent-runs.json`)", "");
  const c = agents.committed.all ?? agents.committed;
  out.push("```json", JSON.stringify(c, null, 1).slice(0, 2500), "```", "");
  out.push(
    `Nested ternaries introduced anywhere: ${agents.nestedIntroduced.length}.`,
    ""
  );
}
const cls = load("classifications.json");
if (cls) {
  out.push("## Hand classification (`classifications.json`)", "");
  out.push(
    table(
      ["Field", "Weighted shares (rater 1)", "Agreement", "κ"],
      Object.keys(cls.shares).map((f) => [
        f,
        kv(cls.shares[f]),
        cls.agreement[f]
          ? `${cls.agreement[f].agree}/${cls.agreement[f].n}`
          : "–",
        cls.agreement[f]?.kappa ?? "–",
      ])
    )
  );
  out.push(
    `By stratum (rater 1): ${Object.entries(cls.byStratum)
      .map(
        ([s, v]) => `${s}: rewrite {${kv(v.rewrite)}}, reads {${kv(v.reads)}}`
      )
      .join("; ")}.`,
    ""
  );
}
const ex = existsSync(join(lib.EXAMPLES_DIR, "examples.json"))
  ? JSON.parse(readFileSync(join(lib.EXAMPLES_DIR, "examples.json"), "utf8"))
  : null;
if (ex) {
  out.push(
    "## Agent-experiment subjects (`examples/nested-ternaries/examples.json`)",
    ""
  );
  for (const [id, s] of Object.entries(ex.subjects)) {
    out.push(
      `### ${id.toUpperCase()} \`${s.file}\``,
      "",
      `${s.origin.permalink}. Verbatim: ${s.verbatim.ok} (${s.verbatim.lines} lines). tsc: ${s.tsc.length}. Oracle: ${s.oracle.calls} scenarios.`,
      "",
      `Oxlint: ${kv(s.lint.oxlint.byRule)}. ESLint: ${kv(s.lint.eslint.byRule)}. Biome: ${kv(s.lint.biome.byRule)}.`,
      ""
    );
    out.push(
      table(
        [
          "Variant",
          "Kind",
          "Oxlint / ESLint / sonarjs / Biome nested reports",
          "Rules added (Oxlint)",
          "Rules added (ESLint)",
          "Rules added (Biome)",
          "tsc",
          "Cognitive",
          "Oracle",
        ],
        Object.entries(s.variants).map(([k, v]) => [
          k,
          v.kind,
          `${v.nestedRules.oxlint} / ${v.nestedRules.eslint} / ${v.nestedRules["eslint-sonarjs"]} / ${v.nestedRules.biome}`,
          kv(
            Object.fromEntries(
              Object.entries(v.changed.oxlint).filter(([, d]) => d > 0)
            )
          ) || "–",
          kv(
            Object.fromEntries(
              Object.entries(v.changed.eslint).filter(([, d]) => d > 0)
            )
          ) || "–",
          kv(
            Object.fromEntries(
              Object.entries(v.changed.biome).filter(([, d]) => d > 0)
            )
          ) || "–",
          v.tsc,
          `${s.cognitive} → ${v.cognitive}`,
          `${v.oracle.verdict}${v.oracle.differing ? ` (${v.oracle.differing}/${v.oracle.of})` : ""}`,
        ])
      )
    );
  }
}
const census2 = load("rule-census.json");
if (census2) {
  out.push(
    "## Ultracite's Oxlint presets on the corpus (`rule-census.json`, core + react + js-plugins)",
    ""
  );
  const ranked = Object.entries(census2.rules)
    .map(([r, v]) => [r, v.reported?.pooled ?? 0])
    .sort((a, b) => b[1] - a[1]);
  const rank = (r) => ranked.findIndex(([x]) => x === r) + 1;
  const rows = census2.focus.map((r) => {
    const v = census2.rules[r];
    return [
      r,
      v?.reported?.pooled ?? 0,
      v?.raw?.pooled ?? 0,
      v?.reported?.per10k ?? 0,
      rank(r),
    ];
  });
  out.push(
    `${ranked.length} rules enabled; rank by pooled reported count.`,
    ""
  );
  out.push(table(["Rule", "Reported", "Raw", "Per 10k", "Rank"], rows));
}
writeFileSync(join(R, "tables.md"), `${out.join("\n").trim()}\n`);
console.log(`tables.md: ${out.length} lines`);
