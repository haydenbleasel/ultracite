const calRows = Object.entries(calibration.cases).map(([id, desc]) => {
  const l = calibration.lint[id] ?? {};
  const cell = (c) => {
    const ds = l[c] ?? [];
    if (!ds.length) {
      return "–";
    }
    const rules = [
      ...new Set(ds.map((d) => d.rule.replace("assist/source/", ""))),
    ];
    return `${rules.join(", ")}${c.startsWith("oxlint") ? (ds.every((d) => d.fix) ? " (fix)" : " (no fix)") : ""}${c.startsWith("eslint") && ds.length > 1 ? ` ×${ds.length}` : ""}`;
  };
  const fixCell = (f) => {
    const c = calibration.fixes[f][id];
    if (!c || !c.changedText) {
      return "–";
    }
    if (c.parseError) {
      return `**file no longer parses**`;
    }
    return (
      c.objects.map((o) => (o.after ? o.after.join(", ") : "?")).join(" / ") ||
      "(text only)"
    );
  };
  const beh = calibration.behaviourChanges[id];
  const types = calibration.typeChanges[id];
  const verdict = beh
    ? fixNames
        .map((f) => (beh[f] === "changed" ? "changed" : "same"))
        .join(" / ")
    : types
      ? fixNames
          .map((f) =>
            types[f].length > types.original.length
              ? `${types[f].length} TS errors`
              : "ok"
          )
          .join(" / ")
      : "";
  return [id, desc, ...cfgs.map(cell), ...fixNames.map(fixCell), verdict];
});
