const fmt = (n) =>
  n === null || n === undefined
    ? "–"
    : typeof n === "number"
      ? n.toLocaleString("en-US")
      : String(n);
const pct = (a, b) =>
  b ? `${(Math.round((a / b) * 1000) / 10).toFixed(1)}%` : "–";
const table = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map((h, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
const ltable = (head, rows) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
const code = (s) =>
  `\`${String(s).replace(/`/g, "'").replace(/\|/g, "\\|").replace(/\n/g, "⏎")}\``;
const out = [];
const h = (level, text) => out.push("", `${"#".repeat(level)} ${text}`, "");
const p = (text) => out.push(text);

out.push(
  "# Sort-keys: generated tables",
  "",
  `Generated by \`scripts/sort-keys-tables.cjs\` on ${new Date().toISOString().slice(0, 10)} from the JSON files in this directory. The method and caveats are in REPORT.md.`
);

