// Rule census: runs Ultracite's own Oxlint presets over the corpus and counts diagnostics per
// rule and per repo, with hits per 10,000 lines. Every post can reuse it: the presets, the
// focus rules and the topic are parameters.
//
// It runs twice per repo:
//   reported  the files as they are, so in-file `eslint-disable` / `oxlint-disable` comments
//             are honoured. This is what `ultracite check` would report.
//   raw       a mirror of the same files with every disable directive neutralised (same-length
//             rewrite, so lines and columns don't move). This counts every occurrence, including
//             the ones a maintainer already suppressed.
//
// Read-only with respect to the clones: files are passed to Oxlint as an explicit list (from
// collect-files.cjs), nested configs are disabled, and nothing is installed or executed.
//
// Usage (from the repo root):
//   node research/corpus/scripts/rule-census.cjs --topic <slug>
//     [--presets core,react]        Oxlint presets under packages/cli/config/oxlint (default core,react)
//     [--focus rule,rule]           rules to tabulate in the Markdown summary and keep per-hit rows for
//     [--repos name,name]           subset of repos.json (default: all)
//     [--modes reported,raw]        which runs to do (default: both)
//
// Writes:
//   results/<topic>/rule-census.json   per-rule and per-repo counts for every enabled rule
//   results/<topic>/rule-census.md     generated tables (top rules and the focus rules)
//   out/rule-census/<topic>/<repo>.<mode>.json   every hit of the focus rules (gitignored),
//                                                 for downstream sampling scripts
"use strict";

const { execFileSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { mkdirSync, readFileSync, rmSync, writeFileSync } = require("node:fs");
const { dirname, join, resolve } = require("node:path");
const { pathToFileURL } = require("node:url");

const { collect } = require("./collect-files.cjs");
const config = require("./repos.json");
const { ULTRACITE } = require("./tools.cjs");

const HERE = resolve(__dirname, "..");
const CHUNK = 400;
// Repos measured as a reference, not part of the pooled corpus numbers.
const DOGFOOD = new Set(["ultracite"]);

// ── arguments ──────────────────────────────────────────────────────────
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? fallback : args[i + 1];
};
const list = (value) => (value ? value.split(",").filter(Boolean) : []);

const TOPIC = arg("topic", process.env.RESEARCH_TOPIC);
if (!TOPIC) {
  throw new Error("Pass --topic <slug> (or set RESEARCH_TOPIC).");
}
const PRESETS = list(arg("presets", "core,react"));
const FOCUS = list(arg("focus", ""));
const ONLY = list(arg("repos", ""));
const MODES = list(arg("modes", "reported,raw"));

const RESULTS_DIR = join(HERE, "results", TOPIC);
const OUT_DIR = join(HERE, "out", "rule-census", TOPIC);

// ── tools ──────────────────────────────────────────────────────────────
const oxlintPkgPath = require.resolve("oxlint/package.json", {
  paths: [ULTRACITE],
});
const oxlintBin = join(dirname(oxlintPkgPath), "bin", "oxlint");
const oxlintVersion = require(oxlintPkgPath).version;

// Oxlint diagnostic codes are "<scope>(<rule>)" and `--rules` lists scopes such as "jsx_a11y";
// config names are "<scope>/<rule>" with dashes, and core ESLint rules have no prefix.
// Some rules report under a different scope than the one they're configured under.
const SCOPE_ALIASES = { "react-hooks": "react" };
const configName = (scope, rule) => {
  if (scope === "eslint") {
    return rule;
  }
  const name = scope.replaceAll("_", "-");
  return `${SCOPE_ALIASES[name] ?? name}/${rule}`;
};

// The catalogue of rules this Oxlint knows, with whether each needs type information.
const catalogue = new Map(
  JSON.parse(
    execFileSync(process.execPath, [oxlintBin, "--rules", "--format", "json"], {
      encoding: "utf8",
      maxBuffer: 1 << 26,
    })
  ).map((r) => [configName(r.scope, r.value), r])
);

// ── the config under test ──────────────────────────────────────────────
const presetPath = (name) =>
  join(ULTRACITE, "packages/cli/config/oxlint", name, "index.mjs");

const writeCensusConfig = () => {
  mkdirSync(OUT_DIR, { recursive: true });
  const file = join(OUT_DIR, "oxlint.config.mjs");
  const imports = PRESETS.map(
    (name, i) =>
      `import preset${i} from ${JSON.stringify(pathToFileURL(presetPath(name)).href)};`
  ).join("\n");
  const extendsList = PRESETS.map((_, i) => `preset${i}`).join(", ");
  writeFileSync(
    file,
    `// Generated by rule-census.cjs. Ultracite's presets, unchanged.\n${imports}\n\nexport default { extends: [${extendsList}] };\n`
  );
  return file;
};

// Every rule the presets turn on (top level; overrides only apply to test/Astro files, which the
// corpus excludes or doesn't contain).
const enabledRules = async () => {
  const rules = {};
  for (const name of PRESETS) {
    const mod = await import(pathToFileURL(presetPath(name)).href);
    Object.assign(rules, mod.default.rules ?? {});
  }
  const severity = (value) => (Array.isArray(value) ? value[0] : value);
  return Object.keys(rules)
    .filter((rule) => !["off", 0].includes(severity(rules[rule])))
    .sort();
};

// ── running oxlint ─────────────────────────────────────────────────────
const runOxlint = (cwd, configFile, files) => {
  let stdout;
  try {
    stdout = execFileSync(
      process.execPath,
      [
        oxlintBin,
        "-c",
        configFile,
        "--disable-nested-config",
        "--format",
        "json",
        ...files,
      ],
      {
        cwd,
        encoding: "utf8",
        maxBuffer: 1024 * 1024 * 1024,
        stdio: ["ignore", "pipe", "pipe"],
      }
    );
  } catch (error) {
    stdout = error.stdout;
    if (!stdout) {
      throw error;
    }
  }
  return JSON.parse(stdout);
};

const lintAll = (cwd, configFile, files) => {
  const diagnostics = [];
  let linted = 0;
  for (let i = 0; i < files.length; i += CHUNK) {
    const report = runOxlint(cwd, configFile, files.slice(i, i + CHUNK));
    diagnostics.push(...report.diagnostics);
    linted += report.number_of_files;
  }
  return { diagnostics, linted };
};

// Same-length neutralisation of inline disable directives, so positions don't move.
const DIRECTIVE = /\b(eslint|oxlint)-(disable|enable)/g;
const neutralise = (text) =>
  text.replace(
    DIRECTIVE,
    (_, tool, verb) => `${"x".repeat(tool.length)}-${verb}`
  );

const writeMirror = (repo, files) => {
  const root = join(OUT_DIR, "mirror", repo.name);
  rmSync(root, { force: true, recursive: true });
  let directives = 0;
  for (const rel of files) {
    const text = readFileSync(join(repo.root, rel), "utf8");
    directives += text.match(DIRECTIVE)?.length ?? 0;
    const dest = join(root, rel);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, neutralise(text));
  }
  return { directives, root };
};

// ── tallying ───────────────────────────────────────────────────────────
const CODE = /^([a-z0-9_-]+)\((.+)\)$/;
const ruleOf = (diagnostic) => {
  const match = CODE.exec(diagnostic.code ?? "");
  if (!match) {
    return null;
  }
  const [, scope, rule] = match;
  return configName(scope.replace(/^eslint-plugin-/, ""), rule);
};

// Diagnostics without a rule code are parse errors (or other tool errors); keep their messages.
const tally = (diagnostics, focus) => {
  const counts = {};
  const hits = [];
  const parseErrors = new Map();
  for (const d of diagnostics) {
    const rule = ruleOf(d);
    if (!rule) {
      parseErrors.set(d.filename, d.message);
      continue;
    }
    counts[rule] = (counts[rule] ?? 0) + 1;
    if (focus.has(rule)) {
      const span = d.labels?.[0]?.span ?? {};
      hits.push({
        column: span.column,
        file: d.filename,
        length: span.length,
        line: span.line,
        message: d.message,
        offset: span.offset,
        rule,
      });
    }
  }
  return {
    counts,
    hits,
    parseErrors: [...parseErrors]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([file, message]) => ({ file, message })),
  };
};

const per10k = (n, lines) => Math.round((n / lines) * 1e5) / 10;

const gitHead = (dir) => {
  try {
    return execFileSync("git", ["-C", dir, "rev-parse", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    return null;
  }
};

// ── main ───────────────────────────────────────────────────────────────
const main = async () => {
  const configFile = writeCensusConfig();
  const enabled = await enabledRules();
  const focus = new Set(FOCUS);
  for (const rule of focus) {
    if (!enabled.includes(rule)) {
      throw new Error(`Focus rule ${rule} is not enabled by ${PRESETS}.`);
    }
  }
  mkdirSync(RESULTS_DIR, { recursive: true });

  const repos = {};
  const byRule = {};
  const names = config.repos
    .map((r) => r.name)
    .filter((n) => ONLY.length === 0 || ONLY.includes(n));

  for (const name of names) {
    const { repo, files } = collect(name);
    const lines = files.reduce(
      (sum, rel) =>
        sum + readFileSync(join(repo.root, rel), "utf8").split("\n").length,
      0
    );
    const entry = {
      dogfood: DOGFOOD.has(name),
      files: files.length,
      lines,
      sha: gitHead(repo.root),
    };
    for (const mode of MODES) {
      const started = Date.now();
      let cwd = repo.root;
      if (mode === "raw") {
        const mirror = writeMirror(repo, files);
        cwd = mirror.root;
        entry.neutralisedDirectives = mirror.directives;
      }
      const { diagnostics, linted } = lintAll(cwd, configFile, files);
      if (linted !== files.length) {
        throw new Error(
          `${name} ${mode}: oxlint linted ${linted} of ${files.length} files`
        );
      }
      const { counts, hits, parseErrors } = tally(diagnostics, focus);
      entry[mode] = {
        diagnostics: diagnostics.length,
        parseErrorFiles: parseErrors,
        seconds: Math.round((Date.now() - started) / 100) / 10,
      };
      for (const [rule, n] of Object.entries(counts)) {
        byRule[rule] ??= {};
        byRule[rule][mode] ??= {};
        byRule[rule][mode][name] = n;
      }
      mkdirSync(OUT_DIR, { recursive: true });
      writeFileSync(
        join(OUT_DIR, `${name}.${mode}.json`),
        JSON.stringify({ hits, mode, repo: name, sha: entry.sha }, null, 1)
      );
      console.log(
        `${name} ${mode}: ${linted} files, ${lines} lines, ${diagnostics.length} diagnostics, ${parseErrors.length} parse errors (${entry[mode].seconds}s)`
      );
    }
    repos[name] = entry;
  }

  const pooledNames = names.filter((n) => !DOGFOOD.has(n));
  const pooledLines = pooledNames.reduce((s, n) => s + repos[n].lines, 0);

  const summarise = (perRepo = {}) => {
    const pooled = pooledNames.reduce((s, n) => s + (perRepo[n] ?? 0), 0);
    return {
      byRepo: Object.fromEntries(names.map((n) => [n, perRepo[n] ?? 0])),
      per10k: per10k(pooled, pooledLines),
      per10kByRepo: Object.fromEntries(
        names.map((n) => [n, per10k(perRepo[n] ?? 0, repos[n].lines)])
      ),
      pooled,
      reposWithHits: pooledNames.filter((n) => (perRepo[n] ?? 0) > 0).length,
    };
  };

  const rules = {};
  for (const rule of [
    ...new Set([...enabled, ...Object.keys(byRule)]),
  ].sort()) {
    rules[rule] = {
      enabled: enabled.includes(rule),
      typeAware: catalogue.get(rule)?.type_aware ?? null,
      ...Object.fromEntries(
        MODES.map((mode) => [mode, summarise(byRule[rule]?.[mode])])
      ),
    };
  }

  // A hit on a rule the presets don't enable means a code was mapped to the wrong name.
  const unmapped = Object.keys(byRule).filter(
    (rule) => !enabled.includes(rule)
  );
  if (unmapped.length > 0) {
    throw new Error(`Hits on rules the presets don't enable: ${unmapped}`);
  }

  const configText = readFileSync(configFile, "utf8");
  const presetHashes = Object.fromEntries(
    PRESETS.map((name) => [
      name,
      createHash("sha256")
        .update(readFileSync(presetPath(name)))
        .digest("hex")
        .slice(0, 16),
    ])
  );
  const result = {
    focus: FOCUS,
    generated: new Date().toISOString().slice(0, 10),
    modes: MODES,
    note: "Pooled numbers cover the external repos only; dogfood repos are listed but not pooled. Type-aware rules never run here (no --type-aware), so they always count 0.",
    pooled: { lines: pooledLines, repos: pooledNames },
    presetHashes,
    presets: PRESETS,
    repos,
    rules,
    tools: {
      node: process.version,
      oxlint: oxlintVersion,
      ultraciteSha: gitHead(ULTRACITE),
    },
    censusConfig: configText.replaceAll(ULTRACITE, "<ultracite>"),
  };
  writeFileSync(
    join(RESULTS_DIR, "rule-census.json"),
    `${JSON.stringify(result, null, 2)}\n`
  );
  writeFileSync(join(RESULTS_DIR, "rule-census.md"), renderTables(result));
  console.log(`wrote ${join(RESULTS_DIR, "rule-census.json")}`);
};

// ── tables ─────────────────────────────────────────────────────────────
const fmt = (n) => n.toLocaleString("en-US");

const renderTables = (result) => {
  const names = Object.keys(result.repos);
  const mode = result.modes.includes("reported") ? "reported" : result.modes[0];
  const out = [
    `# Rule census: ${result.presets.join(" + ")} (Oxlint ${result.tools.oxlint})`,
    "",
    `Generated by \`scripts/rule-census.cjs\` on ${result.generated}. Pooled over ${result.pooled.repos.length} repos (${fmt(result.pooled.lines)} lines); ${names.filter((n) => result.repos[n].dogfood).join(", ") || "no repo"} listed separately.`,
    "",
    "## Repos",
    "",
    "| Repo | SHA | Files | Lines | Diagnostics (reported) | Diagnostics (raw) | Directives neutralised |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ...names.map((n) => {
      const r = result.repos[n];
      return `| ${n} | \`${(r.sha ?? "").slice(0, 10)}\` | ${fmt(r.files)} | ${fmt(r.lines)} | ${r.reported ? fmt(r.reported.diagnostics) : "–"} | ${r.raw ? fmt(r.raw.diagnostics) : "–"} | ${r.neutralisedDirectives ?? "–"} |`;
    }),
    "",
  ];

  const ruleTable = (title, ruleNames) => {
    out.push(
      `## ${title}`,
      "",
      `| Rule | Pooled (${mode}) | Per 10k lines | Repos with hits | ${result.modes.includes("raw") && mode !== "raw" ? "Pooled (raw) | " : ""}${names.join(" | ")} |`,
      `| --- | ---: | ---: | ---: | ${result.modes.includes("raw") && mode !== "raw" ? "---: | " : ""}${names.map(() => "---:").join(" | ")} |`
    );
    for (const rule of ruleNames) {
      const r = result.rules[rule];
      const m = r[mode];
      const raw =
        result.modes.includes("raw") && mode !== "raw"
          ? `${fmt(r.raw.pooled)} | `
          : "";
      out.push(
        `| \`${rule}\`${r.typeAware ? " (type-aware)" : ""} | ${fmt(m.pooled)} | ${m.per10k} | ${m.reposWithHits} of ${result.pooled.repos.length} | ${raw}${names.map((n) => fmt(m.byRepo[n])).join(" | ")} |`
      );
    }
    out.push("");
  };

  if (result.focus.length > 0) {
    ruleTable("Focus rules", result.focus);
  }
  const top = Object.keys(result.rules)
    .filter((rule) => result.rules[rule][mode].pooled > 0)
    .sort((a, b) => result.rules[b][mode].pooled - result.rules[a][mode].pooled)
    .slice(0, 40);
  ruleTable("Top 40 rules by pooled hits", top);

  const silent = Object.keys(result.rules).filter(
    (rule) =>
      result.rules[rule].enabled &&
      result.modes.every((m) => result.rules[rule][m].pooled === 0)
  );
  out.push(
    `## Enabled rules with no hits in any mode (${silent.length})`,
    "",
    silent
      .map(
        (rule) =>
          `\`${rule}\`${result.rules[rule].typeAware ? " (type-aware, not run)" : ""}`
      )
      .join(", "),
    ""
  );
  return out.join("\n");
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
