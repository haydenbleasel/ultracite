const fmt = (n) =>
  typeof n === "number" ? n.toLocaleString("en-US") : (n ?? "–");
const pct = (a, b) => (b ? `${Math.round((a / b) * 1000) / 10}%` : "–");
const per10k = (n, lines) => (lines ? Math.round((n / lines) * 1e5) / 10 : 0);
const short = (r) =>
  r
    .replace(/^jsx-a11y\//, "")
    .replace(/^astro\/jsx-a11y\//, "astro/")
    .replace(/^a11y\//, "")
    .replace(/^react-doctor\//, "rd/")
    .replace(/^github\//, "gh/");
// Right-align a column when every non-empty cell in it is a number, a percentage or a rate.
const NUMERIC = /^(?:[\d,.]+%?|[\d.]+\/10k|[\d,]+ \([\d.]+\/10k\)|–)$/;
const table = (head, rows) => {
  const align = head.map((_, i) =>
    rows.length > 0 && rows.every((r) => NUMERIC.test(String(r[i] ?? "–")))
      ? "---:"
      : "---"
  );
  return [
    `| ${head.join(" | ")} |`,
    `| ${align.join(" | ")} |`,
    ...rows.map(
      (r) =>
        `| ${r
          .map((c) =>
            String(c ?? "–")
              .replaceAll("|", "\\|")
              .replaceAll("\n", " ")
          )
          .join(" | ")} |`
    ),
  ];
};
