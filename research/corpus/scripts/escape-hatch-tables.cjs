// Builds results/<topic>/tables.md from the escape-hatch results: rule-census.json,
// escape-hatch-census.json, linters.json, typed-census.json, and (if present) sample.json plus
// classifications.json. Every number in the topic's REPORT.md comes from these tables.
//
// Usage (from the repo root):
//   node research/corpus/scripts/escape-hatch-tables.cjs [--topic type-escape-hatches]
"use strict";

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { join, resolve } = require("node:path");

const HERE = resolve(__dirname, "..");
const args = process.argv.slice(2);
const TOPIC =
  (args.includes("--topic") && args[args.indexOf("--topic") + 1]) ||
  process.env.RESEARCH_TOPIC ||
  "type-escape-hatches";
const DIR = join(HERE, "results", TOPIC);
const load = (name) =>
  existsSync(join(DIR, name))
    ? JSON.parse(readFileSync(join(DIR, name), "utf8"))
    : null;

const census = load("rule-census.json");
const hatches = load("escape-hatch-census.json");
const linters = load("linters.json");
const typed = load("typed-census.json");
const sample = load("sample.json");
const labels = load("classifications.json");

const fmt = (n) => (typeof n === "number" ? n.toLocaleString("en-US") : "–");
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : "–");
const out = [];
const table = (head, rows) => {
  out.push(
    `| ${head.join(" | ")} |`,
    `| ${head.map((_, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
    ""
  );
};

out.push(
  `# Type escape hatches: generated tables`,
  "",
  `Generated by \`scripts/escape-hatch-tables.cjs\` from the JSON files in this folder. Oxlint ${census.tools.oxlint}, typescript-estree ${hatches.tools["@typescript-eslint/typescript-estree"]}, ${linters ? `ESLint ${linters.tools.eslint} with @typescript-eslint/eslint-plugin ${linters.tools["@typescript-eslint/eslint-plugin"]}, Biome ${linters.tools["@biomejs/biome"]}, ` : ""}TypeScript ${typed?.tools.typescript ?? "–"}, Node ${census.tools.node}.`,
  ""
);

const names = Object.keys(hatches.repos);
const external = names.filter((n) => !hatches.repos[n].dogfood);

// ── 1. per repo ──
out.push(
  "## 1. Escape hatches per repo (every occurrence, suppressions ignored)",
  ""
);
const row = (name, r, lines) => {
  const t = r.tally;
  const ts = t.tsComments;
  const ignore = ts["@ts-ignore"]?.total ?? 0;
  const expect = ts["@ts-expect-error"]?.total ?? 0;
  const asAny =
    (t.assertions.by["as any"] ?? 0) +
    (t.assertions.by["double, through any"] ?? 0);
  return [
    name,
    fmt(lines),
    fmt(t.any.total),
    ((t.any.total / lines) * 1e4).toFixed(1),
    fmt(t.unknown.total),
    fmt(t.nonNull.total),
    ((t.nonNull.total / lines) * 1e4).toFixed(1),
    fmt(t.assertions.total),
    fmt(asAny),
    fmt(t.assertions.by["as const"] ?? 0),
    fmt(ignore),
    fmt(expect),
    fmt(ts["@ts-nocheck"]?.total ?? 0),
  ];
};
table(
  [
    "Repo",
    "Lines",
    "`any`",
    "per 10k",
    "`unknown`",
    "`!`",
    "per 10k",
    "Assertions",
    "of which to `any`",
    "`as const`",
    "`@ts-ignore`",
    "`@ts-expect-error`",
    "`@ts-nocheck`",
  ],
  [
    ...names.map((n) => row(n, hatches.repos[n], hatches.repos[n].lines)),
    row("**8 external, pooled**", hatches.pooled, hatches.pooled.lines),
  ]
);

// ── 2. reported vs raw ──
out.push(
  "## 2. What Ultracite's Oxlint presets report (in-file suppressions honoured) vs every occurrence",
  ""
);
const rules = [
  "typescript/no-explicit-any",
  "typescript/no-non-null-assertion",
  "typescript/ban-ts-comment",
];
table(
  ["Rule", "Mode", ...names, "Pooled (8)", "Repos with hits"],
  rules.flatMap((rule) =>
    ["reported", "raw"].map((mode) => {
      const m = census.rules[rule][mode];
      return [
        `\`${rule}\``,
        mode,
        ...names.map((n) => fmt(m.byRepo[n])),
        fmt(m.pooled),
        `${m.reposWithHits} of ${census.pooled.repos.length}`,
      ];
    })
  )
);
const rank = Object.entries(census.rules)
  .filter(([, r]) => r.reported.pooled > 0)
  .sort((a, b) => b[1].reported.pooled - a[1].reported.pooled)
  .map(([name]) => name);
out.push(
  `Of ${fmt(rank.length)} rules with at least one hit, \`typescript/no-explicit-any\` ranks ${rank.indexOf("typescript/no-explicit-any") + 1} and \`typescript/no-non-null-assertion\` ranks ${rank.indexOf("typescript/no-non-null-assertion") + 1} by pooled reported hits.`,
  "",
  "Most-suppressed rules (raw minus reported hits, pooled), i.e. hits the projects' own disable comments already silence:",
  ""
);
table(
  ["Rule", "Suppressed hits"],
  Object.entries(census.rules)
    .map(([name, r]) => [name, r.raw.pooled - r.reported.pooled])
    .filter(([, n]) => n > 0)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 8)
    .map(([name, n]) => [`\`${name}\``, fmt(n)])
);

// ── 3. where any sits ──
const sortEntries = (o) => Object.entries(o).sort((a, b) => b[1] - a[1]);
const pooled = hatches.pooled.tally;
out.push("## 3. Where `any` sits (pooled, 8 repos)", "");
table(
  ["Site", "`any`", "Share", "`unknown`", "Share"],
  sortEntries(pooled.any.by.site).map(([site, n]) => [
    site,
    fmt(n),
    pct(n, pooled.any.total),
    fmt(pooled.unknown.by.site[site] ?? 0),
    pct(pooled.unknown.by.site[site] ?? 0, pooled.unknown.total),
  ])
);
table(
  ["Form", "`any`", "Share"],
  sortEntries(pooled.any.by.form).map(([form, n]) => [
    form,
    fmt(n),
    pct(n, pooled.any.total),
  ])
);

// ── 4. what ! asserts ──
out.push("## 4. What `!` asserts (pooled, syntactic heuristic)", "");
table(
  ["Asserted expression", "`!`", "Share"],
  sortEntries(pooled.nonNull.by.asserted).map(([k, n]) => [
    k,
    fmt(n),
    pct(n, pooled.nonNull.total),
  ])
);
table(
  ["Used as", "`!`", "Share"],
  sortEntries(pooled.nonNull.by.usage).map(([k, n]) => [
    k,
    fmt(n),
    pct(n, pooled.nonNull.total),
  ])
);
out.push(
  `Definite-assignment assertions (\`let x!: T\`, \`field!: T\`), which no rule here flags: ${fmt(pooled.definite)}.`,
  ""
);

// ── 5. assertions ──
out.push("## 5. Type assertions by kind (pooled)", "");
table(
  ["Kind", "Count", "Share"],
  sortEntries(pooled.assertions.by).map(([k, n]) => [
    k,
    fmt(n),
    pct(n, pooled.assertions.total),
  ])
);
out.push(
  `Angle-bracket assertions: ${fmt(pooled.assertions.angleBracket)}. \`satisfies\` expressions: ${fmt(pooled.satisfies)}.`,
  ""
);

// ── 6. ts comments and suppressions ──
out.push("## 6. `@ts-*` comments and lint suppressions (pooled)", "");
table(
  [
    "Directive",
    "Total",
    "With a reason (≥ 3 characters, as ban-ts-comment measures it)",
  ],
  sortEntries(
    Object.fromEntries(
      Object.entries(pooled.tsComments).map(([k, v]) => [k, v.total])
    )
  ).map(([k, n]) => [
    `\`${k}\``,
    fmt(n),
    `${fmt(pooled.tsComments[k].reasoned)} (${pct(pooled.tsComments[k].reasoned, n)})`,
  ])
);
table(
  ["Suppression comment naming", "Comments"],
  sortEntries(pooled.disables.byRule).map(([k, n]) => [`\`${k}\``, fmt(n)])
);
out.push(
  `Files with a blanket \`eslint-disable\` (no rule named): ${fmt(pooled.disables.blanketFiles)}.`,
  ""
);

// ── 7. linters ──
if (linters?.corpus) {
  out.push(
    "## 7. The same rules in three linters (corpus, suppressions ignored)",
    ""
  );
  const sum = (tool, rule) =>
    external.reduce((s, n) => s + (linters.corpus[n]?.[tool]?.[rule] ?? 0), 0);
  table(
    ["Rule", "Oxlint", "ESLint", "Biome"],
    [
      [
        "`no-explicit-any` / `noExplicitAny`",
        fmt(census.rules["typescript/no-explicit-any"].raw.pooled),
        fmt(sum("eslint", "no-explicit-any")),
        fmt(sum("biome", "no-explicit-any")),
      ],
      [
        "`no-non-null-assertion` / `noNonNullAssertion`",
        fmt(census.rules["typescript/no-non-null-assertion"].raw.pooled),
        fmt(sum("eslint", "no-non-null-assertion")),
        fmt(sum("biome", "no-non-null-assertion")),
      ],
      [
        "`ban-ts-comment` / `noTsIgnore`",
        fmt(census.rules["typescript/ban-ts-comment"].raw.pooled),
        fmt(sum("eslint", "ban-ts-comment")),
        fmt(sum("biome", "noTsIgnore")),
      ],
    ]
  );
  const mismatches = external.flatMap((n) =>
    (linters.corpus[n]?.biomeLineMismatches ?? []).map((m) => ({
      ...m,
      repo: n,
    }))
  );
  table(
    ["Repo", "Line", "Rule", "Census", "Biome", "Code"],
    mismatches.map((m) => [
      m.repo,
      `\`${m.file}:${m.line}\``,
      m.rule,
      m.census,
      m.biome,
      `\`${m.code.replaceAll("|", "\\|")}\``,
    ])
  );
  if (linters.calibration) {
    out.push("### Calibration cases (`calibration/escape-hatches/`)", "");
    table(
      ["Case", "Oxlint", "ESLint (with type information)", "Biome"],
      linters.calibration.map((c) => [
        c.id,
        c.oxlint.join(", ") || "–",
        c.eslint.join(", ") || "–",
        c.biome.join(", ") || "–",
      ])
    );
  }
}

// ── 8. typed ──
if (typed) {
  out.push(
    "## 8. Type-aware rules where types resolve without installing anything",
    ""
  );
  const tnames = Object.keys(typed.repos);
  const ruleNames = [
    ...new Set(tnames.flatMap((n) => Object.keys(typed.repos[n].lint.counts))),
  ].sort();
  table(
    ["Rule", ...tnames],
    ruleNames.map((r) => [
      `\`${r}\``,
      ...tnames.map((n) => fmt(typed.repos[n].lint.counts[r] ?? 0)),
    ])
  );
  table(
    [
      "Repo",
      "Files",
      "TypeScript diagnostics",
      "Unresolved-module diagnostics",
      "By code",
    ],
    tnames.map((n) => {
      const t = typed.repos[n].typeCheck;
      return [
        n,
        fmt(typed.repos[n].files),
        fmt(t.total),
        fmt(t.unresolved),
        Object.entries(t.byCode)
          .map(([c, k]) => `TS${c} × ${k}`)
          .join(", ") || "none",
      ];
    })
  );
  out.push(
    "Each assertion site joined to the two assertion rules (a site is one cast; a double cast is one site):",
    ""
  );
  const kinds = [
    ...new Set(
      tnames.flatMap((n) => Object.keys(typed.repos[n].assertionsByKind ?? {}))
    ),
  ];
  table(
    [
      "Kind",
      ...tnames.flatMap((n) => [
        `${n}: total`,
        `${n}: narrows (unsafe)`,
        `${n}: unnecessary`,
      ]),
      "Both: narrows",
      "Both: unnecessary",
    ],
    kinds.map((k) => {
      const cells = tnames.flatMap((n) => {
        const r = typed.repos[n].assertionsByKind?.[k] ?? {
          total: 0,
          unsafe: 0,
          unnecessary: 0,
        };
        return [fmt(r.total), fmt(r.unsafe), fmt(r.unnecessary)];
      });
      const tot = tnames.reduce(
        (s, n) => s + (typed.repos[n].assertionsByKind?.[k]?.total ?? 0),
        0
      );
      const uns = tnames.reduce(
        (s, n) => s + (typed.repos[n].assertionsByKind?.[k]?.unsafe ?? 0),
        0
      );
      const unn = tnames.reduce(
        (s, n) => s + (typed.repos[n].assertionsByKind?.[k]?.unnecessary ?? 0),
        0
      );
      return [
        k,
        ...cells,
        `${fmt(uns)} of ${fmt(tot)} (${pct(uns, tot)})`,
        `${fmt(unn)} (${pct(unn, tot)})`,
      ];
    })
  );
}

// ── 9. classification ──
if (sample && labels) {
  out.push("## 9. Why maintainers wrote them (hand-classified sample)", "");
  const byId = new Map(labels.labels.map((l) => [l.id, l]));
  for (const kind of sample.kinds) {
    const sites = sample.sites.filter((s) => s.kind === kind);
    const totals = sample.totals[kind];
    const cats = [...new Set(sites.map((s) => byId.get(s.id)?.category))]
      .filter(Boolean)
      .sort();
    // Weighted: each repo's sample share, weighted by that repo's total count.
    const weighted = {};
    const totalAll = Object.values(totals).reduce((a, b) => a + b, 0);
    for (const repo of Object.keys(totals)) {
      const rs = sites.filter((s) => s.repo === repo);
      for (const c of cats) {
        const share = rs.length
          ? rs.filter((s) => byId.get(s.id)?.category === c).length / rs.length
          : 0;
        weighted[c] = (weighted[c] ?? 0) + share * (totals[repo] / totalAll);
      }
    }
    out.push(
      `### \`${kind}\` (n = ${sites.length}, up to ${sample.perRepo} per repo, seed ${sample.seed})`,
      ""
    );
    table(
      [
        "Category",
        "Sampled",
        "Unweighted share",
        "Weighted by repo totals",
        ...Object.keys(totals),
      ],
      cats.map((c) => {
        const n = sites.filter((s) => byId.get(s.id)?.category === c).length;
        return [
          `\`${c}\``,
          fmt(n),
          pct(n, sites.length),
          `${(100 * weighted[c]).toFixed(1)}%`,
          ...Object.keys(totals).map((repo) =>
            fmt(
              sites.filter(
                (s) => s.repo === repo && byId.get(s.id)?.category === c
              ).length
            )
          ),
        ];
      })
    );
    const ack = sites.filter((s) => byId.get(s.id)?.acknowledged).length;
    out.push(
      `Acknowledged by a nearby comment or suppression: ${ack} of ${sites.length} (${pct(ack, sites.length)}).`,
      ""
    );
    for (const field of ["unknownWouldDo", "optionalChainSafe"]) {
      const values = sites.map((s) => byId.get(s.id)?.[field]).filter(Boolean);
      if (values.length > 0) {
        const counts = values.reduce(
          (m, v) => ({ ...m, [v]: (m[v] ?? 0) + 1 }),
          {}
        );
        out.push(
          `\`${field}\`: ${Object.entries(counts)
            .map(([v, n]) => `${v} ${n}`)
            .join(", ")}.`,
          ""
        );
      }
    }
  }
  if (labels.agreement) {
    out.push("### Second-rater agreement", "");
    table(
      [
        "Kind",
        "Re-labelled blind",
        "Same category",
        "Cohen's κ",
        "Same coarse label",
        "Coarse κ",
      ],
      Object.entries(labels.agreement).map(([k, a]) => [
        k,
        fmt(a.n),
        `${a.same} (${pct(a.same, a.n)})`,
        a.kappa.toFixed(2),
        `${a.coarse.same} (${pct(a.coarse.same, a.n)})`,
        a.coarse.kappa.toFixed(2),
      ])
    );
    out.push(
      "Coarse label: for `any`, `convenience` vs any other category; for `!`, `unguarded` vs any other.",
      "",
      `Disagreements: ${Object.values(labels.agreement)
        .flatMap((a) => a.disagreements)
        .map((d) => `${d.id} (${d.first} / ${d.second})`)
        .join(", ")}.`,
      ""
    );
  }
}

writeFileSync(join(DIR, "tables.md"), out.join("\n"));
console.log(`wrote ${join(DIR, "tables.md")}`);
