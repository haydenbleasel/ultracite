/**
 * Regenerates config/bun/rules.mjs and its declaration: every rule name
 * `bun lint` knows (each rule's id and its aliases, e.g.
 * `@typescript-eslint/no-explicit-any` and `typescript/no-explicit-any`),
 * which ultracite/bun's defineConfig uses to drop the preset rules Bun
 * doesn't implement.
 *
 * Usage: bun run scripts/sync-bun-rules.ts [path-to-bun]
 *
 * Bun's rules are its own snapshot of oxlint's (and ESLint's), whatever
 * version of those is installed, so re-run this after upgrading Bun and
 * after a toolchain bump enables new rules; the dropped-rules snapshot in
 * __tests__/bun-config.test.ts then shows what changed.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { z } from "zod";

const bun = process.argv[2] ?? "bun";

const outDir = path.join(import.meta.dirname, "../config/bun");
const outFile = path.join(outDir, "rules.mjs");

const run = (args: string[]): string => {
  // `bun lint` runs a package.json "lint" script instead of linting unless
  // it is already inside one.
  const result = Bun.spawnSync([bun, ...args], {
    env: { ...process.env, npm_lifecycle_event: "lint" },
    stderr: "inherit",
  });

  if (result.exitCode !== 0) {
    throw new Error(`${bun} ${args.join(" ")} failed`);
  }

  return result.stdout.toString().trim();
};

const rulesSchema = z.array(
  z.object({ aliases: z.array(z.string()), id: z.string() })
);

const rules = rulesSchema.parse(
  JSON.parse(run(["lint", "--rules", "--format", "json"]))
);

const names = [
  ...new Set(rules.flatMap((rule) => [rule.id, ...rule.aliases])),
].toSorted();

const version = run(["--revision"]);

writeFileSync(
  outFile,
  `// Generated by scripts/sync-bun-rules.ts from \`bun lint --rules\` (Bun
// ${version}). Do not edit by hand.
export const bunVersion = ${JSON.stringify(version)};

export const bunRules = [
${names.map((name) => `  ${JSON.stringify(name)},`).join("\n")}
];
`
);

writeFileSync(
  path.join(outDir, "rules.d.mts"),
  `// Generated by scripts/sync-bun-rules.ts. Do not edit by hand.
/** The Bun build the rule names were read from. */
export declare const bunVersion: string;

/** Every rule name \`bun lint\` accepts: each rule's id and its aliases. */
export declare const bunRules: readonly string[];
`
);

console.log(
  `Wrote ${String(names.length)} rule names from Bun ${version} to ${path.relative(process.cwd(), outFile)}`
);
